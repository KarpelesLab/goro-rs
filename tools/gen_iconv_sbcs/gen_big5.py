#!/usr/bin/env python3
"""mbmap.php.p / mbmap.php.g (BIG5 only) -> override tables for glibc's BIG5."""
import sys
cs = 'BIG5'
def load(f):
    dec = {}; enc = {}
    for ln in open(f):
        p = ln.split()
        if len(p) != 4 or p[0] != cs:
            continue
        k = int(p[2], 16)
        if p[1] == 'E':
            enc[k] = int(p[3], 16)
        else:
            if k < 0x100:
                continue
            if p[3] in ('ILL', 'INC'):
                continue
            v = p[3]
            if len(v) != 8:
                print('multi', ln, file=sys.stderr)
                continue
            dec[k] = int(v, 16)
    return dec, enc
pd, pe = load(sys.argv[1])
gd, ge = load(sys.argv[2])
dec = []
for k in sorted(set(pd) | set(gd)):
    if pd.get(k) != gd.get(k):
        dec.append((k, pd.get(k, 0)))
enc = []
for k in sorted(set(pe) | set(ge)):
    if pe.get(k) != ge.get(k):
        v = pe.get(k, 0)
        if v > 0xFFFF:
            print('enc multi', hex(k), file=sys.stderr)
        enc.append((k, v))
o = ['//! Where glibc\'s BIG5 differs from libmbfl\'s (generated by comparing',
     '//! the two conversions of every two-byte sequence and BMP character):',
     '//! a 0 code point or byte pair is undefined in glibc.', '']
o.append('pub static BIG5_DEC: [(u16, u32); %d] = [' % len(dec))
for i in range(0, len(dec), 6):
    o.append('    ' + ' '.join('(0x%X, 0x%X),' % x for x in dec[i:i + 6]))
o.append('];')
o.append('')
o.append('pub static BIG5_ENC: [(u32, u16); %d] = [' % len(enc))
for i in range(0, len(enc), 6):
    o.append('    ' + ' '.join('(0x%X, 0x%X),' % x for x in enc[i:i + 6]))
o.append('];')
open(sys.argv[3], 'w').write('\n'.join(o) + '\n')
print(len(dec), len(enc))
