<?php
// usage: php -n dump_comp.php > crates/goro-ext-iconv/src/comp_tables.rs
// glibc's single-byte charsets with combining characters (CP1255, CP1258,
// TCVN5712-1): the decode table, the compositions their decoders apply to
// a base character followed by a combining one, and the decompositions
// their encoders use for the characters without a byte of their own (and
// their one-way mappings).
$charsets = ["CP1255" => ["CP1255", "WINDOWS-1255", "MS-HEBR"], "CP1258" => ["CP1258", "WINDOWS-1258"], "TCVN5712-1" => ["TCVN5712-1", "TCVN", "TCVN-5712", "TCVN5712-1:1993"]];
function dec($cs, $s) {
    $r = @iconv($cs, "UTF-32BE", $s);
    return $r === false ? null : array_values(unpack("N*", $r));
}
echo "//! glibc's single-byte charsets with combining characters (generated by\n";
echo "//! tools/gen_iconv_sbcs/dump_comp.php from glibc iconv): the decode\n";
echo "//! table (0xFFFF: undefined), the compositions of a base character and\n";
echo "//! a combining one (sorted), and the bytes of the characters without\n";
echo "//! a byte of their own or with a one-way mapping (sorted).\n\n";
echo "pub struct CompSbcs {\n    pub dec: [u16; 256],\n    pub comp: &'static [(u16, u16, u16)],\n    /// The byte sequences of characters without a byte of their own, and\n    /// the bytes of one-way mappings.\n    pub decomp: &'static [(u16, &'static [u8])],\n}\n\n";
$names = [];
$i = 0;
$out = "";
foreach ($charsets as $cs => $aliases) {
    $dec = [];
    for ($b = 0; $b < 256; $b++) {
        $d = dec($cs, chr($b));
        $dec[$b] = ($d === null || count($d) != 1) ? 0xFFFF : $d[0];
    }
    // byte sequence of every character reachable by composition
    $seq = [];
    for ($b = 0; $b < 256; $b++) if ($dec[$b] != 0xFFFF) $seq[$dec[$b]] = chr($b);
    $comp = [];
    $changed = true;
    while ($changed) {
        $changed = false;
        foreach ($seq as $base => $bytes) {
            for ($b = 0; $b < 256; $b++) {
                if ($dec[$b] == 0xFFFF) continue;
                $d = dec($cs, $bytes . chr($b));
                if ($d !== null && count($d) == 1) {
                    $key = $base . "," . $dec[$b];
                    if (!isset($comp[$key])) {
                        $comp[$key] = [$base, $dec[$b], $d[0]];
                        if (!isset($seq[$d[0]])) { $seq[$d[0]] = $bytes . chr($b); $changed = true; }
                    }
                }
            }
        }
    }
    $decomp = [];
    for ($cp = 0x80; $cp < 0x10000; $cp++) {
        if ($cp >= 0xD800 && $cp < 0xE000) continue;
        $r = @iconv("UTF-32BE", $cs, pack("N", $cp));
        if ($r === false) continue;
        if (strlen($r) > 1 || $dec[ord($r)] != $cp) $decomp[] = [$cp, $r];
    }
    usort($comp, fn($a, $b) => [$a[0], $a[1]] <=> [$b[0], $b[1]]);
    $out .= "pub static T$i: CompSbcs = CompSbcs {\n    dec: [\n";
    foreach (array_chunk($dec, 16) as $row) $out .= "        " . implode(",", array_map(fn($v) => sprintf("0x%X", $v), $row)) . ",\n";
    $out .= "    ],\n    comp: &[\n";
    foreach (array_chunk(array_values($comp), 6) as $row) $out .= "        " . implode(" ", array_map(fn($c) => sprintf("(0x%X, 0x%X, 0x%X),", ...$c), $row)) . "\n";
    $out .= "    ],\n    decomp: &[\n";
    foreach (array_chunk($decomp, 6) as $row) $out .= "        " . implode(" ", array_map(fn($c) => sprintf("(0x%X, &[%s]),", $c[0], implode(", ", array_map(fn($b) => sprintf("0x%X", ord($b)), str_split($c[1])))), $row)) . "\n";
    $out .= "    ],\n};\n\n";
    foreach ($aliases as $a) $names[$a] = $i;
    $i++;
}
echo $out;
ksort($names, SORT_STRING);
echo "pub static TABLES: [&CompSbcs; $i] = [" . implode(", ", array_map(fn($t) => "&T$t", range(0, $i - 1))) . "];\n\n";
echo "/// Charset names (upper case, sorted) to TABLES indexes.\n";
echo "pub static NAMES: [(&str, u8); " . count($names) . "] = [\n";
foreach ($names as $n => $t) echo "    (\"$n\", $t),\n";
echo "];\n";
