#!/usr/bin/env python3
"""Dump glibc's direct (non-INTERNAL) gconv modules GBBIG5 (EUC-CN <-> BIG5)
and GBGBK (GBK <-> EUC-CN) by converting every two-byte code with the host
glibc's iconv(3), checking the model direct.rs implements, and write
crates/goro-ext-iconv/src/direct_tables.rs.

usage: python3 tools/gen_iconv_sbcs/dump_direct.py > crates/goro-ext-iconv/src/direct_tables.rs
(the host glibc must be the version goro emulates, see charset.rs)
"""
import ctypes
import ctypes.util

libc = ctypes.CDLL(ctypes.util.find_library("c"), use_errno=True)
libc.iconv_open.restype = ctypes.c_void_p
libc.iconv_open.argtypes = [ctypes.c_char_p, ctypes.c_char_p]
libc.iconv.restype = ctypes.c_size_t
libc.iconv.argtypes = [ctypes.c_void_p, ctypes.POINTER(ctypes.c_char_p), ctypes.POINTER(ctypes.c_size_t),
                       ctypes.POINTER(ctypes.c_char_p), ctypes.POINTER(ctypes.c_size_t)]
libc.iconv_close.argtypes = [ctypes.c_void_p]
EILSEQ, EINVAL = 84, 22


def conv(to, frm, data):
    """(output, consumed, errno) of one iconv() call (no flush)."""
    cd = libc.iconv_open(to.encode(), frm.encode())
    assert cd != ctypes.c_void_p(-1).value, (to, frm)
    inbuf = ctypes.create_string_buffer(data, len(data))
    inp = ctypes.c_char_p(ctypes.addressof(inbuf))
    inleft = ctypes.c_size_t(len(data))
    outbuf = ctypes.create_string_buffer(64)
    outp = ctypes.c_char_p(ctypes.addressof(outbuf))
    outleft = ctypes.c_size_t(64)
    r = libc.iconv(cd, ctypes.byref(inp), ctypes.byref(inleft), ctypes.byref(outp), ctypes.byref(outleft))
    err = ctypes.get_errno() if r == ctypes.c_size_t(-1).value else 0
    libc.iconv_close(cd)
    return outbuf.raw[:64 - outleft.value], len(data) - inleft.value, err


def dense(frm, to, leads, trails, index, size, box):
    """The table of a GBBIG5 direction: index(lead, trail) -> code (0: no
    mapping, //IGNORE writes `box`)."""
    t = [0] * size
    seen = {}
    for a in leads:
        for b in trails:
            o, used, err = conv(to, frm, bytes([a, b]) + b"A")
            i = index(a, b)
            if err == 0:
                assert used == 3 and len(o) == 3, (frm, hex(a), hex(b))
                code = (o[0] << 8) | o[1]
            else:
                assert (err, used) == (EILSEQ, 0), (frm, hex(a), hex(b), err, used)
                oi, usedi, erri = conv(to + "//IGNORE", frm, bytes([a, b]) + b"A")
                assert (oi, usedi, erri) == (box + b"A", 3, EILSEQ), (frm, hex(a), hex(b), oi, usedi)
                code = 0
            if i in seen:
                # (trail 0xFF reads the next row's first entry)
                assert seen[i] == code, (frm, hex(a), hex(b))
            seen[i] = code
            if i < size:
                t[i] = code
            else:
                assert code == 0
    return t


def rs_u16(name, doc, t):
    print("/// %s" % doc)
    print("pub static %s: [u16; %d] = [" % (name, len(t)))
    for i in range(0, len(t), 12):
        print("    " + " ".join("0x%04x," % v for v in t[i:i + 12]))
    print("];")


gb_trails = range(0xA1, 0x100)
big5_trails = list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF))

print("// Generated by tools/gen_iconv_sbcs/dump_direct.py from glibc's GBBIG5 and")
print("// GBGBK gconv modules: do not edit.")
print("")
rs_u16("GB2312_TO_BIG5", "EUC-CN -> BIG5 (GBBIG5): (lead - 0xA1) * 94 + trail - 0xA1, leads 0xA1-0xF7 (0: none).",
       dense("EUC-CN", "BIG5", range(0xA1, 0xF8), gb_trails, lambda a, b: (a - 0xA1) * 94 + b - 0xA1, 87 * 94, b"\xa1\xbc"))
print("")
rs_u16("BIG5_TO_GB2312", "BIG5 -> EUC-CN (GBBIG5): (lead - 0xA1) * 157 + trail - (0x40 | 0x62), leads 0xA1-0xF9 (0: none).",
       dense("BIG5", "EUC-CN", range(0xA1, 0xFA), big5_trails,
             lambda a, b: (a - 0xA1) * 157 + (b - 0x40 if b < 0x80 else b - 0x62), 89 * 157, b"\xa1\xf5"))

# GBK -> EUC-CN: a pair passes through unchanged or is illegal (both bytes
# skipped); list the illegal pairs among leads 0xA1-0xF7 / trails >= 0xA1.
bad = []
for a in range(0x80, 0x100):
    for b in range(0x100):
        o, used, err = conv("EUC-CN", "GBK", bytes([a, b]) + b"A")
        ok = err == 0
        if ok:
            assert o == bytes([a, b]) + b"A", (hex(a), hex(b))
        else:
            assert (err, used) == (EILSEQ, 0)
            oi, usedi, erri = conv("EUC-CN//IGNORE", "GBK", bytes([a, b]) + b"A")
            assert (oi, usedi, erri) == (b"A", 3, EILSEQ), (hex(a), hex(b), oi)
        expect_ok = 0xA1 <= a <= 0xF7 and b >= 0xA1
        if expect_ok and not ok:
            bad.append((a << 8) | b)
        else:
            assert ok == expect_ok, (hex(a), hex(b))
print("")
print("/// GBK -> EUC-CN (GBGBK): the pairs of leads 0xA1-0xF7 and trails 0xA1-0xFF")
print("/// it rejects (the others pass through), as ranges.")
print("pub static GBK_TO_GB2312_BAD: &[(u16, u16)] = &[")
start = prev = None
for k in bad:
    if start is None:
        start = prev = k
    elif k == prev + 1:
        prev = k
    else:
        print("    (0x%04x, 0x%04x)," % (start, prev))
        start = prev = k
if start is not None:
    print("    (0x%04x, 0x%04x)," % (start, prev))
print("];")

# the single-byte / end-of-input behaviours the code assumes
for frm, to, leads in [("EUC-CN", "BIG5", range(0xA1, 0xF8)), ("BIG5", "EUC-CN", range(0xA1, 0xFA)),
                       ("GBK", "EUC-CN", range(0x80, 0x100))]:
    for a in range(0x80, 0x100):
        o, used, err = conv(to, frm, bytes([a]))
        assert (err == EINVAL) == (a in leads), (frm, hex(a), err)
        if a not in leads:
            assert err == EILSEQ and used == 0
            oi, usedi, erri = conv(to + "//IGNORE", frm, bytes([a]) + b"A")
            assert oi == b"A" and usedi == 2, (frm, hex(a), oi, usedi)
# EUC-CN -> GBK: a byte >= 0x80 takes the next one unchecked, but only with
# a third byte after them (else "incomplete")
for a in range(0x80, 0x100):
    for b in (0x00, 0x41, 0xA1, 0xFF):
        assert conv("GBK", "EUC-CN", bytes([a, b, 0x41])) == (bytes([a, b, 0x41]), 3, 0)
        o, used, err = conv("GBK", "EUC-CN", bytes([a, b]))
        assert (o, err) == (b"", EINVAL), (hex(a), hex(b), o, used, err)
