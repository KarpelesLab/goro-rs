#!/usr/bin/env python3
"""Generate crates/goro-ext-iconv/src/translit_table.rs from glibc's locale
sources: the transliteration table of the C.UTF-8 locale php runs iconv in
(translit_combining, translit_neutral and its includes).

usage: tools/gen_iconv_translit.py [/usr/share/i18n/locales] > crates/goro-ext-iconv/src/translit_table.rs
"""
import re
import sys

LOC = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/i18n/locales'
table = {}


def tokenize(t):
    """A translit line: a list of fields (split on whitespace and ';'
    outside quotes), each a list of code points; None when malformed."""
    fields = []
    cur = None
    quoted = False
    i = 0
    while i < len(t):
        c = t[i]
        if c == '"':
            quoted = not quoted
            if cur is None:
                cur = []
            i += 1
            continue
        if not quoted and (c in ' \t' or c == ';'):
            if cur is not None:
                fields.append(cur)
                cur = None
            if c == ';':
                fields.append(';')
            i += 1
            continue
        if cur is None:
            cur = []
        if c == '/' and i + 1 < len(t):
            cur.append(ord(t[i + 1]))
            i += 2
            continue
        m = re.match(r'<U([0-9A-Fa-f]+)>', t[i:])
        if m:
            cur.append(int(m.group(1), 16))
            i += len(m.group(0))
            continue
        cur.append(ord(c))
        i += 1
    if quoted:
        return None
    if cur is not None:
        fields.append(cur)
    return fields


def load(name):
    includes = []
    entries = []
    lines = open('%s/%s' % (LOC, name), encoding='utf-8', errors='replace').read().split('\n')
    # join continuation lines
    joined = []
    buf = ''
    for ln in lines:
        if ln.endswith('/'):
            buf += ln[:-1]
            continue
        joined.append(buf + ln)
        buf = ''
    inside = False
    for ln in joined:
        t = re.sub(r'\s%[^"]*$', '', ln).strip()
        if t == 'translit_start':
            inside = True
            continue
        if t == 'translit_end':
            inside = False
            continue
        if not inside or not t or t.startswith('%'):
            continue
        if t.startswith('include'):
            m = re.match(r'include\s+"([^"]+)"', t)
            includes.append(m.group(1))
            continue
        f = tokenize(t)
        if not f or len(f) < 2 or f[0] == ';' or len(f[0]) != 1:
            continue
        alts = [[]]
        for x in f[1:]:
            if x == ';':
                alts.append([])
            else:
                alts[-1].extend(x)
        entries.append((f[0][0], alts))
    return includes, entries


def add(name):
    includes, entries = load(name)
    for cp, alts in entries:
        if cp not in table:
            table[cp] = alts
    for inc in includes:
        add(inc)


# (glibc's table lookup prefers translit_combining's entries to
# translit_neutral's, and translit_neutral's own to its includes')
add('translit_combining')
add('translit_neutral')


def enc(alts):
    out = []
    for a in alts:
        out.append(''.join('\\u{%x}' % c for c in a))
    return '\\0'.join(out)


print('//! glibc\'s transliterations in the C.UTF-8 locale (generated by')
print('//! tools/gen_iconv_translit.py from translit_combining, translit_neutral')
print('//! and its includes): the alternatives of each character, separated')
print('//! by NUL, tried in order.')
print()
print('pub static TRANSLIT: [(u32, &str); %d] = [' % len(table))
for cp in sorted(table):
    print('    (0x%X, "%s"),' % (cp, enc(table[cp])))
print('];')
