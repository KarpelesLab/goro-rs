#!/usr/bin/env python3
"""Generate the constant tables of goro-ext-hash that are published as data.

Inputs are the algorithms' own reference distributions, not PHP's:

  * Tiger: ``sboxes.c`` from the authors' reference package
    (https://biham.cs.technion.ac.il/Reports/Tiger/tiger-src.tar.gz,
    Anderson & Biham, 1996): the four 256-entry 64-bit S boxes.
  * Snefru: ``snefru.c`` version 2.5a (Merkle, Xerox 1990,
    ftp.nluug.nl/pub/security/coast/crypto/snefru/snefru.c): the 16
    "standard S boxes" of 256 32-bit words.

Usage:
    gen_hash_tables.py tiger SBOXES_C > crates/goro-ext-hash/src/tables/tiger.rs
    gen_hash_tables.py snefru SNEFRU_C > crates/goro-ext-hash/src/tables/snefru.rs

Only the hexadecimal constants are read; everything else in the files is
ignored.
"""
import re
import sys


def tiger(path):
    text = open(path).read()
    body = text[text.index('table[4*256]'):]
    vals = re.findall(r'0x([0-9A-Fa-f]{16})LL', body)
    assert len(vals) == 1024, len(vals)
    out = ['// Generated by tools/gen_hash_tables.py from the Tiger reference',
           '// sboxes.c (Anderson & Biham, 1996). Do not edit.',
           '',
           '/// The four Tiger S boxes, t1..t4, 256 entries each.',
           '#[rustfmt::skip]',
           'pub(crate) static TIGER_SBOX: [[u64; 256]; 4] = [']
    for b in range(4):
        out.append('    [')
        for i in range(0, 256, 4):
            row = ', '.join('0x%s' % v.lower() for v in vals[b * 256 + i:b * 256 + i + 4])
            out.append('        %s,' % row)
        out.append('    ],')
    out.append('];')
    print('\n'.join(out))


def snefru(path):
    text = open(path).read()
    start = text.index('standardSBoxes[MAX_SBOX_COUNT][256]')
    end = text.index('};', start)
    body = text[start:end]
    # Drop the "/*  25*/" index comments before collecting the words.
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    vals = re.findall(r'0x([0-9A-Fa-f]{8})L', body)
    assert len(vals) == 16 * 256, len(vals)
    out = ['// Generated by tools/gen_hash_tables.py from snefru.c 2.5a',
           '// (Merkle, Xerox 1990): the standard S boxes. Do not edit.',
           '',
           '/// The 16 standard Snefru S boxes, 256 words each.',
           '#[rustfmt::skip]',
           'pub(crate) static SNEFRU_SBOX: [[u32; 256]; 16] = [']
    for b in range(16):
        out.append('    [')
        for i in range(0, 256, 8):
            row = ', '.join('0x%s' % v.lower() for v in vals[b * 256 + i:b * 256 + i + 8])
            out.append('        %s,' % row)
        out.append('    ],')
    out.append('];')
    print('\n'.join(out))


if __name__ == '__main__':
    {'tiger': tiger, 'snefru': snefru}[sys.argv[1]](sys.argv[2])
