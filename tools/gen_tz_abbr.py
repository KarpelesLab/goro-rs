#!/usr/bin/env python3
"""Generate goro-ext-date's time zone abbreviation table.

Usage: gen_tz_abbr.py LIST.txt OUTPUT.rs

LIST.txt is the output of DateTimeZone::listAbbreviations() on PHP 8.5
(observed behaviour, black box), one "A abbr" line per abbreviation
followed by "dst offset timezone_id" lines ("-" for no identifier), in
PHP's order. It is kept as crates/goro-ext-date/tests/fixtures/
php85_abbreviations.txt.
"""

import sys


def main():
    src, out = sys.argv[1], sys.argv[2]
    entries = []
    cur = None
    for line in open(src, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("A "):
            cur = line[2:]
            continue
        dst, off, tz = line.split(" ")
        entries.append((cur, dst == "1", int(off), None if tz == "-" else tz))
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/gen_tz_abbr.py from the abbreviation list\n")
        fh.write("// observed on PHP 8.5 (DateTimeZone::listAbbreviations()).\n")
        fh.write("// Do not edit.\n\n")
        fh.write("use super::abbr::AbbrEntry;\n\n")
        fh.write("/// Every abbreviation entry, in PHP's listing order.\n")
        fh.write("pub(super) static ENTRIES: &[AbbrEntry] = &[\n")
        for abbr, dst, off, tz in entries:
            tzs = "None" if tz is None else 'Some("%s")' % tz
            fh.write('    AbbrEntry { abbr: "%s", upper: "%s", dst: %s, offset: %d, tz: %s },\n'
                     % (abbr, abbr.upper(), "true" if dst else "false", off, tzs))
        fh.write("];\n")


if __name__ == "__main__":
    main()
