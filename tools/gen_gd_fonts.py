#!/usr/bin/env python3
"""Generates crates/goro-ext-gd/src/font_data.rs: GD's five built-in
bitmap fonts as ISO-8859-2 character cells.

The cells come from the public-domain X11 "misc-fixed" BDF fonts
(xorg font-misc-misc: 5x8, 6x13, 7x13B, 9x15B) and the Sony 8x16 font
(xorg font-sony-misc, permissive licence), which are the fonts GD's
built-ins are documented to be (PHP manual, imagestring: fonts 1-5 are
"built-in fonts in latin2 encoding"; libgd documentation: gdFontTiny,
gdFontSmall, gdFontMediumBold, gdFontLarge, gdFontGiant).

GD's tiny font has older glyph designs for some letters; those seen in
the reference images of the ext/gd tests (imagestring_basic.png,
imagechar_basic.png, read as black boxes) are taken from there
(OVERRIDES).

usage: gen_gd_fonts.py BDF_DIR > crates/goro-ext-gd/src/font_data.rs
"""
import sys
import os

FONTS = [
    ("TINY", "5x8.bdf", 5, 8),
    ("SMALL", "6x13.bdf", 6, 13),
    ("MEDIUM_BOLD", "7x13B.bdf", 7, 13),
    ("LARGE", "8x16.bdf", 8, 16),
    ("GIANT", "9x15B.bdf", 9, 15),
]

# Glyph rows seen in the tests' reference images (font 1).
OVERRIDES = {
    "TINY": {
        "C": [0x0, 0xc, 0x12, 0x10, 0x10, 0x12, 0xc, 0x0],
        "S": [0x0, 0xe, 0x10, 0x10, 0xc, 0x2, 0x1c, 0x0],
        "T": [0x0, 0x1f, 0x4, 0x4, 0x4, 0x4, 0x4, 0x0],
        "e": [0x0, 0x0, 0x0, 0xc, 0x16, 0x18, 0xe, 0x0],
        "g": [0x0, 0x0, 0x0, 0xe, 0x12, 0xe, 0x2, 0xc],
        "i": [0x0, 0x4, 0x0, 0xc, 0x4, 0x4, 0xe, 0x0],
        "n": [0x0, 0x0, 0x0, 0x14, 0x1a, 0x12, 0x12, 0x0],
        "r": [0x0, 0x0, 0x0, 0x14, 0x1a, 0x10, 0x10, 0x0],
        "t": [0x0, 0x8, 0x8, 0x1c, 0x8, 0xa, 0x4, 0x0],
        "x": [0x0, 0x0, 0x0, 0x12, 0xc, 0xc, 0x12, 0x0],
    },
}


def latin2_to_unicode(b):
    if b < 0x80:
        return b
    try:
        return ord(bytes([b]).decode("iso8859-2"))
    except UnicodeDecodeError:
        return None


def parse_bdf(path):
    glyphs = {}
    ascent = descent = None
    enc = None
    bbx = None
    rows = None
    with open(path, encoding="latin-1") as f:
        for line in f:
            p = line.split()
            if not p:
                continue
            if p[0] == "FONT_ASCENT":
                ascent = int(p[1])
            elif p[0] == "FONT_DESCENT":
                descent = int(p[1])
            elif p[0] == "ENCODING":
                enc = int(p[1])
            elif p[0] == "BBX":
                bbx = tuple(int(v) for v in p[1:5])
            elif p[0] == "BITMAP":
                rows = []
            elif p[0] == "ENDCHAR":
                glyphs[enc] = (bbx, rows)
                rows = None
            elif rows is not None:
                rows.append((int(p[0], 16), len(p[0]) * 4))
    return glyphs, ascent, descent


def cell(glyph, w, h, ascent):
    out = [0] * h
    if glyph is None:
        return out
    (bw, bh, xo, yo), rows = glyph
    top = ascent - (yo + bh)
    for r, (bits, nbits) in enumerate(rows):
        y = top + r
        if y < 0 or y >= h:
            continue
        for c in range(bw):
            if bits >> (nbits - 1 - c) & 1:
                x = xo + c
                if 0 <= x < w:
                    out[y] |= 1 << (w - 1 - x)
    return out


def main():
    d = sys.argv[1]
    print("//! GD's built-in fonts (generated by tools/gen_gd_fonts.py from the")
    print("//! public-domain X11 misc-fixed fonts and the Sony 8x16 font; do not edit).")
    print("//! Each glyph is `height` rows, the leftmost pixel in the highest bit")
    print("//! of the `width`-bit row value; 256 glyphs in ISO-8859-2 order.")
    print()
    for name, fn, w, h in FONTS:
        glyphs, ascent, descent = parse_bdf(os.path.join(d, fn))
        # Fonts whose ascent+descent is short of the cell are centred.
        extra = h - (ascent + descent)
        asc = ascent + (extra + 1) // 2 if extra > 0 else ascent
        data = []
        for b in range(256):
            u = latin2_to_unicode(b)
            printable = b >= 0x20 and not (0x7f <= b < 0xa0)
            g = glyphs.get(u) if u is not None and printable else None
            ov = OVERRIDES.get(name, {}).get(chr(b))
            data.extend(ov if ov else cell(g, w, h, asc))
        print(f"pub const {name}_W: usize = {w};")
        print(f"pub const {name}_H: usize = {h};")
        print(f"pub static {name}: [u16; {len(data)}] = [")
        for i in range(0, len(data), 16):
            print("    " + ", ".join(f"0x{v:x}" for v in data[i:i + 16]) + ",")
        print("];")
        print()


main()
