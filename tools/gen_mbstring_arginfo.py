#!/usr/bin/env python3
"""Generate parameter names/types for mbstring functions from php-src's
ext/mbstring/mbstring.stub.php.

Usage: tools/gen_mbstring_arginfo.py /path/to/php-src
Writes crates/goro-ext-mbstring/src/arginfo.rs
"""
import os
import re
import sys

php = sys.argv[1] if len(sys.argv) > 1 else "/home/magicaltux/php-src"
stub = open(os.path.join(php, "ext/mbstring/mbstring.stub.php")).read()
here = os.path.dirname(os.path.abspath(__file__))
out_path = os.path.join(here, "..", "crates/goro-ext-mbstring/src/arginfo.rs")


def rust_type(t):
    t = t.strip()
    if not t:
        return "None"
    if t.startswith("?"):
        return "Some(ParamType::Nullable(Box::new(ParamType::Simple(b\"%s\".to_vec()))))" % t[1:]
    parts = t.split("|")
    if len(parts) == 1:
        return "Some(ParamType::Simple(b\"%s\".to_vec()))" % t
    return "Some(ParamType::Union(vec![%s]))" % ", ".join("ParamType::Simple(b\"%s\".to_vec())" % p for p in parts)


lines = []
for m in re.finditer(r"^function (\w+)\((.*?)\)\s*:", stub, flags=re.M):
    name, params = m.group(1), m.group(2)
    names = []
    types = []
    for p in [p.strip() for p in params.split(",") if p.strip()]:
        p = p.split("=")[0].strip()
        pm = re.match(r"^([\w|?]+\s+)?(&)?(\.\.\.)?\$(\w+)$", p)
        if not pm:
            raise SystemExit("cannot parse param %r of %s" % (p, name))
        ty = (pm.group(1) or "").strip()
        names.append(pm.group(4))
        types.append("None" if pm.group(2) else rust_type(ty))
    lines.append("    vm.builtin_param_names.insert(b\"%s\".to_vec(), vec![%s]);" % (name, ", ".join("b\"%s\".to_vec()" % n for n in names)))
    lines.append("    vm.register_builtin_param_types(b\"%s\", vec![%s]);" % (name, ", ".join(types)))

with open(out_path, "w") as f:
    f.write("// Generated by tools/gen_mbstring_arginfo.py from php-src ext/mbstring/mbstring.stub.php; do not edit.\n")
    f.write("#![cfg_attr(rustfmt, rustfmt_skip)]\n")
    f.write("use goro_core::opcode::ParamType;\nuse goro_core::vm::Vm;\n\n")
    f.write("pub fn register(vm: &mut Vm) {\n")
    f.write("\n".join(lines))
    f.write("\n}\n")
