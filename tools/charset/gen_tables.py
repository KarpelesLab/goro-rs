#!/usr/bin/env python3
"""Generate goro-charset's character set tables from public mapping data.

Usage: python3 -I tools/charset/gen_tables.py DATA_DIR OUT_DIR

DATA_DIR holds the downloaded public data files:
  uc/       unicode.org/Public/MAPPINGS files (ISO8859/*, VENDORS/MICSFT/*,
            VENDORS/MISC/KOI8-R.TXT, VENDORS/APPLE/JAPANESE.TXT,
            OBSOLETE/EASTASIA/{JIS,KSC,OTHER}/*)
  whatwg/   encoding.spec.whatwg.org index-*.txt files
  ucd/      unicode.org/Public/17.0.0/ucd files (EmojiSources.txt, ...)
  x0213/    x0213.org/codetable/jisx0213-2004-std.txt (the JIS X 0213:2004
            mapping table published by Project X0213)

OUT_DIR is crates/goro-charset/src/tables. Every deviation from the public
tables is listed in this script with the observation that justifies it.
"""

import os
import re
import sys

DATA = sys.argv[1]
OUT = sys.argv[2]

HEADER = "// Generated by tools/charset/gen_tables.py from public mapping data. Do not edit.\n\n"


def read_pairs(path, cols=(0, 1)):
    """Read a unicode.org style mapping file: hex columns, '#' comments."""
    pairs = []
    with open(path, encoding="latin-1") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            try:
                vals = [int(parts[c], 16) for c in cols]
            except (IndexError, ValueError):
                continue
            pairs.append(tuple(vals))
    return pairs


def read_whatwg(path):
    """Read a WHATWG index file: pointer, code point."""
    m = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            p, cp = line.split()[:2]
            m[int(p)] = int(cp, 16)
    return m


def uc(name):
    return os.path.join(DATA, "uc", name)


def fmt_array(name, ty, values, per_line=16, vis="pub(crate)"):
    out = ["%s static %s: [%s; %d] = [\n" % (vis, name, ty, len(values))]
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join("0x%X" % v for v in values[i:i + per_line]) + ",\n")
    out.append("];\n\n")
    return "".join(out)


def write(fname, body):
    with open(os.path.join(OUT, fname), "w") as f:
        f.write(HEADER + body)


# ---------------------------------------------------------------------------
# Paged reverse tables: code point -> code (u16), 0 = unmapped.
# A first-level index over 256-code-point pages points into a data array of
# 256-entry pages; page 0 of the data is all zeros (unmapped).


def emit_rev(name, mapping, maxcp=0x10FFFF):
    pages = {}
    for cp, code in mapping.items():
        assert 0 < code <= 0xFFFF, (name, hex(cp), hex(code))
        pages.setdefault(cp >> 8, [0] * 256)[cp & 0xFF] = code
    npages = (maxcp >> 8) + 1
    idx = [0] * npages
    data = [0] * 256
    seen = {}
    for p in sorted(pages):
        key = tuple(pages[p])
        if key not in seen:
            seen[key] = len(data) // 256
            data.extend(pages[p])
        idx[p] = seen[key]
    s = fmt_array(name + "_IDX", "u8" if len(data) // 256 < 256 else "u16", idx, 32)
    s += fmt_array(name + "_DATA", "u16", data)
    return s


def emit_fwd(name, mapping, size):
    vals = [0] * size
    for k, v in mapping.items():
        assert 0 <= k < size
        assert v <= 0xFFFF
        vals[k] = v
    return fmt_array(name, "u16", vals)


def emit_fwd32(name, mapping, size):
    vals = [0] * size
    for k, v in mapping.items():
        vals[k] = v
    return fmt_array(name, "u32", vals)


# ---------------------------------------------------------------------------
# Single-byte encodings: the upper half 0x80..0xFF (0xFFFF = unmapped); the
# lower half is ASCII for all of them.

# ArmSCII-8 (Armenian standard ARMSCII-8, 1997): 0x80..0x9F are C1 controls,
# 0xA1 and 0xFF are unassigned; 0xB2..0xFD alternate capital/small letters.
ARMSCII8 = {0xA0: 0x00A0, 0xA2: 0x0587, 0xA3: 0x0589, 0xA4: 0x0029, 0xA5: 0x0028,
            0xA6: 0x00BB, 0xA7: 0x00AB, 0xA8: 0x2014, 0xA9: 0x002E, 0xAA: 0x055D,
            0xAB: 0x002C, 0xAC: 0x002D, 0xAD: 0x058A, 0xAE: 0x2026, 0xAF: 0x055C,
            0xB0: 0x055B, 0xB1: 0x055E, 0xFE: 0x055A}
for _i in range(38):
    ARMSCII8[0xB2 + 2 * _i] = 0x0531 + _i
    ARMSCII8[0xB3 + 2 * _i] = 0x0561 + _i
for _b in range(0x80, 0xA0):
    ARMSCII8[_b] = _b

SINGLE = [
    # (Rust name, source)
    ("ISO8859_2", "8859-2.TXT"), ("ISO8859_3", "8859-3.TXT"), ("ISO8859_4", "8859-4.TXT"),
    ("ISO8859_5", "8859-5.TXT"), ("ISO8859_6", "8859-6.TXT"), ("ISO8859_7", "8859-7.TXT"),
    ("ISO8859_8", "8859-8.TXT"), ("ISO8859_9", "8859-9.TXT"), ("ISO8859_10", "8859-10.TXT"),
    ("ISO8859_13", "8859-13.TXT"), ("ISO8859_14", "8859-14.TXT"), ("ISO8859_15", "8859-15.TXT"),
    ("ISO8859_16", "8859-16.TXT"), ("CP1251", "CP1251.TXT"), ("CP1252", "CP1252.TXT"),
    ("CP1254", "CP1254.TXT"), ("CP866", "CP866.TXT"), ("CP850", "CP850.TXT"),
    ("KOI8R", "KOI8-R.TXT"), ("KOI8U", None), ("ARMSCII8", None),
]


def koi8u():
    # KOI8-U (RFC 2319): KOI8-R with eight letters replaced.
    m = dict(read_pairs(uc("KOI8-R.TXT")))
    m.update({0xA4: 0x0454, 0xA6: 0x0456, 0xA7: 0x0457, 0xAD: 0x0491,
              0xB4: 0x0404, 0xB6: 0x0406, 0xB7: 0x0407, 0xBD: 0x0490})
    return m


def gen_single():
    body = ""
    for name, src in SINGLE:
        if name == "KOI8U":
            m = koi8u()
        elif name == "ARMSCII8":
            m = ARMSCII8
        elif name == "CP1252":
            # mbstring's Windows-1252 maps 0x81, 0x8D, 0x8F, 0x90 and 0x9D to
            # the C1 controls (observed on PHP 8.5), as the WHATWG index does.
            m = {0x80 + p: cp for p, cp in read_whatwg(os.path.join(DATA, "whatwg", "index-windows-1252.txt")).items()}
        else:
            m = dict(read_pairs(uc(src)))
        for b in range(0x80):
            assert m.get(b, b) == b, (name, b)
        hi = [m.get(b, 0xFFFF) for b in range(0x80, 0x100)]
        body += fmt_array(name, "u16", hi)
    write("single.rs", body)


def main():
    os.makedirs(OUT, exist_ok=True)
    gen_single()


if __name__ == "__main__":
    main()
