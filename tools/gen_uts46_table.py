#!/usr/bin/env python3
"""Generates crates/goro-ext-uri/src/whatwg/idna_table.rs from the Unicode
IDNA mapping table (UTS #46, IdnaMappingTable.txt, published by Unicode,
Inc. at https://www.unicode.org/Public/idna/<version>/).

PHP 8.5's WHATWG URL parser maps domains with the Unicode 16.0 table
(observed on PHP 8.5: every code point gives the result this table
predicts), so goro uses that version.

Usage: gen_uts46_table.py IdnaMappingTable.txt 16.0.0 > idna_table.rs

Statuses are folded for the non-STD3, nontransitional processing the URL
Standard uses: valid, deviation and disallowed_STD3_valid are "valid";
mapped and disallowed_STD3_mapped are "mapped".
"""
import hashlib
import sys

VALID, MAPPED, IGNORED, DISALLOWED = 0, 1, 2, 3

def main():
    path = sys.argv[1]
    raw = open(path, 'rb').read()
    sha = hashlib.sha256(raw).hexdigest()
    version = "Unicode " + sys.argv[2]
    entries = []  # (start, end, status, mapping str or None)
    for line in raw.decode('utf-8').splitlines():
        body = line.split('#', 1)[0].strip()
        if not body:
            continue
        f = [x.strip() for x in body.split(';')]
        if '..' in f[0]:
            a, b = (int(x, 16) for x in f[0].split('..'))
        else:
            a = b = int(f[0], 16)
        st = f[1]
        mp = None
        if st in ('valid', 'deviation', 'disallowed_STD3_valid'):
            s = VALID
        elif st in ('mapped', 'disallowed_STD3_mapped'):
            s = MAPPED
            mp = ''.join(chr(int(x, 16)) for x in f[2].split()) if len(f) > 2 and f[2] else ''
        elif st == 'ignored':
            s = IGNORED
        else:
            s = DISALLOWED
        entries.append([a, b, s, mp])
    entries.sort()
    # Fill gaps (should not exist) as disallowed, merge equal neighbours.
    merged = []
    nxt = 0
    for a, b, s, mp in entries:
        if a > nxt:
            merged.append([nxt, a - 1, DISALLOWED, None])
        if merged and merged[-1][2] == s and merged[-1][3] == mp and merged[-1][1] + 1 == a:
            merged[-1][1] = b
        else:
            merged.append([a, b, s, mp])
        nxt = b + 1
    if nxt <= 0x10FFFF:
        merged.append([nxt, 0x10FFFF, DISALLOWED, None])
    pool = bytearray()
    index = {}
    rows = []
    for a, b, s, mp in merged:
        off = ln = 0
        if s == MAPPED:
            enc = mp.encode('utf-8')
            if enc not in index:
                index[enc] = len(pool)
                pool += enc
            off, ln = index[enc], len(enc)
            assert ln < 256 and off < (1 << 22)
        rows.append((a, s << 30 | off << 8 | ln))
    out = sys.stdout
    out.write('//! UTS #46 IDNA mapping table, generated by tools/gen_uts46_table.py from\n')
    out.write(f'//! the Unicode IdnaMappingTable.txt ({version}; sha256 {sha}).\n')
    out.write('//! Unicode data: Copyright (c) Unicode, Inc., https://www.unicode.org/terms_of_use.html\n')
    out.write('//! Do not edit.\n\n')
    out.write('/// Range starts with packed entries: status << 30 | mapping offset << 8 | mapping length.\n')
    out.write(f'pub(super) static RANGES: [(u32, u32); {len(rows)}] = [\n')
    for a, v in rows:
        out.write(f'    (0x{a:x}, 0x{v:x}),\n')
    out.write('];\n\n')
    out.write('/// UTF-8 mapping targets.\n')
    out.write('pub(super) static MAPPINGS: &[u8] = b"')
    for c in pool:
        if 0x20 <= c < 0x7f and c not in (0x22, 0x5c):
            out.write(chr(c))
        else:
            out.write('\\x%02x' % c)
    out.write('";\n')

main()
