#!/usr/bin/env python3
"""Generate crates/goro-ext-standard/src/html/tables.rs.

Sources (public standards, downloaded into one directory passed as argv[1]):
  entities.json   https://html.spec.whatwg.org/entities.json (HTML5 named character references)
  HTMLlat1.ent, HTMLsymbol.ent, HTMLspecial.ent
                  https://www.w3.org/TR/html401/ (HTML 4.01 character entity sets)
  8859-1.TXT 8859-5.TXT 8859-15.TXT   https://unicode.org/Public/MAPPINGS/ISO8859/
  CP866.TXT       https://unicode.org/Public/MAPPINGS/VENDORS/MICSFT/PC/
  CP1251.TXT CP1252.TXT  https://unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WINDOWS/
  KOI8-R.TXT      https://unicode.org/Public/MAPPINGS/VENDORS/MISC/
  ROMAN.TXT       https://unicode.org/Public/MAPPINGS/VENDORS/APPLE/
plus tools/html5_encode_names.txt (which of several HTML5 names PHP 8.5 uses
when encoding, observed on PHP 8.5).

Usage: tools/gen_html_tables.py DOWNLOAD_DIR > crates/goro-ext-standard/src/html/tables.rs
"""
import json
import os
import re
import sys

src = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))


def read(name):
    with open(os.path.join(src, name), encoding='latin-1') as f:
        return f.read()


# HTML5 named references: only the names terminated by ';' (PHP requires the
# semicolon when decoding).
ents = json.loads(read('entities.json'))
h5 = []
for k, v in ents.items():
    if not k.endswith(';'):
        continue
    cps = v['codepoints']
    assert 1 <= len(cps) <= 2
    h5.append((k[1:-1], cps[0], cps[1] if len(cps) > 1 else 0))
h5.sort(key=lambda e: e[0].encode())

by_cps = {}
for n, a, b in h5:
    by_cps.setdefault((a, b), []).append(n)
chosen = {}
with open(os.path.join(here, 'html5_encode_names.txt')) as f:
    for line in f:
        if line.startswith('#') or not line.strip():
            continue
        *cps, name = line.split()
        cps = [int(c, 16) for c in cps]
        key = (cps[0], cps[1] if len(cps) > 1 else 0)
        assert name in by_cps[key], (key, name)
        chosen[key] = name
h5enc = []
for key, names in by_cps.items():
    if len(names) == 1:
        h5enc.append((key, names[0]))
    else:
        h5enc.append((key, chosen[key]))
h5enc.sort()

# HTML 4.01 entity sets, in DTD order.
h4 = []
for f in ('HTMLlat1.ent', 'HTMLsymbol.ent', 'HTMLspecial.ent'):
    for m in re.finditer(r'<!ENTITY\s+(\w+)\s+CDATA\s+"&#(\d+);"', read(f)):
        h4.append((m.group(1), int(m.group(2))))
assert len(h4) == 252, len(h4)


def mapping(name):
    t = [0xFFFF] * 256
    for line in read(name).splitlines():
        line = line.split('#', 1)[0].split()
        if len(line) >= 2 and line[0].startswith('0x') and line[1].startswith('0x'):
            t[int(line[0], 16)] = int(line[1], 16)
    return t


charsets = [
    ('ISO_8859_1', '8859-1.TXT'), ('ISO_8859_5', '8859-5.TXT'), ('ISO_8859_15', '8859-15.TXT'),
    ('CP866', 'CP866.TXT'), ('CP1251', 'CP1251.TXT'), ('CP1252', 'CP1252.TXT'),
    ('KOI8_R', 'KOI8-R.TXT'), ('MAC_ROMAN', 'ROMAN.TXT'),
]

o = []
o.append('// @generated by tools/gen_html_tables.py from the WHATWG entities.json, the')
o.append('// HTML 4.01 entity sets and the unicode.org charset mappings. Do not edit.')
o.append('')
o.append('/// HTML5 named character references ending in `;` (name without `&`/`;`,')
o.append('/// first code point, second code point or 0), sorted by name bytes.')
o.append('pub static HTML5_NAMES: &[(&str, u32, u32)] = &[')
for n, a, b in h5:
    o.append('    ("%s", 0x%X, 0x%X),' % (n, a, b))
o.append('];')
o.append('')
o.append('/// Name used when encoding to HTML5, sorted by code points (observed on PHP 8.5')
o.append('/// for code points with several names; see tools/html5_encode_names.txt).')
o.append('pub static HTML5_ENCODE: &[(u32, u32, &str)] = &[')
for (a, b), n in h5enc:
    o.append('    (0x%X, 0x%X, "%s"),' % (a, b, n))
o.append('];')
o.append('')
o.append('/// HTML 4.01 character entities (HTMLlat1, HTMLsymbol, HTMLspecial), in DTD order.')
o.append('pub static HTML401: &[(&str, u32)] = &[')
for n, c in h4:
    o.append('    ("%s", 0x%X),' % (n, c))
o.append('];')
for rust, f in charsets:
    t = mapping(f)
    for i in range(0x80):
        if t[i] == 0xFFFF and (i < 0x20 or i == 0x7F):
            t[i] = i  # ROMAN.TXT omits the controls
        assert t[i] == i, (f, i)
    o.append('')
    o.append('/// Bytes 0x80..=0xFF of %s to Unicode (0xFFFF: unmapped), from unicode.org %s.' % (rust, f))
    o.append('pub static %s: [u16; 128] = [' % rust)
    for i in range(0x80, 0x100, 8):
        o.append('    ' + ' '.join('0x%04X,' % t[j] for j in range(i, i + 8)))
    o.append('];')
print('\n'.join(o))
