#!/usr/bin/env python3
"""Generate the Rust data tables of the Oniguruma port
(crates/goro-ext-mbstring/src/oniguruma/{unicode_data.rs,enc_tables.rs})
from the Oniguruma 6.9.10 C sources.

usage: python3 -I tools/gen_onig_unicode.py <onig-src-dir> <out-dir>
"""

import re
import sys

SRC = sys.argv[1]
OUT = sys.argv[2]


def read(name):
    with open(f"{SRC}/{name}", encoding="utf-8") as f:
        return f.read()


def strip_comments(s):
    return re.sub(r"/\*.*?\*/", "", s, flags=re.S)


def ints(body):
    body = re.sub(r"^\s*#.*$", "", body, flags=re.M)
    return [int(x, 0) for x in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body)]


def c_array(src, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit(f"array {name} not found")
    return m.group(1)


def fmt_list(vals, per=12, hexa=True):
    out = []
    for i in range(0, len(vals), per):
        chunk = vals[i:i + per]
        out.append("    " + " ".join((f"0x{v:x}," if hexa else f"{v},") for v in chunk))
    return "\n".join(out)


HEADER = "// Generated by tools/gen_onig_unicode.py from Oniguruma 6.9.10 (BSD-2-Clause,\n" \
         "// Copyright (c) 2002-2024 K.Kosako). Do not edit.\n\n"

# ---------------------------------------------------------------- unicode
prop = strip_comments(read("unicode_property_data.c"))

# CR tables
cr = {}
for m in re.finditer(r"static const OnigCodePoint\s+(CR_\w+)\[\]\s*=\s*\{(.*?)\};", prop, re.S):
    cr[m.group(1)] = ints(m.group(2))
alias = {}
for m in re.finditer(r"#define\s+(CR_\w+)\s+(CR_\w+)", prop):
    alias[m.group(1)] = m.group(2)


def resolve(n):
    while n in alias:
        n = alias[n]
    return n


cr_list = re.findall(r"CR_\w+", c_array(prop, "CodeRanges"))
code_ranges_num = int(re.search(r"#define CODE_RANGES_NUM\s+(\d+)", prop).group(1))
assert len(cr_list) == code_ranges_num, (len(cr_list), code_ranges_num)
prop_name_max = int(re.search(r"#define PROPERTY_NAME_MAX_SIZE\s+(\d+)", prop).group(1))
extpict = int(re.search(r"#define PROP_INDEX_EXTENDEDPICTOGRAPHIC\s+(\d+)", prop).group(1))

# property names: pool strN -> string, wordlist pool_offset(N) -> ctype
pool = {}
for m in re.finditer(r"char unicode_prop_name_pool_str(\d+)\[sizeof\(\"([^\"]*)\"\)\];", prop):
    pool[int(m.group(1))] = m.group(2)
names = {}
for m in re.finditer(r"\{pool_offset\((\d+)\),\s*(\d+)\}", prop):
    s = pool[int(m.group(1))]
    assert s not in names
    names[s] = int(m.group(2))

# folds
fold = strip_comments(read("unicode_fold_data.c"))
f1 = ints(c_array(fold, "OnigUnicodeFolds1"))
f2 = ints(c_array(fold, "OnigUnicodeFolds2"))
f3 = ints(c_array(fold, "OnigUnicodeFolds3"))
fdefs = {k: int(v) for k, v in re.findall(r"#define (FOLDS\d_(?:NORMAL_)?END_INDEX)\s+(\d+)", read("unicode_fold_data.c"))}


def key_indices(fname):
    s = strip_comments(read(fname))
    return [v for v in ints(c_array(s, "wordlist")) if v >= 0]


k1 = key_indices("unicode_fold1_key.c")
k2 = key_indices("unicode_fold2_key.c")
k3 = key_indices("unicode_fold3_key.c")
uk = strip_comments(read("unicode_unfold_key.c"))
unfold = []
for m in re.finditer(r"\{(0x[0-9a-fA-F]+),\s*(-?\d+),\s*(\d+)\}", c_array(uk, "wordlist")):
    code, idx, fl = int(m.group(1), 16), int(m.group(2)), int(m.group(3))
    if idx >= 0:
        unfold.append((code, idx, fl))
unfold.sort()


def range_types(fname, prefix):
    s = strip_comments(read(fname))
    out = []
    for m in re.finditer(r"\{(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*" + prefix + r"(\w+)\s*\}", s):
        out.append((int(m.group(1), 16), int(m.group(2), 16), m.group(3)))
    return out


egcb = range_types("unicode_egcb_data.c", "EGCB_")
wb = range_types("unicode_wb_data.c", "WB_")
EGCB = {"Other": 0, "CR": 1, "LF": 2, "Control": 3, "Extend": 4, "Prepend": 5,
        "Regional_Indicator": 6, "SpacingMark": 7, "ZWJ": 8, "L": 13, "LV": 14,
        "LVT": 15, "T": 16, "V": 17}
WB = ["Any", "ALetter", "CR", "Double_Quote", "Extend", "ExtendNumLet", "Format",
      "Hebrew_Letter", "Katakana", "LF", "MidLetter", "MidNum", "MidNumLet",
      "Newline", "Numeric", "Regional_Indicator", "Single_Quote", "WSegSpace", "ZWJ"]

uni = strip_comments(read("unicode.c"))
uni_ctype = ints(c_array(uni, "EncUNICODE_ISO_8859_1_CtypeTable"))

o = [HEADER, "#![allow(clippy::unreadable_literal)]\n\n"]
o.append(f"pub const CODE_RANGES_NUM: usize = {code_ranges_num};\n")
o.append(f"pub const PROPERTY_NAME_MAX_SIZE: usize = {prop_name_max};\n")
o.append(f"pub const PROP_INDEX_EXTENDEDPICTOGRAPHIC: u32 = {extpict};\n\n")
emitted = set()
for n in cr_list:
    r = resolve(n)
    if r in emitted:
        continue
    emitted.add(r)
    v = cr[r]
    assert v[0] * 2 + 1 == len(v), r
    o.append(f"static {r.upper()}: [u32; {len(v)}] = [\n{fmt_list(v)}\n];\n")
o.append(f"\npub static CODE_RANGES: [&[u32]; {code_ranges_num}] = [\n")
for n in cr_list:
    o.append(f"    &{resolve(n).upper()},\n")
o.append("];\n\n")
items = sorted(names.items())
o.append(f"/// (lowercased name without ' ', '-', '_', ctype), sorted\npub static PROPERTY_NAMES: [(&str, u16); {len(items)}] = [\n")
for s, c in items:
    o.append(f"    (\"{s}\", {c}),\n")
o.append("];\n\n")
o.append("pub static ISO_8859_1_CTYPE: [u16; 256] = [\n" + fmt_list(uni_ctype, 8) + "\n];\n\n")
for k in ("FOLDS1_NORMAL_END_INDEX", "FOLDS1_END_INDEX", "FOLDS2_NORMAL_END_INDEX",
          "FOLDS2_END_INDEX", "FOLDS3_NORMAL_END_INDEX", "FOLDS3_END_INDEX"):
    o.append(f"pub const {k}: usize = {fdefs[k]};\n")
for nm, v in (("FOLDS1", f1), ("FOLDS2", f2), ("FOLDS3", f3)):
    o.append(f"\npub static {nm}: [u32; {len(v)}] = [\n{fmt_list(v)}\n];\n")
for nm, v in (("FOLD1_KEY_INDEXES", k1), ("FOLD2_KEY_INDEXES", k2), ("FOLD3_KEY_INDEXES", k3)):
    o.append(f"\npub static {nm}: [u16; {len(v)}] = [\n{fmt_list(v, 16, False)}\n];\n")
o.append(f"\n/// (code, index, fold_len) sorted by code\npub static UNFOLD_KEYS: [(u32, u16, u8); {len(unfold)}] = [\n")
for c, i, fl in unfold:
    o.append(f"    (0x{c:x}, {i}, {fl}),\n")
o.append("];\n")
o.append(f"\n/// (start, end, EGCB type)\npub static EGCB_RANGES: [(u32, u32, u8); {len(egcb)}] = [\n")
for a, b, t in egcb:
    o.append(f"    (0x{a:x}, 0x{b:x}, {EGCB[t]}),\n")
o.append("];\n")
o.append(f"\n/// (start, end, WB type)\npub static WB_RANGES: [(u32, u32, u8); {len(wb)}] = [\n")
for a, b, t in wb:
    o.append(f"    (0x{a:x}, 0x{b:x}, {WB.index(t)}),\n")
o.append("];\n")
with open(f"{OUT}/unicode_data.rs", "w", encoding="utf-8") as f:
    f.write("".join(o))

# ---------------------------------------------------------------- encodings
o = [HEADER, "#![allow(clippy::unreadable_literal)]\n\n"]
regenc = strip_comments(read("regenc.c"))
o.append("pub static ASCII_CTYPE: [u16; 256] = [\n" + fmt_list(ints(c_array(regenc, "OnigEncAsciiCtypeTable")), 8) + "\n];\n\n")


def octal_table(src, name):
    body = c_array(src, name)
    vals = [int(x, 8) for x in re.findall(r"'\\(\d{3})'", body)]
    assert len(vals) == 256, name
    return vals


o.append("pub static ASCII_LOWER: [u8; 256] = [\n" + fmt_list(octal_table(regenc, "OnigEncAsciiToLowerCaseTable"), 16) + "\n];\n\n")
o.append("pub static ISO_8859_1_LOWER: [u8; 256] = [\n" + fmt_list(octal_table(regenc, "OnigEncISO_8859_1_ToLowerCaseTable"), 16) + "\n];\n\n")

sb = [("iso8859_1", "ISO_8859_1"), ("iso8859_2", "ISO_8859_2"), ("iso8859_3", "ISO_8859_3"),
      ("iso8859_4", "ISO_8859_4"), ("iso8859_5", "ISO_8859_5"), ("iso8859_6", "ISO_8859_6"),
      ("iso8859_7", "ISO_8859_7"), ("iso8859_8", "ISO_8859_8"), ("iso8859_9", "ISO_8859_9"),
      ("iso8859_10", "ISO_8859_10"), ("iso8859_11", "ISO_8859_11"), ("iso8859_13", "ISO_8859_13"),
      ("iso8859_14", "ISO_8859_14"), ("iso8859_15", "ISO_8859_15"), ("iso8859_16", "ISO_8859_16"),
      ("koi8", "KOI8"), ("koi8_r", "KOI8_R")]
o.append("/// A single byte encoding's tables: ctype bits, lower case table (None: ascii\n"
         "/// only folding), case fold pairs, ess-tsett flag, 0xdf -> \"ss\" in mbc_case_fold\n")
o.append("pub struct SingleByteTables {\n    pub ctype: &'static [u16; 256],\n"
         "    pub lower: Option<&'static [u8; 256]>,\n    pub map: &'static [(u8, u8)],\n"
         "    pub ess_tsett: bool,\n    pub df_ss: bool,\n}\n\n")
for fn, nm in sb:
    s = strip_comments(read(fn + ".c"))
    raw = read(fn + ".c")
    ctype = ints(c_array(s, f"Enc{nm}_CtypeTable"))
    assert len(ctype) == 256
    o.append(f"static {nm}_CTYPE: [u16; 256] = [\n{fmt_list(ctype, 8)}\n];\n")
    lower = None
    if f"Enc{nm}_ToLowerCaseTable" in s:
        lower = f"Some(&{nm}_LOWER)"
        o.append(f"static {nm}_LOWER: [u8; 256] = [\n{fmt_list(octal_table(s, f'Enc{nm}_ToLowerCaseTable'), 16)}\n];\n")
    elif fn == "iso8859_1":
        lower = "Some(&ISO_8859_1_LOWER)"
    else:
        lower = "None"
    pairs = []
    ess = False
    if "CaseFoldMap[]" in s:
        pairs = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+)\s*\}", c_array(s, "CaseFoldMap"))]
        m = re.search(r"CaseFoldMap,\s*([01]),", s)
        ess = m.group(1) == "1"
    df = "0xdf && (flag & INTERNAL_ONIGENC_CASE_FOLD_MULTI_CHAR)" in raw
    o.append(f"static {nm}_MAP: [(u8, u8); {len(pairs)}] = [\n")
    for a, b in pairs:
        o.append(f"    (0x{a:x}, 0x{b:x}),\n")
    o.append("];\n")
    o.append(f"pub static {nm}: SingleByteTables = SingleByteTables {{\n    ctype: &{nm}_CTYPE,\n"
             f"    lower: {lower},\n    map: &{nm}_MAP,\n    ess_tsett: {str(ess).lower()},\n"
             f"    df_ss: {str(df).lower()},\n}};\n\n")

for fn, arr, nm in (("euc_jp", "EncLen_EUCJP", "ENCLEN_EUCJP"), ("sjis", "EncLen_SJIS", "ENCLEN_SJIS"),
                    ("sjis", "SJIS_CAN_BE_TRAIL_TABLE", "SJIS_CAN_BE_TRAIL"),
                    ("big5", "EncLen_BIG5", "ENCLEN_BIG5"), ("big5", "BIG5_CAN_BE_TRAIL_TABLE", "BIG5_CAN_BE_TRAIL"),
                    ("euc_tw", "EncLen_EUCTW", "ENCLEN_EUCTW"), ("euc_kr", "EncLen_EUCKR", "ENCLEN_EUCKR"),
                    ("utf8", "EncLen_UTF8", "ENCLEN_UTF8"), ("utf16_be", "EncLen_UTF16", "ENCLEN_UTF16")):
    s = strip_comments(read(fn + ".c"))
    if fn == "utf8":
        s = s.replace("#ifdef USE_RFC3629_RANGE", "").split("#else")[0] + "};"
    v = ints(c_array(s, arr))
    assert len(v) == 256, (fn, arr, len(v))
    o.append(f"pub static {nm}: [u8; 256] = [\n{fmt_list(v, 16, False)}\n];\n\n")
with open(f"{OUT}/enc_tables.rs", "w", encoding="utf-8") as f:
    f.write("".join(o))
