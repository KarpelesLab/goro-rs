#!/usr/bin/env python3
"""Generate crates/goro-ext-intl/src/rbnf_ordinal.rs: CLDR's %digits-ordinal
rule sets (NumberFormatter::ORDINAL) per locale, with the rule sets they
refer to, in ICU's rule text syntax for rbnf.rs.

usage: gen_rbnf_ordinal.py [/usr/share/unicode/cldr/common/rbnf] > crates/goro-ext-intl/src/rbnf_ordinal.rs
"""
import glob
import html
import os
import re
import sys

D = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unicode/cldr/common/rbnf"


def rulesets(xml):
    out = {}
    group = re.search(r'<rulesetGrouping type="OrdinalRules">(.*?)</rulesetGrouping>', xml, re.S)
    if not group:
        return out
    for m in re.finditer(r'<ruleset type="([^"]+)"[^>]*>(.*?)</ruleset>', group.group(1), re.S):
        rules = re.findall(r'<rbnfrule value="([^"]*)"(?: radix="(\d+)")?[^>]*>(.*?)</rbnfrule>', m.group(2), re.S)
        out[m.group(1)] = [(v, r, html.unescape(t)) for v, r, t in rules]
    return out


def refs(text):
    return re.findall(r'%%?([A-Za-z0-9-]+)', text)


def ruleset_text(name, rules, private):
    parts = []
    for v, radix, t in rules:
        t = t.strip()
        if t.endswith(";"):
            t = t[:-1]
        key = v + ("/" + radix if radix else "")
        parts.append("%s: %s" % (key, t))
    return "%s%s: %s;" % ("%%" if private else "%", name, "; ".join(parts))


entries = []
for f in sorted(glob.glob(os.path.join(D, "*.xml"))):
    loc = os.path.basename(f)[:-4]
    xml = open(f, encoding="utf-8").read()
    sets = rulesets(xml)
    if "digits-ordinal" not in sets:
        continue
    private = set(re.findall(r'<ruleset type="([^"]+)" access="private"', xml))
    order, todo = [], ["digits-ordinal"]
    while todo:
        n = todo.pop(0)
        if n in order or n not in sets:
            continue
        order.append(n)
        for _, _, t in sets[n]:
            todo.extend(refs(t))
    text = " ".join(ruleset_text(n, sets[n], n in private) for n in order)
    entries.append((loc, text))

print("// Generated by tools/intl/gen_rbnf_ordinal.py from CLDR's common/rbnf: do not edit.")
print("")
print("/// (locale, ICU rule text starting with %digits-ordinal), sorted by locale.")
print("pub static DIGITS_ORDINAL: &[(&str, &str)] = &[")
for loc, text in entries:
    esc = text.replace("\\", "\\\\").replace('"', '\\"')
    print('    ("%s", "%s"),' % (loc, esc))
print("];")
