#!/usr/bin/env python3
"""Generate crates/goro-ext-intl/src/translit_cldr.rs: the rules of CLDR
transforms run on translit_rules.rs (as ICU builds them from the same
files), comments and blank lines dropped, with the IDs ICU registers them
under (the alias attribute; the backward alias for the reverse; source-
target for the internal ones).

usage: gen_translit_cldr.py [/usr/share/unicode/cldr/common/transforms] > crates/goro-ext-intl/src/translit_cldr.rs
"""
import html
import os
import re
import sys

def rs_str(s):
    """A Rust string literal: backslashes, quotes and the characters clippy
    finds invisible escaped."""
    import unicodedata
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif unicodedata.category(c) in ("Cc", "Cf", "Zl", "Zp") or c in "\u00ad\u200b\u2060\ufeff":
            out.append("\\u{%X}" % ord(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


D = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unicode/cldr/common/transforms"
INDIC = ["Devanagari", "Bengali", "Gujarati", "Gurmukhi", "Kannada", "Malayalam", "Oriya", "Tamil", "Telugu"]
FILES = (["Latin-ASCII", "Han-Latin", "Han-Spacedhan", "Arabic-Latin", "Hebrew-Latin", "Thai-Latin", "Thai-ThaiSemi",
          "Thai-ThaiLogical", "ThaiLogical-Latin", "InterIndic-Latin", "Syriac-Latin", "Thaana-Latin", "Myanmar-Latin",
          "Fullwidth-Halfwidth", "Any-Publishing", "de-ASCII", "Cyrillic-Latin", "Greek-Latin", "Georgian-Latin",
          "Hiragana-Latin", "Hiragana-Katakana", "Latin-Katakana", "CanadianAboriginal-Latin", "Latin-Hangul",
          "Latin-ConjoiningJamo", "Latin-Jamo", "Jamo-Latin", "Latin-Bopomofo", "Latin-NumericPinyin",
          "Pinyin-NumericPinyin"]
         + ["%s-InterIndic" % s for s in INDIC] + ["%s-Latin" % s for s in INDIC])


def strip(rules):
    out = []
    for line in rules.split("\n"):
        # drop a trailing comment (a '#' outside quotes and sets)
        q = False
        depth = 0
        cut = len(line)
        i = 0
        while i < len(line):
            c = line[i]
            if c == "\\" and not q:
                i += 2
                continue
            if c == "'":
                q = not q
            elif not q and c == "[":
                depth += 1
            elif not q and c == "]" and depth > 0:
                depth -= 1
            elif not q and depth == 0 and c == "#":
                cut = i
                break
            i += 1
        line = line[:cut].strip()
        if line:
            out.append(line)
    return "\n".join(out) + "\n"


def ids(attr):
    # (the BCP 47 aliases, "und-Latn-t-und-hani", are left out)
    return [a for a in attr.split() if "-t-" not in a and not a.startswith("und-")]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


rows = []
for name in FILES:
    xml = open(os.path.join(D, name + ".xml"), encoding="utf-8").read()
    attrs = dict(re.findall(r'(\w+)="([^"]*)"', re.search(r"<transform ([^>]*)>", xml).group(1)))
    m = re.search(r"<tRule>(.*?)</tRule>", xml, re.S).group(1)
    s = m.strip()
    if s.startswith("<![CDATA["):
        text = s[9:-3]
    else:
        text = html.unescape(m)
    text = strip(text)
    assert '"####' not in text
    fwd = ids(attrs.get("alias", ""))
    back = ids(attrs.get("backwardAlias", ""))
    src, tgt, var = attrs["source"], attrs["target"], attrs.get("variant")
    if not fwd:
        fwd = ["%s-%s%s" % (src, tgt, "/" + var if var else "")]
    both = attrs.get("direction") == "both"
    if both and not back:
        back = ["%s-%s%s" % (tgt, src, "/" + var if var else "")]
    if not both:
        back = []
    rows.append((name, fwd, back, text))

print("// Generated by tools/intl/gen_translit_cldr.py from CLDR's common/transforms: do not edit.")
print("")
print("/// A CLDR transform: the IDs of its forward and reverse directions, and its rules.")
print("pub struct Transform {")
print("    pub forward: &'static [&'static str],")
print("    pub reverse: &'static [&'static str],")
print("    pub rules: &'static str,")
print("}")
for name, fwd, back, text in rows:
    const = re.sub(r"[^A-Za-z0-9]", "_", name).upper()
    print("")
    print("/// %s" % name)
    print("pub static %s: Transform = Transform {" % const)
    print("    forward: &[%s]," % ", ".join(q(x) for x in fwd))
    print("    reverse: &[%s]," % ", ".join(q(x) for x in back))
    print('    rules: %s,' % rs_str(text))
    print("};")
print("")
print("/// Every transform.")
print("pub static TRANSFORMS: &[&Transform] = &[")
for name, _, _, _ in rows:
    print("    &%s," % re.sub(r"[^A-Za-z0-9]", "_", name).upper())
print("];")
