#!/usr/bin/env python3
"""Generate crates/goro-ext-intl/src/translit_cldr.rs: the rules of CLDR
transforms run on translit_rules.rs (as ICU builds them from the same
files), comments and blank lines dropped.

usage: gen_translit_cldr.py [/usr/share/unicode/cldr/common/transforms] > crates/goro-ext-intl/src/translit_cldr.rs
"""
import os
import re
import sys

D = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unicode/cldr/common/transforms"
# (Rust constant, CLDR file)
TRANSFORMS = [("LATIN_ASCII", "Latin-ASCII.xml")]


def strip(rules):
    out = []
    for line in rules.split("\n"):
        # drop a trailing comment (a '#' outside quotes and sets)
        q = False
        depth = 0
        cut = len(line)
        i = 0
        while i < len(line):
            c = line[i]
            if c == "\\" and not q:
                i += 2
                continue
            if c == "'":
                q = not q
            elif not q and c == "[":
                depth += 1
            elif not q and c == "]" and depth > 0:
                depth -= 1
            elif not q and depth == 0 and c == "#":
                cut = i
                break
            i += 1
        line = line[:cut].strip()
        if line:
            out.append(line)
    return "\n".join(out) + "\n"


print("// Generated by tools/intl/gen_translit_cldr.py from CLDR's common/transforms: do not edit.")
for const, f in TRANSFORMS:
    xml = open(os.path.join(D, f), encoding="utf-8").read()
    m = re.search(r"<tRule><!\[CDATA\[(.*?)\]\]></tRule>", xml, re.S)
    text = strip(m.group(1))
    assert '"####' not in text
    print("")
    print("/// %s" % f[:-4])
    print('pub static %s: &str = r####"%s"####;' % (const, text))
