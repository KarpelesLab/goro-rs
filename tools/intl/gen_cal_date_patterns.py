#!/usr/bin/env python3
"""Generate crates/goro-ext-intl/src/datefmt_cal_patterns.rs: CLDR's date
patterns (full, long, medium, short) of the calendars other than the
Gregorian one, per locale that defines them, and root's calendar aliases.

usage: gen_cal_date_patterns.py [/usr/share/unicode/cldr/common/main] > crates/goro-ext-intl/src/datefmt_cal_patterns.rs
"""
import glob
import html
import os
import re
import sys

D = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unicode/cldr/common/main"
STYLES = ["full", "long", "medium", "short"]


def date_formats(cal_xml):
    m = re.search(r"<dateFormats>(.*?)</dateFormats>", cal_xml, re.S)
    if not m:
        return None
    out = {}
    for st, body in re.findall(r'<dateFormatLength type="(\w+)">(.*?)</dateFormatLength>', m.group(1), re.S):
        # the pattern without alt= / numbers= variants
        for attrs, pat in re.findall(r"<pattern([^>]*)>(.*?)</pattern>", body, re.S):
            if "alt=" in attrs:
                continue
            out[st] = html.unescape(pat)
            break
    return out


rows = []
aliases = []
for f in sorted(glob.glob(os.path.join(D, "*.xml"))):
    loc = os.path.basename(f)[:-4]
    xml = open(f, encoding="utf-8").read()
    for cal, body in re.findall(r'<calendar type="([\w-]+)">(.*?)</calendar>', xml, re.S):
        if cal == "gregorian":
            continue
        if loc == "root":
            a = re.search(r"<dateFormats>\s*<alias source=\"locale\" path=\"\.\./\.\./calendar\[@type='([\w-]+)'\]/dateFormats\"/>", body)
            if a:
                aliases.append((cal, a.group(1)))
        df = date_formats(body)
        if not df:
            continue
        pats = [df.get(s) for s in STYLES]
        if None in pats:
            # (a partial set inherits the rest; keep the locale only when complete)
            continue
        rows.append((loc, cal, pats))


def q(s):
    """A Rust string literal: backslashes, quotes and the characters clippy
    finds invisible escaped."""
    import unicodedata
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif unicodedata.category(c) in ("Cc", "Cf", "Zl", "Zp") or c in "\u00ad\u200b\u2060\ufeff":
            out.append("\\u{%X}" % ord(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


print("// Generated by tools/intl/gen_cal_date_patterns.py from CLDR's common/main: do not edit.")
print("")
print("/// (locale, calendar, [full, long, medium, short]) sorted by locale then calendar.")
print("pub static CAL_DATE_PATTERNS: &[(&str, &str, [&str; 4])] = &[")
for loc, cal, pats in sorted(rows):
    print("    (%s, %s, [%s])," % (q(loc), q(cal), ", ".join(q(p) for p in pats)))
print("];")
print("")
print("/// Root's calendar dateFormats aliases (calendar, target).")
print("pub static CAL_ALIASES: &[(&str, &str)] = &[")
for c, t in aliases:
    print("    (%s, %s)," % (q(c), q(t)))
print("];")
