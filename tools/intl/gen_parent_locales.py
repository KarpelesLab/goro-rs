#!/usr/bin/env python3
"""Generate crates/goro-ext-intl/src/parent_locales.rs: CLDR's parentLocales
(the general ones), the parents the truncation fallback does not give.

usage: gen_parent_locales.py [/usr/share/unicode/cldr/common/supplemental/supplementalData.xml] > crates/goro-ext-intl/src/parent_locales.rs
"""
import re
import sys

F = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unicode/cldr/common/supplemental/supplementalData.xml"
xml = open(F, encoding="utf-8").read()
block = re.search(r"<parentLocales>(.*?)</parentLocales>", xml, re.S).group(1)
pairs = []
for parent, locales in re.findall(r'<parentLocale parent="([^"]+)"[^>]*locales="([^"]+)"', block):
    for loc in locales.split():
        pairs.append((loc, parent))
print("// Generated by tools/intl/gen_parent_locales.py from CLDR's supplementalData: do not edit.")
print("")
print("/// (locale, parent), sorted by locale.")
print("pub static PARENT_LOCALES: &[(&str, &str)] = &[")
for loc, parent in sorted(pairs):
    print('    ("%s", "%s"),' % (loc, parent))
print("];")
