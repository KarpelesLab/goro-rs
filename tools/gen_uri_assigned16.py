#!/usr/bin/env python3
"""Generate crates/goro-core/src/uri/assigned16.rs: the code points assigned
in Unicode 16.0, the version of the IDNA data in php-src's bundled lexbor
(ext/lexbor/lexbor/unicode/res.h). ext/uri's IDNA uses the UTS #46 data of
ICU4X (a newer Unicode version) and treats the code points not assigned in
16.0 as disallowed, as lexbor does.

usage: gen_uri_assigned16.py /path/to/DerivedAge.txt > crates/goro-core/src/uri/assigned16.rs
(DerivedAge.txt of Unicode 16.0 or later)
"""
import sys

ranges = []
for line in open(sys.argv[1], encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line:
        continue
    cps, age = [x.strip() for x in line.split(';')]
    major, minor = (int(x) for x in age.split('.'))
    if (major, minor) > (16, 0):
        continue
    if '..' in cps:
        a, b = (int(x, 16) for x in cps.split('..'))
    else:
        a = b = int(cps, 16)
    ranges.append((a, b))
ranges.sort()
merged = []
for a, b in ranges:
    if merged and a <= merged[-1][1] + 1:
        merged[-1] = (merged[-1][0], max(merged[-1][1], b))
    else:
        merged.append((a, b))
print('// @generated by tools/gen_uri_assigned16.py from DerivedAge.txt. Do not edit.')
print('//! The code points assigned in Unicode 16.0 (sorted, inclusive ranges).')
print()
print('pub static ASSIGNED_16: &[(u32, u32)] = &[')
for a, b in merged:
    print('    (0x%04X, 0x%04X),' % (a, b))
print('];')
