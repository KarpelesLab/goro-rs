#!/usr/bin/env python3
"""Collect the #[\\Deprecated] attributes of php-src's *.stub.php files
(functions, methods, global and class constants) and write
crates/goro-core/src/stub_deprecations.rs: what Reflection reports for the
internal declarations (getAttributes(), ReflectionClassConstant::isDeprecated()).

Usage: tools/gen_stub_deprecations.py [php-src]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PHP_SRC = sys.argv[1] if len(sys.argv) > 1 else "/home/magicaltux/php-src"
OUT = os.path.join(HERE, "..", "crates/goro-core/src/stub_deprecations.rs")

ATTR = re.compile(r"#\[\\Deprecated(?:\((.*?)\))?\]\s*$")
ARG = re.compile(r"""(\w+):\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")""")
CLASS = re.compile(r"^\s*(?:(?:abstract|final|readonly)\s+)*(?:class|interface|trait|enum)\s+(\w+)")
NS = re.compile(r"^\s*namespace\s+([\w\\]+)\s*[;{]")
FUNC = re.compile(r"^\s*(?:(?:public|protected|private|static|final|abstract)\s+)*function\s+&?\s*(\w+)\s*\(")
CONST = re.compile(r"^\s*(?:(?:public|protected|private|final)\s+)*const\s+(?:[\w\\|?]+\s+)?(\w+)\s*=")
CASE = re.compile(r"^\s*case\s+(\w+)")


def php_unescape(s, double=False):
    return re.sub(r"\\([\\\"$])" if double else r"\\([\\'])", r"\1", s)


def rs(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def scan(path, out):
    ns, cls, depth, cls_depth, pending, opened = "", None, 0, None, None, False
    for line in open(path, encoding="utf-8", errors="replace"):
        s = line.strip()
        m = NS.match(line)
        if m:
            ns = m.group(1) + "\\"
        m = CLASS.match(line)
        if m and not s.startswith("*"):
            cls, cls_depth, opened = ns + m.group(1), depth, False
        m = ATTR.search(s) if s.startswith("#[") else None
        if m:
            pending = [(k, php_unescape(sq) if sq or not dq else php_unescape(dq, True))
                       for k, sq, dq in ARG.findall(m.group(1) or "")]
        elif pending is not None and not s.startswith(("#[", "/*", "*", "//")) and s:
            name = None
            fm, cm, km = FUNC.match(line), CONST.match(line), CASE.match(line)
            if fm:
                name = (cls + "::" + fm.group(1)) if cls else ns + fm.group(1)
                kind = 1 if cls else 0
            elif cm:
                name = (cls + "::" + cm.group(1)) if cls else ns + cm.group(1)
                kind = 3 if cls else 2
            elif km and cls:
                name, kind = cls + "::" + km.group(1), 3
            if name is not None:
                key = name.lower() if kind in (0, 1) else name
                if kind == 3:
                    c, k = name.split("::")
                    key = c.lower() + "::" + k
                out[(kind, key)] = pending
            pending = None
        depth += line.count("{") - line.count("}")
        if cls is not None and depth > cls_depth:
            opened = True
        elif cls is not None and opened and depth <= cls_depth:
            cls, cls_depth = None, None


def main():
    out = {}
    for root, dirs, files in os.walk(PHP_SRC):
        if "/tests" in root or "/.git" in root:
            continue
        for fn in files:
            if fn.endswith(".stub.php") and "zend_test" not in root and "/ext/dl_test" not in root:
                scan(os.path.join(root, fn), out)
    with open(OUT, "w") as fo:
        fo.write("// Generated by tools/gen_stub_deprecations.py from php-src's *.stub.php; do not edit.\n")
        fo.write("// The #[\\Deprecated] attributes of internal declarations: (kind, key, named arguments).\n")
        fo.write("// kind: 0 = function, 1 = method, 2 = global constant, 3 = class constant / enum case;\n")
        fo.write("// key: lowercase function / \"class::method\", the constant name / \"lowercase class::NAME\".\n")
        fo.write("#![cfg_attr(rustfmt, rustfmt_skip)]\n")
        fo.write("pub static DEPRECATED: &[(u8, &str, &[(&str, &str)])] = &[\n")
        for (kind, key) in sorted(out, key=lambda k: (k[0], k[1].encode())):
            args = ", ".join('("%s", "%s")' % (rs(k), rs(v)) for k, v in out[(kind, key)])
            fo.write('    (%d, "%s", &[%s]),\n' % (kind, rs(key), args))
        fo.write("];\n")
    print("%d deprecated declarations" % len(out))


main()
