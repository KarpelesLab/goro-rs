//! from the PHP manual and libsodium's documentation, since the reference
//! build's libsodium 1.0.18 predates AEGIS).

/// A constant's value.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ConstValue {
    Int(i64),
    Str(&'static str),
}

