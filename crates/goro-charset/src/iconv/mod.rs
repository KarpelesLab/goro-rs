/// `ICONV_IMPL`.
pub const ICONV_IMPL: &str = "glibc";
/// `ICONV_VERSION`.
pub const ICONV_VERSION: &str = "2.43";
/// `ICONV_MIME_DECODE_STRICT`.
pub const MIME_DECODE_STRICT: i64 = 1;
/// `ICONV_MIME_DECODE_CONTINUE_ON_ERROR`.
pub const MIME_DECODE_CONTINUE_ON_ERROR: i64 = 2;
/// Longest charset argument PHP accepts, minus one.
pub const MAX_CHARSET_LEN: usize = 64;

/// An error PHP throws from an iconv function.
///
/// The message is the full `getMessage()` text, `func(): ` prefix included.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IconvError {
    /// `ValueError`.
    ValueError(String),
}

/// A diagnostic PHP emits without throwing. The message excludes the
/// `func(): ` prefix.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Diag {
    /// `E_WARNING`.
    Warning(String),
    /// `E_NOTICE`.
    Notice(String),
    /// `E_DEPRECATED`.
    Deprecated(String),
}
