//! Character set conversion as PHP's iconv extension exposes it.
//!
//! PHP 8.5 on Linux builds the extension on glibc's iconv (ICONV_IMPL
//! "glibc", ICONV_VERSION "2.43"), whose tables, charset names and error
//! handling differ from mbstring's. This module reproduces that behaviour as
//! observed on the reference PHP binary, from public mapping data:
//!
//! - [`iconv`]: `iconv()`, with `//TRANSLIT` and `//IGNORE`;
//! - [`strlen`], [`substr`], [`strpos`], [`strrpos`]: `iconv_strlen()` and
//!   friends;
//! - [`mime_encode`], [`mime_decode`], [`mime_decode_headers`]:
//!   `iconv_mime_encode()`, `iconv_mime_decode()`, `iconv_mime_decode_headers()`;
//! - [`convert`] and [`Charset`] for callers that want the conversion without
//!   PHP's diagnostics (stream filters, `ob_iconv_handler`).
//!
//! The functions take and return bytes and push PHP's warnings and notices
//! into a `Vec<Diag>`; messages exclude the `func(): ` prefix, which the
//! wiring layer adds. Errors PHP throws come back as [`IconvError`], with
//! the prefix.
//!
//! Tables are generated by `tools/charset/gen_iconv.py`; see
//! `tools/charset/iconv-data/` for what was observed and how.
//!
//! Known differences from PHP 8.5 / glibc 2.43:
//! - glibc charsets not implemented (they report "Wrong encoding"): EUC-TW,
//!   ISO-2022-JP-2, ISO-2022-JP-3, ISO-2022-CN, ISO-2022-CN-EXT, TSCII and
//!   the stateful EBCDIC DBCS code pages (IBM930, 933, 935, 937, 939, 1364,
//!   1371, 1388, 1390, 1399);
//! - with //IGNORE, PHP fails ("incomplete multibyte character") or loses
//!   output when an ignored character is followed by more than about 8160
//!   characters from a UTF-16, UTF-32, UCS-2, UCS-4 or GB18030 source; this
//!   module converts such input normally;
//! - CP949: A2 E8 followed by another byte, with //IGNORE, is "incomplete" in
//!   PHP;
//! - //TRANSLIT into the ISO-2022 encoders: glibc drops or repeats escape
//!   sequences in a few multi-character replacements (U+3395 into
//!   ISO-2022-JP, most replacements into ISO-2022-KR);
//! - //TRANSLIT replacement lists come from UCD/CLDR corrected for the 15
//!   target charsets that were observed; other targets may pick another
//!   replacement where glibc's locale data has one unknown here;
//! - MIME: Q encoding into stateful charsets (ISO-2022-JP, UTF-7), some
//!   ICONV_MIME_DECODE_CONTINUE_ON_ERROR recoveries, the errno shown in
//!   "Unknown error (N)", and lone CRs or 8-bit bytes in headers.

