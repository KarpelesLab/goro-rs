//! Character set conversion as PHP's iconv extension exposes it.
//!
//! PHP 8.5 on Linux builds the extension on glibc's iconv (ICONV_IMPL
//! "glibc", ICONV_VERSION "2.43"), whose tables, charset names and error
//! handling differ from mbstring's. This module reproduces that behaviour as
//! observed on the reference PHP binary, from public mapping data:
//!
//! - [`iconv`]: `iconv()`, with `//TRANSLIT` and `//IGNORE`;
//! - [`strlen`], [`substr`], [`strpos`], [`strrpos`]: `iconv_strlen()` and
//!   friends;
//! - [`mime_encode`], [`mime_decode`], [`mime_decode_headers`]:
//!   `iconv_mime_encode()`, `iconv_mime_decode()`, `iconv_mime_decode_headers()`;
//! - [`convert`] and [`Charset`] for callers that want the conversion without
//!   PHP's diagnostics (stream filters, `ob_iconv_handler`).
//!
//! The functions take and return bytes and push PHP's warnings and notices
//! into a `Vec<Diag>`; messages exclude the `func(): ` prefix, which the
//! wiring layer adds. Errors PHP throws come back as [`IconvError`], with
//! the prefix.
//!
//! Tables are generated by `tools/charset/gen_iconv.py`; see
//! `tools/charset/iconv-data/` for what was observed and how.

