//! Tag name tables.
//!
//! The IFD0/EXIF table is the list `exif_tagname()` returns on PHP 8.5
//! (one call per tag id, observed); the GPS and Interoperability tables
//! were observed on PHP 8.5 through `exif_read_data()` on TIFF files
//! listing every tag id. The names are those of the TIFF 6.0, TIFF/EP
//! and Exif 2.3 (CIPA DC-008) tag registries, with PHP's spellings.

/// The table a tag id is looked up in.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Table {
    Ifd,
    Gps,
    Interop,
    Maker(crate::makernote::Maker),
}

