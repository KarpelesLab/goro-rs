pub(crate) fn lookup(t: &[(u16, &'static str)], tag: u16) -> Option<&'static str> {
    t.binary_search_by_key(&tag, |e| e.0).ok().map(|i| t[i].1)
}

/// `exif_tagname()`: the IFD table only.
pub fn ifd_name(tag: u16) -> Option<&'static str> {
    lookup(IFD, tag)
}

/// The name of `tag` in `table`, if it has one.
pub fn name(table: Table, tag: u16) -> Option<&'static str> {
    match table {
        Table::Ifd => lookup(IFD, tag),
        Table::Gps => GPS.get(tag as usize).copied(),
        Table::Interop => lookup(INTEROP, tag),
        Table::Maker(m) => lookup(crate::makernote::table(m), tag),
    }
}

/// The name PHP prints: the table's name or `UndefinedTag:0x%04X`.
pub fn display_name(table: Table, tag: u16) -> String {
    match name(table, tag) {
        Some(n) => n.to_string(),
        None => format!("UndefinedTag:0x{tag:04X}"),
    }
}

/// The name in diagnostics: the table's name or "UndefinedTag".
pub fn diag_name(table: Table, tag: u16) -> &'static str {
    name(table, tag).unwrap_or("UndefinedTag")
}

