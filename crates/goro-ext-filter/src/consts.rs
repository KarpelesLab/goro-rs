/// A constant to register: name, value, and whether reading it raises
/// "Constant X is deprecated since 8.1, use htmlspecialchars() instead"
/// (tests ext/filter/tests/025.phpt, 026.phpt: FILTER_SANITIZE_STRING and
/// FILTER_SANITIZE_STRIPPED; the deprecation is on the constant, not the
/// filter: `filter_var($v, 513)` is silent).
pub struct Constant {
    pub name: &'static str,
    pub value: i64,
    pub deprecated: bool,
}

const fn c(name: &'static str, value: i64) -> Constant {
    Constant {
        name,
        value,
        deprecated: false,
    }
}

/// The deprecation message for a deprecated constant (test 025.phpt).
pub fn deprecation_message(name: &str) -> String {
    format!("Constant {name} is deprecated since 8.1, use htmlspecialchars() instead")
}

