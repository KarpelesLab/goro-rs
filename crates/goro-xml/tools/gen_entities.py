#!/usr/bin/env python3
"""Generates src/html5/entities.rs from the WHATWG named character
reference table (https://html.spec.whatwg.org/entities.json).

Usage: python3 -I tools/gen_entities.py entities.json > src/html5/entities.rs
"""
import json
import sys

with open(sys.argv[1], encoding="utf-8") as f:
    data = json.load(f)

items = sorted((name[1:], v["characters"]) for name, v in data.items())


def lit(s):
    out = []
    for ch in s:
        c = ord(ch)
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % c)
    return '"' + "".join(out) + '"'


print("//! The WHATWG HTML named character references table (generated by")
print("//! `tools/gen_entities.py` from https://html.spec.whatwg.org/entities.json).")
print("//! Names are without the leading `&`; sorted by byte value.")
print()
print("/// (name, replacement) pairs, sorted by name.")
print("pub static ENTITIES: &[(&str, &str)] = &[")
for name, chars in items:
    print("    (%s, %s)," % (lit(name), lit(chars)))
print("];")
