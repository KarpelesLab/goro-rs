#!/usr/bin/env python3
"""Generates src/html5/encoding_tables.rs from the WHATWG Encoding Standard
data files (https://encoding.spec.whatwg.org/encodings.json and the
index-<name>.txt files of the single-byte encodings).

Usage: python3 -I tools/gen_encodings.py encodings.json INDEX_DIR > src/html5/encoding_tables.rs
"""
import json
import os
import sys

with open(sys.argv[1], encoding="utf-8") as f:
    groups = json.load(f)
idx_dir = sys.argv[2]

names = []
labels = []
single = []
for g in groups:
    for e in g["encodings"]:
        names.append(e["name"])
        for l in e["labels"]:
            labels.append((l, e["name"]))
        if g["heading"].startswith("Legacy single-byte"):
            single.append(e["name"])

variant = {}
for n in names:
    v = "".join(p.capitalize() for p in n.replace("-", " ").replace("_", " ").split())
    variant[n] = v

print("//! WHATWG Encoding Standard tables (generated by `tools/gen_encodings.py`")
print("//! from https://encoding.spec.whatwg.org/encodings.json and the")
print("//! single-byte index files).")
print()
print("/// The encodings of the WHATWG Encoding Standard.")
print("#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]")
print("#[allow(missing_docs)]")
print("pub enum WhatwgEncoding {")
for n in names:
    print("    %s," % variant[n])
print("}")
print()
print("impl WhatwgEncoding {")
print("    /// The encoding's name (as `Dom\\HTMLDocument::$charset` reports it).")
print("    pub fn name(self) -> &'static str {")
print("        match self {")
for n in names:
    print("            WhatwgEncoding::%s => %s," % (variant[n], json.dumps(n)))
print("        }")
print("    }")
print("}")
print()
print("/// (label, encoding), sorted by label.")
print("pub(crate) static LABELS: &[(&str, WhatwgEncoding)] = &[")
for l, n in sorted(labels):
    print("    (%s, WhatwgEncoding::%s)," % (json.dumps(l), variant[n]))
print("];")
print()
print("/// The upper halves (bytes 0x80..=0xFF) of the single-byte encodings;")
print("/// 0 marks an unmapped byte.")
print("pub(crate) fn single_byte_table(e: WhatwgEncoding) -> Option<&'static [u16; 128]> {")
print("    Some(match e {")
for n in single:
    print("        WhatwgEncoding::%s => &%s," % (variant[n], "SB_" + variant[n].upper()))
print("        _ => return None,")
print("    })")
print("}")
for n in single:
    table = [0] * 128
    # ISO-8859-8-I uses the ISO-8859-8 index.
    fname = "index-%s.txt" % n.lower().replace("iso-8859-8-i", "iso-8859-8")
    with open(os.path.join(idx_dir, fname), encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            table[int(parts[0])] = int(parts[1], 16)
    print()
    print("static SB_%s: [u16; 128] = [" % variant[n].upper())
    for i in range(0, 128, 8):
        print("    " + ", ".join("0x%04X" % v for v in table[i:i + 8]) + ",")
    print("];")
