/// The symbolic name of an error code (`intl_error_name()`): "[BOGUS
/// UErrorCode]" for values outside the enumeration (ICU's u_errorName).
pub fn error_name(code: i64) -> &'static str {
    // the first name of a value wins, except the *_START aliases, which ICU
    // names after the first real code
    for (n, v) in CODES.iter().chain(EXTRA_NAMES) {
        if *v == code
            && !n.ends_with("_START")
            && !n.ends_with("_LIMIT")
            && *n != "U_MULTIPLE_DECIMAL_SEPERATORS"
            && !n.starts_with("U_STRINGPREP_")
        {
            return n;
        }
    }
    "[BOGUS UErrorCode]"
}

/// Whether `code` is a failure (ICU's U_FAILURE: positive values).
pub fn is_failure(code: i64) -> bool {
    code > 0
}
