const WINDOW_STARTING_INT: i32 = 0;
const WINDOW_ENDING_INT: i32 = 1;
const WINDOW_NTH_VALUE_INT: i32 = 2;
const WINDOW_STARTING_NUM: i32 = 3;
const WINDOW_ENDING_NUM: i32 = 4;

/*
** A "PRECEDING <expr>" (eCond==0) or "FOLLOWING <expr>" (eCond==1) or the
** value of the second argument to nth_value() (eCond==2) has just been
** evaluated and the result left in register reg. This function generates VM
** code to check that the value is a non-negative integer and throws an
** exception if it is not.
*/
fn windowCheckValue(db: &mut Sqlite3, reg: i32, eCond: i32) {
    const azErr: [&[u8]; 5] = [
        b"frame starting offset must be a non-negative integer",
        b"frame ending offset must be a non-negative integer",
        b"second argument to nth_value must be a positive integer",
        b"frame starting offset must be a non-negative number",
        b"frame ending offset must be a non-negative number",
    ];
    const aOp: [u8; 5] = [OP_Ge, OP_Ge, OP_Gt, OP_Ge, OP_Ge];
    sqlite3GetVdbe(db);
    let regZero = sqlite3GetTempReg(db);
    debug_assert!(eCond >= 0 && (eCond as usize) < azErr.len());
    sqlite3VdbeAddOp2(db.v(), OP_Integer, 0, regZero);
    if eCond >= WINDOW_STARTING_NUM {
        let regString = sqlite3GetTempReg(db);
        let v = db.v();
        sqlite3VdbeAddOp4(
            v,
            OP_String8,
            0,
            regString,
            0,
            P4::Z(Vec::new()),
            P4_STATIC as i32,
        );
        let a = sqlite3VdbeCurrentAddr(v) + 2;
        sqlite3VdbeAddOp3(v, OP_Ge, regString, a, reg);
        sqlite3VdbeChangeP5(v, SQLITE_AFF_NUMERIC as u16 | SQLITE_JUMPIFNULL);
        debug_assert!(eCond == 3 || eCond == 4);
    } else {
        let v = db.v();
        let a = sqlite3VdbeCurrentAddr(v) + 2;
        sqlite3VdbeAddOp2(v, OP_MustBeInt, reg, a);
        debug_assert!(eCond == 0 || eCond == 1 || eCond == 2);
    }
    {
        let v = db.v();
        let a = sqlite3VdbeCurrentAddr(v) + 2;
        sqlite3VdbeAddOp3(v, aOp[eCond as usize], regZero, a, reg);
        sqlite3VdbeChangeP5(v, SQLITE_AFF_NUMERIC as u16);
    }
    sqlite3MayAbort(db);
    let v = db.v();
    sqlite3VdbeAddOp2(v, OP_Halt, SQLITE_ERROR, OE_Abort as i32);
    sqlite3VdbeAppendP4(v, P4::Z(azErr[eCond as usize].to_vec()), P4_STATIC as i32);
    sqlite3ReleaseTempReg(db, regZero);
}

/*
** Return the number of arguments passed to the window-function associated
** with the object passed as the only argument to this function.
*/
fn windowArgCount(db: &Sqlite3, pWin: WindowId) -> i32 {
    let pOwner = db.win(pWin).pOwner;
    debug_assert!(db.ex(pOwner).UseXList());
    let pList = db.ex(pOwner).x.pList;
    if pList.nn() { db.el(pList).nExpr() } else { 0 }
}

/*
** See comments above struct WindowCodeArg.
*/
#[derive(Clone, Copy, Default)]
struct WindowCsrAndReg {
    csr: i32, /* Cursor number */
    reg: i32, /* First in array of peer values */
}

/*
** A single instance of this structure is allocated on the stack by
** sqlite3WindowCodeStep() and a pointer to it passed to the various helper
** routines. This is to reduce the number of arguments required by each
** helper function.
**
** regArg:
**   Each window function requires an accumulator register (just as an
**   ordinary aggregate function does). This variable is set to the first
**   in an array of accumulator registers - one for each window function
**   in the WindowCodeArg.pMWin list.
**
** eDelete:
**   The window functions implementation sometimes caches the input rows
**   that it processes in a temporary table. If it is not zero, this
**   variable indicates when rows may be removed from the temp table (in
**   order to reduce memory requirements - it would always be safe just
**   to leave them there). Possible values for eDelete are:
**
**      WINDOW_RETURN_ROW:
**        An input row can be discarded after it is returned to the caller.
**
**      WINDOW_AGGINVERSE:
**        An input row can be discarded after the window functions xInverse()
**        callbacks have been invoked in it.
**
**      WINDOW_AGGSTEP:
**        An input row can be discarded after the window functions xStep()
**        callbacks have been invoked in it.
**
** start,current,end
**   Consider a window-frame similar to the following:
**
**     (ORDER BY a, b GROUPS BETWEEN 2 PRECEDING AND 2 FOLLOWING)
**
**   The windows functions implementation caches the input rows in a temp
**   table, sorted by "a, b" (it actually populates the cache lazily, and
**   aggressively removes rows once they are no longer required, but that's
**   a mere detail). It keeps three cursors open on the temp table. One
**   (current) that points to the next row to return to the query engine
**   once its window function values have been calculated. Another (end)
**   points to the next row to call the xStep() method of each window function
**   on (so that it is 2 groups ahead of current). And a third (start) that
**   points to the next row to call the xInverse() method of each window
**   function on.
**
**   Each cursor (start, current and end) consists of a VDBE cursor
**   (WindowCsrAndReg.csr) and an array of registers (starting at
**   WindowCodeArg.reg) that always contains a copy of the peer values
**   read from the corresponding cursor.
**
**   Depending on the window-frame in question, all three cursors may not
**   be required. In this case both WindowCodeArg.csr and reg are set to
**   0.
**
** Rust: pParse and pVdbe are reached through `db`.
*/
#[derive(Clone, Copy, Default)]
struct WindowCodeArg {
    pMWin: WindowId, /* First in list of functions being processed */
    addrGosub: i32,  /* OP_Gosub to this address to return one row */
    regGosub: i32,   /* Register used with OP_Gosub(addrGosub) */
    regArg: i32,     /* First in array of accumulator registers */
    eDelete: i32,    /* See above */
    regRowid: i32,

    start: WindowCsrAndReg,
    current: WindowCsrAndReg,
    end: WindowCsrAndReg,
}

/*
** Generate VM code to read the window frames peer values from cursor csr into
** an array of registers starting at reg.
*/
fn windowReadPeerValues(db: &mut Sqlite3, p: &WindowCodeArg, csr: i32, reg: i32) {
    let pMWin = p.pMWin;
    let pOrderBy = db.win(pMWin).pOrderBy;
    if pOrderBy.nn() {
        sqlite3GetVdbe(db);
        let pPart = db.win(pMWin).pPartition;
        let iColOff = db.win(pMWin).nBufferCol + if pPart.nn() { db.el(pPart).nExpr() } else { 0 };
        let n = db.el(pOrderBy).nExpr();
        for i in 0..n {
            sqlite3VdbeAddOp3(db.v(), OP_Column, csr, iColOff + i, reg + i);
        }
    }
}

/*
** Generate VM code to invoke either xStep() (if bInverse is 0) or
** xInverse (if bInverse is non-zero) for each window function in the
** linked list starting at pMWin. Or, for built-in window functions
** that do not use the standard function API, generate the required
** inline VM code.
**
** If argument csr is greater than or equal to 0, then argument reg is
** the first register in an array of registers guaranteed to be large
** enough to hold the array of arguments for each function. In this case
** the arguments are extracted from the current row of csr into the
** array of registers before invoking OP_AggStep or OP_AggInverse
**
** Or, if csr is less than zero, then the array of registers at reg is
** already populated with all columns from the current row of the sub-query.
**
** If argument regPartSize is non-zero, then it is a register containing the
** number of rows in the current partition.
*/
fn windowAggStep(
    db: &mut Sqlite3,
    _p: &WindowCodeArg,
    pMWin: WindowId, /* Linked list of window functions */
    csr: i32,        /* Read arguments from this cursor */
    bInverse: i32,   /* True to invoke xInverse instead of xStep */
    reg: i32,        /* Array of registers */
) {
    sqlite3GetVdbe(db);
    let (mIEphCsr, mRegStartRowid) = {
        let m = db.win(pMWin);
        (m.iEphCsr, m.regStartRowid)
    };
    let mut pWin = pMWin;
    while pWin.nn() {
        let w = db.win(pWin).clone();
        let pFunc = w.pWFunc.clone().expect("window function");
        let mut nArg = if w.bExprArgs != 0 {
            0
        } else {
            windowArgCount(db, pWin)
        };
        let mut addrIf = 0;

        debug_assert!(bInverse == 0 || w.eStart != TK_UNBOUNDED);

        /* All OVER clauses in the same window function aggregate step must
         ** be the same. */
        debug_assert!(pWin == pMWin || sqlite3WindowCompare(db, pWin, pMWin, 0) != 1);

        for i in 0..nArg {
            if i != 1 || !isBuiltinWin(&pFunc, nth_valueName) {
                sqlite3VdbeAddOp3(db.v(), OP_Column, csr, w.iArgCol + i, reg + i);
            } else {
                sqlite3VdbeAddOp3(db.v(), OP_Column, mIEphCsr, w.iArgCol + i, reg + i);
            }
        }
        let mut regArg = reg;

        if w.pFilter.nn() {
            debug_assert!(db.ex(w.pOwner).UseXList());
            let regTmp = sqlite3GetTempReg(db);
            sqlite3VdbeAddOp3(db.v(), OP_Column, csr, w.iArgCol + nArg, regTmp);
            addrIf = sqlite3VdbeAddOp3(db.v(), OP_IfNot, regTmp, 0, 1);
            sqlite3ReleaseTempReg(db, regTmp);
        }

        if mRegStartRowid == 0
            && (pFunc.funcFlags & SQLITE_FUNC_MINMAX) != 0
            && w.eStart != TK_UNBOUNDED
        {
            let v = db.v();
            let addrIsNull = sqlite3VdbeAddOp1(v, OP_IsNull, regArg);
            if bInverse == 0 {
                sqlite3VdbeAddOp2(v, OP_AddImm, w.regApp + 1, 1);
                sqlite3VdbeAddOp2(v, OP_SCopy, regArg, w.regApp);
                sqlite3VdbeAddOp3(v, OP_MakeRecord, w.regApp, 2, w.regApp + 2);
                sqlite3VdbeAddOp2(v, OP_IdxInsert, w.csrApp, w.regApp + 2);
            } else {
                sqlite3VdbeAddOp4Int(v, OP_SeekGE, w.csrApp, 0, regArg, 1);
                sqlite3VdbeAddOp1(v, OP_Delete, w.csrApp);
                let a = sqlite3VdbeCurrentAddr(v) - 2;
                sqlite3VdbeJumpHere(v, a);
            }
            sqlite3VdbeJumpHere(v, addrIsNull);
        } else if w.regApp != 0 {
            debug_assert!(w.pFilter.is_null());
            debug_assert!(
                isBuiltinWin(&pFunc, nth_valueName) || isBuiltinWin(&pFunc, first_valueName)
            );
            debug_assert!(bInverse == 0 || bInverse == 1);
            sqlite3VdbeAddOp2(db.v(), OP_AddImm, w.regApp + 1 - bInverse, 1);
        } else if !(isBuiltinWin(&pFunc, leadName) || isBuiltinWin(&pFunc, lagName)) {
            /* pFunc->xSFunc!=noopStepFunc */
            if w.bExprArgs != 0 {
                let mut iOp = sqlite3VdbeCurrentAddr(db.v());

                debug_assert!(db.ex(w.pOwner).UseXList());
                let pOwnerList = db.ex(w.pOwner).x.pList;
                nArg = db.el(pOwnerList).nExpr();
                regArg = sqlite3GetTempRange(db, nArg);
                sqlite3ExprCodeExprList(db, pOwnerList, regArg, 0, 0);

                let v = db.v();
                let iEnd = sqlite3VdbeCurrentAddr(v);
                while iOp < iEnd {
                    let pOp = sqlite3VdbeGetOp(v, iOp);
                    if pOp.opcode == OP_Column && pOp.p1 == mIEphCsr {
                        pOp.p1 = csr;
                    }
                    iOp += 1;
                }
            }
            if (pFunc.funcFlags & SQLITE_FUNC_NEEDCOLL) != 0 {
                debug_assert!(nArg > 0);
                debug_assert!(db.ex(w.pOwner).UseXList());
                let pOwnerList = db.ex(w.pOwner).x.pList;
                let e0 = db.el(pOwnerList).a[0].pExpr;
                let pColl = sqlite3ExprNNCollSeq(db, e0);
                sqlite3VdbeAddOp4(
                    db.v(),
                    OP_CollSeq,
                    0,
                    0,
                    0,
                    coll_p4(pColl),
                    P4_COLLSEQ as i32,
                );
            }
            let v = db.v();
            sqlite3VdbeAddOp3(
                v,
                if bInverse != 0 {
                    OP_AggInverse
                } else {
                    OP_AggStep
                },
                bInverse,
                regArg,
                w.regAccum,
            );
            sqlite3VdbeAppendP4(v, P4::Func(pFunc.clone()), P4_FUNCDEF as i32);
            sqlite3VdbeChangeP5(v, nArg as u16);
            if w.bExprArgs != 0 {
                sqlite3ReleaseTempRange(db, regArg, nArg);
            }
        }

        if addrIf != 0 {
            sqlite3VdbeJumpHere(db.v(), addrIf);
        }
        pWin = w.pNextWin;
    }
}

/*
** Values that may be passed as the second argument to windowCodeOp().
*/
const WINDOW_RETURN_ROW: i32 = 1;
const WINDOW_AGGINVERSE: i32 = 2;
const WINDOW_AGGSTEP: i32 = 3;

/*
** Generate VM code to invoke either xValue() (bFin==0) or xFinalize()
** (bFin==1) for each window function in the linked list starting at
** pMWin. Or, for built-in window-functions that do not use the standard
** API, generate the equivalent VM code.
*/
fn windowAggFinal(db: &mut Sqlite3, p: &WindowCodeArg, bFin: i32) {
    let pMWin = p.pMWin;
    sqlite3GetVdbe(db);
    let mRegStartRowid = db.win(pMWin).regStartRowid;

    let mut pWin = pMWin;
    while pWin.nn() {
        let w = db.win(pWin).clone();
        let pFunc = w.pWFunc.clone().expect("window function");
        if mRegStartRowid == 0
            && (pFunc.funcFlags & SQLITE_FUNC_MINMAX) != 0
            && w.eStart != TK_UNBOUNDED
        {
            let v = db.v();
            sqlite3VdbeAddOp2(v, OP_Null, 0, w.regResult);
            sqlite3VdbeAddOp1(v, OP_Last, w.csrApp);
            sqlite3VdbeAddOp3(v, OP_Column, w.csrApp, 0, w.regResult);
            let a = sqlite3VdbeCurrentAddr(v) - 2;
            sqlite3VdbeJumpHere(v, a);
        } else if w.regApp != 0 {
            debug_assert!(mRegStartRowid == 0);
        } else {
            let nArg = windowArgCount(db, pWin);
            let v = db.v();
            if bFin != 0 {
                sqlite3VdbeAddOp2(v, OP_AggFinal, w.regAccum, nArg);
                sqlite3VdbeAppendP4(v, P4::Func(pFunc.clone()), P4_FUNCDEF as i32);
                sqlite3VdbeAddOp2(v, OP_Copy, w.regAccum, w.regResult);
                sqlite3VdbeAddOp2(v, OP_Null, 0, w.regAccum);
            } else {
                sqlite3VdbeAddOp3(v, OP_AggValue, w.regAccum, nArg, w.regResult);
                sqlite3VdbeAppendP4(v, P4::Func(pFunc.clone()), P4_FUNCDEF as i32);
            }
        }
        pWin = w.pNextWin;
    }
}

/*
** Generate code to calculate the current values of all window functions in the
** p->pMWin list by doing a full scan of the current window frame. Store the
** results in the Window.regResult registers, ready to return the upper
** layer.
*/
fn windowFullScan(db: &mut Sqlite3, p: &WindowCodeArg) {
    let pMWin = p.pMWin;

    let mut regCPeer = 0; /* Current peer values */
    let mut regPeer = 0; /* AggStep peer values */

    debug_assert!(pMWin.nn());
    let m = db.win(pMWin).clone();
    let csr = m.csrApp;
    let nPeer = if m.pOrderBy.nn() {
        db.el(m.pOrderBy).nExpr()
    } else {
        0
    };

    let lblNext = sqlite3VdbeMakeLabel(db);
    let lblBrk = sqlite3VdbeMakeLabel(db);

    let regCRowid = sqlite3GetTempReg(db); /* Current rowid value */
    let regRowid = sqlite3GetTempReg(db); /* AggStep rowid value */
    if nPeer != 0 {
        regCPeer = sqlite3GetTempRange(db, nPeer);
        regPeer = sqlite3GetTempRange(db, nPeer);
    }

    sqlite3VdbeAddOp2(db.v(), OP_Rowid, m.iEphCsr, regCRowid);
    windowReadPeerValues(db, p, m.iEphCsr, regCPeer);

    let mut pWin = pMWin;
    while pWin.nn() {
        let regAccum = db.win(pWin).regAccum;
        sqlite3VdbeAddOp2(db.v(), OP_Null, 0, regAccum);
        pWin = db.win(pWin).pNextWin;
    }

    let addrNext;
    {
        let v = db.v();
        sqlite3VdbeAddOp3(v, OP_SeekGE, csr, lblBrk, m.regStartRowid);
        addrNext = sqlite3VdbeCurrentAddr(v);
        sqlite3VdbeAddOp2(v, OP_Rowid, csr, regRowid);
        sqlite3VdbeAddOp3(v, OP_Gt, m.regEndRowid, lblBrk, regRowid);
    }

    if m.eExclude == TK_CURRENT {
        sqlite3VdbeAddOp3(db.v(), OP_Eq, regCRowid, lblNext, regRowid);
    } else if m.eExclude != TK_NO {
        let mut addrEq = 0;
        let mut pKeyInfo: Option<KeyInfoRef> = None;

        if m.pOrderBy.nn() {
            pKeyInfo = sqlite3KeyInfoFromExprList(db, m.pOrderBy, 0, 0);
        }
        if m.eExclude == TK_TIES {
            addrEq = sqlite3VdbeAddOp3(db.v(), OP_Eq, regCRowid, 0, regRowid);
        }
        if pKeyInfo.is_some() {
            windowReadPeerValues(db, p, csr, regPeer);
            let v = db.v();
            sqlite3VdbeAddOp3(v, OP_Compare, regPeer, regCPeer, nPeer);
            sqlite3VdbeAppendP4(v, keyinfo_p4(pKeyInfo), P4_KEYINFO as i32);
            let addr = sqlite3VdbeCurrentAddr(v) + 1;
            sqlite3VdbeAddOp3(v, OP_Jump, addr, lblNext, addr);
        } else {
            sqlite3VdbeAddOp2(db.v(), OP_Goto, 0, lblNext);
        }
        if addrEq != 0 {
            sqlite3VdbeJumpHere(db.v(), addrEq);
        }
    }

    windowAggStep(db, p, pMWin, csr, 0, p.regArg);

    {
        let v = db.v();
        sqlite3VdbeResolveLabel(v, lblNext);
        sqlite3VdbeAddOp2(v, OP_Next, csr, addrNext);
        sqlite3VdbeJumpHere(v, addrNext - 1);
        sqlite3VdbeJumpHere(v, addrNext + 1);
    }
    sqlite3ReleaseTempReg(db, regRowid);
    sqlite3ReleaseTempReg(db, regCRowid);
    if nPeer != 0 {
        sqlite3ReleaseTempRange(db, regPeer, nPeer);
        sqlite3ReleaseTempRange(db, regCPeer, nPeer);
    }

    windowAggFinal(db, p, 1);
}

/*
** Invoke the sub-routine at regGosub (generated by code in select.c) to
** return the current row of Window.iEphCsr. If all window functions are
** aggregate window functions that use the standard API, a single
** OP_Gosub instruction is all that this routine generates. Extra VM code
** for per-row processing is only generated for the following built-in window
** functions:
**
**   nth_value()
**   first_value()
**   lag()
**   lead()
*/
fn windowReturnOneRow(db: &mut Sqlite3, p: &WindowCodeArg) {
    let pMWin = p.pMWin;

    if db.win(pMWin).regStartRowid != 0 {
        windowFullScan(db, p);
    } else {
        let iEph = db.win(pMWin).iEphCsr;
        let mut pWin = pMWin;
        while pWin.nn() {
            let w = db.win(pWin).clone();
            let pFunc = w.pWFunc.clone().expect("window function");
            debug_assert!(db.ex(w.pOwner).UseXList());
            if isBuiltinWin(&pFunc, nth_valueName) || isBuiltinWin(&pFunc, first_valueName) {
                let csr = w.csrApp;
                let lbl = sqlite3VdbeMakeLabel(db);
                let tmpReg = sqlite3GetTempReg(db);
                sqlite3VdbeAddOp2(db.v(), OP_Null, 0, w.regResult);

                if isBuiltinWin(&pFunc, nth_valueName) {
                    sqlite3VdbeAddOp3(db.v(), OP_Column, iEph, w.iArgCol + 1, tmpReg);
                    windowCheckValue(db, tmpReg, WINDOW_NTH_VALUE_INT);
                } else {
                    sqlite3VdbeAddOp2(db.v(), OP_Integer, 1, tmpReg);
                }
                let v = db.v();
                sqlite3VdbeAddOp3(v, OP_Add, tmpReg, w.regApp, tmpReg);
                sqlite3VdbeAddOp3(v, OP_Gt, w.regApp + 1, lbl, tmpReg);
                sqlite3VdbeAddOp3(v, OP_SeekRowid, csr, 0, tmpReg);
                sqlite3VdbeAddOp3(v, OP_Column, csr, w.iArgCol, w.regResult);
                sqlite3VdbeResolveLabel(v, lbl);
                sqlite3ReleaseTempReg(db, tmpReg);
            } else if isBuiltinWin(&pFunc, leadName) || isBuiltinWin(&pFunc, lagName) {
                let nArg = db.el(db.ex(w.pOwner).x.pList).nExpr();
                let csr = w.csrApp;
                let lbl = sqlite3VdbeMakeLabel(db);
                let tmpReg = sqlite3GetTempReg(db);

                if nArg < 3 {
                    sqlite3VdbeAddOp2(db.v(), OP_Null, 0, w.regResult);
                } else {
                    sqlite3VdbeAddOp3(db.v(), OP_Column, iEph, w.iArgCol + 2, w.regResult);
                }
                sqlite3VdbeAddOp2(db.v(), OP_Rowid, iEph, tmpReg);
                if nArg < 2 {
                    let val = if isBuiltinWin(&pFunc, leadName) {
                        1
                    } else {
                        -1
                    };
                    sqlite3VdbeAddOp2(db.v(), OP_AddImm, tmpReg, val);
                } else {
                    let op = if isBuiltinWin(&pFunc, leadName) {
                        OP_Add
                    } else {
                        OP_Subtract
                    };
                    let tmpReg2 = sqlite3GetTempReg(db);
                    sqlite3VdbeAddOp3(db.v(), OP_Column, iEph, w.iArgCol + 1, tmpReg2);
                    sqlite3VdbeAddOp3(db.v(), op, tmpReg2, tmpReg, tmpReg);
                    sqlite3ReleaseTempReg(db, tmpReg2);
                }

                let v = db.v();
                sqlite3VdbeAddOp3(v, OP_SeekRowid, csr, lbl, tmpReg);
                sqlite3VdbeAddOp3(v, OP_Column, csr, w.iArgCol, w.regResult);
                sqlite3VdbeResolveLabel(v, lbl);
                sqlite3ReleaseTempReg(db, tmpReg);
            }
            pWin = w.pNextWin;
        }
    }
    sqlite3VdbeAddOp2(db.v(), OP_Gosub, p.regGosub, p.addrGosub);
}

/*
** Generate code to set the accumulator register for each window function
** in the linked list passed as the second argument to NULL. And perform
** any equivalent initialization required by any built-in window functions
** in the list.
*/
fn windowInitAccum(db: &mut Sqlite3, pMWin: WindowId) -> i32 {
    sqlite3GetVdbe(db);
    let mut nArg = 0;
    let mRegStartRowid = db.win(pMWin).regStartRowid;
    let mut pWin = pMWin;
    while pWin.nn() {
        let w = db.win(pWin).clone();
        let pFunc = w.pWFunc.clone().expect("window function");
        debug_assert!(w.regAccum != 0);
        sqlite3VdbeAddOp2(db.v(), OP_Null, 0, w.regAccum);
        nArg = nArg.max(windowArgCount(db, pWin));
        if mRegStartRowid == 0 {
            if isBuiltinWin(&pFunc, nth_valueName) || isBuiltinWin(&pFunc, first_valueName) {
                sqlite3VdbeAddOp2(db.v(), OP_Integer, 0, w.regApp);
                sqlite3VdbeAddOp2(db.v(), OP_Integer, 0, w.regApp + 1);
            }

            if (pFunc.funcFlags & SQLITE_FUNC_MINMAX) != 0 && w.csrApp != 0 {
                debug_assert!(w.eStart != TK_UNBOUNDED);
                sqlite3VdbeAddOp1(db.v(), OP_ResetSorter, w.csrApp);
                sqlite3VdbeAddOp2(db.v(), OP_Integer, 0, w.regApp + 1);
            }
        }
        pWin = w.pNextWin;
    }
    let regArg = db.ppr().nMem + 1;
    db.pp().nMem += nArg;
    regArg
}

/*
** Return true if the current frame should be cached in the ephemeral table,
** even if there are no xInverse() calls required.
*/
fn windowCacheFrame(db: &Sqlite3, pMWin: WindowId) -> bool {
    if db.win(pMWin).regStartRowid != 0 {
        return true;
    }
    let mut pWin = pMWin;
    while pWin.nn() {
        if let Some(pFunc) = &db.win(pWin).pWFunc {
            if isBuiltinWin(pFunc, nth_valueName)
                || isBuiltinWin(pFunc, first_valueName)
                || isBuiltinWin(pFunc, leadName)
                || isBuiltinWin(pFunc, lagName)
            {
                return true;
            }
        }
        pWin = db.win(pWin).pNextWin;
    }
    false
}

/*
** regOld and regNew are each the first register in an array of size
** pOrderBy->nExpr. This function generates code to compare the two
** arrays of registers using the collation sequences and other comparison
** parameters specified by pOrderBy.
**
** If the two arrays are not equal, the contents of regNew is copied to
** regOld and control falls through. Otherwise, if the contents of the arrays
** are equal, an OP_Goto is executed. The address of the OP_Goto is returned.
*/
fn windowIfNewPeer(
    db: &mut Sqlite3,
    pOrderBy: ExprListId,
    regNew: i32, /* First in array of new values */
    regOld: i32, /* First in array of old values */
    addr: i32,   /* Jump here */
) {
    sqlite3GetVdbe(db);
    if pOrderBy.nn() {
        let nVal = db.el(pOrderBy).nExpr();
        let pKeyInfo = sqlite3KeyInfoFromExprList(db, pOrderBy, 0, 0);
        let v = db.v();
        sqlite3VdbeAddOp3(v, OP_Compare, regOld, regNew, nVal);
        sqlite3VdbeAppendP4(v, keyinfo_p4(pKeyInfo), P4_KEYINFO as i32);
        let a = sqlite3VdbeCurrentAddr(v) + 1;
        sqlite3VdbeAddOp3(v, OP_Jump, a, addr, a);
        sqlite3VdbeAddOp3(v, OP_Copy, regNew, regOld, nVal - 1);
    } else {
        sqlite3VdbeAddOp2(db.v(), OP_Goto, 0, addr);
    }
}

/*
** This function is called as part of generating VM programs for RANGE
** offset PRECEDING/FOLLOWING frame boundaries. Assuming "ASC" order for
** the ORDER BY term in the window, and that argument op is OP_Ge, it generates
** code equivalent to:
**
**   if( csr1.peerVal + regVal >= csr2.peerVal ) goto lbl;
**
** The value of parameter op may also be OP_Gt or OP_Le. In these cases the
** operator in the above pseudo-code is replaced with ">" or "<=", respectively.
**
** If the sort-order for the ORDER BY term in the window is DESC, then the
** comparison is reversed. Instead of adding regVal to csr1.peerVal, it is
** subtracted. And the comparison operator is inverted to - ">=" becomes "<=",
** ">" becomes "<", and so on. So, with DESC sort order, if the argument op
** is OP_Ge, the generated code is equivalent to:
**
**   if( csr1.peerVal - regVal <= csr2.peerVal ) goto lbl;
**
** A special type of arithmetic is used such that if csr1.peerVal is not
** a numeric type (real or integer), then the result of the addition
** or subtraction is a a copy of csr1.peerVal.
*/
fn windowCodeRangeTest(
    db: &mut Sqlite3,
    p: &WindowCodeArg,
    op: u8,      /* OP_Ge, OP_Gt, or OP_Le */
    csr1: i32,   /* Cursor number for cursor 1 */
    regVal: i32, /* Register containing non-negative number */
    csr2: i32,   /* Cursor number for cursor 2 */
    lbl: i32,    /* Jump destination if condition is true */
) {
    let mut op = op;
    sqlite3GetVdbe(db);
    let pOrderBy = db.win(p.pMWin).pOrderBy; /* ORDER BY clause for window */
    let reg1 = sqlite3GetTempReg(db); /* Reg. for csr1.peerVal+regVal */
    let reg2 = sqlite3GetTempReg(db); /* Reg. for csr2.peerVal */
    let regString = {
        let pp = db.pp();
        pp.nMem += 1;
        pp.nMem
    }; /* Reg. for constant value '' */
    let mut arith = OP_Add; /* OP_Add or OP_Subtract */
    let addrDone = sqlite3VdbeMakeLabel(db); /* Address past OP_Ge */

    /* Read the peer-value from each cursor into a register */
    windowReadPeerValues(db, p, csr1, reg1);
    windowReadPeerValues(db, p, csr2, reg2);

    debug_assert!(op == OP_Ge || op == OP_Gt || op == OP_Le);
    debug_assert!(pOrderBy.nn() && db.el(pOrderBy).nExpr() == 1);
    let sortFlags = db.el(pOrderBy).a[0].fg.sortFlags;
    if (sortFlags & KEYINFO_ORDER_DESC) != 0 {
        op = match op {
            OP_Ge => OP_Le,
            OP_Gt => OP_Lt,
            _ => {
                debug_assert!(op == OP_Le);
                OP_Ge
            }
        };
        arith = OP_Subtract;
    }

    /* If the BIGNULL flag is set for the ORDER BY, then it is required to
     ** consider NULL values to be larger than all other values, instead of
     ** the usual smaller. The VDBE opcodes OP_Ge and so on do not handle this
     ** (and adding that capability causes a performance regression), so
     ** instead if the BIGNULL flag is set then cases where either reg1 or
     ** reg2 are NULL are handled separately in the following block. The code
     ** generated is equivalent to:
     **
     **   if( reg1 IS NULL ){
     **     if( op==OP_Ge ) goto lbl;
     **     if( op==OP_Gt && reg2 IS NOT NULL ) goto lbl;
     **     if( op==OP_Le && reg2 IS NULL ) goto lbl;
     **   }else if( reg2 IS NULL ){
     **     if( op==OP_Le ) goto lbl;
     **   }
     **
     ** Additionally, if either reg1 or reg2 are NULL but the jump to lbl is
     ** not taken, control jumps over the comparison operator coded below this
     ** block.  */
    if (sortFlags & KEYINFO_ORDER_BIGNULL) != 0 {
        let v = db.v();
        /* This block runs if reg1 contains a NULL. */
        let addr = sqlite3VdbeAddOp1(v, OP_NotNull, reg1);
        match op {
            OP_Ge => {
                sqlite3VdbeAddOp2(v, OP_Goto, 0, lbl);
            }
            OP_Gt => {
                sqlite3VdbeAddOp2(v, OP_NotNull, reg2, lbl);
            }
            OP_Le => {
                sqlite3VdbeAddOp2(v, OP_IsNull, reg2, lbl);
            }
            _ => {
                debug_assert!(op == OP_Lt); /* no-op */
            }
        }
        sqlite3VdbeAddOp2(v, OP_Goto, 0, addrDone);

        /* This block runs if reg1 is not NULL, but reg2 is. */
        sqlite3VdbeJumpHere(v, addr);
        sqlite3VdbeAddOp2(
            v,
            OP_IsNull,
            reg2,
            if op == OP_Gt || op == OP_Ge {
                addrDone
            } else {
                lbl
            },
        );
    }

    /* Register reg1 currently contains csr1.peerVal (the peer-value from csr1).
     ** This block adds (or subtracts for DESC) the numeric value in regVal
     ** from it. Or, if reg1 is not numeric (it is a NULL, a text value or a blob),
     ** then leave reg1 as it is. In pseudo-code, this is implemented as:
     **
     **   if( reg1>='' ) goto addrGe;
     **   reg1 = reg1 +/- regVal
     **   addrGe:
     **
     ** Since all strings and blobs are greater-than-or-equal-to an empty string,
     ** the add/subtract is skipped for these, as required. If reg1 is a NULL,
     ** then the arithmetic is performed, but since adding or subtracting from
     ** NULL is always NULL anyway, this case is handled as required too.  */
    {
        let v = db.v();
        sqlite3VdbeAddOp4(
            v,
            OP_String8,
            0,
            regString,
            0,
            P4::Z(Vec::new()),
            P4_STATIC as i32,
        );
        let addrGe = sqlite3VdbeAddOp3(v, OP_Ge, regString, 0, reg1);
        if (op == OP_Ge && arith == OP_Add) || (op == OP_Le && arith == OP_Subtract) {
            sqlite3VdbeAddOp3(v, op, reg2, lbl, reg1);
        }
        sqlite3VdbeAddOp3(v, arith, regVal, reg1, reg1);
        sqlite3VdbeJumpHere(v, addrGe);

        /* Compare registers reg2 and reg1, taking the jump if required. Note that
         ** control skips over this test if the BIGNULL flag is set and either
         ** reg1 or reg2 contain a NULL value.  */
        sqlite3VdbeAddOp3(v, op, reg2, lbl, reg1);
    }
    let e0 = db.el(pOrderBy).a[0].pExpr;
    let pColl = sqlite3ExprNNCollSeq(db, e0);
    {
        let v = db.v();
        sqlite3VdbeAppendP4(v, coll_p4(pColl), P4_COLLSEQ as i32);
        sqlite3VdbeChangeP5(v, SQLITE_NULLEQ);
        sqlite3VdbeResolveLabel(v, addrDone);
    }

    debug_assert!(op == OP_Ge || op == OP_Gt || op == OP_Lt || op == OP_Le);
    sqlite3ReleaseTempReg(db, reg1);
    sqlite3ReleaseTempReg(db, reg2);
}

/*
** Helper function for sqlite3WindowCodeStep(). Each call to this function
** generates VM code for a single RETURN_ROW, AGGSTEP or AGGINVERSE
** operation. Refer to the header comment for sqlite3WindowCodeStep() for
** details.
*/
fn windowCodeOp(
    db: &mut Sqlite3,
    p: &WindowCodeArg, /* Context object */
    op: i32,           /* WINDOW_RETURN_ROW, AGGSTEP or AGGINVERSE */
    regCountdown: i32, /* Register for OP_IfPos countdown */
    jumpOnEof: i32,    /* Jump here if stepped cursor reaches EOF */
) -> i32 {
    let csr: i32;
    let reg: i32;
    let pMWin = p.pMWin;
    let m = db.win(pMWin).clone();
    let mut ret = 0;
    let bPeer = (m.eFrmType != TK_ROWS) as i32;

    let lblDone = sqlite3VdbeMakeLabel(db);
    let mut addrNextRange = 0;

    /* Special case - WINDOW_AGGINVERSE is always a no-op if the frame
     ** starts with UNBOUNDED PRECEDING. */
    if op == WINDOW_AGGINVERSE && m.eStart == TK_UNBOUNDED {
        debug_assert!(regCountdown == 0 && jumpOnEof == 0);
        return 0;
    }

    if regCountdown > 0 {
        if m.eFrmType == TK_RANGE {
            addrNextRange = sqlite3VdbeCurrentAddr(db.v());
            debug_assert!(op == WINDOW_AGGINVERSE || op == WINDOW_AGGSTEP);
            if op == WINDOW_AGGINVERSE {
                if m.eStart == TK_FOLLOWING {
                    windowCodeRangeTest(
                        db,
                        p,
                        OP_Le,
                        p.current.csr,
                        regCountdown,
                        p.start.csr,
                        lblDone,
                    );
                } else {
                    windowCodeRangeTest(
                        db,
                        p,
                        OP_Ge,
                        p.start.csr,
                        regCountdown,
                        p.current.csr,
                        lblDone,
                    );
                }
            } else {
                windowCodeRangeTest(
                    db,
                    p,
                    OP_Gt,
                    p.end.csr,
                    regCountdown,
                    p.current.csr,
                    lblDone,
                );
            }
        } else {
            sqlite3VdbeAddOp3(db.v(), OP_IfPos, regCountdown, lblDone, 1);
        }
    }

    if op == WINDOW_RETURN_ROW && m.regStartRowid == 0 {
        windowAggFinal(db, p, 0);
    }
    let addrContinue = sqlite3VdbeCurrentAddr(db.v());

    /* If this is a (RANGE BETWEEN a FOLLOWING AND b FOLLOWING) or
     ** (RANGE BETWEEN b PRECEDING AND a PRECEDING) frame, ensure the
     ** start cursor does not advance past the end cursor within the
     ** temporary table. It otherwise might, if (a>b). Also ensure that,
     ** if the input cursor is still finding new rows, that the end
     ** cursor does not go past it to EOF. */
    if m.eStart == m.eEnd && regCountdown != 0 && m.eFrmType == TK_RANGE {
        let regRowid1 = sqlite3GetTempReg(db);
        let regRowid2 = sqlite3GetTempReg(db);
        if op == WINDOW_AGGINVERSE {
            let v = db.v();
            sqlite3VdbeAddOp2(v, OP_Rowid, p.start.csr, regRowid1);
            sqlite3VdbeAddOp2(v, OP_Rowid, p.end.csr, regRowid2);
            sqlite3VdbeAddOp3(v, OP_Ge, regRowid2, lblDone, regRowid1);
        } else if p.regRowid != 0 {
            let v = db.v();
            sqlite3VdbeAddOp2(v, OP_Rowid, p.end.csr, regRowid1);
            sqlite3VdbeAddOp3(v, OP_Ge, p.regRowid, lblDone, regRowid1);
        }
        sqlite3ReleaseTempReg(db, regRowid1);
        sqlite3ReleaseTempReg(db, regRowid2);
        debug_assert!(m.eStart == TK_PRECEDING || m.eStart == TK_FOLLOWING);
    }

    match op {
        WINDOW_RETURN_ROW => {
            csr = p.current.csr;
            reg = p.current.reg;
            windowReturnOneRow(db, p);
        }

        WINDOW_AGGINVERSE => {
            csr = p.start.csr;
            reg = p.start.reg;
            if m.regStartRowid != 0 {
                debug_assert!(m.regEndRowid != 0);
                sqlite3VdbeAddOp2(db.v(), OP_AddImm, m.regStartRowid, 1);
            } else {
                windowAggStep(db, p, pMWin, csr, 1, p.regArg);
            }
        }

        _ => {
            debug_assert!(op == WINDOW_AGGSTEP);
            csr = p.end.csr;
            reg = p.end.reg;
            if m.regStartRowid != 0 {
                debug_assert!(m.regEndRowid != 0);
                sqlite3VdbeAddOp2(db.v(), OP_AddImm, m.regEndRowid, 1);
            } else {
                windowAggStep(db, p, pMWin, csr, 0, p.regArg);
            }
        }
    }

    if op == p.eDelete {
        let v = db.v();
        sqlite3VdbeAddOp1(v, OP_Delete, csr);
        sqlite3VdbeChangeP5(v, OPFLAG_SAVEPOSITION);
    }

    {
        let v = db.v();
        if jumpOnEof != 0 {
            let a = sqlite3VdbeCurrentAddr(v) + 2;
            sqlite3VdbeAddOp2(v, OP_Next, csr, a);
            ret = sqlite3VdbeAddOp0(v, OP_Goto);
        } else {
            let a = sqlite3VdbeCurrentAddr(v) + 1 + bPeer;
            sqlite3VdbeAddOp2(v, OP_Next, csr, a);
            if bPeer != 0 {
                sqlite3VdbeAddOp2(v, OP_Goto, 0, lblDone);
            }
        }
    }

    if bPeer != 0 {
        let nReg = if m.pOrderBy.nn() {
            db.el(m.pOrderBy).nExpr()
        } else {
            0
        };
        let regTmp = if nReg != 0 {
            sqlite3GetTempRange(db, nReg)
        } else {
            0
        };
        windowReadPeerValues(db, p, csr, regTmp);
        windowIfNewPeer(db, m.pOrderBy, regTmp, reg, addrContinue);
        sqlite3ReleaseTempRange(db, regTmp, nReg);
    }

    if addrNextRange != 0 {
        sqlite3VdbeAddOp2(db.v(), OP_Goto, 0, addrNextRange);
    }
    sqlite3VdbeResolveLabel(db.v(), lblDone);
    ret
}

/*
** Allocate and return a duplicate of the Window object indicated by the
** third argument. Set the Window.pOwner field of the new object to
** pOwner.
*/
/// C: `Window * sqlite3WindowDup(sqlite3 *db, Expr *pOwner, Window *p)`
pub fn sqlite3WindowDup(db: &mut Sqlite3, pOwner: ExprId, p: WindowId) -> WindowId {
    if p.is_null() {
        return WindowId::NULL;
    }
    let src = db.win(p).clone();
    let mut new = Window::default();
    new.zName = src.zName.clone();
    new.zBase = src.zBase.clone();
    new.pFilter = sqlite3ExprDup(db, src.pFilter, 0);
    new.pWFunc = src.pWFunc.clone();
    new.pPartition = sqlite3ExprListDup(db, src.pPartition, 0);
    new.pOrderBy = sqlite3ExprListDup(db, src.pOrderBy, 0);
    new.eFrmType = src.eFrmType;
    new.eEnd = src.eEnd;
    new.eStart = src.eStart;
    new.eExclude = src.eExclude;
    new.regResult = src.regResult;
    new.regAccum = src.regAccum;
    new.iArgCol = src.iArgCol;
    new.iEphCsr = src.iEphCsr;
    new.bExprArgs = src.bExprArgs;
    new.pStart = sqlite3ExprDup(db, src.pStart, 0);
    new.pEnd = sqlite3ExprDup(db, src.pEnd, 0);
    new.pOwner = pOwner;
    new.bImplicitFrame = src.bImplicitFrame;
    db.arena.new_window(new)
}

/*
** Return a copy of the linked list of Window objects passed as the
** second argument.
*/
/// C: `Window * sqlite3WindowListDup(sqlite3 *db, Window *p)`
pub fn sqlite3WindowListDup(db: &mut Sqlite3, p: WindowId) -> WindowId {
    let mut pRet = WindowId::NULL;
    let mut pLast = WindowId::NULL; /* pp = &pLast->pNextWin (or &pRet) */

    let mut pWin = p;
    while pWin.nn() {
        let pNew = sqlite3WindowDup(db, ExprId::NULL, pWin);
        if pLast.is_null() {
            pRet = pNew;
        } else {
            db.winm(pLast).pNextWin = pNew;
        }
        if pNew.is_null() {
            break;
        }
        pLast = pNew;
        pWin = db.win(pWin).pNextWin;
    }

    pRet
}

/*
** Return true if it can be determined at compile time that expression
** pExpr evaluates to a value that, when cast to an integer, is greater
** than zero. False otherwise.
**
** If an OOM error occurs, this function sets the Parse.db.mallocFailed
** flag and returns zero.
*/
fn windowExprGtZero(db: &mut Sqlite3, pExpr: ExprId) -> bool {
    let mut ret = false;
    let mut pVal: Option<Box<Mem>> = None;
    let enc = db.enc;
    sqlite3ValueFromExpr(db, pExpr, enc, SQLITE_AFF_NUMERIC, &mut pVal);
    if let Some(mut v) = pVal {
        if sqlite3_value_int(&mut v) > 0 {
            ret = true;
        }
        sqlite3ValueFree(db, &mut v);
    }
    ret
}

/*
** sqlite3WhereBegin() has already been called for the SELECT statement
** passed as the second argument when this function is invoked. It generates
** code to populate the Window.regResult register for each window function
** and invoke the sub-routine at instruction addrGosub once for each row.
** sqlite3WhereEnd() is always called before returning.
**
** This function handles several different types of window frames, which
** require slightly different processing. The following pseudo code is
** used to implement window frames of the form:
**
**   ROWS BETWEEN <expr1> PRECEDING AND <expr2> FOLLOWING
**
** Other window frame types use variants of the following:
**
**     ... loop started by sqlite3WhereBegin() ...
**       if( new partition ){
**         Gosub flush
**       }
**       Insert new row into eph table.
**
**       if( first row of partition ){
**         // Rewind three cursors, all open on the eph table.
**         Rewind(csrEnd);
**         Rewind(csrStart);
**         Rewind(csrCurrent);
**
**         regEnd = <expr2>          // FOLLOWING expression
**         regStart = <expr1>        // PRECEDING expression
**       }else{
**         // First time this branch is taken, the eph table contains two
**         // rows. The first row in the partition, which all three cursors
**         // currently point to, and the following row.
**         AGGSTEP
**         if( (regEnd--)<=0 ){
**           RETURN_ROW
**           if( (regStart--)<=0 ){
**             AGGINVERSE
**           }
**         }
**       }
**     }
**     flush:
**       AGGSTEP
**       while( 1 ){
**         RETURN ROW
**         if( csrCurrent is EOF ) break;
**         if( (regStart--)<=0 ){
**           AggInverse(csrStart)
**           Next(csrStart)
**         }
**       }
**
** The pseudo-code above uses the following shorthand:
**
**   AGGSTEP:    invoke the aggregate xStep() function for each window function
**               with arguments read from the current row of cursor csrEnd, then
**               step cursor csrEnd forward one row (i.e. sqlite3BtreeNext()).
**
**   RETURN_ROW: return a row to the caller based on the contents of the
**               current row of csrCurrent and the current state of all
**               aggregates. Then step cursor csrCurrent forward one row.
**
**   AGGINVERSE: invoke the aggregate xInverse() function for each window
**               functions with arguments read from the current row of cursor
**               csrStart. Then step csrStart forward one row.
**
** There are two other ROWS window frames that are handled significantly
** differently from the above - "BETWEEN <expr> PRECEDING AND <expr> PRECEDING"
** and "BETWEEN <expr> FOLLOWING AND <expr> FOLLOWING". These are special
** cases because they change the order in which the three cursors (csrStart,
** csrCurrent and csrEnd) iterate through the ephemeral table. Cases that
** use UNBOUNDED or CURRENT ROW are much simpler variations on one of these
** three.
**
**   ROWS BETWEEN <expr1> PRECEDING AND <expr2> PRECEDING
**
**     ... loop started by sqlite3WhereBegin() ...
**       if( new partition ){
**         Gosub flush
**       }
**       Insert new row into eph table.
**       if( first row of partition ){
**         Rewind(csrEnd) ; Rewind(csrStart) ; Rewind(csrCurrent)
**         regEnd = <expr2>
**         regStart = <expr1>
**       }else{
**         if( (regEnd--)<=0 ){
**           AGGSTEP
**         }
**         RETURN_ROW
**         if( (regStart--)<=0 ){
**           AGGINVERSE
**         }
**       }
**     }
**     flush:
**       if( (regEnd--)<=0 ){
**         AGGSTEP
**       }
**       RETURN_ROW
**
**
**   ROWS BETWEEN <expr1> FOLLOWING AND <expr2> FOLLOWING
**
**   ... loop started by sqlite3WhereBegin() ...
**     if( new partition ){
**       Gosub flush
**     }
**     Insert new row into eph table.
**     if( first row of partition ){
**       Rewind(csrEnd) ; Rewind(csrStart) ; Rewind(csrCurrent)
**       regEnd = <expr2>
**       regStart = regEnd - <expr1>
**     }else{
**       AGGSTEP
**       if( (regEnd--)<=0 ){
**         RETURN_ROW
**       }
**       if( (regStart--)<=0 ){
**         AGGINVERSE
**       }
**     }
**   }
**   flush:
**     AGGSTEP
**     while( 1 ){
**       if( (regEnd--)<=0 ){
**         RETURN_ROW
**         if( eof ) break;
**       }
**       if( (regStart--)<=0 ){
**         AGGINVERSE
**         if( eof ) break
**       }
**     }
**     while( !eof csrCurrent ){
**       RETURN_ROW
**     }
**
** For the most part, the patterns above are adapted to support UNBOUNDED by
** assuming that it is equivalent to "infinity PRECEDING/FOLLOWING" and
** CURRENT ROW by assuming that it is equivalent to "0 PRECEDING/FOLLOWING".
** This is optimized of course - branches that will never be taken and
** conditions that are always true are omitted from the VM code. The only
** exceptional case is:
**
**   ROWS BETWEEN <expr1> FOLLOWING AND UNBOUNDED FOLLOWING
**
**     ... loop started by sqlite3WhereBegin() ...
**     if( new partition ){
**       Gosub flush
**     }
**     Insert new row into eph table.
**     if( first row of partition ){
**       Rewind(csrEnd) ; Rewind(csrStart) ; Rewind(csrCurrent)
**       regStart = <expr1>
**     }else{
**       AGGSTEP
**     }
**   }
**   flush:
**     AGGSTEP
**     while( 1 ){
**       if( (regStart--)<=0 ){
**         AGGINVERSE
**         if( eof ) break
**       }
**       RETURN_ROW
**     }
**     while( !eof csrCurrent ){
**       RETURN_ROW
**     }
**
** Also requiring special handling are the cases:
**
**   ROWS BETWEEN <expr1> PRECEDING AND <expr2> PRECEDING
**   ROWS BETWEEN <expr1> FOLLOWING AND <expr2> FOLLOWING
**
** when (expr1 < expr2). This is detected at runtime, not by this function.
** To handle this case, the pseudo-code programs depicted above are modified
** slightly to be:
**
**     ... loop started by sqlite3WhereBegin() ...
**     if( new partition ){
**       Gosub flush
**     }
**     Insert new row into eph table.
**     if( first row of partition ){
**       Rewind(csrEnd) ; Rewind(csrStart) ; Rewind(csrCurrent)
**       regEnd = <expr2>
**       regStart = <expr1>
**       if( regEnd < regStart ){
**         RETURN_ROW
**         delete eph table contents
**         continue
**       }
**     ...
**
** The new "continue" statement in the above jumps to the next iteration
** of the outer loop - the one started by sqlite3WhereBegin().
**
** The various GROUPS cases are implemented using the same patterns as
** ROWS. The VM code is modified slightly so that:
**
**   1. The else branch in the main loop is only taken if the row just
**      added to the ephemeral table is the start of a new group. In
**      other words, it becomes:
**
**         ... loop started by sqlite3WhereBegin() ...
**         if( new partition ){
**           Gosub flush
**         }
**         Insert new row into eph table.
**         if( first row of partition ){
**           Rewind(csrEnd) ; Rewind(csrStart) ; Rewind(csrCurrent)
**           regEnd = <expr2>
**           regStart = <expr1>
**         }else if( new group ){
**           ...
**         }
**       }
**
**   2. Instead of processing a single row, each RETURN_ROW, AGGSTEP or
**      AGGINVERSE step processes the current row of the relevant cursor and
**      all subsequent rows belonging to the same group.
**
** RANGE window frames are a little different again. As for GROUPS, the
** main loop runs once per group only. And RETURN_ROW, AGGSTEP and AGGINVERSE
** deal in groups instead of rows. As for ROWS and GROUPS, there are three
** basic cases:
**
**   RANGE BETWEEN <expr1> PRECEDING AND <expr2> FOLLOWING
**
**     ... loop started by sqlite3WhereBegin() ...
**       if( new partition ){
**         Gosub flush
**       }
**       Insert new row into eph table.
**       if( first row of partition ){
**         Rewind(csrEnd) ; Rewind(csrStart) ; Rewind(csrCurrent)
**         regEnd = <expr2>
**         regStart = <expr1>
**       }else{
**         AGGSTEP
**         while( (csrCurrent.key + regEnd) < csrEnd.key ){
**           RETURN_ROW
**           while( csrStart.key + regStart) < csrCurrent.key ){
**             AGGINVERSE
**           }
**         }
**       }
**     }
**     flush:
**       AGGSTEP
**       while( 1 ){
**         RETURN ROW
**         if( csrCurrent is EOF ) break;
**           while( csrStart.key + regStart) < csrCurrent.key ){
**             AGGINVERSE
**           }
**         }
**       }
**
** In the above notation, "csr.key" means the current value of the ORDER BY
** expression (there is only ever 1 for a RANGE that uses an <expr> FOLLOWING
** or <expr PRECEDING) read from cursor csr.
**
**   RANGE BETWEEN <expr1> PRECEDING AND <expr2> PRECEDING
**
**     ... loop started by sqlite3WhereBegin() ...
**       if( new partition ){
**         Gosub flush
**       }
**       Insert new row into eph table.
**       if( first row of partition ){
**         Rewind(csrEnd) ; Rewind(csrStart) ; Rewind(csrCurrent)
**         regEnd = <expr2>
**         regStart = <expr1>
**       }else{
**         while( (csrEnd.key + regEnd) <= csrCurrent.key ){
**           AGGSTEP
**         }
**         while( (csrStart.key + regStart) < csrCurrent.key ){
**           AGGINVERSE
**         }
**         RETURN_ROW
**       }
**     }
**     flush:
**       while( (csrEnd.key + regEnd) <= csrCurrent.key ){
**         AGGSTEP
**       }
**       while( (csrStart.key + regStart) < csrCurrent.key ){
**         AGGINVERSE
**       }
**       RETURN_ROW
**
**   RANGE BETWEEN <expr1> FOLLOWING AND <expr2> FOLLOWING
**
**     ... loop started by sqlite3WhereBegin() ...
**       if( new partition ){
**         Gosub flush
**       }
**       Insert new row into eph table.
**       if( first row of partition ){
**         Rewind(csrEnd) ; Rewind(csrStart) ; Rewind(csrCurrent)
**         regEnd = <expr2>
**         regStart = <expr1>
**       }else{
**         AGGSTEP
**         while( (csrCurrent.key + regEnd) < csrEnd.key ){
**           while( (csrCurrent.key + regStart) > csrStart.key ){
**             AGGINVERSE
**           }
**           RETURN_ROW
**         }
**       }
**     }
**     flush:
**       AGGSTEP
**       while( 1 ){
**         while( (csrCurrent.key + regStart) > csrStart.key ){
**           AGGINVERSE
**           if( eof ) break "while( 1 )" loop.
**         }
**         RETURN_ROW
**       }
**       while( !eof csrCurrent ){
**         RETURN_ROW
**       }
**
** The text above leaves out many details. Refer to the code and comments
** below for a more complete picture.
*/
/// C: `void sqlite3WindowCodeStep( Parse *pParse, Select *p, WhereInfo *pWInfo, int regGosub, int addrGosub )`
pub fn sqlite3WindowCodeStep(
    db: &mut Sqlite3,
    p: SelectId,
    pWInfo: &mut crate::where_::WhereInfo,
    regGosub: i32,
    addrGosub: i32,
) {
    let pMWin = db.sel(p).pWin;
    let m = db.win(pMWin).clone();
    let pOrderBy = m.pOrderBy;
    sqlite3GetVdbe(db);
    let (csrInput, nInput) = {
        let pSrc = db.sel(p).pSrc;
        let it = &db.src(pSrc).a[0];
        (
            it.iCursor, /* Cursor of sub-select */
            it.pSTab
                .as_ref()
                .map(|t| t.borrow().nCol as i32)
                .unwrap_or(0), /* Number of cols returned by sub */
        )
    };
    let mut addrGosubFlush = 0; /* Address of OP_Gosub to flush: */
    let mut addrInteger = 0; /* Address of OP_Integer */
    let mut regNewPeer = 0; /* Peer values for new row (part of regNew) */
    let mut regPeer = 0; /* Peer values for current row */
    let mut regFlushPart = 0; /* Register for "Gosub flush_partition" */
    let mut regStart = 0; /* Value of <expr> PRECEDING */
    let mut regEnd = 0; /* Value of <expr> FOLLOWING */

    debug_assert!(
        m.eStart == TK_PRECEDING
            || m.eStart == TK_CURRENT
            || m.eStart == TK_FOLLOWING
            || m.eStart == TK_UNBOUNDED
    );
    debug_assert!(
        m.eEnd == TK_FOLLOWING
            || m.eEnd == TK_CURRENT
            || m.eEnd == TK_UNBOUNDED
            || m.eEnd == TK_PRECEDING
    );
    debug_assert!(
        m.eExclude == 0
            || m.eExclude == TK_CURRENT
            || m.eExclude == TK_GROUP
            || m.eExclude == TK_TIES
            || m.eExclude == TK_NO
    );

    let lblWhereEnd = sqlite3VdbeMakeLabel(db); /* Label just before sqlite3WhereEnd() code */

    /* Fill in the context object */
    let mut s = WindowCodeArg::default();
    s.pMWin = pMWin;
    s.regGosub = regGosub;
    s.addrGosub = addrGosub;
    s.current.csr = m.iEphCsr;
    let csrWrite = s.current.csr + 1; /* Cursor used to write to eph. table */
    s.start.csr = s.current.csr + 2;
    s.end.csr = s.current.csr + 3;

    /* Figure out when rows may be deleted from the ephemeral table. There
     ** are four options - they may never be deleted (eDelete==0), they may
     ** be deleted as soon as they are no longer part of the window frame
     ** (eDelete==WINDOW_AGGINVERSE), they may be deleted as after the row
     ** has been returned to the caller (WINDOW_RETURN_ROW), or they may
     ** be deleted after they enter the frame (WINDOW_AGGSTEP). */
    match m.eStart {
        TK_FOLLOWING => {
            if m.eFrmType != TK_RANGE && windowExprGtZero(db, m.pStart) {
                s.eDelete = WINDOW_RETURN_ROW;
            }
        }
        TK_UNBOUNDED => {
            if !windowCacheFrame(db, pMWin) {
                if m.eEnd == TK_PRECEDING {
                    if m.eFrmType != TK_RANGE && windowExprGtZero(db, m.pEnd) {
                        s.eDelete = WINDOW_AGGSTEP;
                    }
                } else {
                    s.eDelete = WINDOW_RETURN_ROW;
                }
            }
        }
        _ => {
            s.eDelete = WINDOW_AGGINVERSE;
        }
    }

    /* Allocate registers for the array of values from the sub-query, the
     ** same values in record form, and the rowid used to insert said record
     ** into the ephemeral table.  */
    let regNew = db.ppr().nMem + 1; /* Array of registers holding new input row */
    db.pp().nMem += nInput;
    let regRecord = {
        let pp = db.pp();
        pp.nMem += 1;
        pp.nMem
    }; /* regNew array in record form */
    s.regRowid = {
        let pp = db.pp();
        pp.nMem += 1;
        pp.nMem
    };

    /* If the window frame contains an "<expr> PRECEDING" or "<expr> FOLLOWING"
     ** clause, allocate registers to store the results of evaluating each
     ** <expr>.  */
    if m.eStart == TK_PRECEDING || m.eStart == TK_FOLLOWING {
        let pp = db.pp();
        pp.nMem += 1;
        regStart = pp.nMem;
    }
    if m.eEnd == TK_PRECEDING || m.eEnd == TK_FOLLOWING {
        let pp = db.pp();
        pp.nMem += 1;
        regEnd = pp.nMem;
    }

    /* If this is not a "ROWS BETWEEN ..." frame, then allocate arrays of
     ** registers to store copies of the ORDER BY expressions (peer values)
     ** for the main loop, and for each cursor (start, current and end). */
    if m.eFrmType != TK_ROWS {
        let nPeer = if pOrderBy.nn() {
            db.el(pOrderBy).nExpr()
        } else {
            0
        };
        regNewPeer = regNew + m.nBufferCol;
        if m.pPartition.nn() {
            regNewPeer += db.el(m.pPartition).nExpr();
        }
        let pp = db.pp();
        regPeer = pp.nMem + 1;
        pp.nMem += nPeer;
        s.start.reg = pp.nMem + 1;
        pp.nMem += nPeer;
        s.current.reg = pp.nMem + 1;
        pp.nMem += nPeer;
        s.end.reg = pp.nMem + 1;
        pp.nMem += nPeer;
    }

    /* Load the column values for the row returned by the sub-select
     ** into an array of registers starting at regNew. Assemble them into
     ** a record in register regRecord. */
    {
        let v = db.v();
        for iInput in 0..nInput {
            sqlite3VdbeAddOp3(v, OP_Column, csrInput, iInput, regNew + iInput);
        }
        sqlite3VdbeAddOp3(v, OP_MakeRecord, regNew, nInput, regRecord);
    }

    /* An input row has just been read into an array of registers starting
     ** at regNew. If the window has a PARTITION clause, this block generates
     ** VM code to check if the input row is the start of a new partition.
     ** If so, it does an OP_Gosub to an address to be filled in later. The
     ** address of the OP_Gosub is stored in local variable addrGosubFlush. */
    if m.pPartition.nn() {
        let pPart = m.pPartition;
        let nPart = db.el(pPart).nExpr();
        let regNewPart = regNew + m.nBufferCol;
        let pKeyInfo = sqlite3KeyInfoFromExprList(db, pPart, 0, 0);

        regFlushPart = {
            let pp = db.pp();
            pp.nMem += 1;
            pp.nMem
        };
        let regPart = db.win(pMWin).regPart;
        let v = db.v();
        let addr = sqlite3VdbeAddOp3(v, OP_Compare, regNewPart, regPart, nPart);
        sqlite3VdbeAppendP4(v, keyinfo_p4(pKeyInfo), P4_KEYINFO as i32);
        sqlite3VdbeAddOp3(v, OP_Jump, addr + 2, addr + 4, addr + 2);
        addrGosubFlush = sqlite3VdbeAddOp1(v, OP_Gosub, regFlushPart);
        sqlite3VdbeAddOp3(v, OP_Copy, regNewPart, regPart, nPart - 1);
    }

    /* Insert the new row into the ephemeral table */
    let regOne = db.win(pMWin).regOne;
    let addrNe; /* Address of OP_Ne */
    {
        let v = db.v();
        sqlite3VdbeAddOp2(v, OP_NewRowid, csrWrite, s.regRowid);
        sqlite3VdbeAddOp3(v, OP_Insert, csrWrite, regRecord, s.regRowid);
        addrNe = sqlite3VdbeAddOp3(v, OP_Ne, regOne, 0, s.regRowid);
    }

    /* This block is run for the first row of each partition */
    s.regArg = windowInitAccum(db, pMWin);

    if regStart != 0 {
        sqlite3ExprCode(db, m.pStart, regStart);
        windowCheckValue(
            db,
            regStart,
            if m.eFrmType == TK_RANGE {
                WINDOW_STARTING_NUM
            } else {
                WINDOW_STARTING_INT
            },
        );
    }
    if regEnd != 0 {
        sqlite3ExprCode(db, m.pEnd, regEnd);
        windowCheckValue(
            db,
            regEnd,
            if m.eFrmType == TK_RANGE {
                WINDOW_ENDING_NUM
            } else {
                WINDOW_ENDING_INT
            },
        );
    }

    if m.eFrmType != TK_RANGE && m.eStart == m.eEnd && regStart != 0 {
        let op = if m.eStart == TK_FOLLOWING {
            OP_Ge
        } else {
            OP_Le
        };
        let addrGe = sqlite3VdbeAddOp3(db.v(), op, regStart, 0, regEnd);
        windowAggFinal(db, &s, 0);
        sqlite3VdbeAddOp1(db.v(), OP_Rewind, s.current.csr);
        windowReturnOneRow(db, &s);
        let v = db.v();
        sqlite3VdbeAddOp1(v, OP_ResetSorter, s.current.csr);
        sqlite3VdbeAddOp2(v, OP_Goto, 0, lblWhereEnd);
        sqlite3VdbeJumpHere(v, addrGe);
    }
    if m.eStart == TK_FOLLOWING && m.eFrmType != TK_RANGE && regEnd != 0 {
        debug_assert!(m.eEnd == TK_FOLLOWING);
        sqlite3VdbeAddOp3(db.v(), OP_Subtract, regStart, regEnd, regStart);
    }

    {
        let v = db.v();
        if m.eStart != TK_UNBOUNDED {
            sqlite3VdbeAddOp1(v, OP_Rewind, s.start.csr);
        }
        sqlite3VdbeAddOp1(v, OP_Rewind, s.current.csr);
        sqlite3VdbeAddOp1(v, OP_Rewind, s.end.csr);
    }
    if regPeer != 0 && pOrderBy.nn() {
        let n = db.el(pOrderBy).nExpr();
        let v = db.v();
        sqlite3VdbeAddOp3(v, OP_Copy, regNewPeer, regPeer, n - 1);
        sqlite3VdbeAddOp3(v, OP_Copy, regPeer, s.start.reg, n - 1);
        sqlite3VdbeAddOp3(v, OP_Copy, regPeer, s.current.reg, n - 1);
        sqlite3VdbeAddOp3(v, OP_Copy, regPeer, s.end.reg, n - 1);
    }

    {
        let v = db.v();
        sqlite3VdbeAddOp2(v, OP_Goto, 0, lblWhereEnd);
        sqlite3VdbeJumpHere(v, addrNe);
    }

    /* Beginning of the block executed for the second and subsequent rows. */
    if regPeer != 0 {
        windowIfNewPeer(db, pOrderBy, regNewPeer, regPeer, lblWhereEnd);
    }
    if m.eStart == TK_FOLLOWING {
        windowCodeOp(db, &s, WINDOW_AGGSTEP, 0, 0);
        if m.eEnd != TK_UNBOUNDED {
            if m.eFrmType == TK_RANGE {
                let lbl = sqlite3VdbeMakeLabel(db);
                let addrNext = sqlite3VdbeCurrentAddr(db.v());
                windowCodeRangeTest(db, &s, OP_Ge, s.current.csr, regEnd, s.end.csr, lbl);
                windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 0);
                windowCodeOp(db, &s, WINDOW_RETURN_ROW, 0, 0);
                let v = db.v();
                sqlite3VdbeAddOp2(v, OP_Goto, 0, addrNext);
                sqlite3VdbeResolveLabel(v, lbl);
            } else {
                windowCodeOp(db, &s, WINDOW_RETURN_ROW, regEnd, 0);
                windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 0);
            }
        }
    } else if m.eEnd == TK_PRECEDING {
        let bRPS = m.eStart == TK_PRECEDING && m.eFrmType == TK_RANGE;
        windowCodeOp(db, &s, WINDOW_AGGSTEP, regEnd, 0);
        if bRPS {
            windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 0);
        }
        windowCodeOp(db, &s, WINDOW_RETURN_ROW, 0, 0);
        if !bRPS {
            windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 0);
        }
    } else {
        let mut addr = 0;
        windowCodeOp(db, &s, WINDOW_AGGSTEP, 0, 0);
        if m.eEnd != TK_UNBOUNDED {
            if m.eFrmType == TK_RANGE {
                let mut lbl = 0;
                addr = sqlite3VdbeCurrentAddr(db.v());
                if regEnd != 0 {
                    lbl = sqlite3VdbeMakeLabel(db);
                    windowCodeRangeTest(db, &s, OP_Ge, s.current.csr, regEnd, s.end.csr, lbl);
                }
                windowCodeOp(db, &s, WINDOW_RETURN_ROW, 0, 0);
                windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 0);
                if regEnd != 0 {
                    let v = db.v();
                    sqlite3VdbeAddOp2(v, OP_Goto, 0, addr);
                    sqlite3VdbeResolveLabel(v, lbl);
                }
            } else {
                if regEnd != 0 {
                    addr = sqlite3VdbeAddOp3(db.v(), OP_IfPos, regEnd, 0, 1);
                }
                windowCodeOp(db, &s, WINDOW_RETURN_ROW, 0, 0);
                windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 0);
                if regEnd != 0 {
                    sqlite3VdbeJumpHere(db.v(), addr);
                }
            }
        }
    }

    /* End of the main input loop */
    sqlite3VdbeResolveLabel(db.v(), lblWhereEnd);
    sqlite3WhereEnd(db, pWInfo);

    /* Fall through */
    if m.pPartition.nn() {
        let v = db.v();
        addrInteger = sqlite3VdbeAddOp2(v, OP_Integer, 0, regFlushPart);
        sqlite3VdbeJumpHere(v, addrGosubFlush);
    }

    s.regRowid = 0;
    let addrEmpty = sqlite3VdbeAddOp1(db.v(), OP_Rewind, csrWrite); /* Address of OP_Rewind in flush: */
    if m.eEnd == TK_PRECEDING {
        let bRPS = m.eStart == TK_PRECEDING && m.eFrmType == TK_RANGE;
        windowCodeOp(db, &s, WINDOW_AGGSTEP, regEnd, 0);
        if bRPS {
            windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 0);
        }
        windowCodeOp(db, &s, WINDOW_RETURN_ROW, 0, 0);
    } else if m.eStart == TK_FOLLOWING {
        let mut addrStart;
        let addrBreak1;
        let addrBreak2;
        windowCodeOp(db, &s, WINDOW_AGGSTEP, 0, 0);
        if m.eFrmType == TK_RANGE {
            addrStart = sqlite3VdbeCurrentAddr(db.v());
            addrBreak2 = windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 1);
            addrBreak1 = windowCodeOp(db, &s, WINDOW_RETURN_ROW, 0, 1);
        } else if m.eEnd == TK_UNBOUNDED {
            addrStart = sqlite3VdbeCurrentAddr(db.v());
            addrBreak1 = windowCodeOp(db, &s, WINDOW_RETURN_ROW, regStart, 1);
            addrBreak2 = windowCodeOp(db, &s, WINDOW_AGGINVERSE, 0, 1);
        } else {
            debug_assert!(m.eEnd == TK_FOLLOWING);
            /* assert( regStart>=0 );
             ** regEnd = regEnd - regStart;
             ** regStart = 0;   */
            {
                let v = db.v();
                sqlite3VdbeAddOp3(v, OP_Subtract, regStart, regEnd, regEnd);
                sqlite3VdbeAddOp2(v, OP_Integer, 0, regStart);
                addrStart = sqlite3VdbeCurrentAddr(v);
            }
            addrBreak1 = windowCodeOp(db, &s, WINDOW_RETURN_ROW, regEnd, 1);
            addrBreak2 = windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 1);
        }
        {
            let v = db.v();
            sqlite3VdbeAddOp2(v, OP_Goto, 0, addrStart);
            sqlite3VdbeJumpHere(v, addrBreak2);
            addrStart = sqlite3VdbeCurrentAddr(v);
        }
        let addrBreak3 = windowCodeOp(db, &s, WINDOW_RETURN_ROW, 0, 1);
        let v = db.v();
        sqlite3VdbeAddOp2(v, OP_Goto, 0, addrStart);
        sqlite3VdbeJumpHere(v, addrBreak1);
        sqlite3VdbeJumpHere(v, addrBreak3);
    } else {
        windowCodeOp(db, &s, WINDOW_AGGSTEP, 0, 0);
        let addrStart = sqlite3VdbeCurrentAddr(db.v());
        let addrBreak = windowCodeOp(db, &s, WINDOW_RETURN_ROW, 0, 1);
        windowCodeOp(db, &s, WINDOW_AGGINVERSE, regStart, 0);
        let v = db.v();
        sqlite3VdbeAddOp2(v, OP_Goto, 0, addrStart);
        sqlite3VdbeJumpHere(v, addrBreak);
    }
    sqlite3VdbeJumpHere(db.v(), addrEmpty);

    sqlite3VdbeAddOp1(db.v(), OP_ResetSorter, s.current.csr);
    if m.pPartition.nn() {
        let (regStartRowid, regEndRowid) = {
            let w = db.win(pMWin);
            (w.regStartRowid, w.regEndRowid)
        };
        let v = db.v();
        if regStartRowid != 0 {
            sqlite3VdbeAddOp2(v, OP_Integer, 1, regStartRowid);
            sqlite3VdbeAddOp2(v, OP_Integer, 0, regEndRowid);
        }
        let a = sqlite3VdbeCurrentAddr(v);
        sqlite3VdbeChangeP1(v, addrInteger, a);
        sqlite3VdbeAddOp1(v, OP_Return, regFlushPart);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn window_function_table() {
        let defs = sqlite3WindowFunctionDefs();
        let names: Vec<(&[u8], i16)> = defs.iter().map(|d| (&d.zName[..], d.nArg)).collect();
        assert_eq!(
            names,
            vec![
                (&b"row_number"[..], 0),
                (&b"dense_rank"[..], 0),
                (&b"rank"[..], 0),
                (&b"percent_rank"[..], 0),
                (&b"cume_dist"[..], 0),
                (&b"ntile"[..], 1),
                (&b"last_value"[..], 1),
                (&b"nth_value"[..], 2),
                (&b"first_value"[..], 1),
                (&b"lead"[..], 1),
                (&b"lead"[..], 2),
                (&b"lead"[..], 3),
                (&b"lag"[..], 1),
                (&b"lag"[..], 2),
                (&b"lag"[..], 3),
            ]
        );
        for d in &defs {
            assert_eq!(
                d.funcFlags,
                SQLITE_FUNC_BUILTIN | SQLITE_UTF8 as u32 | SQLITE_FUNC_WINDOW
            );
            assert!(
                d.xSFunc.is_some()
                    && d.xFinalize.is_some()
                    && d.xValue.is_some()
                    && d.xInverse.is_some()
            );
            assert!(isBuiltinWin(d, &d.zName));
        }
    }
}
