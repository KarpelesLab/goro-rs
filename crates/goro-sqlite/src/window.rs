/*
** Implementation of built-in window function row_number(). Assumes that the
** window frame has been coerced to:
**
**   ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
*/
fn row_numberStepFunc(pCtx: &mut Context<'_>, _apArg: &mut [Mem]) {
    if let Some(p) = sqlite3_aggregate_context::<i64>(pCtx, 8) {
        *p += 1;
    }
}
fn row_numberValueFunc(pCtx: &mut Context<'_>) {
    let v = sqlite3_aggregate_context::<i64>(pCtx, 8)
        .map(|p| *p)
        .unwrap_or(0);
    sqlite3_result_int64(pCtx, v);
}

/*
** Context object type used by rank(), dense_rank(), percent_rank() and
** cume_dist().
*/
#[derive(Default)]
struct CallCount {
    nValue: i64,
    nStep: i64,
    nTotal: i64,
}
const SZ_CALLCOUNT: i32 = 24;

/*
** Implementation of built-in window function dense_rank(). Assumes that
** the window frame has been set to:
**
**   RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
*/
fn dense_rankStepFunc(pCtx: &mut Context<'_>, _apArg: &mut [Mem]) {
    if let Some(p) = sqlite3_aggregate_context::<CallCount>(pCtx, SZ_CALLCOUNT) {
        p.nStep = 1;
    }
}
fn dense_rankValueFunc(pCtx: &mut Context<'_>) {
    let v = match sqlite3_aggregate_context::<CallCount>(pCtx, SZ_CALLCOUNT) {
        Some(p) => {
            if p.nStep != 0 {
                p.nValue += 1;
                p.nStep = 0;
            }
            p.nValue
        }
        None => return,
    };
    sqlite3_result_int64(pCtx, v);
}

/*
** Implementation of built-in window function nth_value(). This
** implementation is used in "slow mode" only - when the EXCLUDE clause
** is not set to the default value "NO OTHERS".
*/
#[derive(Default)]
struct NthValueCtx {
    nStep: i64,
    pValue: Option<Box<Mem>>,
}
const SZ_NTHVALUECTX: i32 = 16;

fn nth_valueStepFunc(pCtx: &mut Context<'_>, apArg: &mut [Mem]) {
    if sqlite3_aggregate_context::<NthValueCtx>(pCtx, SZ_NTHVALUECTX).is_none() {
        return;
    }
    let iVal: i64;
    match sqlite3_value_numeric_type(pCtx.db, &mut apArg[1]) {
        SQLITE_INTEGER => {
            iVal = sqlite3_value_int64(&mut apArg[1]);
        }
        SQLITE_FLOAT => {
            let fVal = sqlite3_value_double(&mut apArg[1]);
            if sqlite3RealToI64(fVal) as f64 != fVal {
                return nth_value_error(pCtx);
            }
            iVal = fVal as i64;
        }
        _ => return nth_value_error(pCtx),
    }
    if iVal <= 0 {
        return nth_value_error(pCtx);
    }

    let take = {
        let p = sqlite3_aggregate_context::<NthValueCtx>(pCtx, SZ_NTHVALUECTX).unwrap();
        p.nStep += 1;
        iVal == p.nStep
    };
    if take {
        let v = sqlite3_value_dup(&apArg[0]);
        let ok = v.is_some();
        sqlite3_aggregate_context::<NthValueCtx>(pCtx, SZ_NTHVALUECTX)
            .unwrap()
            .pValue = v;
        if !ok {
            sqlite3_result_error_nomem(pCtx);
        }
    }
}
fn nth_value_error(pCtx: &mut Context<'_>) {
    sqlite3_result_error(
        pCtx,
        Some(b"second argument to nth_value must be a positive integer"),
        -1,
    );
}
fn nth_valueFinalizeFunc(pCtx: &mut Context<'_>) {
    let v = match sqlite3_aggregate_context::<NthValueCtx>(pCtx, 0) {
        Some(p) => p.pValue.take(),
        None => None,
    };
    if let Some(mut v) = v {
        sqlite3_result_value(pCtx, &mut v);
        sqlite3_value_free(&mut v);
    }
}

fn first_valueStepFunc(pCtx: &mut Context<'_>, apArg: &mut [Mem]) {
    let need = match sqlite3_aggregate_context::<NthValueCtx>(pCtx, SZ_NTHVALUECTX) {
        Some(p) => p.pValue.is_none(),
        None => false,
    };
    if need {
        let v = sqlite3_value_dup(&apArg[0]);
        let ok = v.is_some();
        sqlite3_aggregate_context::<NthValueCtx>(pCtx, SZ_NTHVALUECTX)
            .unwrap()
            .pValue = v;
        if !ok {
            sqlite3_result_error_nomem(pCtx);
        }
    }
}
fn first_valueFinalizeFunc(pCtx: &mut Context<'_>) {
    let v = match sqlite3_aggregate_context::<NthValueCtx>(pCtx, SZ_NTHVALUECTX) {
        Some(p) => p.pValue.take(),
        None => None,
    };
    if let Some(mut v) = v {
        sqlite3_result_value(pCtx, &mut v);
        sqlite3_value_free(&mut v);
    }
}

/*
** Implementation of built-in window function rank(). Assumes that
** the window frame has been set to:
**
**   RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
*/
fn rankStepFunc(pCtx: &mut Context<'_>, _apArg: &mut [Mem]) {
    if let Some(p) = sqlite3_aggregate_context::<CallCount>(pCtx, SZ_CALLCOUNT) {
        p.nStep += 1;
        if p.nValue == 0 {
            p.nValue = p.nStep;
        }
    }
}
fn rankValueFunc(pCtx: &mut Context<'_>) {
    let v = match sqlite3_aggregate_context::<CallCount>(pCtx, SZ_CALLCOUNT) {
        Some(p) => {
            let v = p.nValue;
            p.nValue = 0;
            v
        }
        None => return,
    };
    sqlite3_result_int64(pCtx, v);
}

/*
** Implementation of built-in window function percent_rank(). Assumes that
** the window frame has been set to:
**
**   GROUPS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING
*/
fn percent_rankStepFunc(pCtx: &mut Context<'_>, apArg: &mut [Mem]) {
    debug_assert!(apArg.is_empty());
    if let Some(p) = sqlite3_aggregate_context::<CallCount>(pCtx, SZ_CALLCOUNT) {
        p.nTotal += 1;
    }
}
fn percent_rankInvFunc(pCtx: &mut Context<'_>, apArg: &mut [Mem]) {
    debug_assert!(apArg.is_empty());
    let p = sqlite3_aggregate_context::<CallCount>(pCtx, SZ_CALLCOUNT);
    debug_assert!(p.is_some());
    if let Some(p) = p {
        p.nStep += 1;
    }
}
fn percent_rankValueFunc(pCtx: &mut Context<'_>) {
    let r = match sqlite3_aggregate_context::<CallCount>(pCtx, SZ_CALLCOUNT) {
        Some(p) => {
            p.nValue = p.nStep;
            if p.nTotal > 1 {
                p.nValue as f64 / (p.nTotal - 1) as f64
            } else {
                0.0
            }
        }
        None => return,
    };
    sqlite3_result_double(pCtx, r);
}
use percent_rankValueFunc as percent_rankFinalizeFunc;

/*
** Implementation of built-in window function cume_dist(). Assumes that
** the window frame has been set to:
**
**   GROUPS BETWEEN 1 FOLLOWING AND UNBOUNDED FOLLOWING
*/
fn cume_distStepFunc(pCtx: &mut Context<'_>, apArg: &mut [Mem]) {
    debug_assert!(apArg.is_empty());
    if let Some(p) = sqlite3_aggregate_context::<CallCount>(pCtx, SZ_CALLCOUNT) {
        p.nTotal += 1;
    }
}
fn cume_distInvFunc(pCtx: &mut Context<'_>, apArg: &mut [Mem]) {
    debug_assert!(apArg.is_empty());
    let p = sqlite3_aggregate_context::<CallCount>(pCtx, SZ_CALLCOUNT);
    debug_assert!(p.is_some());
    if let Some(p) = p {
        p.nStep += 1;
    }
}
fn cume_distValueFunc(pCtx: &mut Context<'_>) {
    let r = match sqlite3_aggregate_context::<CallCount>(pCtx, 0) {
        Some(p) => p.nStep as f64 / p.nTotal as f64,
        None => return,
    };
    sqlite3_result_double(pCtx, r);
}
use cume_distValueFunc as cume_distFinalizeFunc;

/*
** Context object for ntile() window function.
*/
#[derive(Default)]
struct NtileCtx {
    nTotal: i64, /* Total rows in partition */
    nParam: i64, /* Parameter passed to ntile(N) */
    iRow: i64,   /* Current row */
}
const SZ_NTILECTX: i32 = 24;

/*
** Implementation of ntile(). This assumes that the window frame has
** been coerced to:
**
**   ROWS CURRENT ROW AND UNBOUNDED FOLLOWING
*/
fn ntileStepFunc(pCtx: &mut Context<'_>, apArg: &mut [Mem]) {
    debug_assert!(apArg.len() == 1);
    let first = match sqlite3_aggregate_context::<NtileCtx>(pCtx, SZ_NTILECTX) {
        Some(p) => p.nTotal == 0,
        None => return,
    };
    if first {
        let nParam = sqlite3_value_int64(&mut apArg[0]);
        sqlite3_aggregate_context::<NtileCtx>(pCtx, SZ_NTILECTX)
            .unwrap()
            .nParam = nParam;
        if nParam <= 0 {
            sqlite3_result_error(
                pCtx,
                Some(b"argument of ntile must be a positive integer"),
                -1,
            );
        }
    }
    sqlite3_aggregate_context::<NtileCtx>(pCtx, SZ_NTILECTX)
        .unwrap()
        .nTotal += 1;
}
fn ntileInvFunc(pCtx: &mut Context<'_>, apArg: &mut [Mem]) {
    debug_assert!(apArg.len() == 1);
    let p = sqlite3_aggregate_context::<NtileCtx>(pCtx, SZ_NTILECTX);
    debug_assert!(p.is_some());
    if let Some(p) = p {
        p.iRow += 1;
    }
}
fn ntileValueFunc(pCtx: &mut Context<'_>) {
    let v = match sqlite3_aggregate_context::<NtileCtx>(pCtx, SZ_NTILECTX) {
        Some(p) if p.nParam > 0 => {
            let nSize = (p.nTotal / p.nParam) as i32 as i64;
            if nSize == 0 {
                p.iRow + 1
            } else {
                let nLarge = p.nTotal - p.nParam * nSize;
                let iSmall = nLarge * (nSize + 1);
                let iRow = p.iRow;

                debug_assert!((nLarge * (nSize + 1) + (p.nParam - nLarge) * nSize) == p.nTotal);

                if iRow < iSmall {
                    1 + iRow / (nSize + 1)
                } else {
                    1 + nLarge + (iRow - iSmall) / nSize
                }
            }
        }
        _ => return,
    };
    sqlite3_result_int64(pCtx, v);
}
use ntileValueFunc as ntileFinalizeFunc;

/*
** Context object for last_value() window function.
*/
#[derive(Default)]
struct LastValueCtx {
    pVal: Option<Box<Mem>>,
    nVal: i32,
}
const SZ_LASTVALUECTX: i32 = 16;

/*
** Implementation of last_value().
*/
fn last_valueStepFunc(pCtx: &mut Context<'_>, apArg: &mut [Mem]) {
    if sqlite3_aggregate_context::<LastValueCtx>(pCtx, SZ_LASTVALUECTX).is_none() {
        return;
    }
    let v = sqlite3_value_dup(&apArg[0]);
    let ok = v.is_some();
    {
        let p = sqlite3_aggregate_context::<LastValueCtx>(pCtx, SZ_LASTVALUECTX).unwrap();
        if let Some(mut old) = p.pVal.take() {
            sqlite3_value_free(&mut old);
        }
        p.pVal = v;
        if ok {
            p.nVal += 1;
        }
    }
    if !ok {
        sqlite3_result_error_nomem(pCtx);
    }
}
fn last_valueInvFunc(pCtx: &mut Context<'_>, _apArg: &mut [Mem]) {
    if let Some(p) = sqlite3_aggregate_context::<LastValueCtx>(pCtx, SZ_LASTVALUECTX) {
        p.nVal -= 1;
        if p.nVal == 0 {
            if let Some(mut old) = p.pVal.take() {
                sqlite3_value_free(&mut old);
            }
        }
    }
}
fn last_valueValueFunc(pCtx: &mut Context<'_>) {
    let v = match sqlite3_aggregate_context::<LastValueCtx>(pCtx, 0) {
        Some(p) => p.pVal.as_ref().map(|m| (**m).clone()),
        None => None,
    };
    if let Some(mut v) = v {
        sqlite3_result_value(pCtx, &mut v);
    }
}
fn last_valueFinalizeFunc(pCtx: &mut Context<'_>) {
    let v = match sqlite3_aggregate_context::<LastValueCtx>(pCtx, SZ_LASTVALUECTX) {
        Some(p) => p.pVal.take(),
        None => None,
    };
    if let Some(mut v) = v {
        sqlite3_result_value(pCtx, &mut v);
        sqlite3_value_free(&mut v);
    }
}

/*
** Static names for the built-in window function names.  These static
** names are used, rather than string literals, so that FuncDef objects
** can be associated with a particular window function by direct
** comparison of the zName pointer.  Example:
**
**       if( pFuncDef->zName==row_valueName ){ ... }
*/
const row_numberName: &[u8] = b"row_number";
const dense_rankName: &[u8] = b"dense_rank";
const rankName: &[u8] = b"rank";
const percent_rankName: &[u8] = b"percent_rank";
const cume_distName: &[u8] = b"cume_dist";
const ntileName: &[u8] = b"ntile";
const last_valueName: &[u8] = b"last_value";
const nth_valueName: &[u8] = b"nth_value";
const first_valueName: &[u8] = b"first_value";
const leadName: &[u8] = b"lead";
const lagName: &[u8] = b"lag";

/// The Rust equivalent of the C test `pFunc->zName==xxxName`: true if
/// pFunc is the built-in window function `zName`.
fn isBuiltinWin(pFunc: &FuncDef, zName: &[u8]) -> bool {
    (pFunc.funcFlags & SQLITE_FUNC_WINDOW) != 0 && pFunc.zName == zName
}

/*
** No-op implementations of xStep() and xFinalize().  Used as place-holders
** for built-in window functions that never call those interfaces.
**
** The noopValueFunc() is called but is expected to do nothing.  The
** noopStepFunc() is never called, and so it is marked with NO_TEST to
** let the test coverage routine know not to expect this function to be
** invoked.
*/
fn noopStepFunc(_p: &mut Context<'_>, _a: &mut [Mem]) {}
fn noopValueFunc(_p: &mut Context<'_>) { /*no-op*/
}
use noopStepFunc as nth_valueInvFunc;
use noopStepFunc as first_valueInvFunc;
use noopValueFunc as nth_valueValueFunc;
use noopValueFunc as first_valueValueFunc;

fn windowFuncDef(
    zName: &[u8],
    nArg: i16,
    xStep: fn(&mut Context<'_>, &mut [Mem]),
    xFinal: fn(&mut Context<'_>),
    xValue: fn(&mut Context<'_>),
    xInverse: fn(&mut Context<'_>, &mut [Mem]),
) -> FuncDef {
    FuncDef {
        nArg,
        funcFlags: SQLITE_FUNC_BUILTIN | SQLITE_UTF8 as u32 | SQLITE_FUNC_WINDOW,
        pUserData: FuncUserData::None,
        xSFunc: Some(Rc::new(xStep)),
        xFinalize: Some(Rc::new(xFinal)),
        xValue: Some(Rc::new(xValue)),
        xInverse: Some(Rc::new(xInverse)),
        zName: zName.to_vec(),
        pDestructor: None,
    }
}

/* Window functions that use all window interfaces: xStep, xFinal,
** xValue, and xInverse */
macro_rules! WINDOWFUNCALL {
    ($name:ident, $nArg:expr) => {
        paste_win!($name, $nArg, all)
    };
}
macro_rules! paste_win {
    (row_number, $n:expr, x) => {
        windowFuncDef(
            row_numberName,
            $n,
            row_numberStepFunc,
            row_numberValueFunc,
            row_numberValueFunc,
            noopStepFunc,
        )
    };
    (dense_rank, $n:expr, x) => {
        windowFuncDef(
            dense_rankName,
            $n,
            dense_rankStepFunc,
            dense_rankValueFunc,
            dense_rankValueFunc,
            noopStepFunc,
        )
    };
    (rank, $n:expr, x) => {
        windowFuncDef(
            rankName,
            $n,
            rankStepFunc,
            rankValueFunc,
            rankValueFunc,
            noopStepFunc,
        )
    };
    (percent_rank, $n:expr, all) => {
        windowFuncDef(
            percent_rankName,
            $n,
            percent_rankStepFunc,
            percent_rankFinalizeFunc,
            percent_rankValueFunc,
            percent_rankInvFunc,
        )
    };
    (cume_dist, $n:expr, all) => {
        windowFuncDef(
            cume_distName,
            $n,
            cume_distStepFunc,
            cume_distFinalizeFunc,
            cume_distValueFunc,
            cume_distInvFunc,
        )
    };
    (ntile, $n:expr, all) => {
        windowFuncDef(
            ntileName,
            $n,
            ntileStepFunc,
            ntileFinalizeFunc,
            ntileValueFunc,
            ntileInvFunc,
        )
    };
    (last_value, $n:expr, all) => {
        windowFuncDef(
            last_valueName,
            $n,
            last_valueStepFunc,
            last_valueFinalizeFunc,
            last_valueValueFunc,
            last_valueInvFunc,
        )
    };
    (nth_value, $n:expr, all) => {
        windowFuncDef(
            nth_valueName,
            $n,
            nth_valueStepFunc,
            nth_valueFinalizeFunc,
            nth_valueValueFunc,
            nth_valueInvFunc,
        )
    };
    (first_value, $n:expr, all) => {
        windowFuncDef(
            first_valueName,
            $n,
            first_valueStepFunc,
            first_valueFinalizeFunc,
            first_valueValueFunc,
            first_valueInvFunc,
        )
    };
}
