/* Window functions that use all window interfaces: xStep, the
** same routine for xFinalize and xValue and which never call
** xInverse. */
macro_rules! WINDOWFUNCX {
    ($name:ident, $nArg:expr) => {
        paste_win!($name, $nArg, x)
    };
}

