/// Write code to erase the table with root-page iTable from database iDb.
/// Also write code to modify the sqlite_schema table and internal schema
/// if a root-page of another table is moved by the btree-layer whilst
/// erasing iTable (this can happen with an auto-vacuum database).
fn destroyRootPage(db: &mut Sqlite3, iTable: i32, iDb: i32) {
    get_vdbe(db);
    let r1 = crate::expr::sqlite3GetTempReg(db);
    if iTable < 2 {
        sqlite3ErrorMsg(db, b"corrupt schema", &[]);
    }
    sqlite3VdbeAddOp3(db.v(), OP_Destroy, iTable, r1, iDb);
    sqlite3MayAbort(db);
    // OP_Destroy stores an in integer r1. If this integer
    // is non-zero, then it is the root page number of a table moved to
    // location iTable. The following code modifies the sqlite_schema table to
    // reflect this.
    //
    // The "#NNN" in the SQL is a special constant that means whatever value
    // is in register NNN.  See grammar rules associated with the TK_REGISTER
    // token for additional information.
    let zDb = db.aDb[iDb as usize].zDbSName.clone();
    sqlite3NestedParse(
        db,
        Some(b"UPDATE %Q.sqlite_master SET rootpage=%d WHERE #%d AND rootpage=#%d"),
        &[(&zDb).into(), iTable.into(), r1.into(), r1.into()],
    );
    crate::expr::sqlite3ReleaseTempReg(db, r1);
}

/// Write VDBE code to erase table pTab and all associated indices on disk.
/// Code to update the sqlite_schema tables and internal schema definitions
/// in case a root-page belonging to another table is moved by the btree layer
/// is also added (this can happen with an auto-vacuum database).
fn destroyTable(db: &mut Sqlite3, pTab: &TableRef) {
    // If the database may be auto-vacuum capable (if SQLITE_OMIT_AUTOVACUUM
    // is not defined), then it is important to call OP_Destroy on the
    // table and index root-pages in order, starting with the numerically
    // largest root-page number. This guarantees that none of the root-pages
    // to be destroyed is relocated by an earlier OP_Destroy. i.e. if the
    // following were coded:
    //
    // OP_Destroy 4 0
    // ...
    // OP_Destroy 5 0
    //
    // and root page 5 happened to be the largest root-page number in the
    // database, then root page 5 would be moved to page 4 by the
    // "OP_Destroy 4 0" opcode. The subsequent "OP_Destroy 5 0" would hit
    // a free-list page.
    let (iTab, sid) = {
        let t = pTab.borrow();
        (t.tnum, t.pSchema)
    };
    let mut iDestroyed: Pgno = 0;

    loop {
        let mut iLargest: Pgno = 0;

        if iDestroyed == 0 || iTab < iDestroyed {
            iLargest = iTab;
        }
        for pIdx in pTab.borrow().pIndex.iter() {
            let iIdx = pIdx.borrow().tnum;
            if (iDestroyed == 0 || iIdx < iDestroyed) && iIdx > iLargest {
                iLargest = iIdx;
            }
        }
        if iLargest == 0 {
            return;
        } else {
            let iDb = db.schema_index(sid);
            debug_assert!(iDb >= 0 && iDb < db.nDb());
            destroyRootPage(db, iLargest as i32, iDb);
            iDestroyed = iLargest;
        }
    }
}

/// Remove entries from the sqlite_statN tables (for N in (1,2,3))
/// after a DROP INDEX or DROP TABLE command.
fn sqlite3ClearStatTables(db: &mut Sqlite3, iDb: i32, zType: &[u8], zName: &[u8]) {
    let zDbName = db.aDb[iDb as usize].zDbSName.clone();
    for i in 1..=4 {
        let zTab = format!("sqlite_stat{}", i).into_bytes();
        if sqlite3FindTable(db, Some(&zTab), zDbName.as_deref()).is_some() {
            sqlite3NestedParse(
                db,
                Some(b"DELETE FROM %Q.%s WHERE %s=%Q"),
                &[
                    (&zDbName).into(),
                    (&zTab).into(),
                    zType.into(),
                    zName.into(),
                ],
            );
        }
    }
}

/// C: `void sqlite3CodeDropTable(Parse *pParse, Table *pTab, int iDb, int isView)`
///
/// Generate code to drop a table.
pub fn sqlite3CodeDropTable(db: &mut Sqlite3, pTab: &TableRef, iDb: i32, isView: i32) {
    let ok = get_vdbe(db);
    debug_assert!(ok);
    sqlite3BeginWriteOperation(db, 1, iDb);

    let (isVirtual, tabFlags, zName) = {
        let t = pTab.borrow();
        (t.IsVirtual(), t.tabFlags, t.zName.clone())
    };
    if isVirtual {
        sqlite3VdbeAddOp0(db.v(), OP_VBegin);
    }

    // Drop all triggers associated with the table being dropped. Code
    // is generated to remove entries from sqlite_schema and/or
    // sqlite_temp_schema if required.
    for pTrigger in crate::trigger::sqlite3TriggerList(db, pTab) {
        crate::trigger::sqlite3DropTriggerPtr(db, &pTrigger);
    }

    // Remove any entries of the sqlite_sequence table associated with
    // the table being dropped. This is done before the table is dropped
    // at the btree level, in case the sqlite_sequence table needs to
    // move as a result of the drop (can happen in auto-vacuum mode).
    let zDbSName = db.aDb[iDb as usize].zDbSName.clone();
    if (tabFlags & TF_Autoincrement) != 0 {
        sqlite3NestedParse(
            db,
            Some(b"DELETE FROM %Q.sqlite_sequence WHERE name=%Q"),
            &[(&zDbSName).into(), (&zName).into()],
        );
    }

    // Drop all entries in the schema table that refer to the
    // table. The program name loops through the schema table and deletes
    // every row that refers to a table of the same name as the one being
    // dropped. Triggers are handled separately because a trigger can be
    // created in the temp database that refers to a table in another
    // database.
    sqlite3NestedParse(
        db,
        Some(b"DELETE FROM %Q.sqlite_master WHERE tbl_name=%Q and type!='trigger'"),
        &[(&zDbSName).into(), (&zName).into()],
    );
    if isView == 0 && !isVirtual {
        destroyTable(db, pTab);
    }

    // Remove the table entry from SQLite's internal schema and modify
    // the schema cookie.
    if isVirtual {
        sqlite3VdbeAddOp4(db.v(), OP_VDestroy, iDb, 0, 0, P4::Z(zName.clone()), 0);
        sqlite3MayAbort(db);
    }
    sqlite3VdbeAddOp4(db.v(), OP_DropTable, iDb, 0, 0, P4::Z(zName), 0);
    sqlite3ChangeCookie(db, iDb);
    sqliteViewResetAll(db, iDb);
}

/// C: `int sqlite3ReadOnlyShadowTables(sqlite3 *db)`
///
/// Return TRUE if shadow tables should be read-only in the current
/// context.
///
pub fn sqlite3ReadOnlyShadowTables(db: &mut Sqlite3) -> i32 {
    if (db.flags & SQLITE_Defensive) != 0
        && db.pVtabCtx.is_empty()
        && db.nVdbeExec == 0
        && !crate::vtab::sqlite3VtabInSync(db)
    {
        return 1;
    }
    0
}

/// Return true if it is not allowed to drop the given table
fn tableMayNotBeDropped(db: &mut Sqlite3, pTab: &TableRef) -> bool {
    let (zName, tabFlags) = {
        let t = pTab.borrow();
        (t.zName.clone(), t.tabFlags)
    };
    if strneq(&zName, b"sqlite_", 7) {
        if strneq(tail(&zName, 7), b"stat", 4) {
            return false;
        }
        if strneq(tail(&zName, 7), b"parameters", 10) {
            return false;
        }
        return true;
    }
    if (tabFlags & TF_Shadow) != 0 && sqlite3ReadOnlyShadowTables(db) != 0 {
        return true;
    }
    if (tabFlags & TF_Eponymous) != 0 {
        return true;
    }
    false
}

/// C: `void sqlite3DropTable(Parse *pParse, SrcList *pName, int isView, int noErr)`
///
/// This routine is called to do the work of a DROP TABLE statement.
/// pName is the name of the table to be dropped.
pub fn sqlite3DropTable(db: &mut Sqlite3, pName: SrcListId, isView: i32, noErr: i32) {
    'exit_drop_table: {
        if db.mallocFailed != 0 {
            break 'exit_drop_table;
        }
        debug_assert!(db.ppr().nErr == 0);
        debug_assert!(db.src(pName).nSrc() == 1);
        if crate::prepare::sqlite3ReadSchema(db) != 0 {
            break 'exit_drop_table;
        }
        if noErr != 0 {
            db.suppressErr += 1;
        }
        let pTab = sqlite3LocateTableItem(db, isView as u32, SrcItemId(pName, 0));
        if noErr != 0 {
            db.suppressErr -= 1;
        }

        let pTab = match pTab {
            Some(t) => t,
            None => {
                if noErr != 0 {
                    let zDb = db.item(SrcItemId(pName, 0)).u4.zDatabase.clone();
                    sqlite3CodeVerifyNamedSchema(db, zDb.as_deref());
                    sqlite3ForceNotReadOnly(db);
                }
                break 'exit_drop_table;
            }
        };
        let iDb = db.schema_index(pTab.borrow().pSchema);
        debug_assert!(iDb >= 0 && iDb < db.nDb());

        // If pTab is a virtual table, call ViewGetColumnNames() to ensure
        // it is initialized.
        if pTab.borrow().IsVirtual() && sqlite3ViewGetColumnNames(db, &pTab) != 0 {
            break 'exit_drop_table;
        }
        let (zTabName, isVirtual, isViewTab, modName) = {
            let t = pTab.borrow();
            (
                t.zName.clone(),
                t.IsVirtual(),
                t.IsView(),
                t.u.vtab.azArg.first().cloned(),
            )
        };
        {
            let code;
            let zTab = SCHEMA_TABLE(iDb);
            let zDb = db.aDb[iDb as usize].zDbSName.clone();
            let mut zArg2: Option<ZStr> = None;
            if sqlite3AuthCheck(db, SQLITE_DELETE, Some(zTab), None, zDb.as_deref()) != 0 {
                break 'exit_drop_table;
            }
            if isView != 0 {
                if OMIT_TEMPDB == 0 && iDb == 1 {
                    code = SQLITE_DROP_TEMP_VIEW;
                } else {
                    code = SQLITE_DROP_VIEW;
                }
            } else if isVirtual {
                code = SQLITE_DROP_VTABLE;
                // C: sqlite3GetVTable(db, pTab)->pMod->zName, the module name
                // (azArg[0]).
                zArg2 = modName;
            } else if OMIT_TEMPDB == 0 && iDb == 1 {
                code = SQLITE_DROP_TEMP_TABLE;
            } else {
                code = SQLITE_DROP_TABLE;
            }
            if sqlite3AuthCheck(db, code, Some(&zTabName), zArg2.as_deref(), zDb.as_deref()) != 0 {
                break 'exit_drop_table;
            }
            if sqlite3AuthCheck(db, SQLITE_DELETE, Some(&zTabName), None, zDb.as_deref()) != 0 {
                break 'exit_drop_table;
            }
        }
        if tableMayNotBeDropped(db, &pTab) {
            errmsg!(db, "table %s may not be dropped", &zTabName);
            break 'exit_drop_table;
        }

        // Ensure DROP TABLE is not used on a view, and DROP VIEW is not used
        // on a table.
        if isView != 0 && !isViewTab {
            errmsg!(db, "use DROP TABLE to delete table %s", &zTabName);
            break 'exit_drop_table;
        }
        if isView == 0 && isViewTab {
            errmsg!(db, "use DROP VIEW to delete view %s", &zTabName);
            break 'exit_drop_table;
        }

        // Generate code to remove the table from the schema table
        // on disk.
        if get_vdbe(db) {
            sqlite3BeginWriteOperation(db, 1, iDb);
            if isView == 0 {
                sqlite3ClearStatTables(db, iDb, b"tbl", &zTabName);
                crate::fkey::sqlite3FkDropTable(db, pName, &pTab);
            }
            sqlite3CodeDropTable(db, &pTab, iDb, isView);
        }
    }

    // exit_drop_table:
    sqlite3SrcListDelete(db, pName);
}

