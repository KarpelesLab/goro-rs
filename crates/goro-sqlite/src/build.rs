/// C: `Cte * sqlite3CteNew( Parse *pParse, Token *pName, ExprList *pArglist, Select *pQuery, u8 eM10d )`
///
/// Create a new CTE object
pub fn sqlite3CteNew(
    db: &mut Sqlite3,
    pName: &Token,
    pArglist: ExprListId,
    pQuery: SelectId,
    eM10d: u8,
) -> Option<Box<Cte>> {
    let zName = sqlite3NameFromToken(db, pName).unwrap_or_default();
    Some(Box::new(Cte {
        zName,
        pCols: pArglist,
        pSelect: pQuery,
        eM10d,
        ..Default::default()
    }))
}

/// Clear information from a Cte object, but do not deallocate storage
/// for the object itself.
fn cteClear(db: &mut Sqlite3, pCte: &Cte) {
    sqlite3ExprListDelete(db, pCte.pCols);
    crate::select::sqlite3SelectDelete(db, pCte.pSelect);
}

/// C: `void sqlite3CteDelete(sqlite3 *db, Cte *pCte)`
///
/// Free the contents of the CTE object passed as the second argument.
pub fn sqlite3CteDelete(db: &mut Sqlite3, pCte: Option<Box<Cte>>) {
    if let Some(c) = pCte {
        cteClear(db, &c);
    }
}

/// C: `With * sqlite3WithAdd( Parse *pParse, With *pWith, Cte *pCte )`
///
/// This routine is invoked once per CTE by the parser while parsing a
/// WITH clause.  The CTE described by the third argument is added to
/// the WITH clause of the second argument.  If the second argument is
/// NULL, then a new WITH argument is created.
pub fn sqlite3WithAdd(db: &mut Sqlite3, pWith: WithId, pCte: Option<Box<Cte>>) -> WithId {
    let pCte = match pCte {
        Some(c) => c,
        None => return pWith,
    };

    // Check that the CTE name is unique within this WITH clause. If
    // not, store an error in the Parse structure.
    let zName = pCte.zName.clone();
    if pWith.nn() {
        let n = db.arena.with(pWith).a.len();
        for i in 0..n {
            let same = streq(&zName, &db.arena.with(pWith).a[i].zName);
            if same {
                errmsg!(db, "duplicate WITH table name: %s", &zName);
            }
        }
    }

    let pNew = if pWith.nn() {
        pWith
    } else {
        db.arena.new_with(With::default())
    };
    db.arena.withm(pNew).a.push(*pCte);
    pNew
}

/// C: `void sqlite3WithDelete(sqlite3 *db, With *pWith)`
///
/// Free the contents of the With object passed as the second argument.
pub fn sqlite3WithDelete(db: &mut Sqlite3, pWith: WithId) {
    if pWith.nn() {
        let ctes = db.arena.with(pWith).a.clone();
        for c in ctes.iter() {
            cteClear(db, c);
        }
    }
}

/// C: `void sqlite3WithDeleteGeneric(sqlite3 *db, void *pWith)`
pub fn sqlite3WithDeleteGeneric(db: &mut Sqlite3, pWith: WithId) {
    sqlite3WithDelete(db, pWith);
}

