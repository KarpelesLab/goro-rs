/// C: `void sqlite3CreateView( Parse *pParse, Token *pBegin, Token *pName1, Token *pName2, ExprList *pCNames, Select *pSelect, int isTemp, int noErr )`
///
/// The parser calls this routine in order to create a new VIEW
pub fn sqlite3CreateView(
    db: &mut Sqlite3,
    pBegin: &Token,
    pName1: &Token,
    pName2: &Token,
    pCNames: ExprListId,
    mut pSelect: SelectId,
    isTemp: i32,
    noErr: i32,
) {
    'create_view_fail: {
        if db.ppr().nVar > 0 {
            sqlite3ErrorMsg(db, b"parameters are not allowed in views", &[]);
            break 'create_view_fail;
        }
        sqlite3StartTable(db, pName1, pName2, isTemp, 1, 0, noErr);
        let p = match db.ppr().pNewTable.clone() {
            Some(p) if db.ppr().nErr == 0 => p,
            _ => break 'create_view_fail,
        };

        // Legacy versions of SQLite allowed the use of the magic "rowid" column
        // on a view, even though views do not have rowids.  The following flag
        // setting fixes this problem.
        p.borrow_mut().tabFlags |= TF_NoVisibleRowid; // Never allow rowid in view

        let mut pName = Token::default();
        sqlite3TwoPartName(db, pName1, pName2, &mut pName);
        let sid = p.borrow().pSchema;
        let iDb = db.schema_index(sid);
        debug_assert!(iDb >= 0 && iDb < db.nDb());
        let mut sFix = DbFixer::default();
        crate::attach::sqlite3FixInit(db, &mut sFix, iDb, Some(b"view"), &pName);
        if crate::attach::sqlite3FixSelect(db, &mut sFix, pSelect) != 0 {
            break 'create_view_fail;
        }

        // Make a copy of the entire SELECT statement that defines the view.
        // This will force all the Expr.token.z values to be dynamically
        // allocated rather than point to the input string - which means that
        // they will persist after the current sqlite3_exec() call returns.
        db.selm(pSelect).selFlags |= SF_View;
        let vs = if db.ppr().IN_RENAME_OBJECT() {
            let s = pSelect;
            pSelect = SelectId::NULL;
            s
        } else {
            crate::expr::sqlite3SelectDup(db, pSelect, EXPRDUP_REDUCE)
        };
        let chk = crate::expr::sqlite3ExprListDup(db, pCNames, EXPRDUP_REDUCE);
        {
            let mut t = p.borrow_mut();
            t.u.view.pSelect = Tree::from_id(vs);
            t.pCheck = Tree::from_id(chk);
            t.eTabType = TABTYP_VIEW;
        }
        if db.mallocFailed != 0 {
            break 'create_view_fail;
        }

        // Locate the end of the CREATE VIEW statement.  Make sEnd point to
        // the end.
        let mut sEnd = db.ppr().sLastToken.clone();
        if sEnd.at(0) != b';' {
            sEnd.off += sEnd.n;
        }
        sEnd.n = 0;
        let mut n = sEnd.off as i64 - pBegin.off as i64;
        debug_assert!(n > 0);
        while n > 0 && sqlite3Isspace(pBegin.at((n - 1) as isize)) {
            n -= 1;
        }
        sEnd.z = pBegin.z.clone();
        sEnd.off = (pBegin.off as i64 + n - 1) as u32;
        sEnd.n = 1;

        // Use sqlite3EndTable() to add the view to the schema table
        sqlite3EndTable(db, None, Some(&sEnd), 0, SelectId::NULL);
    }

    // create_view_fail:
    crate::select::sqlite3SelectDelete(db, pSelect);
    if db.ppr().IN_RENAME_OBJECT() {
        crate::alter::sqlite3RenameExprlistUnmap(db, pCNames);
    }
    sqlite3ExprListDelete(db, pCNames);
}

/// The Table structure pTable is really a VIEW.  Fill in the names of
/// the columns of the view in the pTable structure.  Return non-zero if
/// there are errors.  If an error is seen an error message is left
/// in pParse->zErrMsg.
fn viewGetColumnNames(db: &mut Sqlite3, pTable: &TableRef) -> i32 {
    let mut nErr = 0; // Number of errors encountered

    if pTable.borrow().IsVirtual() {
        db.nSchemaLock += 1;
        let rc = crate::vtab::sqlite3VtabCallConnect(db, pTable);
        db.nSchemaLock -= 1;
        return rc;
    }

    // A positive nCol means the columns names for this view are
    // already known.  This routine is not called unless either the
    // table is virtual or nCol is zero.
    debug_assert!(pTable.borrow().nCol <= 0);

    // A negative nCol is a special marker meaning that we are currently
    // trying to compute the column names.  If we enter this routine with
    // a negative nCol, it means two or more views form a loop, like this:
    //
    //     CREATE VIEW one AS SELECT * FROM two;
    //     CREATE VIEW two AS SELECT * FROM one;
    //
    // Actually, the error above is now caught prior to reaching this point.
    // But the following test is still important as it does come up
    // in the following:
    //
    //     CREATE TABLE main.ex1(a);
    //     CREATE TEMP VIEW ex1 AS SELECT a FROM ex1;
    //     SELECT * FROM temp.ex1;
    if pTable.borrow().nCol < 0 {
        let z = pTable.borrow().zName.clone();
        errmsg!(db, "view %s is circularly defined", &z);
        return 1;
    }

    // If we get this far, it means we need to compute the table names.
    // Note that the call to sqlite3ResultSetOfSelect() will expand any
    // "*" elements in the results set of the view and will assign cursors
    // to the elements of the FROM clause.  But we do not want these changes
    // to be permanent.  So the computation is done on a copy of the SELECT
    // statement that defines the view.
    debug_assert!(pTable.borrow().IsView());
    let vsel = {
        let t = pTable.borrow();
        t.u.view.pSelect.clone()
    };
    let vs = db.tree(&vsel);
    let pSel = crate::expr::sqlite3SelectDup(db, vs, 0);
    if pSel.nn() {
        let (eParseMode, nTab, nSelect) = {
            let p = db.ppr();
            (p.eParseMode, p.nTab, p.nSelect)
        };
        db.pp().eParseMode = PARSE_MODE_NORMAL;
        let src = db.sel(pSel).pSrc;
        sqlite3SrcListAssignCursors(db, src);
        pTable.borrow_mut().nCol = -1;
        let xAuth = db.xAuth.take();
        let pSelTab = crate::select::sqlite3ResultSetOfSelect(db, pSel, SQLITE_AFF_NONE);
        db.xAuth = xAuth;
        db.pp().nTab = nTab;
        db.pp().nSelect = nSelect;
        let hasCheck = pTable.borrow().pCheck.is_some();
        match &pSelTab {
            None => {
                pTable.borrow_mut().nCol = 0;
                nErr += 1;
            }
            Some(_) if hasCheck => {
                // CREATE VIEW name(arglist) AS ...
                // The names of the columns in the table are taken from
                // arglist which is stored in pTable->pCheck.  The pCheck field
                // normally holds CHECK constraints on an ordinary table, but for
                // a VIEW it holds the list of column names.
                let chk = {
                    let t = pTable.borrow();
                    t.pCheck.clone()
                };
                let l = db.tree(&chk);
                let mut nCol: i16 = 0;
                let mut aCol: Vec<Column> = Vec::new();
                crate::select::sqlite3ColumnsFromExprList(db, l, &mut nCol, &mut aCol);
                {
                    let mut t = pTable.borrow_mut();
                    t.nCol = nCol;
                    t.aCol = aCol;
                }
                let nExpr = {
                    let el = db.sel(pSel).pEList;
                    db.el(el).nExpr()
                };
                if db.ppr().nErr == 0 && nCol as i32 == nExpr {
                    debug_assert!(db.mallocFailed == 0);
                    crate::select::sqlite3SubqueryColumnTypes(db, pTable, pSel, SQLITE_AFF_NONE);
                }
            }
            Some(st) => {
                // CREATE VIEW name AS...  without an argument list.  Construct
                // the column names from the SELECT statement that defines the view.
                let mut s = st.borrow_mut();
                let mut t = pTable.borrow_mut();
                debug_assert!(t.aCol.is_empty());
                t.nCol = s.nCol;
                t.aCol = std::mem::take(&mut s.aCol);
                t.tabFlags |= s.tabFlags & COLFLAG_NOINSERT as u32;
                s.nCol = 0;
            }
        }
        {
            let mut t = pTable.borrow_mut();
            t.nNVCol = t.nCol;
        }
        if let Some(st) = pSelTab {
            sqlite3DeleteTable(db, &st);
        }
        crate::select::sqlite3SelectDelete(db, pSel);
        db.pp().eParseMode = eParseMode;
    } else {
        nErr += 1;
    }
    let iDb = db.schema_index(pTable.borrow().pSchema);
    if iDb >= 0 {
        db.aDb[iDb as usize].pSchema.schemaFlags |= DB_UnresetViews;
    }
    if db.mallocFailed != 0 {
        sqlite3DeleteColumnNames(db, pTable);
    }
    nErr + db.ppr().nErr
}

/// C: `int sqlite3ViewGetColumnNames(Parse *pParse, Table *pTable)`
pub fn sqlite3ViewGetColumnNames(db: &mut Sqlite3, pTable: &TableRef) -> i32 {
    {
        let t = pTable.borrow();
        if !t.IsVirtual() && t.nCol > 0 {
            return 0;
        }
    }
    viewGetColumnNames(db, pTable)
}

/// Clear the column names from every VIEW in database idx.
fn sqliteViewResetAll(db: &mut Sqlite3, idx: i32) {
    if !db.DbHasProperty(idx, DB_UnresetViews) {
        return;
    }
    for pTab in db.aDb[idx as usize].pSchema.tblHash.values() {
        if pTab.borrow().IsView() {
            sqlite3DeleteColumnNames(db, &pTab);
        }
    }
    db.DbClearProperty(idx, DB_UnresetViews);
}

/// C: `void sqlite3RootPageMoved(sqlite3 *db, int iDb, Pgno iFrom, Pgno iTo)`
///
/// This function is called by the VDBE to adjust the internal schema
/// used by SQLite when the btree layer moves a table root page. The
/// root-page of a table or index in database iDb has changed from iFrom
/// to iTo.
///
/// Ticket #1728:  The symbol table might still contain information
/// on tables and/or indices that are the process of being deleted.
/// If you are unlucky, one of those deleted indices or tables might
/// have the same rootpage number as the real table or index that is
/// being moved.  So we cannot stop searching after the first match
/// because the first match might be for one of the deleted indices
/// or tables and not the table/index that is actually being moved.
/// We must continue looping until all tables and indices with
/// rootpage==iFrom have been converted to have a rootpage of iTo
/// in order to be certain that we got the right one.
pub fn sqlite3RootPageMoved(db: &mut Sqlite3, iDb: i32, iFrom: Pgno, iTo: Pgno) {
    let s = &db.aDb[iDb as usize].pSchema;
    for (_, pTab) in s.tblHash.iter() {
        let mut t = pTab.borrow_mut();
        if t.tnum == iFrom {
            t.tnum = iTo;
        }
    }
    for (_, pIdx) in s.idxHash.iter() {
        let mut x = pIdx.borrow_mut();
        if x.tnum == iFrom {
            x.tnum = iTo;
        }
    }
}

