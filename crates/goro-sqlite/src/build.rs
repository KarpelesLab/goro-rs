/// Generate code that will erase and refill index *pIdx.  This is
/// used to initialize a newly created index or to recompute the
/// content of an index in response to a REINDEX command.
///
/// if memRootPage is not negative, it means that the index is newly
/// created.  The register specified by memRootPage contains the
/// root page number of the index.  If memRootPage is negative, then
/// the index already exists and must be cleared before being refilled and
/// the root page number of the index is taken from pIndex->tnum.
fn sqlite3RefillIndex(db: &mut Sqlite3, pIndex: &IndexRef, memRootPage: i32) {
    let pTab = pIndex.borrow().table(); // The table that is indexed
    let iTab = {
        let p = db.pp();
        p.nTab += 1;
        p.nTab - 1
    }; // Btree cursor used for pTab
    let iIdx = {
        let p = db.pp();
        p.nTab += 1;
        p.nTab - 1
    }; // Btree cursor used for pIndex
    let iDb = db.schema_index(pIndex.borrow().pSchema);
    let (zIdxName, nKeyCol, isUnique, bAscKeyBug, idxTnum) = {
        let x = pIndex.borrow();
        (
            x.zName.clone(),
            x.nKeyCol as i32,
            x.IsUniqueIndex(),
            x.bAscKeyBug,
            x.tnum,
        )
    };
    let (tabTnum, zTabName) = {
        let t = pTab.borrow();
        (t.tnum, t.zName.clone())
    };

    let zDb = db.aDb[iDb as usize].zDbSName.clone();
    if sqlite3AuthCheck(db, SQLITE_REINDEX, Some(&zIdxName), None, zDb.as_deref()) != 0 {
        return;
    }

    // Require a write-lock on the table to perform this operation
    sqlite3TableLock(db, iDb, tabTnum, 1, Some(&zTabName));

    if !get_vdbe(db) {
        return;
    }
    let tnum: Pgno = if memRootPage >= 0 {
        memRootPage as Pgno
    } else {
        idxTnum
    };
    let pKey = sqlite3KeyInfoOfIndex(db, pIndex);
    debug_assert!(pKey.is_some() || db.ppr().nErr != 0);
    let p4key = |k: &Option<KeyInfoRef>| match k {
        Some(k) => P4::KeyInfo(k.clone()),
        None => P4::None,
    };

    // Open the sorter cursor if we are to use one.
    let iSorter = {
        let p = db.pp();
        p.nTab += 1;
        p.nTab - 1
    };
    sqlite3VdbeAddOp4(
        db.v(),
        OP_SorterOpen,
        iSorter,
        0,
        nKeyCol,
        p4key(&pKey),
        P4_KEYINFO as i32,
    );

    // Open the table. Loop through all rows of the table, inserting index
    // records into the sorter.
    crate::insert::sqlite3OpenTable(db, iTab, iDb, &pTab, OP_OpenRead as i32);
    let mut addr1 = sqlite3VdbeAddOp2(db.v(), OP_Rewind, iTab, 0);
    let regRecord = crate::expr::sqlite3GetTempReg(db);
    sqlite3MultiWrite(db);

    let mut iPartIdxLabel = 0;
    crate::delete::sqlite3GenerateIndexKey(
        db,
        pIndex,
        iTab,
        regRecord,
        0,
        Some(&mut iPartIdxLabel),
        None,
        0,
    );
    sqlite3VdbeAddOp2(db.v(), OP_SorterInsert, iSorter, regRecord);
    crate::delete::sqlite3ResolvePartIdxLabel(db, iPartIdxLabel);
    {
        let v = db.v();
        sqlite3VdbeAddOp2(v, OP_Next, iTab, addr1 + 1);
        sqlite3VdbeJumpHere(v, addr1);
        if memRootPage < 0 {
            sqlite3VdbeAddOp2(v, OP_Clear, tnum as i32, iDb);
        }
        sqlite3VdbeAddOp4(
            v,
            OP_OpenWrite,
            iIdx,
            tnum as i32,
            iDb,
            p4key(&pKey),
            P4_KEYINFO as i32,
        );
        sqlite3VdbeChangeP5(
            v,
            OPFLAG_BULKCSR | if memRootPage >= 0 { OPFLAG_P2ISREG } else { 0 },
        );

        addr1 = sqlite3VdbeAddOp2(v, OP_SorterSort, iSorter, 0);
    }
    let addr2;
    if isUnique {
        let j2 = sqlite3VdbeGoto(db.v(), 1);
        addr2 = sqlite3VdbeCurrentAddr(db.v());
        sqlite3VdbeAddOp4Int(db.v(), OP_SorterCompare, iSorter, j2, regRecord, nKeyCol);
        sqlite3UniqueConstraint(db, OE_Abort as i32, pIndex);
        sqlite3VdbeJumpHere(db.v(), j2);
    } else {
        // Most CREATE INDEX and REINDEX statements that are not UNIQUE can not
        // abort. The exception is if one of the indexed expressions contains a
        // user function that throws an exception when it is evaluated. But the
        // overhead of adding a statement journal to a CREATE INDEX statement is
        // very small (since most of the pages written do not contain content that
        // needs to be restored if the statement aborts), so we call
        // sqlite3MayAbort() for all CREATE INDEX statements.
        sqlite3MayAbort(db);
        addr2 = sqlite3VdbeCurrentAddr(db.v());
    }
    {
        let v = db.v();
        sqlite3VdbeAddOp3(v, OP_SorterData, iSorter, regRecord, iIdx);
        if bAscKeyBug == 0 {
            // This OP_SeekEnd opcode makes index insert for a REINDEX go much
            // faster by avoiding unnecessary seeks.  But the optimization does
            // not work for UNIQUE constraint indexes on WITHOUT ROWID tables
            // with DESC primary keys, since those indexes have there keys in
            // a different order from the main table.
            // See ticket: https://sqlite.org/src/info/bba7b69f9849b5bf
            sqlite3VdbeAddOp1(v, OP_SeekEnd, iIdx);
        }
        sqlite3VdbeAddOp2(v, OP_IdxInsert, iIdx, regRecord);
        sqlite3VdbeChangeP5(v, OPFLAG_USESEEKRESULT);
    }
    crate::expr::sqlite3ReleaseTempReg(db, regRecord);
    let v = db.v();
    sqlite3VdbeAddOp2(v, OP_SorterNext, iSorter, addr2);
    sqlite3VdbeJumpHere(v, addr1);

    sqlite3VdbeAddOp1(v, OP_Close, iTab);
    sqlite3VdbeAddOp1(v, OP_Close, iIdx);
    sqlite3VdbeAddOp1(v, OP_Close, iSorter);
}

/// C: `Index * sqlite3AllocateIndexObject( sqlite3 *db, int nCol, int nExtra, char **ppExtra )`
///
/// Allocate heap space to hold an Index object with nCol columns.
///
/// Rust: the arrays are Vecs (azColl, aiColumn, aSortOrder with nCol
/// entries, aiRowLogEst with nCol+1); the "extra" space is not needed
/// (nExtra and ppExtra are ignored).
pub fn sqlite3AllocateIndexObject(
    db: &mut Sqlite3,
    nCol: i32,
    nExtra: i32,
    ppExtra: &mut Option<ZStr>,
) -> Option<IndexRef> {
    let _ = (nExtra, ppExtra);
    debug_assert!(nCol <= 2 * db.aLimit[SQLITE_LIMIT_COLUMN as usize]);
    debug_assert!(nCol > 0);
    let n = nCol.max(0) as usize;
    Some(Rc::new(RefCell::new(Index {
        azColl: vec![Vec::new(); n],
        aiRowLogEst: vec![0; n + 1],
        aiColumn: vec![0; n],
        aSortOrder: vec![0; n],
        nColumn: nCol as u16,
        nKeyCol: (nCol - 1) as u16,
        ..Default::default()
    })))
}

/// C: `int sqlite3HasExplicitNulls(Parse *pParse, ExprList *pList)`
///
/// If expression list pList contains an expression that was parsed with
/// an explicit "NULLS FIRST" or "NULLS LAST" clause, leave an error in
/// pParse and return non-zero. Otherwise, return zero.
pub fn sqlite3HasExplicitNulls(db: &mut Sqlite3, pList: ExprListId) -> i32 {
    if pList.nn() {
        let n = db.el(pList).nExpr();
        for i in 0..n as usize {
            let fg = db.el(pList).a[i].fg;
            if fg.bNulls != 0 {
                let sf = fg.sortFlags;
                let z: &[u8] = if sf == 0 || sf == 3 {
                    b"FIRST"
                } else {
                    b"LAST"
                };
                errmsg!(db, "unsupported use of NULLS %s", z);
                return 1;
            }
        }
    }
    0
}

/// C: `void sqlite3CreateIndex( Parse *pParse, Token *pName1, Token *pName2, SrcList *pTblName, ExprList *pList, int onError, Token *pStart, Expr *pPIWhere, int sortOrder, int ifNotExist, u8 idxType )`
///
/// Create a new index for an SQL table.  pName1.pName2 is the name of the index
/// and pTblList is the name of the table that is to be indexed.  Both will
/// be NULL for a primary key or an index that is created to satisfy a
/// UNIQUE constraint.  If pTable and pIndex are NULL, use pParse->pNewTable
/// as the table to be indexed.  pParse->pNewTable is a table that is
/// currently being constructed by a CREATE TABLE statement.
///
/// pList is a list of columns to be indexed.  pList will be NULL if this
/// is a primary key or unique-constraint on the most recent column added
/// to the table currently under construction.
///
/// Rust: pName1, pName2 and pStart may be None (C NULL).
pub fn sqlite3CreateIndex(
    db: &mut Sqlite3,
    pName1: Option<&Token>,
    pName2: Option<&Token>,
    pTblName: SrcListId,
    mut pList: ExprListId,
    onError: i32,
    pStart: Option<&Token>,
    mut pPIWhere: ExprId,
    sortOrder: i32,
    ifNotExist: i32,
    idxType: u8,
) {
    let mut pTab: Option<TableRef> = None; // Table to be indexed
    let mut pIndex: Option<IndexRef> = None; // The index to be created
    let mut pPk: Option<IndexRef> = None; // PRIMARY KEY index for WITHOUT ROWID tables

    'exit_create_index: {
        if db.ppr().nErr != 0 {
            break 'exit_create_index;
        }
        if db.ppr().IN_DECLARE_VTAB() && idxType != SQLITE_IDXTYPE_PRIMARYKEY {
            break 'exit_create_index;
        }
        if SQLITE_OK != crate::prepare::sqlite3ReadSchema(db) {
            break 'exit_create_index;
        }
        if sqlite3HasExplicitNulls(db, pList) != 0 {
            break 'exit_create_index;
        }

        let mut iDb: i32;
        let mut pName: Option<Token> = None; // Unqualified name of the index to create

        // Find the table that is to be indexed.  Return early if not found.
        if pTblName.nn() {
            // Use the two-part index name to determine the database
            // to search for the table. 'Fix' the table name to this db
            // before looking up the table.
            let (n1, n2) = (
                pName1.cloned().unwrap_or_default(),
                pName2.cloned().unwrap_or_default(),
            );
            let mut un = Token::default();
            iDb = sqlite3TwoPartName(db, &n1, &n2, &mut un);
            if iDb < 0 {
                break 'exit_create_index;
            }
            pName = Some(un.clone());

            // If the index name was unqualified, check if the table
            // is a temp table. If so, set the database to 1. Do not do this
            // if initializing a database schema.
            if db.init.busy == 0 {
                pTab = crate::delete::sqlite3SrcListLookup(db, pTblName);
                if n2.n == 0 {
                    if let Some(t) = &pTab {
                        if t.borrow().pSchema == db.aDb[1].pSchema.id {
                            iDb = 1;
                        }
                    }
                }
            }

            let mut sFix = DbFixer::default();
            crate::attach::sqlite3FixInit(db, &mut sFix, iDb, Some(b"index"), &un);
            if crate::attach::sqlite3FixSrcList(db, &mut sFix, pTblName) != 0 {
                // Because the parser constructs pTblName from a single identifier,
                // sqlite3FixSrcList can never fail.
                debug_assert!(false);
            }
            pTab = sqlite3LocateTableItem(db, 0, SrcItemId(pTblName, 0));
            let t = match &pTab {
                Some(t) => t.clone(),
                None => break 'exit_create_index,
            };
            if iDb == 1 && db.aDb[iDb as usize].pSchema.id != t.borrow().pSchema {
                let z = t.borrow().zName.clone();
                errmsg!(
                    db,
                    "cannot create a TEMP index on non-TEMP table \"%s\"",
                    &z
                );
                break 'exit_create_index;
            }
            if !t.borrow().HasRowid() {
                pPk = sqlite3PrimaryKeyIndex(&t);
            }
        } else {
            debug_assert!(pStart.is_none());
            pTab = db.ppr().pNewTable.clone();
            match &pTab {
                Some(t) => iDb = db.schema_index(t.borrow().pSchema),
                None => break 'exit_create_index,
            }
        }
        let pTabR = pTab.clone().unwrap();
        let zDbSName = db.aDb[iDb as usize].zDbSName.clone();
        let (zTabName, isView, isVirtual) = {
            let t = pTabR.borrow();
            (t.zName.clone(), t.IsView(), t.IsVirtual())
        };
        let isNewTable = db
            .ppr()
            .pNewTable
            .as_ref()
            .map_or(false, |x| Rc::ptr_eq(x, &pTabR));

        if strneq(&zTabName, b"sqlite_", 7) && db.init.busy == 0 && pTblName.nn() {
            errmsg!(db, "table %s may not be indexed", &zTabName);
            break 'exit_create_index;
        }
        if isView {
            sqlite3ErrorMsg(db, b"views may not be indexed", &[]);
            break 'exit_create_index;
        }
        if isVirtual {
            sqlite3ErrorMsg(db, b"virtual tables may not be indexed", &[]);
            break 'exit_create_index;
        }

        // Find the name of the index.  Make sure there is not already another
        // index or table with the same name.
        //
        // Exception:  If we are reading the names of permanent indices from the
        // sqlite_schema table (because some other process changed the schema) and
        // one of the index names collides with the name of a temporary table or
        // index, then we will continue to process this index.
        //
        // If pName==0 it means that we are
        // dealing with a primary key or UNIQUE constraint.  We have to invent our
        // own name.
        let mut zName: ZStr;
        if let Some(pn) = &pName {
            zName = match sqlite3NameFromToken(db, pn) {
                Some(z) => z,
                None => break 'exit_create_index,
            };
            if SQLITE_OK
                != sqlite3CheckObjectName(db, Some(&zName), Some(b"index"), Some(&zTabName))
            {
                break 'exit_create_index;
            }
            if !db.ppr().IN_RENAME_OBJECT() {
                if db.init.busy == 0
                    && sqlite3FindTable(db, Some(&zName), zDbSName.as_deref()).is_some()
                {
                    errmsg!(db, "there is already a table named %s", &zName);
                    break 'exit_create_index;
                }
                if sqlite3FindIndex(db, Some(&zName), zDbSName.as_deref()).is_some() {
                    if ifNotExist == 0 {
                        errmsg!(db, "index %s already exists", &zName);
                    } else if db.init.busy != 0 {
                        sqlite3ErrorMsg(db, b"", &[]); // corruptSchema() will do the error
                    } else {
                        sqlite3CodeVerifySchema(db, iDb);
                        sqlite3ForceNotReadOnly(db);
                    }
                    break 'exit_create_index;
                }
            }
        } else {
            let n = pTabR.borrow().pIndex.len() as i32 + 1;
            zName = mprintf!(db, "sqlite_autoindex_%s_%d", &zTabName, n);

            // Automatic index names generated from within sqlite3_declare_vtab()
            // must have names that are distinct from normal automatic index names.
            // The following statement converts "sqlite3_autoindex..." into
            // "sqlite3_butoindex..." in order to make the names distinct.
            // The "vtab_err.test" test demonstrates the need of this statement.
            if db.ppr().IN_SPECIAL_PARSE() {
                zName[7] += 1;
            }
        }

        // Check for authorization to create an index.
        if !db.ppr().IN_RENAME_OBJECT() {
            if sqlite3AuthCheck(
                db,
                SQLITE_INSERT,
                Some(SCHEMA_TABLE(iDb)),
                None,
                zDbSName.as_deref(),
            ) != 0
            {
                break 'exit_create_index;
            }
            let mut i = SQLITE_CREATE_INDEX;
            if OMIT_TEMPDB == 0 && iDb == 1 {
                i = SQLITE_CREATE_TEMP_INDEX;
            }
            if sqlite3AuthCheck(db, i, Some(&zName), Some(&zTabName), zDbSName.as_deref()) != 0 {
                break 'exit_create_index;
            }
        }

        // If pList==0, it means this routine was called to make a primary
        // key out of the last column added to the table under construction.
        // So create a fake list to simulate this.
        if pList.is_null() {
            let zCn = {
                let mut t = pTabR.borrow_mut();
                let k = (t.nCol - 1) as usize;
                t.aCol[k].colFlags |= COLFLAG_UNIQUE;
                t.aCol[k].zCnName.clone()
            };
            let prevCol = Token::from_bytes(&zCn);
            let e = crate::expr::sqlite3ExprAlloc(db, TK_ID as i32, &prevCol, 0);
            pList = sqlite3ExprListAppend(db, ExprListId::NULL, e);
            if pList.is_null() {
                break 'exit_create_index;
            }
            debug_assert!(db.el(pList).nExpr() == 1);
            crate::expr::sqlite3ExprListSetSortOrder(
                db,
                pList,
                sortOrder,
                SQLITE_SO_UNDEFINED as i32,
            );
        } else {
            crate::expr::sqlite3ExprListCheckLength(db, pList, Some(b"index"));
            if db.ppr().nErr != 0 {
                break 'exit_create_index;
            }
        }

        // Allocate the index structure.
        let nExpr = db.el(pList).nExpr();
        let nExtraCol = match &pPk {
            Some(pk) => pk.borrow().nKeyCol as i32,
            None => 1,
        };
        let mut zExtra: Option<ZStr> = None;
        let idx = match sqlite3AllocateIndexObject(db, nExpr + nExtraCol, 0, &mut zExtra) {
            Some(x) => x,
            None => break 'exit_create_index,
        };
        pIndex = Some(idx.clone());
        {
            let mut x = idx.borrow_mut();
            x.zName = zName.clone();
            x.pTable = Rc::downgrade(&pTabR);
            x.onError = onError as u8;
            x.uniqNotNull = (onError != OE_None as i32) as u8;
            x.idxType = idxType;
            x.pSchema = db.aDb[iDb as usize].pSchema.id;
            x.nKeyCol = nExpr as u16;
        }
        if pPIWhere.nn() {
            crate::resolve::sqlite3ResolveSelfReference(
                db,
                Some(&pTabR),
                NC_PartIdx,
                pPIWhere,
                ExprListId::NULL,
            );
            idx.borrow_mut().pPartIdxWhere = Tree::from_id(pPIWhere);
            pPIWhere = ExprId::NULL;
        }

        // Check to see if we should honor DESC requests on index columns
        let sortOrderMask: u8 = if db.aDb[iDb as usize].pSchema.file_format >= 4 {
            0xff // Honor DESC
        } else {
            0 // Ignore DESC
        };

        // Analyze the list of expressions that form the terms of the index and
        // report any errors.  In the common case where the expression is exactly
        // a table column, store that column in aiColumn[].  For general expressions,
        // populate pIndex->aColExpr and store XN_EXPR (-2) in aiColumn[].
        //
        // TODO: Issue a warning if two or more columns of the index are identical.
        // TODO: Issue a warning if the table primary key is used as part of the
        // index key.
        let pListItems = pList;
        if db.ppr().IN_RENAME_OBJECT() {
            idx.borrow_mut().aColExpr = Tree::from_id(pList);
            pList = ExprListId::NULL;
        }
        let nKeyCol = idx.borrow().nKeyCol as usize;
        let mut i = 0usize;
        while i < nKeyCol {
            let itemExpr = db.el(pListItems).a[i].pExpr;
            sqlite3StringToId(db, itemExpr);
            crate::resolve::sqlite3ResolveSelfReference(
                db,
                Some(&pTabR),
                NC_IdxExpr,
                itemExpr,
                ExprListId::NULL,
            );
            if db.ppr().nErr != 0 {
                break 'exit_create_index;
            }
            let pCExpr = sqlite3ExprSkipCollate(db, itemExpr);
            let j: i32;
            let (cop, ciCol) = {
                let e = db.ex(pCExpr);
                (e.op, e.iColumn)
            };
            if cop != TK_COLUMN {
                if isNewTable {
                    sqlite3ErrorMsg(
                        db,
                        b"expressions prohibited in PRIMARY KEY and UNIQUE constraints",
                        &[],
                    );
                    break 'exit_create_index;
                }
                let mut x = idx.borrow_mut();
                if x.aColExpr.is_none() {
                    x.aColExpr = Tree::from_id(pList);
                    pList = ExprListId::NULL;
                }
                j = XN_EXPR as i32;
                x.aiColumn[i] = XN_EXPR;
                x.uniqNotNull = 0;
                x.bHasExpr = 1;
            } else {
                let mut jj = ciCol as i32;
                debug_assert!(jj <= 0x7fff);
                let t = pTabR.borrow();
                let mut x = idx.borrow_mut();
                if jj < 0 {
                    jj = t.iPKey as i32;
                } else {
                    if t.aCol[jj as usize].notNull == 0 {
                        x.uniqNotNull = 0;
                    }
                    if (t.aCol[jj as usize].colFlags & COLFLAG_VIRTUAL) != 0 {
                        x.bHasVCol = 1;
                        x.bHasExpr = 1;
                    }
                }
                x.aiColumn[i] = jj as i16;
                j = jj;
            }
            let mut zColl: Option<ZStr> = None;
            {
                let e = db.ex(itemExpr);
                if e.op == TK_COLLATE {
                    debug_assert!(!e.HasProperty(EP_IntValue));
                    zColl = e.u.zToken.clone();
                }
            }
            if zColl.is_none() && j >= 0 {
                zColl = sqlite3ColumnColl(&pTabR.borrow().aCol[j as usize]);
            }
            let zColl = zColl.unwrap_or_else(|| sqlite3StrBINARY.to_vec());
            if db.init.busy == 0
                && crate::callback::sqlite3LocateCollSeq(db, Some(&zColl)).is_none()
            {
                break 'exit_create_index;
            }
            let sf = db.el(pListItems).a[i].fg.sortFlags;
            let mut x = idx.borrow_mut();
            x.azColl[i] = zColl;
            x.aSortOrder[i] = sf & sortOrderMask;
            i += 1;
        }

        // Append the table key to the end of the index.  For WITHOUT ROWID
        // tables (when pPk!=0) this will be the declared PRIMARY KEY.  For
        // normal tables (when pPk==0) this will be the rowid.
        if let Some(pk) = &pPk {
            let pk = pk.borrow().clone();
            let mut x = idx.borrow_mut();
            let nk = x.nKeyCol as i32;
            for j in 0..pk.nKeyCol as i32 {
                let c = pk.aiColumn[j as usize];
                debug_assert!(c >= 0);
                if isDupColumn(&x, nk, &pk, j) {
                    x.nColumn -= 1;
                } else {
                    x.aiColumn[i] = c;
                    x.azColl[i] = pk.azColl[j as usize].clone();
                    x.aSortOrder[i] = pk.aSortOrder[j as usize];
                    i += 1;
                }
            }
            debug_assert!(i == x.nColumn as usize);
        } else {
            let mut x = idx.borrow_mut();
            x.aiColumn[i] = XN_ROWID;
            x.azColl[i] = sqlite3StrBINARY.to_vec();
        }
        sqlite3DefaultRowEst(&idx);
        if db.ppr().pNewTable.is_none() {
            let t = pTabR.borrow();
            estimateIndexWidth(&idx, &t);
        }

        // If this index contains every column of its table, then mark
        // it as a covering index
        {
            let t = pTabR.borrow();
            let mut x = idx.borrow_mut();
            recomputeColumnsNotIndexed(&mut x, &t);
            if pTblName.nn() && x.nColumn as i32 >= t.nCol as i32 {
                x.isCovering = 1;
                for j in 0..t.nCol as i32 {
                    if j == t.iPKey as i32 {
                        continue;
                    }
                    if index_column_of(&x, j) >= 0 {
                        continue;
                    }
                    x.isCovering = 0;
                    break;
                }
            }
        }

        if isNewTable {
            // This routine has been called to create an automatic index as a
            // result of a PRIMARY KEY or UNIQUE clause on a column definition, or
            // a PRIMARY KEY or UNIQUE clause following the column definitions.
            // i.e. one of:
            //
            // CREATE TABLE t(x PRIMARY KEY, y);
            // CREATE TABLE t(x, y, UNIQUE(x, y));
            //
            // Either way, check to see if the table already has such an index. If
            // so, don't bother creating this one. This only applies to
            // automatically created indices. Users can do as they wish with
            // explicit indices.
            //
            // Two UNIQUE or PRIMARY KEY constraints are considered equivalent
            // (and thus suppressing the second one) even if they have different
            // sort orders.
            //
            // If there are different collating sequences or if the columns of
            // the constraint occur in different orders, then the constraints are
            // considered distinct and both result in separate indices.
            let existing = pTabR.borrow().pIndex.clone();
            for pIdx in existing.iter() {
                let same = {
                    let a = pIdx.borrow();
                    let b = idx.borrow();
                    debug_assert!(a.IsUniqueIndex());
                    debug_assert!(a.idxType != SQLITE_IDXTYPE_APPDEF);
                    debug_assert!(b.IsUniqueIndex());
                    if a.nKeyCol != b.nKeyCol {
                        false
                    } else {
                        let mut k = 0usize;
                        while k < a.nKeyCol as usize {
                            debug_assert!(a.aiColumn[k] >= 0);
                            if a.aiColumn[k] != b.aiColumn[k] {
                                break;
                            }
                            if !streq(&a.azColl[k], &b.azColl[k]) {
                                break;
                            }
                            k += 1;
                        }
                        k == a.nKeyCol as usize
                    }
                };
                if same {
                    let (aOn, bOn) = (pIdx.borrow().onError, idx.borrow().onError);
                    if aOn != bOn {
                        // This constraint creates the same index as a previous
                        // constraint specified somewhere in the CREATE TABLE statement.
                        // However the ON CONFLICT clauses are different. If both this
                        // constraint and the previous equivalent constraint have explicit
                        // ON CONFLICT clauses this is an error. Otherwise, use the
                        // explicitly specified behavior for the index.
                        if !(aOn == OE_Default || bOn == OE_Default) {
                            sqlite3ErrorMsg(db, b"conflicting ON CONFLICT clauses specified", &[]);
                        }
                        if aOn == OE_Default {
                            pIdx.borrow_mut().onError = bOn;
                        }
                    }
                    if idxType == SQLITE_IDXTYPE_PRIMARYKEY {
                        pIdx.borrow_mut().idxType = idxType;
                    }
                    if db.ppr().IN_RENAME_OBJECT() {
                        // C: pIndex->pNext = pParse->pNewIndex; pParse->pNewIndex = pIndex;
                        // (Parse::pNewIndex holds a single index in the port.)
                        db.pp().pNewIndex = pIndex.take();
                    }
                    break 'exit_create_index;
                }
            }
        }

        if !db.ppr().IN_RENAME_OBJECT() {
            // Link the new Index structure to its table and to the other
            // in-memory database structures.
            debug_assert!(db.ppr().nErr == 0);
            let hasRowid = pTabR.borrow().HasRowid();
            if db.init.busy != 0 {
                debug_assert!(!db.ppr().IN_SPECIAL_PARSE());
                if pTblName.nn() {
                    idx.borrow_mut().tnum = db.init.newTnum;
                    if crate::prepare::sqlite3IndexHasDuplicateRootPage(&idx) != 0 {
                        sqlite3ErrorMsg(db, b"invalid rootpage", &[]);
                        db.pp().rc = SQLITE_CORRUPT;
                        break 'exit_create_index;
                    }
                }
                publish_index(db, &idx);
                let p = db.aDb[iDb as usize]
                    .pSchema
                    .idxHash
                    .insert(&zName, idx.clone());
                if p.is_some() {
                    debug_assert!(false); // Malloc must have failed
                    break 'exit_create_index;
                }
                db.mDbFlags |= DBFLAG_SchemaChange;
            }
            // If this is the initial CREATE INDEX statement (or CREATE TABLE if the
            // index is an implied index for a UNIQUE or PRIMARY KEY constraint) then
            // emit code to allocate the index rootpage on disk and make an entry for
            // the index in the sqlite_schema table and populate the index with
            // content.  But, do not do this if we are simply reading the sqlite_schema
            // table to parse the schema, or if this index is the PRIMARY KEY index
            // of a WITHOUT ROWID table.
            //
            // If pTblName==0 it means this index is generated as an implied PRIMARY KEY
            // or UNIQUE index in a CREATE TABLE statement.  Since the table
            // has just been created, it contains no data and the index initialization
            // step can be skipped.
            else if hasRowid || pTblName.nn() {
                let iMem = {
                    let p = db.pp();
                    p.nMem += 1;
                    p.nMem
                };

                if !get_vdbe(db) {
                    break 'exit_create_index;
                }

                sqlite3BeginWriteOperation(db, 1, iDb);

                // Create the rootpage for the index using CreateIndex. But before
                // doing so, code a Noop instruction and store its address in
                // Index.tnum. This is required in case this index is actually a
                // PRIMARY KEY and the table is actually a WITHOUT ROWID table. In
                // that case the convertToWithoutRowidTable() routine will replace
                // the Noop with a Goto to jump over the VDBE code generated below.
                let a = sqlite3VdbeAddOp0(db.v(), OP_Noop);
                idx.borrow_mut().tnum = a as Pgno;
                sqlite3VdbeAddOp3(db.v(), OP_CreateBtree, iDb, iMem, BTREE_BLOBKEY);

                // Gather the complete text of the CREATE INDEX statement into
                // the zStmt variable
                debug_assert!(pName.is_some() || pStart.is_none());
                let zStmt: Option<ZStr> = if pStart.is_some() {
                    let pn = pName.clone().unwrap_or_default();
                    let last = db.ppr().sLastToken.clone();
                    let mut n = (last.off as i64 - pn.off as i64) + last.n as i64;
                    if n > 0 && pn.at((n - 1) as isize) == b';' {
                        n -= 1;
                    }
                    // A named index with an explicit CREATE INDEX statement
                    let src: ZStr = match &pn.z {
                        Some(z) => z[pn.off as usize..].to_vec(),
                        None => Vec::new(),
                    };
                    let u: &[u8] = if onError == OE_None as i32 {
                        b""
                    } else {
                        b" UNIQUE"
                    };
                    Some(mprintf!(db, "CREATE%s INDEX %.*s", u, n, &src))
                } else {
                    // An automatic index created by a PRIMARY KEY or UNIQUE constraint
                    None
                };

                // Add an entry in sqlite_schema for this index
                sqlite3NestedParse(
                    db,
                    Some(b"INSERT INTO %Q.sqlite_master VALUES('index',%Q,%Q,#%d,%Q);"),
                    &[
                        (&zDbSName).into(),
                        (&zName).into(),
                        (&zTabName).into(),
                        iMem.into(),
                        (&zStmt).into(),
                    ],
                );

                // Fill the index with data and reparse the schema. Code an OP_Expire
                // to invalidate all pre-compiled statements.
                if pTblName.nn() {
                    sqlite3RefillIndex(db, &idx, iMem);
                    sqlite3ChangeCookie(db, iDb);
                    let zWhere = mprintf!(db, "name='%q' AND type='index'", &zName);
                    sqlite3VdbeAddParseSchemaOp(db, iDb, Some(zWhere), 0);
                    sqlite3VdbeAddOp2(db.v(), OP_Expire, 0, 1);
                }

                let tnum = idx.borrow().tnum as i32;
                sqlite3VdbeJumpHere(db.v(), tnum);
            }
        }
        if db.init.busy != 0 || pTblName.is_null() {
            pTabR.borrow_mut().pIndex.insert(0, idx);
            pIndex = None;
        } else if db.ppr().IN_RENAME_OBJECT() {
            debug_assert!(db.ppr().pNewIndex.is_none());
            db.pp().pNewIndex = pIndex.take();
        }
    }

    // Clean up before exiting
    // exit_create_index:
    if let Some(x) = &pIndex {
        sqlite3FreeIndex(db, x);
    }
    if let Some(t) = &pTab {
        // Ensure all REPLACE indexes on pTab are at the end of the pIndex list.
        // The list was already ordered when this routine was entered, so at this
        // point at most a single index (the newly added index) will be out of
        // order.  So we have to reorder at most one index.
        let mut tb = t.borrow_mut();
        let v = &mut tb.pIndex;
        if let Some(mut k) = v.iter().position(|x| x.borrow().onError == OE_Replace) {
            while k + 1 < v.len() && v[k + 1].borrow().onError != OE_Replace {
                v.swap(k, k + 1);
                k += 1;
            }
        }
    }
    sqlite3ExprDelete(db, pPIWhere);
    sqlite3ExprListDelete(db, pList);
    sqlite3SrcListDelete(db, pTblName);
}

/// C: `void sqlite3DefaultRowEst(Index *pIdx)`
///
/// Fill the Index.aiRowEst[] array with default information - information
/// to be used when we have not run the ANALYZE command.
///
/// aiRowEst[0] is supposed to contain the number of elements in the index.
/// Since we do not know, guess 1 million.  aiRowEst[1] is an estimate of the
/// number of rows in the table that match any particular value of the
/// first column of the index.  aiRowEst[2] is an estimate of the number
/// of rows that match any particular combination of the first 2 columns
/// of the index.  And so forth.  It must always be the case that
///
///           aiRowEst[N]<=aiRowEst[N-1]
///           aiRowEst[N]>=1
///
/// Apart from that, we have little to go on besides intuition as to
/// how aiRowEst[] should be initialized.  The numbers generated here
/// are based on typical values found in actual indices.
pub fn sqlite3DefaultRowEst(pIdx: &IndexRef) {
    //                10,  9,  8,  7,  6
    const aVal: [LogEst; 5] = [33, 32, 30, 28, 26];
    let pTab = pIdx.borrow().table();
    let mut x = pIdx.borrow_mut();
    let nKeyCol = x.nKeyCol as usize;
    let nCopy = aVal.len().min(nKeyCol);

    // Indexes with default row estimates should not have stat1 data
    debug_assert!(x.hasStat1 == 0);

    // Set the first entry (number of rows in the index) to the estimated
    // number of rows in the table, or half the number of rows in the table
    // for a partial index.
    //
    // 2020-05-27:  If some of the stat data is coming from the sqlite_stat1
    // table but other parts we are having to guess at, then do not let the
    // estimated number of rows in the table be less than 1000 (LogEst 99).
    // Failure to do this can cause the indexes for which we do not have
    // stat1 data to be ignored by the query planner.
    let mut v = pTab.borrow().nRowLogEst;
    if v < 99 {
        v = 99;
        pTab.borrow_mut().nRowLogEst = 99;
    }
    if x.pPartIdxWhere.is_some() {
        v -= 10;
    }
    if x.aiRowLogEst.len() < nKeyCol + 1 {
        x.aiRowLogEst.resize(nKeyCol + 1, 0);
    }
    x.aiRowLogEst[0] = v;

    // Estimate that a[1] is 10, a[2] is 9, a[3] is 8, a[4] is 7, a[5] is
    // 6 and each subsequent value (if any) is 5.
    x.aiRowLogEst[1..=nCopy].copy_from_slice(&aVal[..nCopy]);
    for i in (nCopy + 1)..=nKeyCol {
        x.aiRowLogEst[i] = 23;
    }

    if x.IsUniqueIndex() {
        x.aiRowLogEst[nKeyCol] = 0;
    }
}

/// C: `void sqlite3DropIndex(Parse *pParse, SrcList *pName, int ifExists)`
///
/// This routine will drop an existing named index.  This routine
/// implements the DROP INDEX statement.
pub fn sqlite3DropIndex(db: &mut Sqlite3, pName: SrcListId, ifExists: i32) {
    'exit_drop_index: {
        if db.mallocFailed != 0 {
            break 'exit_drop_index;
        }
        debug_assert!(db.ppr().nErr == 0); // Never called with prior non-OOM errors
        debug_assert!(db.src(pName).nSrc() == 1);
        if SQLITE_OK != crate::prepare::sqlite3ReadSchema(db) {
            break 'exit_drop_index;
        }
        let (zName, zDatabase) = {
            let it = db.item(SrcItemId(pName, 0));
            (it.zName.clone(), it.u4.zDatabase.clone())
        };
        let pIndex = match sqlite3FindIndex(db, zName.as_deref(), zDatabase.as_deref()) {
            Some(x) => x,
            None => {
                if ifExists == 0 {
                    errmsg!(db, "no such index: %S", SrcItemId(pName, 0));
                } else {
                    sqlite3CodeVerifyNamedSchema(db, zDatabase.as_deref());
                    sqlite3ForceNotReadOnly(db);
                }
                db.pp().checkSchema = 1;
                break 'exit_drop_index;
            }
        };
        if pIndex.borrow().idxType != SQLITE_IDXTYPE_APPDEF {
            sqlite3ErrorMsg(
                db,
                b"index associated with UNIQUE or PRIMARY KEY constraint cannot be dropped",
                &[],
            );
            break 'exit_drop_index;
        }
        let iDb = db.schema_index(pIndex.borrow().pSchema);
        debug_assert!(iDb >= 0 && iDb < db.nDb());
        let (zIdxName, tnum) = {
            let x = pIndex.borrow();
            (x.zName.clone(), x.tnum)
        };
        {
            let mut code = SQLITE_DROP_INDEX;
            let zTabName = pIndex.borrow().table().borrow().zName.clone();
            let zDb = db.aDb[iDb as usize].zDbSName.clone();
            let zTab = SCHEMA_TABLE(iDb);
            if sqlite3AuthCheck(db, SQLITE_DELETE, Some(zTab), None, zDb.as_deref()) != 0 {
                break 'exit_drop_index;
            }
            if OMIT_TEMPDB == 0 && iDb == 1 {
                code = SQLITE_DROP_TEMP_INDEX;
            }
            if sqlite3AuthCheck(db, code, Some(&zIdxName), Some(&zTabName), zDb.as_deref()) != 0 {
                break 'exit_drop_index;
            }
        }

        // Generate code to remove the index and from the schema table
        if get_vdbe(db) {
            sqlite3BeginWriteOperation(db, 1, iDb);
            let zDbSName = db.aDb[iDb as usize].zDbSName.clone();
            sqlite3NestedParse(
                db,
                Some(b"DELETE FROM %Q.sqlite_master WHERE name=%Q AND type='index'"),
                &[(&zDbSName).into(), (&zIdxName).into()],
            );
            sqlite3ClearStatTables(db, iDb, b"idx", &zIdxName);
            sqlite3ChangeCookie(db, iDb);
            destroyRootPage(db, tnum as i32, iDb);
            sqlite3VdbeAddOp4(db.v(), OP_DropIndex, iDb, 0, 0, P4::Z(zIdxName), 0);
        }
    }

    // exit_drop_index:
    sqlite3SrcListDelete(db, pName);
}

/// C: `void * sqlite3ArrayAllocate( sqlite3 *db, void *pArray, int szEntry, int *pnEntry, int *pIdx )`
///
/// pArray is a pointer to an array of objects. This routine
/// extends the array so that there is space for a new object at the end
/// and returns the index of the new (default-initialized) entry.
///
/// Rust: generic over a Vec (the C memory-management details are moot).
pub fn sqlite3ArrayAllocate<T: Default>(pArray: &mut Vec<T>) -> i32 {
    pArray.push(T::default());
    (pArray.len() - 1) as i32
}

