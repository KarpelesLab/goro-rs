/// C: `void sqlite3ColumnSetExpr( Parse *pParse, Table *pTab, Column *pCol, Expr *pExpr )`
///
/// Set the expression associated with a column.  This is usually
/// the DEFAULT value, but might also be the expression that computes
/// the value for a generated column.
///
/// Rust: pCol is the index of the column in pTab->aCol.  If the default
/// list of the table was published (owned), it is imported into the arena
/// and becomes live again (the table must be re-published).
pub fn sqlite3ColumnSetExpr(db: &mut Sqlite3, pTab: &TableRef, pCol: usize, pExpr: ExprId) {
    let (iDflt, tree) = {
        let t = pTab.borrow();
        debug_assert!(t.IsOrdinaryTable());
        (t.aCol[pCol].iDflt as i32, t.u.tab.pDfltList.clone())
    };
    let pList = db.tree(&tree);
    let nExpr = if pList.nn() { db.el(pList).nExpr() } else { 0 };
    if iDflt == 0 || pList.is_null() || nExpr < iDflt {
        let newDflt = if pList.is_null() { 1 } else { nExpr + 1 };
        let l = sqlite3ExprListAppend(db, pList, pExpr);
        let mut t = pTab.borrow_mut();
        t.aCol[pCol].iDflt = newDflt as u16;
        t.u.tab.pDfltList = Tree::from_id(l);
    } else {
        let old = db.el(pList).a[(iDflt - 1) as usize].pExpr;
        sqlite3ExprDelete(db, old);
        db.elm(pList).a[(iDflt - 1) as usize].pExpr = pExpr;
        pTab.borrow_mut().u.tab.pDfltList = Tree::from_id(pList);
    }
}

/// If the expression contains any TK_FUNCTION, send it to the authorizer
/// and if the authorization fails then raise an error.
fn authFunctions(w: &mut Walker<'_>, p: ExprId) -> i32 {
    if w.db.ex(p).op == TK_FUNCTION {
        let z = w.db.ex(p).u.zToken.clone();
        let rc = sqlite3AuthCheck(w.db, SQLITE_FUNCTION, None, z.as_deref(), None);
        if rc != 0 {
            errmsg!(w.db, "not authorized to use function: %#T", p);
            return WRC_Abort;
        }
    }
    WRC_Continue
}
fn sqlite3FuncAuth(db: &mut Sqlite3, pExpr: ExprId) {
    let mut w = Walker::new(db);
    w.xExprCallback = Some(authFunctions);
    crate::walker::sqlite3WalkExpr(&mut w, pExpr);
}

/// C: `Expr * sqlite3ColumnExpr(Table *pTab, Column *pCol)`
///
/// Return the expression associated with a column.  The expression might be
/// the DEFAULT clause or the AS clause of a generated column.
/// Return NULL if the column has no associated expression.
///
/// There are two variants of this routine.  sqlite3ColumnExpr() just
/// returns the expression with no side effects.  sqlite3ColumnExprAuth()
/// takes the extra step of invoking the authorizer (if one is defined)
/// and raising an error if the returned expression uses any unauthorized
/// SQL function.
///
/// Rust: takes the connection (an owned default list is imported into the
/// arena; each call makes a fresh copy) and the column index.
pub fn sqlite3ColumnExpr(db: &mut Sqlite3, pTab: &TableRef, pCol: usize) -> ExprId {
    let (iDflt, tree) = {
        let t = pTab.borrow();
        if t.aCol[pCol].iDflt == 0 {
            return ExprId::NULL;
        }
        if !t.IsOrdinaryTable() {
            return ExprId::NULL;
        }
        (t.aCol[pCol].iDflt as i32, t.u.tab.pDfltList.clone())
    };
    if tree.is_none() {
        return ExprId::NULL;
    }
    let l = db.tree(&tree);
    if db.el(l).nExpr() < iDflt {
        return ExprId::NULL;
    }
    db.el(l).a[(iDflt - 1) as usize].pExpr
}

/// C: `Expr * sqlite3ColumnExprAuth(Table *pTab, Column *pCol, Parse *pParse)`
pub fn sqlite3ColumnExprAuth(db: &mut Sqlite3, pTab: &TableRef, pCol: usize) -> ExprId {
    let pExpr = sqlite3ColumnExpr(db, pTab, pCol);
    if db.xAuth.is_some() {
        sqlite3FuncAuth(db, pExpr);
    }
    pExpr
}

