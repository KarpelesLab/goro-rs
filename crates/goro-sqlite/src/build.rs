/// C: `int sqlite3FindDbName(sqlite3 *db, const char *zName)`
///
/// Parameter zName points to a nul-terminated buffer containing the name
/// of a database ("main", "temp" or the name of an attached db). This
/// function returns the index of the named database in db->aDb[], or
/// -1 if the named db cannot be found.
pub fn sqlite3FindDbName(db: &mut Sqlite3, zName: Option<&[u8]>) -> i32 {
    let mut i: i32 = -1; // Database number
    if zName.is_some() {
        i = db.nDb() - 1;
        while i >= 0 {
            if 0 == sqlite3_stricmp(db.aDb[i as usize].zDbSName.as_deref(), zName) {
                break;
            }
            // "main" is always an acceptable alias for the primary database
            // even if it has been renamed using SQLITE_DBCONFIG_MAINDBNAME.
            if i == 0 && 0 == sqlite3_stricmp(Some(b"main"), zName) {
                break;
            }
            i -= 1;
        }
    }
    i
}

/// C: `int sqlite3FindDb(sqlite3 *db, Token *pName)`
///
/// The token *pName contains the name of a database (either "main" or
/// "temp" or the name of an attached db). This routine returns the
/// index of the named database in db->aDb[], or -1 if the named db
/// does not exist.
pub fn sqlite3FindDb(db: &mut Sqlite3, pName: &Token) -> i32 {
    let zName = sqlite3NameFromToken(db, pName);
    sqlite3FindDbName(db, zName.as_deref())
}

/// C: `int sqlite3TwoPartName( Parse *pParse, Token *pName1, Token *pName2, Token **pUnqual )`
///
/// The table or view or trigger name is passed to this routine via tokens
/// pName1 and pName2. If the table name was fully qualified, for example:
///
/// CREATE TABLE xxx.yyy (...);
///
/// Then pName1 is set to "xxx" and pName2 "yyy". On the other hand if
/// the table name is not fully qualified, i.e.:
///
/// CREATE TABLE yyy(...);
///
/// Then pName1 is set to "yyy" and pName2 is "".
///
/// This routine sets the *ppUnqual pointer to point at the token (pName1 or
/// pName2) that stores the unqualified table name.  The index of the
/// database "xxx" is returned.
///
/// Rust: *pUnqual receives a copy of the unqualified-name token.
pub fn sqlite3TwoPartName(
    db: &mut Sqlite3,
    pName1: &Token,
    pName2: &Token,
    pUnqual: &mut Token,
) -> i32 {
    let iDb;
    if pName2.n > 0 {
        if db.init.busy != 0 {
            sqlite3ErrorMsg(db, b"corrupt database", &[]);
            return -1;
        }
        *pUnqual = pName2.clone();
        iDb = sqlite3FindDb(db, pName1);
        if iDb < 0 {
            errmsg!(db, "unknown database %T", pName1);
            return -1;
        }
    } else {
        iDb = db.init.iDb as i32;
        *pUnqual = pName1.clone();
    }
    iDb
}

