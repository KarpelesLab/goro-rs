/// C: `static void sqlite3DeleteReturning(sqlite3 *db, void *pArg)`
///
/// Clean up the data structures associated with the RETURNING clause.
///
/// Rust: registered with sqlite3ParserAddCleanup() by sqlite3AddReturning()
/// as in C; it reads the Returning object of the parse being reset.
pub fn sqlite3DeleteReturning(db: &mut Sqlite3) {
    let zName = match db.ppr().u1.d.pReturning.as_ref() {
        Some(r) => r.zName.clone(),
        None => return,
    };
    let pHash = &mut db.aDb[1].pSchema.trigHash;
    let isOurs = match (
        pHash.find(&zName),
        db.parses.last().and_then(|p| p.u1.d.pReturning.as_ref()),
    ) {
        (Some(t), Some(r)) => Rc::ptr_eq(t, &r.retTrig),
        _ => false,
    };
    if isOurs {
        db.aDb[1].pSchema.trigHash.remove(&zName);
    }
}

/// C: `void sqlite3AddReturning(Parse *pParse, ExprList *pList)`
///
/// Add the RETURNING clause to the parse currently underway.
///
/// This routine creates a special TEMP trigger that will fire for each row
/// of the DML statement.  That TEMP trigger contains a single SELECT
/// statement with a result set that is the argument of the RETURNING clause.
/// The trigger has the Trigger.bReturning flag and an opcode of
/// TK_RETURNING instead of TK_SELECT, so that the trigger code generator
/// knows to handle it specially.  The TEMP trigger is automatically
/// removed at the end of the parse.
///
/// When this routine is called, we do not yet know if the RETURNING clause
/// is attached to a DELETE, INSERT, or UPDATE, so construct it as a
/// RETURNING trigger instead.  It will then be converted into the appropriate
/// type on the first call to sqlite3TriggersExist().
pub fn sqlite3AddReturning(db: &mut Sqlite3, pList: ExprListId) {
    if db.ppr().pNewTrigger.is_some() {
        sqlite3ErrorMsg(db, b"cannot use RETURNING in a trigger", &[]);
    }
    db.pp().bReturning = 1;
    let sid = db.aDb[1].pSchema.id;
    let retTrig: TriggerRef = Rc::new(RefCell::new(Trigger {
        op: TK_RETURNING,
        tr_tm: TRIGGER_AFTER,
        bReturning: 1,
        pSchema: sid,
        pTabSchema: sid,
        ..Default::default()
    }));
    let zName: ZStr = format!(
        "sqlite_returning_{:x}",
        Rc::as_ptr(&retTrig) as *const u8 as usize
    )
    .into_bytes();
    let step = db.arena.new_tstep(TriggerStep {
        op: TK_RETURNING,
        pTrig: Rc::downgrade(&retTrig),
        pExprList: pList,
        ..Default::default()
    });
    {
        let mut t = retTrig.borrow_mut();
        t.zName = zName.clone();
        t.step_list = Tree::Live(step);
    }
    db.pp().u1.d.pReturning = Some(Box::new(Returning {
        pReturnEL: pList,
        retTrig: retTrig.clone(),
        iRetCur: 0,
        nRetCol: 0,
        iRetReg: 0,
        zName: zName.clone(),
    }));
    crate::prepare::sqlite3ParserAddCleanup(db, Box::new(sqlite3DeleteReturning));
    if db.mallocFailed != 0 {
        return;
    }
    db.aDb[1].pSchema.trigHash.insert(&zName, retTrig);
}

/// C: `void sqlite3AddColumn(Parse *pParse, Token sName, Token sType)`
///
/// Add a new column to the table currently being constructed.
///
/// The parser calls this routine once for each column declaration
/// in a CREATE TABLE statement.  sqlite3StartTable() gets called
/// first to get things going.  Then this routine is called for each
/// column.
pub fn sqlite3AddColumn(db: &mut Sqlite3, mut sName: Token, mut sType: Token) {
    let mut eType: u8 = COLTYPE_CUSTOM;
    let mut szEst: u8 = 1;
    let mut affinity: u8 = SQLITE_AFF_BLOB;

    let p = match db.ppr().pNewTable.clone() {
        Some(p) => p,
        None => return,
    };
    let (nCol, zTabName) = {
        let t = p.borrow();
        (t.nCol as i32, t.zName.clone())
    };
    if nCol + 1 > db.aLimit[SQLITE_LIMIT_COLUMN as usize] {
        errmsg!(db, "too many columns on %s", &zTabName);
        return;
    }
    if !db.ppr().IN_RENAME_OBJECT() {
        crate::util::sqlite3DequoteToken(&mut sName);
    }

    // Because keywords GENERATE ALWAYS can be converted into identifiers
    // by the parser, we can sometimes end up with a typename that ends
    // with "generated always".  Check for this case and omit the surplus
    // text.
    if sType.n >= 16 && strneq(tail(sType.text(), (sType.n - 6) as usize), b"always", 6) {
        sType.n -= 6;
        while sType.n > 0 && sqlite3Isspace(sType.at(sType.n as isize - 1)) {
            sType.n -= 1;
        }
        if sType.n >= 9 && strneq(tail(sType.text(), (sType.n - 9) as usize), b"generated", 9) {
            sType.n -= 9;
            while sType.n > 0 && sqlite3Isspace(sType.at(sType.n as isize - 1)) {
                sType.n -= 1;
            }
        }
    }

    // Check for standard typenames.  For standard typenames we will
    // set the Column.eType field rather than storing the typename after
    // the column name, in order to save space.
    if sType.n >= 3 {
        crate::util::sqlite3DequoteToken(&mut sType);
        for i in 0..SQLITE_N_STDTYPE {
            if sType.n == sqlite3StdTypeLen[i] as u32
                && strneq(sType.text(), sqlite3StdType[i], sType.n as i32)
            {
                sType.n = 0;
                eType = (i + 1) as u8;
                affinity = sqlite3StdTypeAffinity[i];
                if affinity <= SQLITE_AFF_TEXT {
                    szEst = 5;
                }
                break;
            }
        }
    }

    let mut z = sName.text().to_vec();
    if db.ppr().IN_RENAME_OBJECT() {
        sqlite3RenameTokenMap(db, rename_key_column(&p, nCol), &sName);
    }
    crate::util::sqlite3Dequote(&mut z);
    if nCol > 0 && crate::select::sqlite3ColumnIndex(&p, Some(&z)) >= 0 {
        errmsg!(db, "duplicate column name: %s", &z);
        return;
    }
    let mut col = Column {
        hName: crate::util::sqlite3StrIHash(Some(&z)),
        zCnName: z,
        ..Default::default()
    };

    if sType.n == 0 {
        // If there is no type specified, columns have the default affinity
        // 'BLOB' with a default size of 4 bytes.
        col.affinity = affinity;
        col.eCType = eType;
        col.szEst = szEst;
    } else {
        let mut zType = sType.text().to_vec();
        crate::util::sqlite3Dequote(&mut zType);
        col.affinity = sqlite3AffinityType(Some(&zType), Some(&mut col));
        col.colFlags |= COLFLAG_HASTYPE;
        col.zCnType = Some(zType);
    }
    {
        let mut t = p.borrow_mut();
        if t.nCol <= 0xff {
            let h = (col.hName as usize) % t.aHx.len();
            t.aHx[h] = t.nCol as u8;
        }
        t.aCol.push(col);
        t.nCol += 1;
        t.nNVCol += 1;
    }
    sqlite3ColumnPropertiesFromName(&p, nCol as usize);
    db.pp().u1.cr.constraintName.n = 0;
}

/// C: `void sqlite3AddNotNull(Parse *pParse, int onError)`
///
/// This routine is called by the parser while in the middle of
/// parsing a CREATE TABLE statement.  A "NOT NULL" constraint has
/// been seen on a column.  This routine sets the notNull flag on
/// the column currently under construction.
pub fn sqlite3AddNotNull(db: &mut Sqlite3, onError: i32) {
    let p = match db.ppr().pNewTable.clone() {
        Some(p) => p,
        None => return,
    };
    let mut t = p.borrow_mut();
    if t.nCol < 1 {
        return;
    }
    let iCol = (t.nCol - 1) as usize;
    t.aCol[iCol].notNull = onError as u8;
    t.tabFlags |= TF_HasNotNull;

    // Set the uniqNotNull flag on any UNIQUE or PK indexes already created
    // on this column.
    if (t.aCol[iCol].colFlags & COLFLAG_UNIQUE) != 0 {
        for pIdx in t.pIndex.iter() {
            let mut x = pIdx.borrow_mut();
            debug_assert!(x.nKeyCol == 1 && x.onError != OE_None);
            if x.aiColumn[0] as i32 == iCol as i32 {
                x.uniqNotNull = 1;
            }
        }
    }
}

/// C: `char sqlite3AffinityType(const char *zIn, Column *pCol)`
///
/// Scan the column type name zType (length nType) and return the
/// associated affinity type.
///
/// This routine does a case-independent search of zType for the
/// substrings in the following table. If one of the substrings is
/// found, the corresponding affinity is returned. If zType contains
/// more than one of the substrings, entries toward the top of
/// the table take priority. For example, if zType is 'BLOBINT',
/// SQLITE_AFF_INTEGER is returned.
///
/// Substring     | Affinity
/// --------------------------------
/// 'INT'         | SQLITE_AFF_INTEGER
/// 'CHAR'        | SQLITE_AFF_TEXT
/// 'CLOB'        | SQLITE_AFF_TEXT
/// 'TEXT'        | SQLITE_AFF_TEXT
/// 'BLOB'        | SQLITE_AFF_BLOB
/// 'REAL'        | SQLITE_AFF_REAL
/// 'FLOA'        | SQLITE_AFF_REAL
/// 'DOUB'        | SQLITE_AFF_REAL
///
/// If none of the substrings in the above table are found,
/// SQLITE_AFF_NUMERIC is returned.
///
/// Rust: pCol may be None (C NULL).
pub fn sqlite3AffinityType(zIn: Option<&[u8]>, pCol: Option<&mut Column>) -> u8 {
    let z = zIn.unwrap_or(b"");
    let mut h: u32 = 0;
    let mut aff = SQLITE_AFF_NUMERIC;
    let mut zChar: Option<usize> = None;
    let w = |a: u8, b: u8, c: u8, d: u8| {
        ((a as u32) << 24) + ((b as u32) << 16) + ((c as u32) << 8) + d as u32
    };

    let mut i = 0;
    while i < z.len() && z[i] != 0 {
        let x = z[i];
        h = (h << 8).wrapping_add(sqlite3UpperToLower[x as usize] as u32);
        i += 1;
        let next = if i < z.len() { z[i] } else { 0 };
        if h == w(b'c', b'h', b'a', b'r') {
            // CHAR
            aff = SQLITE_AFF_TEXT;
            zChar = Some(i);
        } else if h == w(b'c', b'l', b'o', b'b') {
            // CLOB
            aff = SQLITE_AFF_TEXT;
        } else if h == w(b't', b'e', b'x', b't') {
            // TEXT
            aff = SQLITE_AFF_TEXT;
        } else if h == w(b'b', b'l', b'o', b'b')
            && (aff == SQLITE_AFF_NUMERIC || aff == SQLITE_AFF_REAL)
        {
            // BLOB
            aff = SQLITE_AFF_BLOB;
            if next == b'(' {
                zChar = Some(i);
            }
        } else if h == w(b'r', b'e', b'a', b'l') && aff == SQLITE_AFF_NUMERIC {
            // REAL
            aff = SQLITE_AFF_REAL;
        } else if h == w(b'f', b'l', b'o', b'a') && aff == SQLITE_AFF_NUMERIC {
            // FLOA
            aff = SQLITE_AFF_REAL;
        } else if h == w(b'd', b'o', b'u', b'b') && aff == SQLITE_AFF_NUMERIC {
            // DOUB
            aff = SQLITE_AFF_REAL;
        } else if (h & 0x00FFFFFF) == (((b'i' as u32) << 16) + ((b'n' as u32) << 8) + b't' as u32) {
            // INT
            aff = SQLITE_AFF_INTEGER;
            break;
        }
    }

    // If pCol is not NULL, store an estimate of the field size.  The
    // estimate is scaled so that the size of an integer is 1.
    if let Some(pCol) = pCol {
        let mut v: i32 = 0; // default size is approx 4 bytes
        if aff < SQLITE_AFF_NUMERIC {
            if let Some(mut k) = zChar {
                while k < z.len() && z[k] != 0 {
                    if sqlite3Isdigit(z[k]) {
                        // BLOB(k), VARCHAR(k), CHAR(k) -> r=(k/4+1)
                        crate::util::sqlite3GetInt32(Some(&z[k..]), &mut v);
                        break;
                    }
                    k += 1;
                }
            } else {
                v = 16; // BLOB, TEXT, CLOB -> r=5  (approx 20 bytes)
            }
        }
        v = v / 4 + 1;
        if v > 255 {
            v = 255;
        }
        pCol.szEst = v as u8;
    }
    aff
}

/// C: `void sqlite3AddDefaultValue( Parse *pParse, Expr *pExpr, const char *zStart, const char *zEnd )`
///
/// The expression is the default value for the most recently added column
/// of the table currently under construction.
///
/// Default value expressions must be constant.  Raise an exception if this
/// is not the case.
///
/// This routine is called by the parser while in the middle of
/// parsing a CREATE TABLE statement.
///
/// Rust: the C zStart/zEnd pointers are offsets iStart/iEnd into zSrc (the
/// SQL text the tokens come from).
pub fn sqlite3AddDefaultValue(
    db: &mut Sqlite3,
    pExpr: ExprId,
    zSrc: &[u8],
    iStart: usize,
    iEnd: usize,
) {
    if let Some(p) = db.ppr().pNewTable.clone() {
        let isInit = (db.init.busy != 0 && db.init.iDb != 1) as u8;
        let (iCol, zCnName, colFlags) = {
            let t = p.borrow();
            let i = (t.nCol - 1) as usize;
            (i, t.aCol[i].zCnName.clone(), t.aCol[i].colFlags)
        };
        if crate::expr::sqlite3ExprIsConstantOrFunction(db, pExpr, isInit) == 0 {
            errmsg!(db, "default value of column [%s] is not constant", &zCnName);
        } else if (colFlags & COLFLAG_GENERATED) != 0 {
            sqlite3ErrorMsg(db, b"cannot use DEFAULT on a generated column", &[]);
        } else {
            // A copy of pExpr is used instead of the original, as pExpr contains
            // tokens that point to volatile memory.
            let x = db.arena.new_expr(Expr {
                op: TK_SPAN,
                u: ExprU {
                    zToken: Some(span_dup(zSrc, iStart, iEnd)),
                    iValue: 0,
                },
                pLeft: pExpr,
                flags: EP_Skip,
                ..Default::default()
            });
            let pDfltExpr = crate::expr::sqlite3ExprDup(db, x, EXPRDUP_REDUCE);
            sqlite3ColumnSetExpr(db, &p, iCol, pDfltExpr);
            // Reject unauthorized functions from DEFAULT clauses
            if db.init.busy == 0 && db.xAuth.is_some() {
                sqlite3FuncAuth(db, pExpr);
            }
        }
    }
    if db.ppr().IN_RENAME_OBJECT() {
        crate::alter::sqlite3RenameExprUnmap(db, pExpr);
    }
    sqlite3ExprDelete(db, pExpr);
}

/// Backwards Compatibility Hack:
///
/// Historical versions of SQLite accepted strings as column names in
/// indexes and PRIMARY KEY constraints and in UNIQUE constraints.  Example:
///
///     CREATE TABLE xyz(a,b,c,d,e,PRIMARY KEY('a'),UNIQUE('b','c' COLLATE trim)
///     CREATE INDEX abc ON xyz('c','d' DESC,'e' COLLATE nocase DESC);
///
/// This is goofy.  But to preserve backwards compatibility we continue to
/// accept it.  This routine does the necessary conversion.  It converts
/// the expression given in its argument from a TK_STRING into a TK_ID
/// if the expression is just a TK_STRING with an optional COLLATE clause.
/// If the expression is anything other than TK_STRING, the expression is
/// unchanged.
fn sqlite3StringToId(db: &mut Sqlite3, p: ExprId) {
    let (op, l) = {
        let e = db.ex(p);
        (e.op, e.pLeft)
    };
    if op == TK_STRING {
        db.exm(p).op = TK_ID;
    } else if op == TK_COLLATE && l.nn() && db.ex(l).op == TK_STRING {
        db.exm(l).op = TK_ID;
    }
}

/// Tag the given column as being part of the PRIMARY KEY
fn makeColumnPartOfPrimaryKey(db: &mut Sqlite3, pTab: &TableRef, iCol: usize) {
    let flags = {
        let mut t = pTab.borrow_mut();
        t.aCol[iCol].colFlags |= COLFLAG_PRIMKEY;
        t.aCol[iCol].colFlags
    };
    if (flags & COLFLAG_GENERATED) != 0 {
        sqlite3ErrorMsg(
            db,
            b"generated columns cannot be part of the PRIMARY KEY",
            &[],
        );
    }
}

/// C: `void sqlite3AddPrimaryKey( Parse *pParse, ExprList *pList, int onError, int autoInc, int sortOrder )`
///
/// Designate the PRIMARY KEY for the table.  pList is a list of names
/// of columns that form the primary key.  If pList is NULL, then the
/// most recently added column of the table is the primary key.
///
/// A table can have at most one primary key.  If the table already has
/// a primary key (and this is the second primary key) then create an
/// error.
///
/// If the PRIMARY KEY is on a single column whose datatype is INTEGER,
/// then we will try to use that column as the rowid.  Set the Table.iPKey
/// field of the table under construction to be the index of the
/// INTEGER PRIMARY KEY column.  Table.iPKey is set to -1 if there is
/// no INTEGER PRIMARY KEY.
///
/// If the key is not an INTEGER PRIMARY KEY, then create a unique
/// index for the key.  No index is created for INTEGER PRIMARY KEYs.
pub fn sqlite3AddPrimaryKey(
    db: &mut Sqlite3,
    mut pList: ExprListId,
    onError: i32,
    autoInc: i32,
    sortOrder: i32,
) {
    let mut iCol: i32 = -1;
    let mut pCol: Option<usize> = None;
    'primary_key_exit: {
        let pTab = match db.ppr().pNewTable.clone() {
            Some(t) => t,
            None => break 'primary_key_exit,
        };
        let (tabFlags, zName, nCol) = {
            let t = pTab.borrow();
            (t.tabFlags, t.zName.clone(), t.nCol as i32)
        };
        if (tabFlags & TF_HasPrimaryKey) != 0 {
            errmsg!(db, "table \"%s\" has more than one primary key", &zName);
            break 'primary_key_exit;
        }
        pTab.borrow_mut().tabFlags |= TF_HasPrimaryKey;
        let nTerm;
        if pList.is_null() {
            iCol = nCol - 1;
            pCol = Some(iCol as usize);
            makeColumnPartOfPrimaryKey(db, &pTab, iCol as usize);
            nTerm = 1;
        } else {
            nTerm = db.el(pList).nExpr();
            for i in 0..nTerm {
                let e = db.el(pList).a[i as usize].pExpr;
                let pCExpr = sqlite3ExprSkipCollate(db, e);
                debug_assert!(pCExpr.nn());
                sqlite3StringToId(db, pCExpr);
                if db.ex(pCExpr).op == TK_ID {
                    debug_assert!(!db.ex(pCExpr).HasProperty(EP_IntValue));
                    let tok = db.ex(pCExpr).u.zToken.clone();
                    iCol = crate::select::sqlite3ColumnIndex(&pTab, tok.as_deref());
                    if iCol >= 0 {
                        pCol = Some(iCol as usize);
                        makeColumnPartOfPrimaryKey(db, &pTab, iCol as usize);
                    }
                }
            }
        }
        let isIntegerCol = pCol.map_or(false, |c| pTab.borrow().aCol[c].eCType == COLTYPE_INTEGER);
        if nTerm == 1 && pCol.is_some() && isIntegerCol && sortOrder != SQLITE_SO_DESC as i32 {
            if db.ppr().IN_RENAME_OBJECT() && pList.nn() {
                let e = db.el(pList).a[0].pExpr;
                let pCExpr = sqlite3ExprSkipCollate(db, e);
                sqlite3RenameTokenRemap(db, Some(rename_key_ipkey(&pTab)), RenameKey::Expr(pCExpr));
            }
            {
                let mut t = pTab.borrow_mut();
                t.iPKey = iCol as i16;
                t.keyConf = onError as u8;
                debug_assert!(autoInc == 0 || autoInc == 1);
                t.tabFlags |= (autoInc as u32) * TF_Autoincrement;
            }
            if pList.nn() {
                let sf = db.el(pList).a[0].fg.sortFlags;
                db.pp().iPkSortOrder = sf;
            }
            let _ = sqlite3HasExplicitNulls(db, pList);
        } else if autoInc != 0 {
            sqlite3ErrorMsg(
                db,
                b"AUTOINCREMENT is only allowed on an INTEGER PRIMARY KEY",
                &[],
            );
        } else {
            sqlite3CreateIndex(
                db,
                None,
                None,
                SrcListId::NULL,
                pList,
                onError,
                None,
                ExprId::NULL,
                sortOrder,
                0,
                SQLITE_IDXTYPE_PRIMARYKEY,
            );
            pList = ExprListId::NULL;
        }
    }

    // primary_key_exit:
    sqlite3ExprListDelete(db, pList);
}

/// C: `void sqlite3AddCheckConstraint( Parse *pParse, Expr *pCheckExpr, const char *zStart, const char *zEnd )`
///
/// Add a new CHECK constraint to the table currently under construction.
///
/// Rust: zStart (the opening "(") and zEnd (the closing ")") are offsets
/// iStart/iEnd into the SQL text zSrc that the tokens come from.
pub fn sqlite3AddCheckConstraint(
    db: &mut Sqlite3,
    pCheckExpr: ExprId,
    zSrc: &Rc<[u8]>,
    iStart: usize,
    iEnd: usize,
) {
    let pTab = db.ppr().pNewTable.clone();
    let ro = {
        let i = db.init.iDb as usize;
        match db.aDb[i].pBt.clone() {
            Some(b) => crate::btree::sqlite3BtreeIsReadonly(&b) != 0,
            None => false,
        }
    };
    if let (Some(pTab), false, false) = (pTab, db.ppr().IN_DECLARE_VTAB(), ro) {
        let cur = {
            let t = pTab.borrow();
            t.pCheck.clone()
        };
        let cur = db.tree(&cur);
        let l = sqlite3ExprListAppend(db, cur, pCheckExpr);
        pTab.borrow_mut().pCheck = Tree::from_id(l);
        let cn = db.ppr().u1.cr.constraintName.clone();
        if cn.n != 0 {
            crate::expr::sqlite3ExprListSetName(db, l, &cn, 1);
        } else {
            let mut zStart = iStart + 1;
            while zStart < zSrc.len() && sqlite3Isspace(zSrc[zStart]) {
                zStart += 1;
            }
            let mut zEnd = iEnd.min(zSrc.len());
            while zEnd > zStart && sqlite3Isspace(zSrc[zEnd - 1]) {
                zEnd -= 1;
            }
            let t = Token {
                z: Some(zSrc.clone()),
                off: zStart as u32,
                n: (zEnd - zStart) as u32,
            };
            crate::expr::sqlite3ExprListSetName(db, l, &t, 1);
        }
    } else {
        sqlite3ExprDelete(db, pCheckExpr);
    }
}

/// C: `void sqlite3AddCollateType(Parse *pParse, Token *pToken)`
///
/// Set the collation function of the most recently parsed table column
/// to the CollSeq given.
pub fn sqlite3AddCollateType(db: &mut Sqlite3, pToken: &Token) {
    let p = match db.ppr().pNewTable.clone() {
        Some(p) => p,
        None => return,
    };
    if db.ppr().IN_RENAME_OBJECT() {
        return;
    }
    let i = (p.borrow().nCol - 1) as usize;
    let zColl = match sqlite3NameFromToken(db, pToken) {
        Some(z) => z,
        None => return,
    };

    if crate::callback::sqlite3LocateCollSeq(db, Some(&zColl)).is_some() {
        let mut t = p.borrow_mut();
        sqlite3ColumnSetColl(db, &mut t.aCol[i], Some(&zColl));

        // If the column is declared as "<name> PRIMARY KEY COLLATE <type>",
        // then an index may have been created on this column before the
        // collation type was added. Correct this if it is the case.
        let c = sqlite3ColumnColl(&t.aCol[i]).unwrap_or_default();
        for pIdx in t.pIndex.iter() {
            let mut x = pIdx.borrow_mut();
            debug_assert!(x.nKeyCol == 1);
            if x.aiColumn[0] as usize == i {
                x.azColl[0] = c.clone();
            }
        }
    }
}

/// C: `void sqlite3AddGenerated(Parse *pParse, Expr *pExpr, Token *pType)`
///
/// Change the most recently parsed column to be a GENERATED ALWAYS AS
/// column.
///
/// Rust: pType may be None (C NULL).
pub fn sqlite3AddGenerated(db: &mut Sqlite3, mut pExpr: ExprId, pType: Option<&Token>) {
    let mut eType: u16 = COLFLAG_VIRTUAL;
    'generated_done: {
        let pTab = match db.ppr().pNewTable.clone() {
            Some(t) => t,
            // generated column in an CREATE TABLE IF NOT EXISTS that already exists
            None => break 'generated_done,
        };
        let iCol = (pTab.borrow().nCol - 1) as usize;
        'generated_error: {
            if db.ppr().IN_DECLARE_VTAB() {
                sqlite3ErrorMsg(db, b"virtual tables cannot use computed columns", &[]);
                break 'generated_done;
            }
            if pTab.borrow().aCol[iCol].iDflt > 0 {
                break 'generated_error;
            }
            if let Some(t) = pType {
                if t.n == 7 && strneq(b"virtual", t.text(), 7) {
                    // no-op
                } else if t.n == 6 && strneq(b"stored", t.text(), 6) {
                    eType = COLFLAG_STORED;
                } else {
                    break 'generated_error;
                }
            }
            let (colFlags, affinity) = {
                let mut t = pTab.borrow_mut();
                if eType == COLFLAG_VIRTUAL {
                    t.nNVCol -= 1;
                }
                t.aCol[iCol].colFlags |= eType;
                t.tabFlags |= eType as u32;
                (t.aCol[iCol].colFlags, t.aCol[iCol].affinity)
            };
            if (colFlags & COLFLAG_PRIMKEY) != 0 {
                makeColumnPartOfPrimaryKey(db, &pTab, iCol); // For the error message
            }
            if pExpr.nn() && db.ex(pExpr).op == TK_ID {
                // The value of a generated column needs to be a real expression, not
                // just a reference to another column, in order for covering index
                // optimizations to work correctly.  So if the value is not an
                // expression, turn it into one by adding a unary "+" operator.
                pExpr = crate::expr::sqlite3PExpr(db, TK_UPLUS as i32, pExpr, ExprId::NULL);
            }
            if pExpr.nn() && db.ex(pExpr).op != TK_RAISE {
                db.exm(pExpr).affExpr = affinity;
            }
            sqlite3ColumnSetExpr(db, &pTab, iCol, pExpr);
            pExpr = ExprId::NULL;
            break 'generated_done;
        }
        // generated_error:
        let zCnName = pTab.borrow().aCol[iCol].zCnName.clone();
        errmsg!(db, "error in generated column \"%s\"", &zCnName);
    }
    // generated_done:
    sqlite3ExprDelete(db, pExpr);
}

/// C: `void sqlite3ChangeCookie(Parse *pParse, int iDb)`
///
/// Generate code that will increment the schema cookie.
///
/// The schema cookie is used to determine when the schema for the
/// database changes.  After each schema change, the cookie value
/// changes.  When a process first reads the schema it records the
/// cookie.  Thereafter, whenever it goes to access the database,
/// it checks the cookie to make sure the schema has not changed
/// since it was last read.
///
/// This plan is not completely bullet-proof.  It is possible for
/// the schema to change multiple times and for the cookie to be
/// set back to prior value.  But schema changes are infrequent
/// and the probability of hitting the same cookie value is only
/// 1 chance in 2^32.  So we're safe enough.
///
/// IMPLEMENTATION-OF: R-34230-56049 SQLite automatically increments
/// the schema-version whenever the schema changes.
pub fn sqlite3ChangeCookie(db: &mut Sqlite3, iDb: i32) {
    let c = (1u32.wrapping_add(db.aDb[iDb as usize].pSchema.schema_cookie as u32)) as i32;
    sqlite3VdbeAddOp3(db.v(), OP_SetCookie, iDb, BTREE_SCHEMA_VERSION, c);
}

/// Measure the number of characters needed to output the given
/// identifier.  The number returned includes any quotes used
/// but does not include the null terminator.
///
/// The estimate is conservative.  It might be larger that what is
/// really needed.
fn identLength(z: &[u8]) -> i64 {
    let mut n: i64 = 0;
    for &c in z {
        if c == 0 {
            break;
        }
        if c == b'"' {
            n += 1;
        }
        n += 1;
    }
    n + 2
}

/// sqlite3KeywordCode(z, n): the token code of the keyword z[0..n], or
/// TK_ID if it is not a keyword.  Computed with the tokenizer.
fn keyword_code(z: &[u8]) -> i32 {
    let mut t: i32 = TK_ID as i32;
    let n = crate::tokenize::sqlite3GetToken(z, &mut t);
    if n as usize != z.len() {
        return TK_ID as i32;
    }
    t
}

/// The first parameter is a pointer to an output buffer. The second
/// parameter is a pointer to an integer that contains the offset at
/// which to write into the output buffer. This function copies the
/// nul-terminated string pointed to by the third parameter, zSignedIdent,
/// to the specified offset in the buffer and updates *pIdx to refer
/// to the first byte after the last byte written before returning.
///
/// If the string zSignedIdent consists entirely of alphanumeric
/// characters, does not begin with a digit and is not an SQL keyword,
/// then it is copied to the output buffer exactly as it is. Otherwise,
/// it is quoted using double-quotes.
fn identPut(z: &mut Vec<u8>, zIdent: &[u8]) {
    let mut j = 0;
    while j < zIdent.len() {
        if !crate::global::sqlite3Isalnum(zIdent[j]) && zIdent[j] != b'_' {
            break;
        }
        j += 1;
    }
    let needQuote = (!zIdent.is_empty() && sqlite3Isdigit(zIdent[0]))
        || j == 0
        || keyword_code(&zIdent[..j]) != TK_ID as i32
        || j < zIdent.len();

    if needQuote {
        z.push(b'"');
    }
    for &c in zIdent {
        z.push(c);
        if c == b'"' {
            z.push(b'"');
        }
    }
    if needQuote {
        z.push(b'"');
    }
}

/// Generate a CREATE TABLE statement appropriate for the given
/// table.  Memory to hold the text of the statement is obtained
/// from sqliteMalloc() and must be freed by the calling function.
fn createTableStmt(db: &mut Sqlite3, p: &TableRef) -> ZStr {
    let _ = db;
    let t = p.borrow();
    let mut n: i64 = 0;
    for c in t.aCol.iter() {
        n += identLength(&c.zCnName) + 5;
    }
    n += identLength(&t.zName);
    let (mut zSep, zSep2, zEnd): (&[u8], &[u8], &[u8]) = if n < 50 {
        (b"", b",", b")")
    } else {
        (b"\n  ", b",\n  ", b"\n)")
    };
    let mut zStmt: Vec<u8> = Vec::with_capacity((n + 35 + 6 * t.nCol as i64) as usize);
    zStmt.extend_from_slice(b"CREATE TABLE ");
    identPut(&mut zStmt, &t.zName);
    zStmt.push(b'(');
    for c in t.aCol.iter() {
        const azType: [&[u8]; 6] = [
            /* SQLITE_AFF_BLOB    */ b"", /* SQLITE_AFF_TEXT    */ b" TEXT",
            /* SQLITE_AFF_NUMERIC */ b" NUM", /* SQLITE_AFF_INTEGER */ b" INT",
            /* SQLITE_AFF_REAL    */ b" REAL", /* SQLITE_AFF_FLEXNUM */ b" NUM",
        ];
        zStmt.extend_from_slice(zSep);
        zSep = zSep2;
        identPut(&mut zStmt, &c.zCnName);
        let k = (c.affinity as i32 - SQLITE_AFF_BLOB as i32).clamp(0, 5) as usize;
        zStmt.extend_from_slice(azType[k]);
    }
    zStmt.extend_from_slice(zEnd);
    zStmt
}

/// Resize an Index object to hold N columns total.  Return SQLITE_OK
/// on success and SQLITE_NOMEM on an OOM error.
fn resizeIndexObject(pIdx: &mut Index, N: i32) -> i32 {
    if pIdx.nColumn as i32 >= N {
        return SQLITE_OK;
    }
    debug_assert!(pIdx.isResized == 0);
    let n = N as usize;
    if pIdx.azColl.len() < n {
        pIdx.azColl.resize(n, Vec::new());
    }
    if pIdx.aiRowLogEst.len() < n {
        pIdx.aiRowLogEst.resize(n, 0);
    }
    if pIdx.aiColumn.len() < n {
        pIdx.aiColumn.resize(n, 0);
    }
    if pIdx.aSortOrder.len() < n {
        pIdx.aSortOrder.resize(n, 0);
    }
    pIdx.nColumn = N as u16;
    pIdx.isResized = 1;
    SQLITE_OK
}

/// C: `int sqlite3IndexBloomable(const Index *pIdx, int N)`
///
/// Return true if the index pIdx can support a Bloom filter on its
/// first N columns.  Specifically, return true if all of the first N
/// columns have the BINARY collating sequence or no collating sequence
/// at all, and return false if there are any non-BINARY collating
/// seqeuences on any of the first N columns.  tag-202607231411
pub fn sqlite3IndexBloomable(pIdx: &IndexRef, N: i32) -> i32 {
    let x = pIdx.borrow();
    debug_assert!(N <= x.nColumn as i32);
    for i in 0..N as usize {
        if !streq(&x.azColl[i], b"BINARY") {
            return 0;
        }
    }
    1
}

/// Estimate the total row width for a table.
fn estimateTableWidth(pTab: &mut Table) {
    let mut wTable: u32 = 0;
    for c in pTab.aCol.iter() {
        wTable += c.szEst as u32;
    }
    if pTab.iPKey < 0 {
        wTable += 1;
    }
    pTab.szTabRow = crate::util::sqlite3LogEst((wTable * 4) as u64);
}

/// Estimate the average size of a row for an index.
fn estimateIndexWidth(pIdx: &IndexRef, pTab: &Table) {
    let mut x = pIdx.borrow_mut();
    let mut wIndex: u32 = 0;
    for i in 0..x.nColumn as usize {
        let c = x.aiColumn[i];
        debug_assert!(c < pTab.nCol);
        wIndex += if c < 0 {
            1
        } else {
            pTab.aCol[c as usize].szEst as u32
        };
    }
    x.szIdxRow = crate::util::sqlite3LogEst((wIndex * 4) as u64);
}

/// Return true if column number x is any of the first nCol entries of aiCol[].
/// This is used to determine if the column number x appears in any of the
/// first nCol entries of an index.
fn hasColumn(aiCol: &[i16], nCol: i32, x: i32) -> bool {
    aiCol
        .iter()
        .take(nCol.max(0) as usize)
        .any(|&c| c as i32 == x)
}

/// Return true if any of the first nKey entries of index pIdx exactly
/// match the iCol-th entry of pPk.  pPk is always a WITHOUT ROWID
/// PRIMARY KEY index.  pIdx is an index on the same table.  pIdx may
/// or may not be the same index as pPk.
///
/// The first nKey entries of pIdx are guaranteed to be ordinary columns,
/// not a rowid or expression.
///
/// This routine differs from hasColumn() in that both the column and the
/// collating sequence must match for this routine, but for hasColumn() only
/// the column name must match.
fn isDupColumn(pIdx: &Index, nKey: i32, pPk: &Index, iCol: i32) -> bool {
    debug_assert!(nKey <= pIdx.nColumn as i32);
    debug_assert!(pPk.idxType == SQLITE_IDXTYPE_PRIMARYKEY);
    let j = pPk.aiColumn[iCol as usize];
    debug_assert!(j != XN_ROWID && j != XN_EXPR);
    for i in 0..nKey as usize {
        if pIdx.aiColumn[i] == j && streq(&pIdx.azColl[i], &pPk.azColl[iCol as usize]) {
            return true;
        }
    }
    false
}

/// Recompute the colNotIdxed field of the Index.
///
/// colNotIdxed is a bitmask that has a 0 bit representing each indexed
/// columns that are within the first 63 columns of the table and a 1 for
/// all other bits (all columns that are not in the index).  The
/// high-order bit of colNotIdxed is always 1.  All unindexed columns
/// of the table have a 1.
///
/// 2019-10-24:  For the purpose of this computation, virtual columns are
/// not considered to be covered by the index, even if they are in the
/// index, because we do not trust the logic in whereIndexExprTrans() to be
/// able to find all instances of a reference to the indexed table column
/// and convert them into references to the index.  Hence we always want
/// the actual table at hand in order to recompute the virtual column, if
/// necessary.
///
/// The colNotIdxed mask is AND-ed with the SrcList.a[].colUsed mask
/// to determine if the index is covering index.
fn recomputeColumnsNotIndexed(pIdx: &mut Index, pTab: &Table) {
    let mut m: Bitmask = 0;
    let mut j = pIdx.nColumn as i32 - 1;
    while j >= 0 {
        let x = pIdx.aiColumn[j as usize] as i32;
        if x >= 0 && (pTab.aCol[x as usize].colFlags & COLFLAG_VIRTUAL) == 0 && x < BMS - 1 {
            m |= MASKBIT(x);
        }
        j -= 1;
    }
    pIdx.colNotIdxed = !m;
    debug_assert!((pIdx.colNotIdxed >> 63) == 1);
}

/// This routine runs at the end of parsing a CREATE TABLE statement that
/// has a WITHOUT ROWID clause.  The job of this routine is to convert both
/// internal schema data structures and the generated VDBE code so that they
/// are appropriate for a WITHOUT ROWID table instead of a rowid table.
/// Changes include:
///
///     (1)  Set all columns of the PRIMARY KEY schema object to be NOT NULL.
///     (2)  Convert P3 parameter of the OP_CreateBtree from BTREE_INTKEY
///          into BTREE_BLOBKEY.
///     (3)  Bypass the creation of the sqlite_schema table entry
///          for the PRIMARY KEY as the primary key index is now
///          identified by the sqlite_schema table entry of the table itself.
///     (4)  Set the Index.tnum of the PRIMARY KEY Index object in the
///          schema to the rootpage from the main table.
///     (5)  Add all table columns to the PRIMARY KEY Index object
///          so that the PRIMARY KEY is a covering index.  The surplus
///          columns are part of KeyInfo.nAllField and are not used for
///          sorting or lookup or uniqueness checks.
///     (6)  Replace the rowid tail on all automatically generated UNIQUE
///          indices with the PRIMARY KEY columns.
///
/// For virtual tables, only (1) is performed.
fn convertToWithoutRowidTable(db: &mut Sqlite3, pTab: &TableRef) {
    // Mark every PRIMARY KEY column as NOT NULL (except for imposter tables)
    if db.init.imposterTable == 0 {
        let mut t = pTab.borrow_mut();
        for c in t.aCol.iter_mut() {
            if (c.colFlags & COLFLAG_PRIMKEY) != 0 && c.notNull == OE_None {
                c.notNull = OE_Abort;
            }
        }
        t.tabFlags |= TF_HasNotNull;
    }

    // Convert the P3 operand of the OP_CreateBtree opcode from BTREE_INTKEY
    // into BTREE_BLOBKEY.
    debug_assert!(db.ppr().bReturning == 0);
    let addrCrTab = db.ppr().u1.cr.addrCrTab;
    if addrCrTab != 0 {
        sqlite3VdbeChangeP3(db.v(), addrCrTab, BTREE_BLOBKEY);
    }

    // Locate the PRIMARY KEY index.  Or, if this table was originally
    // an INTEGER PRIMARY KEY table, create a new PRIMARY KEY index.
    let pPk: IndexRef;
    let iPKey = pTab.borrow().iPKey;
    if iPKey >= 0 {
        let name = pTab.borrow().aCol[iPKey as usize].zCnName.clone();
        let ipkToken = Token::from_bytes(&name);
        let e = crate::expr::sqlite3ExprAlloc(db, TK_ID as i32, &ipkToken, 0);
        let pList = sqlite3ExprListAppend(db, ExprListId::NULL, e);
        if pList.is_null() {
            pTab.borrow_mut().tabFlags &= !TF_WithoutRowid;
            return;
        }
        if db.ppr().IN_RENAME_OBJECT() {
            let e0 = db.el(pList).a[0].pExpr;
            sqlite3RenameTokenRemap(db, Some(RenameKey::Expr(e0)), rename_key_ipkey(pTab));
        }
        let so = db.ppr().iPkSortOrder;
        db.elm(pList).a[0].fg.sortFlags = so;
        debug_assert!(
            db.ppr()
                .pNewTable
                .as_ref()
                .map_or(false, |x| Rc::ptr_eq(x, pTab))
        );
        let keyConf = {
            let mut t = pTab.borrow_mut();
            t.iPKey = -1;
            t.keyConf
        };
        sqlite3CreateIndex(
            db,
            None,
            None,
            SrcListId::NULL,
            pList,
            keyConf as i32,
            None,
            ExprId::NULL,
            0,
            0,
            SQLITE_IDXTYPE_PRIMARYKEY,
        );
        if db.ppr().nErr != 0 {
            pTab.borrow_mut().tabFlags &= !TF_WithoutRowid;
            return;
        }
        pPk = sqlite3PrimaryKeyIndex(pTab).expect("PRIMARY KEY index");
        debug_assert!(pPk.borrow().nKeyCol == 1);
    } else {
        pPk = sqlite3PrimaryKeyIndex(pTab).expect("PRIMARY KEY index");

        // Remove all redundant columns from the PRIMARY KEY.  For example, change
        // "PRIMARY KEY(a,b,a,b,c,b,c,d)" into just "PRIMARY KEY(a,b,c,d)".  Later
        // code assumes the PRIMARY KEY contains no repeated columns.
        let mut pk = pPk.borrow_mut();
        let mut j: i32 = 1;
        let nKeyCol = pk.nKeyCol as i32;
        for i in 1..nKeyCol {
            if isDupColumn(&pk, j, &pk, i) {
                pk.nColumn -= 1;
            } else {
                let (i, ju) = (i as usize, j as usize);
                pk.azColl[ju] = pk.azColl[i].clone();
                pk.aSortOrder[ju] = pk.aSortOrder[i];
                pk.aiColumn[ju] = pk.aiColumn[i];
                j += 1;
            }
        }
        pk.nKeyCol = j as u16;
    }
    let nPk;
    let pkTnum;
    {
        let mut pk = pPk.borrow_mut();
        pk.isCovering = 1;
        if db.init.imposterTable == 0 {
            pk.uniqNotNull = 1;
        }
        pk.nColumn = pk.nKeyCol;
        nPk = pk.nKeyCol as i32;
        pkTnum = pk.tnum;
    }

    // Bypass the creation of the PRIMARY KEY btree and the sqlite_schema
    // table entry. This is only required if currently generating VDBE
    // code for a CREATE TABLE (not when parsing one as part of reading
    // a database schema).
    if db.ppr().pVdbe.is_some() && pkTnum > 0 {
        debug_assert!(db.init.busy == 0);
        sqlite3VdbeChangeOpcode(db.v(), pkTnum as i32, OP_Goto);
    }

    // The root page of the PRIMARY KEY is the table root page
    let tabTnum = pTab.borrow().tnum;
    pPk.borrow_mut().tnum = tabTnum;

    // Update the in-memory representation of all UNIQUE indices by converting
    // the final rowid column into one or more columns of the PRIMARY KEY.
    let indexes = pTab.borrow().pIndex.clone();
    {
        let pk = pPk.borrow().clone();
        for pIdx in indexes.iter() {
            if Rc::ptr_eq(pIdx, &pPk) {
                continue;
            }
            let mut x = pIdx.borrow_mut();
            if x.IsPrimaryKeyIndex() {
                continue;
            }
            let nKeyCol = x.nKeyCol as i32;
            let mut n = 0;
            for i in 0..nPk {
                if !isDupColumn(&x, nKeyCol, &pk, i) {
                    n += 1;
                }
            }
            if n == 0 {
                // This index is a superset of the primary key
                x.nColumn = x.nKeyCol;
                continue;
            }
            if resizeIndexObject(&mut x, nKeyCol + n) != 0 {
                return;
            }
            let mut j = nKeyCol as usize;
            for i in 0..nPk {
                if !isDupColumn(&x, nKeyCol, &pk, i) {
                    x.aiColumn[j] = pk.aiColumn[i as usize];
                    x.azColl[j] = pk.azColl[i as usize].clone();
                    if pk.aSortOrder[i as usize] != 0 {
                        // See ticket https://sqlite.org/src/info/bba7b69f9849b5bf
                        x.bAscKeyBug = 1;
                    }
                    j += 1;
                }
            }
            debug_assert!(x.nColumn as i32 >= nKeyCol + n);
        }
    }

    // Add all table columns to the PRIMARY KEY index
    let t = pTab.borrow();
    let mut pk = pPk.borrow_mut();
    let mut nExtra = 0;
    for i in 0..t.nCol as i32 {
        if !hasColumn(&pk.aiColumn, nPk, i) && (t.aCol[i as usize].colFlags & COLFLAG_VIRTUAL) == 0
        {
            nExtra += 1;
        }
    }
    if resizeIndexObject(&mut pk, nPk + nExtra) != 0 {
        return;
    }
    let mut j = nPk;
    for i in 0..t.nCol as i32 {
        if !hasColumn(&pk.aiColumn, j, i) && (t.aCol[i as usize].colFlags & COLFLAG_VIRTUAL) == 0 {
            let zColl = sqlite3ColumnColl(&t.aCol[i as usize]);
            debug_assert!(j < pk.nColumn as i32);
            pk.aiColumn[j as usize] = i as i16;
            pk.azColl[j as usize] = zColl.unwrap_or_else(|| sqlite3StrBINARY.to_vec());
            j += 1;
        }
    }
    debug_assert!(pk.nColumn as i32 == j);
    debug_assert!(t.nNVCol as i32 <= j);
    recomputeColumnsNotIndexed(&mut pk, &t);
}

/// C: `int sqlite3IsShadowTableOf(sqlite3 *db, Table *pTab, const char *zName)`
///
/// Return true if pTab is a virtual table and zName is a shadow table name
/// for that virtual table.
pub fn sqlite3IsShadowTableOf(db: &mut Sqlite3, pTab: &TableRef, zName: Option<&[u8]>) -> i32 {
    let (nName, zMod) = {
        let t = pTab.borrow();
        if !t.IsVirtual() {
            return 0;
        }
        let nName = t.zName.len();
        let z = zName.unwrap_or(b"");
        if !strneq(z, &t.zName, nName as i32) {
            return 0;
        }
        if z.get(nName) != Some(&b'_') {
            return 0;
        }
        (nName, t.u.vtab.azArg.first().cloned().unwrap_or_default())
    };
    let Some(pMod) = db.aModule.find(&zMod).cloned() else {
        return 0;
    };
    let pModule = pMod.borrow().pModule.clone();
    if pModule.iVersion() < 3 {
        return 0;
    }
    if !pModule.has_xShadowName() {
        return 0;
    }
    let z = zName.unwrap_or(b"");
    pModule.xShadowName(&z[nName + 1..]) as i32
}

/// C: `void sqlite3MarkAllShadowTablesOf(sqlite3 *db, Table *pTab)`
///
/// Table pTab is a virtual table.  If it the virtual table implementation
/// exists and has an xShadowName method, then loop over all other ordinary
/// tables within the same schema looking for shadow tables of pTab, and mark
/// any shadow tables seen using the TF_Shadow flag.
pub fn sqlite3MarkAllShadowTablesOf(db: &mut Sqlite3, pTab: &TableRef) {
    debug_assert!(pTab.borrow().IsVirtual());
    let (zMod, zName, pSchema) = {
        let t = pTab.borrow();
        (
            t.u.vtab.azArg.first().cloned().unwrap_or_default(),
            t.zName.clone(),
            t.pSchema,
        )
    };
    let Some(pMod) = db.aModule.find(&zMod).cloned() else {
        return;
    };
    let pModule = pMod.borrow().pModule.clone();
    if pModule.iVersion() < 3 {
        return;
    }
    if !pModule.has_xShadowName() {
        return;
    }
    let nName = zName.len();
    let iDb = db.schema_index(pSchema);
    if iDb < 0 {
        return;
    }
    let tables = db.aDb[iDb as usize].pSchema.tblHash.values();
    for pOther in tables.iter() {
        let mut o = pOther.borrow_mut();
        if !o.IsOrdinaryTable() {
            continue;
        }
        if (o.tabFlags & TF_Shadow) != 0 {
            continue;
        }
        if strneq(&o.zName, &zName, nName as i32)
            && o.zName.get(nName) == Some(&b'_')
            && pModule.xShadowName(&o.zName[nName + 1..])
        {
            o.tabFlags |= TF_Shadow;
        }
    }
}

/// C: `int sqlite3ShadowTableName(sqlite3 *db, const char *zName)`
///
/// Return true if zName is a shadow table name in the current database
/// connection.
pub fn sqlite3ShadowTableName(db: &mut Sqlite3, zName: Option<&[u8]>) -> i32 {
    let z = zName.unwrap_or(b"");
    let zTail = match z.iter().rposition(|&c| c == b'_') {
        Some(i) => i,
        None => return 0,
    };
    let zCopy = z[..zTail].to_vec();
    let pTab = match sqlite3FindTable(db, Some(&zCopy), None) {
        Some(t) => t,
        None => return 0,
    };
    if !pTab.borrow().IsVirtual() {
        return 0;
    }
    sqlite3IsShadowTableOf(db, &pTab, zName)
}

/// Publish the parse trees of a table and of its indices (they become
/// owned by the schema, see PORTING.md section 2).
fn publish_table(db: &mut Sqlite3, p: &TableRef) {
    let indexes = {
        let mut t = p.borrow_mut();
        t.pCheck.publish(&db.arena);
        t.u.tab.pDfltList.publish(&db.arena);
        t.u.view.pSelect.publish(&db.arena);
        t.pIndex.clone()
    };
    for pIdx in indexes.iter() {
        publish_index(db, pIdx);
    }
}

fn publish_index(db: &mut Sqlite3, pIdx: &IndexRef) {
    let mut x = pIdx.borrow_mut();
    x.pPartIdxWhere.publish(&db.arena);
    x.aColExpr.publish(&db.arena);
}

/// C: `void sqlite3EndTable( Parse *pParse, Token *pCons, Token *pEnd, u32 tabOpts, Select *pSelect )`
///
/// This routine is called to report the final ")" that terminates
/// a CREATE TABLE statement.
///
/// The table structure that other action routines have been building
/// is added to the internal hash tables, assuming no errors have
/// occurred.
///
/// An entry for the table is made in the schema table on disk, unless
/// this is a temporary table or db->init.busy==1.  When db->init.busy==1
/// it means we are reading the sqlite_schema table because we just
/// connected to the database or because the sqlite_schema table has
/// recently changed, so the entry for this table already exists in
/// the sqlite_schema table.  We do not want to create it again.
///
/// If the pSelect argument is not NULL, it means that this routine
/// was called to create a table generated from a
/// "CREATE TABLE ... AS SELECT ..." statement.  The column names of
/// the new table will match the result set of the SELECT.
///
/// Rust: pCons and pEnd may be None (C NULL).
pub fn sqlite3EndTable(
    db: &mut Sqlite3,
    pCons: Option<&Token>,
    pEnd: Option<&Token>,
    tabOpts: u32,
    pSelect: SelectId,
) {
    if pEnd.is_none() && pSelect.is_null() {
        return;
    }
    let p = match db.ppr().pNewTable.clone() {
        Some(p) => p,
        None => return,
    };

    let zTabName = p.borrow().zName.clone();
    if pSelect.is_null() && sqlite3ShadowTableName(db, Some(&zTabName)) != 0 {
        p.borrow_mut().tabFlags |= TF_Shadow;
    }

    // If the db->init.busy is 1 it means we are reading the SQL off the
    // "sqlite_schema" or "sqlite_temp_schema" table on the disk.
    // So do not write to the disk again.  Extract the root page number
    // for the table from the db->init.newTnum field.  (The page number
    // should have been put there by the sqliteOpenCb routine.)
    //
    // If the root page number is 1, that means this is the sqlite_schema
    // table itself.  So mark it read-only.
    if db.init.busy != 0 {
        if pSelect.nn() || (!p.borrow().IsOrdinaryTable() && db.init.newTnum != 0) {
            sqlite3ErrorMsg(db, b"", &[]);
            return;
        }
        let mut t = p.borrow_mut();
        t.tnum = db.init.newTnum;
        if t.tnum == 1 {
            t.tabFlags |= TF_Readonly;
        }
    }

    // Special processing for tables that include the STRICT keyword:
    //
    //   *  Do not allow custom column datatypes.  Every column must have
    //      a datatype that is one of INT, INTEGER, REAL, TEXT, or BLOB.
    //
    //   *  If a PRIMARY KEY is defined, other than the INTEGER PRIMARY KEY,
    //      then all columns of the PRIMARY KEY must have a NOT NULL
    //      constraint.
    if (tabOpts & TF_Strict) != 0 {
        p.borrow_mut().tabFlags |= TF_Strict;
        let nCol = p.borrow().nCol as usize;
        for ii in 0..nCol {
            let mut t = p.borrow_mut();
            let iPKey = t.iPKey;
            let pCol = &mut t.aCol[ii];
            if pCol.eCType == COLTYPE_CUSTOM {
                let zCn = pCol.zCnName.clone();
                if (pCol.colFlags & COLFLAG_HASTYPE) != 0 {
                    let ty = crate::util::sqlite3ColumnType(&mut pCol.clone(), Some(b""))
                        .unwrap_or_default();
                    drop(t);
                    errmsg!(
                        db,
                        "unknown datatype for %s.%s: \"%s\"",
                        &zTabName,
                        &zCn,
                        &ty
                    );
                } else {
                    drop(t);
                    errmsg!(db, "missing datatype for %s.%s", &zTabName, &zCn);
                }
                return;
            } else if pCol.eCType == COLTYPE_ANY {
                pCol.affinity = SQLITE_AFF_BLOB;
            }
            if (pCol.colFlags & COLFLAG_PRIMKEY) != 0
                && iPKey as usize != ii
                && pCol.notNull == OE_None
            {
                pCol.notNull = OE_Abort;
                t.tabFlags |= TF_HasNotNull;
            }
        }
    }

    // Special processing for WITHOUT ROWID Tables
    if (tabOpts & TF_WithoutRowid) != 0 {
        let tabFlags = p.borrow().tabFlags;
        if (tabFlags & TF_Autoincrement) != 0 {
            sqlite3ErrorMsg(
                db,
                b"AUTOINCREMENT not allowed on WITHOUT ROWID tables",
                &[],
            );
            return;
        }
        if (tabFlags & TF_HasPrimaryKey) == 0 {
            errmsg!(db, "PRIMARY KEY missing on table %s", &zTabName);
            return;
        }
        p.borrow_mut().tabFlags |= TF_WithoutRowid | TF_NoVisibleRowid;
        convertToWithoutRowidTable(db, &p);
    }
    let sid = p.borrow().pSchema;
    let iDb = db.schema_index(sid);
    debug_assert!(iDb >= 0 && iDb <= db.nDb());

    // Resolve names in all CHECK constraint expressions.
    if p.borrow().pCheck.is_some() {
        let chk = {
            let t = p.borrow();
            t.pCheck.clone()
        };
        let l = db.tree(&chk);
        p.borrow_mut().pCheck = Tree::from_id(l);
        crate::resolve::sqlite3ResolveSelfReference(db, Some(&p), NC_IsCheck, ExprId::NULL, l);
        if db.ppr().nErr != 0 {
            // If errors are seen, delete the CHECK constraints now, else they might
            // actually be used if PRAGMA writable_schema=ON is set.
            sqlite3ExprListDelete(db, l);
            p.borrow_mut().pCheck = Tree::None;
        }
    }
    if (p.borrow().tabFlags & TF_HasGenerated) != 0 {
        let mut nNG = 0;
        let nCol = p.borrow().nCol as usize;
        for ii in 0..nCol {
            let colFlags = p.borrow().aCol[ii].colFlags;
            if (colFlags & COLFLAG_GENERATED) != 0 {
                let pX = sqlite3ColumnExpr(db, &p, ii);
                if crate::resolve::sqlite3ResolveSelfReference(
                    db,
                    Some(&p),
                    NC_GenCol,
                    pX,
                    ExprListId::NULL,
                ) != 0
                {
                    // If there are errors in resolving the expression, change the
                    // expression to a NULL.  This prevents code generators that operate
                    // on the expression from inserting extra parts into the expression
                    // tree that have been allocated from lookaside memory, which is
                    // illegal in a schema and will lead to errors or heap corruption
                    // when the database connection closes.
                    let e = crate::expr::sqlite3ExprAlloc(db, TK_NULL as i32, &Token::default(), 0);
                    sqlite3ColumnSetExpr(db, &p, ii, e);
                }
            } else {
                nNG += 1;
            }
        }
        if nNG == 0 {
            sqlite3ErrorMsg(db, b"must have at least one non-generated column", &[]);
            return;
        }
    }

    // Estimate the average row size for the table and for all implied indices
    {
        let mut t = p.borrow_mut();
        estimateTableWidth(&mut t);
    }
    {
        let t = p.borrow();
        for pIdx in t.pIndex.iter() {
            estimateIndexWidth(pIdx, &t);
        }
    }

    // If not initializing, then create a record for the new table
    // in the schema table of the database.
    //
    // If this is a TEMPORARY table, write the entry into the auxiliary
    // file instead of into the main database file.
    if db.init.busy == 0 {
        if !get_vdbe(db) {
            return;
        }

        sqlite3VdbeAddOp1(db.v(), OP_Close, 0);

        // Initialize zType for the new view or table.
        let (zType, zType2): (&[u8], &[u8]) = if p.borrow().IsOrdinaryTable() {
            // A regular table
            (b"table", b"TABLE")
        } else {
            // A view
            (b"view", b"VIEW")
        };

        // If this is a CREATE TABLE xx AS SELECT ..., execute the SELECT
        // statement to populate the new table. The root-page number for the
        // new table is in register pParse->u1.cr.regRoot.
        //
        // Once the SELECT has been coded by sqlite3Select(), it is in a
        // suitable state to query for the column names and types to be used
        // by the new table.
        //
        // A shared-cache write-lock is not required to write to the new table,
        // as a schema-lock must have already been obtained to create it. Since
        // a schema-lock excludes all other database users, the write-lock would
        // be redundant.
        if pSelect.nn() {
            if db.ppr().IN_SPECIAL_PARSE() {
                db.pp().rc = SQLITE_ERROR;
                db.pp().nErr += 1;
                return;
            }
            let (iCsr, regYield, regRec, regRowid) = {
                let pp = db.pp();
                let iCsr = pp.nTab;
                pp.nTab += 1;
                pp.nMem += 1;
                let regYield = pp.nMem;
                pp.nMem += 1;
                let regRec = pp.nMem;
                pp.nMem += 1;
                let regRowid = pp.nMem;
                (iCsr, regYield, regRec, regRowid)
            };
            sqlite3MayAbort(db);
            let regRoot = db.ppr().u1.cr.regRoot;
            let addrTop;
            {
                let v = db.v();
                sqlite3VdbeAddOp3(v, OP_OpenWrite, iCsr, regRoot, iDb);
                sqlite3VdbeChangeP5(v, OPFLAG_P2ISREG);
                addrTop = sqlite3VdbeCurrentAddr(v) + 1;
                sqlite3VdbeAddOp3(v, OP_InitCoroutine, regYield, 0, addrTop);
            }
            if db.ppr().nErr != 0 {
                return;
            }
            let pSelTab =
                match crate::select::sqlite3ResultSetOfSelect(db, pSelect, SQLITE_AFF_BLOB) {
                    Some(t) => t,
                    None => return,
                };
            {
                let mut st = pSelTab.borrow_mut();
                let mut t = p.borrow_mut();
                debug_assert!(t.aCol.is_empty());
                t.nCol = st.nCol;
                t.nNVCol = st.nCol;
                t.aCol = std::mem::take(&mut st.aCol);
                st.nCol = 0;
            }
            sqlite3DeleteTable(db, &pSelTab);
            let mut dest = SelectDest::default();
            crate::select::sqlite3SelectDestInit(&mut dest, SRT_Coroutine as i32, regYield);
            crate::select::sqlite3Select(db, pSelect, &mut dest);
            if db.ppr().nErr != 0 {
                return;
            }
            sqlite3VdbeEndCoroutine(db, regYield);
            let v = db.v();
            sqlite3VdbeJumpHere(v, addrTop - 1);
            let addrInsLoop = sqlite3VdbeAddOp1(v, OP_Yield, dest.iSDParm);
            sqlite3VdbeAddOp3(v, OP_MakeRecord, dest.iSdst, dest.nSdst, regRec);
            crate::insert::sqlite3TableAffinity(v, &p, 0);
            sqlite3VdbeAddOp2(v, OP_NewRowid, iCsr, regRowid);
            sqlite3VdbeAddOp3(v, OP_Insert, iCsr, regRec, regRowid);
            sqlite3VdbeGoto(v, addrInsLoop);
            sqlite3VdbeJumpHere(v, addrInsLoop);
            sqlite3VdbeAddOp1(v, OP_Close, iCsr);
        }

        // Compute the complete text of the CREATE statement
        let zStmt: ZStr = if pSelect.nn() {
            createTableStmt(db, &p)
        } else {
            let pEnd2: Token = if tabOpts != 0 {
                db.ppr().sLastToken.clone()
            } else {
                pEnd.cloned().unwrap_or_default()
            };
            let sName = db.ppr().sNameToken.clone();
            let mut n = pEnd2.off as i64 - sName.off as i64;
            if pEnd2.at(0) != b';' {
                n += pEnd2.n as i64;
            }
            let src: &[u8] = match &sName.z {
                Some(z) => &z[sName.off as usize..],
                None => b"",
            };
            let src = src.to_vec();
            mprintf!(db, "CREATE %s %.*s", zType2, n, &src)
        };

        // A slot for the record has already been allocated in the
        // schema table.  We just need to update that slot with all
        // the information we've collected.
        let zDbSName = db.aDb[iDb as usize].zDbSName.clone();
        let (regRoot, regRowid) = (db.ppr().u1.cr.regRoot, db.ppr().u1.cr.regRowid);
        sqlite3NestedParse(
            db,
            Some(b"UPDATE %Q.sqlite_master SET type='%s', name=%Q, tbl_name=%Q, rootpage=#%d, sql=%Q WHERE rowid=#%d"),
            &[
                (&zDbSName).into(),
                zType.into(),
                (&zTabName).into(),
                (&zTabName).into(),
                regRoot.into(),
                (&zStmt).into(),
                regRowid.into(),
            ],
        );
        sqlite3ChangeCookie(db, iDb);

        // Check to see if we need to create an sqlite_sequence table for
        // keeping track of autoincrement keys.
        if (p.borrow().tabFlags & TF_Autoincrement) != 0 && !db.ppr().IN_SPECIAL_PARSE() {
            if db.aDb[iDb as usize].pSchema.pSeqTab.is_none() {
                sqlite3NestedParse(
                    db,
                    Some(b"CREATE TABLE %Q.sqlite_sequence(name,seq)"),
                    &[(&zDbSName).into()],
                );
            }
        }

        // Reparse everything to update our internal data structures
        let zWhere = mprintf!(db, "tbl_name='%q' AND type!='trigger'", &zTabName);
        sqlite3VdbeAddParseSchemaOp(db, iDb, Some(zWhere), 0);

        // Test for cycles in generated columns and illegal expressions
        // in CHECK constraints and in DEFAULT clauses.
        if (p.borrow().tabFlags & TF_HasGenerated) != 0 {
            let z = mprintf!(db, "SELECT*FROM\"%w\".\"%w\"", &zDbSName, &zTabName);
            sqlite3VdbeAddOp4(
                db.v(),
                OP_SqlExec,
                0x0001,
                0,
                0,
                P4::Z(z),
                P4_DYNAMIC as i32,
            );
        }
    }

    // Add the table to the in-memory representation of the database.
    if db.init.busy != 0 {
        debug_assert!({
            let t = p.borrow();
            t.HasRowid() || t.iPKey < 0
        });
        publish_table(db, &p);
        let i = iDb as usize;
        let pOld = db.aDb[i].pSchema.tblHash.insert(&zTabName, p.clone());
        if pOld.is_some() {
            debug_assert!(false);
            return;
        }
        db.pp().pNewTable = None;
        db.mDbFlags |= DBFLAG_SchemaChange;

        // If this is the magic sqlite_sequence table used by autoincrement,
        // then record a pointer to this table in the main database structure
        // so that INSERT can find the table easily.
        debug_assert!(db.ppr().nested == 0);
        if zTabName == b"sqlite_sequence" {
            db.aDb[i].pSchema.pSeqTab = Some(p.clone());
        }
    }

    if pSelect.is_null() && p.borrow().IsOrdinaryTable() {
        let pEnd = pEnd.cloned().unwrap_or_default();
        let mut pCons = pCons.cloned().unwrap_or_default();
        if pCons.z.is_none() {
            pCons = pEnd;
        }
        let sName = db.ppr().sNameToken.off as i64;
        p.borrow_mut().u.tab.addColOffset = 13 + (pCons.off as i64 - sName) as i32;
    }
}

