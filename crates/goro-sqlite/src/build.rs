/// Given a token, return a string that consists of the text of that
/// token.  Space to hold the returned string
/// is obtained from sqliteMalloc() and must be freed by the calling
/// function.
///
/// Any quotation marks (ex:  "name", 'name', [name], or `name`) that
/// surround the body of the token are removed.
///
/// Rust: a token whose z is None stands for the C NULL token pointer.
pub fn sqlite3NameFromToken(db: &mut Sqlite3, pName: &Token) -> Option<ZStr> {
    let _ = db;
    pName.z.as_ref()?;
    let mut z = pName.text().to_vec();
    crate::util::sqlite3Dequote(&mut z);
    Some(z)
}

/// C: `void sqlite3OpenSchemaTable(Parse *p, int iDb)`
