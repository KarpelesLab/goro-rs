/// C: `int sqlite3TableColumnToIndex(Index *pIdx, int iCol)`
///
/// Convert an table column number into a index column number.  That is,
/// for the column iCol in the table (as defined by the CREATE TABLE statement)
/// find the (first) offset of that column in index pIdx.  Or return -1
/// if column iCol is not used in index pIdx.
pub fn sqlite3TableColumnToIndex(pIdx: &IndexRef, iCol: i32) -> i32 {
    let x = pIdx.borrow();
    index_column_of(&x, iCol)
}
fn index_column_of(x: &Index, iCol: i32) -> i32 {
    let iCol16 = iCol as i16;
    for i in 0..x.nColumn as usize {
        if iCol16 == x.aiColumn[i] {
            return i as i32;
        }
    }
    -1
}

/// C: `i16 sqlite3StorageColumnToTable(Table *pTab, i16 iCol)`
///
/// Convert a storage column number into a table column number.
///
/// The storage column number (0,1,2,....) is the index of the value
/// as it appears in the record on disk.  The true column number
/// is the index (0,1,2,...) of the column in the CREATE TABLE statement.
///
/// The storage column number is less than the table column number if
/// and only there are VIRTUAL columns to the left.
pub fn sqlite3StorageColumnToTable(pTab: &TableRef, mut iCol: i16) -> i16 {
    let t = pTab.borrow();
    if (t.tabFlags & TF_HasVirtual) != 0 {
        let mut i: i16 = 0;
        while i <= iCol {
            if (t.aCol[i as usize].colFlags & COLFLAG_VIRTUAL) != 0 {
                iCol += 1;
            }
            i += 1;
        }
    }
    iCol
}

/// C: `i16 sqlite3TableColumnToStorage(Table *pTab, i16 iCol)`
///
/// Convert a table column number into a storage column number.
///
/// The storage column number (0,1,2,....) is the index of the value
/// as it appears in the record on disk.  Or, if the input column is
/// the N-th virtual column (zero-based) then the storage number is
/// the number of non-virtual columns in the table plus N.
///
/// The true column number is the index (0,1,2,...) of the column in
/// the CREATE TABLE statement.
///
/// If the input column is a VIRTUAL column, then it should not appear
/// in storage.  But the value sometimes is cached in registers that
/// follow the range of registers used to construct storage.  This
/// avoids computing the same VIRTUAL column multiple times, and provides
/// values for use by OP_Param opcodes in triggers.  Hence, if the
/// input column is a VIRTUAL table, put it after all the other columns.
///
/// In the following, N means "normal column", S means STORED, and
/// V means VIRTUAL.  Suppose the CREATE TABLE has columns like this:
///
///        CREATE TABLE ex(N,S,V,N,S,V,N,S,V);
///                     -- 0 1 2 3 4 5 6 7 8
///
/// Then the mapping from this function is as follows:
///
///    INPUTS:     0 1 2 3 4 5 6 7 8
///    OUTPUTS:    0 1 6 2 3 7 4 5 8
///
/// So, in other words, this routine shifts all the virtual columns to
/// the end.
///
/// If the pTab does not have any virtual columns, then this routine is
/// no-op that always return iCol.  If iCol is negative (indicating the
/// ROWID column) then this routine return iCol.
pub fn sqlite3TableColumnToStorage(pTab: &TableRef, iCol: i16) -> i16 {
    let t = pTab.borrow();
    debug_assert!(iCol < t.nCol);
    if (t.tabFlags & TF_HasVirtual) == 0 || iCol < 0 {
        return iCol;
    }
    let mut n: i16 = 0;
    let mut i: i16 = 0;
    while i < iCol {
        if (t.aCol[i as usize].colFlags & COLFLAG_VIRTUAL) == 0 {
            n += 1;
        }
        i += 1;
    }
    if (t.aCol[i as usize].colFlags & COLFLAG_VIRTUAL) != 0 {
        // iCol is a virtual column itself
        t.nNVCol + i - n
    } else {
        // iCol is a normal or stored column
        n
    }
}

/// Insert a single OP_JournalMode query opcode in order to force the
/// prepared statement to return false for sqlite3_stmt_readonly().  This
/// is used by CREATE TABLE IF NOT EXISTS and similar if the table already
/// exists, so that the prepared statement for CREATE TABLE IF NOT EXISTS
/// will return false for sqlite3_stmt_readonly() even if that statement
/// is a read-only no-op.
fn sqlite3ForceNotReadOnly(db: &mut Sqlite3) {
    db.pp().nMem += 1;
    let iReg = db.ppr().nMem;
    if get_vdbe(db) {
        let v = db.v();
        sqlite3VdbeAddOp3(v, OP_JournalMode, 0, iReg, PAGER_JOURNALMODE_QUERY);
        sqlite3VdbeUsesBtree(v, 0);
    }
}

