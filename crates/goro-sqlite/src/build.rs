/// C: `void sqlite3CreateForeignKey( Parse *pParse, ExprList *pFromCol, Token *pTo, ExprList *pToCol, int flags )`
///
/// This routine is called to create a new foreign key on the table
/// currently under construction.  pFromCol determines which columns
/// in the current table point to the foreign key.  If pFromCol==0 then
/// connect the key to the last column inserted.  pTo is the name of
/// the table referred to (a.k.a the "parent" table).  pToCol is a list
/// of tables in the parent pTo table.  flags contains all
/// information about the conflict resolution algorithms specified
/// in the ON DELETE, ON UPDATE and ON INSERT clauses.
///
/// An FKey structure is created and added to the table currently
/// under construction in the pParse->pNewTable field.
///
/// The foreign key is set for IMMEDIATE processing.  A subsequent call
/// to sqlite3DeferForeignKey() might change this to DEFERRED.
pub fn sqlite3CreateForeignKey(
    db: &mut Sqlite3,
    pFromCol: ExprListId,
    pTo: &Token,
    pToCol: ExprListId,
    flags: i32,
) {
    'fk_end: {
        let p = match db.ppr().pNewTable.clone() {
            Some(p) if !db.ppr().IN_DECLARE_VTAB() => p,
            _ => break 'fk_end,
        };
        let nCol: i32;
        let pNCol = p.borrow().nCol as i32;
        if pFromCol.is_null() {
            let iCol = pNCol - 1;
            if iCol < 0 {
                break 'fk_end;
            }
            if pToCol.nn() && db.el(pToCol).nExpr() != 1 {
                let zc = p.borrow().aCol[iCol as usize].zCnName.clone();
                errmsg!(
                    db,
                    "foreign key on %s should reference only one column of table %T",
                    &zc,
                    pTo
                );
                break 'fk_end;
            }
            nCol = 1;
        } else if pToCol.nn() && db.el(pToCol).nExpr() != db.el(pFromCol).nExpr() {
            sqlite3ErrorMsg(
                db,
                b"number of columns in foreign key does not match the number of columns in the referenced table",
                &[],
            );
            break 'fk_end;
        } else {
            nCol = db.el(pFromCol).nExpr();
        }
        let mut zTo = pTo.text().to_vec();
        crate::util::sqlite3Dequote(&mut zTo);
        let pFKey: FKeyRef = Rc::new(RefCell::new(FKey {
            pFrom: Rc::downgrade(&p),
            zTo: zTo.clone(),
            nCol,
            aCol: vec![FKeyCol::default(); nCol as usize],
            ..Default::default()
        }));
        debug_assert!(p.borrow().IsOrdinaryTable());
        if db.ppr().IN_RENAME_OBJECT() {
            sqlite3RenameTokenMap(db, rename_key_fkey_to(&pFKey), pTo);
        }
        if pFromCol.is_null() {
            pFKey.borrow_mut().aCol[0].iFrom = pNCol - 1;
        } else {
            for i in 0..nCol {
                let zEName = db.el(pFromCol).a[i as usize].zEName.clone();
                let mut found = -1;
                {
                    let t = p.borrow();
                    for j in 0..t.nCol as i32 {
                        if sqlite3StrICmp(Some(&t.aCol[j as usize].zCnName), zEName.as_deref()) == 0
                        {
                            found = j;
                            break;
                        }
                    }
                }
                if found < 0 {
                    errmsg!(
                        db,
                        "unknown column \"%s\" in foreign key definition",
                        &zEName
                    );
                    break 'fk_end;
                }
                pFKey.borrow_mut().aCol[i as usize].iFrom = found;
                if db.ppr().IN_RENAME_OBJECT() {
                    sqlite3RenameTokenRemap(
                        db,
                        Some(rename_key_fkey_from_col(&pFKey, i)),
                        rename_key_elist_item(pFromCol, i),
                    );
                }
            }
        }
        if pToCol.nn() {
            for i in 0..nCol {
                let zEName = db.el(pToCol).a[i as usize].zEName.clone();
                pFKey.borrow_mut().aCol[i as usize].zCol = Some(zEName.unwrap_or_default());
                if db.ppr().IN_RENAME_OBJECT() {
                    sqlite3RenameTokenRemap(
                        db,
                        Some(rename_key_fkey_to_col(&pFKey, i)),
                        rename_key_elist_item(pToCol, i),
                    );
                }
            }
        }
        {
            let mut f = pFKey.borrow_mut();
            f.isDeferred = 0;
            f.aAction[0] = (flags & 0xff) as u8; // ON DELETE action
            f.aAction[1] = ((flags >> 8) & 0xff) as u8; // ON UPDATE action
        }

        // pNextTo = sqlite3HashInsert(&p->pSchema->fkeyHash, pFKey->zTo, pFKey):
        // the new FKey becomes the head of the list of FKeys with this parent.
        let sid = p.borrow().pSchema;
        let iDb = db.schema_index(sid);
        if iDb >= 0 {
            let h = &mut db.aDb[iDb as usize].pSchema.fkeyHash;
            if let Some(list) = h.find_mut(&zTo) {
                list.insert(0, pFKey.clone());
            } else {
                h.insert(&zTo, vec![pFKey.clone()]);
            }
        }

        // Link the foreign key to the table as the last step.
        p.borrow_mut().u.tab.pFKey.insert(0, pFKey);
    }

    // fk_end:
    sqlite3ExprListDelete(db, pFromCol);
    sqlite3ExprListDelete(db, pToCol);
}

/// C: `void sqlite3DeferForeignKey(Parse *pParse, int isDeferred)`
///
/// This routine is called when an INITIALLY IMMEDIATE or INITIALLY DEFERRED
/// clause is seen as part of a foreign key definition.  The isDeferred
/// parameter is 1 for INITIALLY DEFERRED and 0 for INITIALLY IMMEDIATE.
/// The behavior of the most recently created foreign key is adjusted
/// accordingly.
pub fn sqlite3DeferForeignKey(db: &mut Sqlite3, isDeferred: i32) {
    let pTab = match db.ppr().pNewTable.clone() {
        Some(t) => t,
        None => return,
    };
    let t = pTab.borrow();
    if !t.IsOrdinaryTable() {
        return;
    }
    if let Some(pFKey) = t.u.tab.pFKey.first() {
        debug_assert!(isDeferred == 0 || isDeferred == 1); // EV: R-30323-21917
        pFKey.borrow_mut().isDeferred = isDeferred as u8;
    }
}

