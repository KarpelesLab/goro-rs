/// Record the fact that we want to lock a table at run-time.
///
/// The table to be locked has root page iTab and is found in database iDb.
/// A read or a write lock can be taken depending on isWritelock.
///
/// This routine just records the fact that the lock is desired.  The
/// code to make the lock occur is generated by a later call to
/// codeTableLocks() which occurs during sqlite3FinishCoding().
fn lockTable(db: &mut Sqlite3, iDb: i32, iTab: Pgno, isWriteLock: u8, zName: &[u8]) {
    debug_assert!(iDb >= 0);
    let pToplevel = db.toplevel();
    for p in pToplevel.aTableLock.iter_mut() {
        if p.iDb == iDb && p.iTab == iTab {
            p.isWriteLock = (p.isWriteLock != 0 || isWriteLock != 0) as u8;
            return;
        }
    }
    pToplevel.aTableLock.push(TableLock {
        iDb,
        iTab,
        isWriteLock,
        zLockName: zName.to_vec(),
    });
}

/// C: `void sqlite3TableLock( Parse *pParse, int iDb, Pgno iTab, u8 isWriteLock, const char *zName )`
pub fn sqlite3TableLock(
    db: &mut Sqlite3,
    iDb: i32,
    iTab: Pgno,
    isWriteLock: u8,
    zName: Option<&[u8]>,
) {
    if iDb == 1 {
        return;
    }
    let pBt = match db.aDb[iDb as usize].pBt.clone() {
        Some(b) => b,
        None => return,
    };
    if crate::btree::sqlite3BtreeSharable(&pBt) == 0 {
        return;
    }
    lockTable(db, iDb, iTab, isWriteLock, zName.unwrap_or(b""));
}

/// Code an OP_TableLock instruction for each table locked by the
/// statement (configured by calls to sqlite3TableLock()).
fn codeTableLocks(db: &mut Sqlite3) {
    let locks = db.ppr().aTableLock.clone();
    let v = db.v();
    for p in locks.iter() {
        sqlite3VdbeAddOp4(
            v,
            OP_TableLock,
            p.iDb,
            p.iTab as i32,
            p.isWriteLock as i32,
            P4::Z(p.zLockName.clone()),
            P4_STATIC as i32,
        );
    }
}

/// C: `int sqlite3DbMaskAllZero(yDbMask m)`
pub fn sqlite3DbMaskAllZero(m: yDbMask) -> i32 {
    (m == 0) as i32
}

