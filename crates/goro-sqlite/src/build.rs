/// C: `void sqlite3DeleteColumnNames(sqlite3 *db, Table *pTable)`
///
/// Delete memory allocated for the column names of a table or view (the
/// Table.aCol[] array).
pub fn sqlite3DeleteColumnNames(db: &mut Sqlite3, pTable: &TableRef) {
    let _ = db;
    let mut t = pTable.borrow_mut();
    if !t.aCol.is_empty() {
        t.aCol.clear();
        t.nCol = 0;
        if t.IsOrdinaryTable() {
            t.u.tab.pDfltList = Tree::None;
        }
    }
}

/// Remove the memory data structures associated with the given
/// Table.  No changes are made to disk by this routine.
///
/// This routine just deletes the data structure.  It does not unlink
/// the table data structure from the hash table.  But it does destroy
/// memory structures of the indices and foreign keys associated with
/// the table.
fn deleteTable(db: &mut Sqlite3, pTable: &TableRef) {
    // Delete all indices associated with this table.
    let (indexes, isVirtual, isOrdinary) = {
        let mut t = pTable.borrow_mut();
        (
            std::mem::take(&mut t.pIndex),
            t.IsVirtual(),
            t.IsOrdinaryTable(),
        )
    };
    for pIndex in indexes.iter() {
        if !isVirtual {
            let (sid, zName) = {
                let x = pIndex.borrow();
                (x.pSchema, x.zName.clone())
            };
            let i = db.schema_index(sid);
            if i >= 0 {
                let h = &mut db.aDb[i as usize].pSchema.idxHash;
                let same = h.find(&zName).map_or(false, |x| Rc::ptr_eq(x, pIndex));
                if same {
                    h.remove(&zName);
                }
            }
        }
        sqlite3FreeIndex(db, pIndex);
    }

    if isOrdinary {
        crate::fkey::sqlite3FkDelete(db, pTable);
    } else if isVirtual {
        crate::vtab::sqlite3VtabClear(db, pTable);
    } else {
        let mut t = pTable.borrow_mut();
        debug_assert!(t.IsView());
        t.u.view.pSelect = Tree::None;
    }

    // Delete the Table structure itself.
    sqlite3DeleteColumnNames(db, pTable);
    let mut t = pTable.borrow_mut();
    t.zColAff = None;
    t.pCheck = Tree::None;
}

/// C: `void sqlite3DeleteTable(sqlite3 *db, Table *pTable)`
///
/// Rust: the memory is reclaimed when the last Rc goes away; this function
/// keeps the C reference count (nTabRef) and runs the side effects of
/// deleteTable() (unlinking indices and foreign keys) when it reaches 0.
pub fn sqlite3DeleteTable(db: &mut Sqlite3, pTable: &TableRef) {
    // Do not delete the table until the reference count reaches zero.
    let n = {
        let mut t = pTable.borrow_mut();
        t.nTabRef = t.nTabRef.wrapping_sub(1);
        t.nTabRef
    };
    if n > 0 {
        return;
    }
    deleteTable(db, pTable);
}

/// C: `void sqlite3DeleteTableGeneric(sqlite3 *db, void *pTable)`
pub fn sqlite3DeleteTableGeneric(db: &mut Sqlite3, pTable: &TableRef) {
    sqlite3DeleteTable(db, pTable);
}

/// C: `void sqlite3UnlinkAndDeleteTable(sqlite3 *db, int iDb, const char *zTabName)`
///
/// Unlink the given table from the hash tables and the delete the
/// table structure with all its indices and foreign keys.
pub fn sqlite3UnlinkAndDeleteTable(db: &mut Sqlite3, iDb: i32, zTabName: Option<&[u8]>) {
    debug_assert!(iDb >= 0 && iDb < db.nDb());
    let p = db.aDb[iDb as usize]
        .pSchema
        .tblHash
        .remove(zTabName.unwrap_or(b""));
    if let Some(p) = p {
        sqlite3DeleteTable(db, &p);
    }
    db.mDbFlags |= DBFLAG_SchemaChange;
}

/// C: `char * sqlite3NameFromToken(sqlite3 *db, const Token *pName)`
