/// Return true if any column of pIndex uses the zColl collation
fn collationMatch(zColl: &[u8], pIndex: &IndexRef) -> bool {
    let x = pIndex.borrow();
    for i in 0..x.nColumn as usize {
        if streq(&x.azColl[i], zColl) {
            return true;
        }
    }
    false
}

/// C: `void sqlite3Reindex(Parse *pParse, Token *pName1, Token *pName2)`
///
/// Generate code for the REINDEX command.
///
///        REINDEX                            -- 1
///        REINDEX  <collation>               -- 2
///        REINDEX  ?<database>.?<indexname>  -- 3
///        REINDEX  ?<database>.?<tablename>  -- 4
///        REINDEX  EXPRESSIONS               -- 5
///
/// Form 1 causes all indexes in all attached databases to be rebuilt.
/// Form 2 rebuilds all indexes in all databases that use the named
/// collating function.  Forms 3 and 4 rebuild the named index or all
/// indexes associated with the named table, respectively.  Form 5
/// rebuilds all expression indexes in addition to all collations,
/// indexes, or tables named "EXPRESSIONS".
///
/// If the name is ambiguous such that it matches two or more of
/// forms 2 through 5, then rebuild the union of all matching indexes,
/// taken care to avoid rebuilding the same index more than once.
///
/// Rust: pName1/pName2 may be None (C NULL).
pub fn sqlite3Reindex(db: &mut Sqlite3, pName1: Option<&Token>, pName2: Option<&Token>) {
    let mut z: Option<ZStr> = None; // Name of a table or index or collation
    let mut zDb: Option<ZStr> = None; // Name of the database
    let mut iReDb: i32 = -1; // The database index number
    let mut bMatch = false; // At least one name match
    let mut zColl: Option<ZStr> = None; // Rebuild indexes using this collation
    let mut pReTab: Option<TableRef> = None; // Rebuild all indexes of this table
    let mut pReIndex: Option<IndexRef> = None; // Rebuild this index
    let mut isExprIdx = false; // Rebuild all expression indexes
    let mut bAll = false; // Rebuild all indexes

    // Read the database schema. If an error occurs, leave an error message
    // and code in pParse and return NULL.
    if SQLITE_OK != crate::prepare::sqlite3ReadSchema(db) {
        return;
    }

    match pName1 {
        None => {
            // rebuild all indexes
            bMatch = true;
            bAll = true;
        }
        Some(n1) => {
            let n2 = pName2.cloned().unwrap_or_default();
            if n2.z.is_none() {
                debug_assert!(n1.z.is_some());
                z = sqlite3NameFromToken(db, n1);
                if z.is_none() {
                    return;
                }
            } else {
                let mut pObjName = Token::default();
                iReDb = sqlite3TwoPartName(db, n1, &n2, &mut pObjName);
                if iReDb < 0 {
                    return;
                }
                z = sqlite3NameFromToken(db, &pObjName);
                if z.is_none() {
                    return;
                }
                zDb = db.aDb[iReDb as usize].zDbSName.clone();
            }
        }
    }
    if !bAll {
        let zz = z.clone().unwrap_or_default();
        if zDb.is_none() && streq(&zz, b"expressions") {
            isExprIdx = true;
            bMatch = true;
        }
        let enc = db.ENC();
        if zDb.is_none() && crate::callback::sqlite3FindCollSeq(db, enc, Some(&zz), 0).is_some() {
            zColl = Some(zz.clone());
            bMatch = true;
        }
        if zColl.is_none() {
            pReTab = sqlite3FindTable(db, Some(&zz), zDb.as_deref());
            if pReTab.is_some() {
                bMatch = true;
            }
        }
        if zColl.is_none() {
            pReIndex = sqlite3FindIndex(db, Some(&zz), zDb.as_deref());
            if pReIndex.is_some() {
                bMatch = true;
            }
        }
    }
    if bMatch {
        for iDb in 0..db.nDb() {
            if iReDb >= 0 && iReDb != iDb {
                continue;
            }
            for pTab in db.aDb[iDb as usize].pSchema.tblHash.values() {
                if pTab.borrow().IsVirtual() {
                    continue;
                }
                let indexes = pTab.borrow().pIndex.clone();
                for pIdx in indexes.iter() {
                    if bAll
                        || pReTab.as_ref().map_or(false, |t| Rc::ptr_eq(t, &pTab))
                        || pReIndex.as_ref().map_or(false, |x| Rc::ptr_eq(x, pIdx))
                        || (isExprIdx && pIdx.borrow().bHasExpr != 0)
                        || zColl.as_ref().map_or(false, |c| collationMatch(c, pIdx))
                    {
                        sqlite3BeginWriteOperation(db, 0, iDb);
                        sqlite3RefillIndex(db, pIdx, -1);
                    }
                } // End loop over indexes of pTab
            } // End loop over tables of iDb
        } // End loop over databases
    } else {
        sqlite3ErrorMsg(db, b"unable to identify the object to be reindexed", &[]);
    }
}

/// C: `KeyInfo * sqlite3KeyInfoOfIndex(Parse *pParse, Index *pIdx)`
///
/// Return a KeyInfo structure that is appropriate for the given Index.
///
/// The caller should invoke sqlite3KeyInfoUnref() on the returned object
/// when it has finished using it.
///
/// Rust: C tests `zColl==sqlite3StrBINARY` (pointer identity with the
/// static default name); the port compares with the exact bytes "BINARY".
pub fn sqlite3KeyInfoOfIndex(db: &mut Sqlite3, pIdx: &IndexRef) -> Option<KeyInfoRef> {
    let (nCol, nKey, uniqNotNull, azColl, aSortOrder) = {
        let x = pIdx.borrow();
        (
            x.nColumn as i32,
            x.nKeyCol as i32,
            x.uniqNotNull,
            x.azColl.clone(),
            x.aSortOrder.clone(),
        )
    };
    if db.ppr().nErr != 0 {
        return None;
    }
    let pKey = if uniqNotNull != 0 {
        crate::select::sqlite3KeyInfoAlloc(db, nKey, nCol - nKey)
    } else {
        crate::select::sqlite3KeyInfoAlloc(db, nCol, 0)
    };
    let pKey = pKey?;
    for i in 0..nCol as usize {
        let zColl = &azColl[i];
        let c = if zColl.as_slice() == sqlite3StrBINARY {
            None
        } else {
            crate::callback::sqlite3LocateCollSeq(db, Some(zColl))
        };
        let mut k = pKey.borrow_mut();
        k.aColl[i] = c;
        k.aSortFlags[i] = aSortOrder[i];
        debug_assert!(0 == (k.aSortFlags[i] & KEYINFO_ORDER_BIGNULL));
    }
    if db.ppr().nErr != 0 {
        debug_assert!(db.ppr().rc == SQLITE_ERROR_MISSING_COLLSEQ);
        let (bNoQuery, sid, zName) = {
            let x = pIdx.borrow();
            (x.bNoQuery, x.pSchema, x.zName.clone())
        };
        let i = db.schema_index(sid);
        let inHash = i >= 0 && db.aDb[i as usize].pSchema.idxHash.find(&zName).is_some();
        if bNoQuery == 0 && inHash {
            // Deactivate the index because it contains an unknown collating
            // sequence.  The only way to reactive the index is to reload the
            // schema.  Adding the missing collating sequence later does not
            // reactive the index.  The application had the chance to register
            // the missing index using the collation-needed callback.  For
            // simplicity, SQLite will not give the application a second chance.
            //
            // Except, do not do this if the index is not in the schema hash
            // table. In this case the index is currently being constructed
            // by a CREATE INDEX statement, and retrying will not help.
            pIdx.borrow_mut().bNoQuery = 1;
            db.pp().rc = SQLITE_ERROR_RETRY;
        }
        crate::select::sqlite3KeyInfoUnref(db, &pKey);
        return None;
    }
    Some(pKey)
}

