/// C: `void sqlite3BeginTransaction(Parse *pParse, int type)`
///
/// Generate VDBE code for a BEGIN statement.
pub fn sqlite3BeginTransaction(db: &mut Sqlite3, type_: i32) {
    if sqlite3AuthCheck(db, SQLITE_TRANSACTION, Some(b"BEGIN"), None, None) != 0 {
        return;
    }
    if !get_vdbe(db) {
        return;
    }
    if type_ != TK_DEFERRED as i32 {
        for i in 0..db.nDb() {
            let pBt = db.aDb[i as usize].pBt.clone();
            let eTxnType = if pBt.map_or(false, |b| crate::btree::sqlite3BtreeIsReadonly(&b) != 0) {
                0 // Read txn
            } else if type_ == TK_EXCLUSIVE as i32 {
                2 // Exclusive txn
            } else {
                1 // Write txn
            };
            let v = db.v();
            sqlite3VdbeAddOp2(v, OP_Transaction, i, eTxnType);
            sqlite3VdbeUsesBtree(v, i);
        }
    }
    sqlite3VdbeAddOp0(db.v(), OP_AutoCommit);
}

/// C: `void sqlite3EndTransaction(Parse *pParse, int eType)`
///
/// Generate VDBE code for a COMMIT or ROLLBACK statement.
/// Code for ROLLBACK is generated if eType==TK_ROLLBACK.  Otherwise
/// code is generated for a COMMIT.
pub fn sqlite3EndTransaction(db: &mut Sqlite3, eType: i32) {
    let isRollback = (eType == TK_ROLLBACK as i32) as i32;
    let z: &[u8] = if isRollback != 0 {
        b"ROLLBACK"
    } else {
        b"COMMIT"
    };
    if sqlite3AuthCheck(db, SQLITE_TRANSACTION, Some(z), None, None) != 0 {
        return;
    }
    if get_vdbe(db) {
        sqlite3VdbeAddOp2(db.v(), OP_AutoCommit, 1, isRollback);
    }
}

/// C: `void sqlite3Savepoint(Parse *pParse, int op, Token *pName)`
///
/// This function is called by the parser when it parses a command to create,
/// release or rollback an SQL savepoint.
pub fn sqlite3Savepoint(db: &mut Sqlite3, op: i32, pName: &Token) {
    if let Some(zName) = sqlite3NameFromToken(db, pName) {
        let hasV = get_vdbe(db);
        const az: [&[u8]; 3] = [b"BEGIN", b"RELEASE", b"ROLLBACK"];
        debug_assert!(SAVEPOINT_BEGIN == 0 && SAVEPOINT_RELEASE == 1 && SAVEPOINT_ROLLBACK == 2);
        if !hasV
            || sqlite3AuthCheck(
                db,
                SQLITE_SAVEPOINT,
                Some(az[op as usize]),
                Some(&zName),
                None,
            ) != 0
        {
            return;
        }
        sqlite3VdbeAddOp4(
            db.v(),
            OP_Savepoint,
            op,
            0,
            0,
            P4::Z(zName),
            P4_DYNAMIC as i32,
        );
    }
}

/// Make sure the TEMP database is open and available for use (parse
/// number iParse receives the error messages).
fn openTempDatabase(db: &mut Sqlite3, iParse: usize) -> i32 {
    if db.aDb[1].pBt.is_none() && db.parses[iParse].explain == 0 {
        const flags: i32 = SQLITE_OPEN_READWRITE
            | SQLITE_OPEN_CREATE
            | SQLITE_OPEN_EXCLUSIVE
            | SQLITE_OPEN_DELETEONCLOSE
            | SQLITE_OPEN_TEMP_DB;

        let pVfs = db.pVfs.clone();
        let mut pBt: Option<BtreeP> = None;
        let rc = crate::btree::sqlite3BtreeOpen(db, &pVfs, None, &mut pBt, 0, flags);
        if rc != SQLITE_OK {
            // sqlite3ErrorMsg() on the given parse
            let cur = db.parses.len() - 1;
            if iParse == cur {
                sqlite3ErrorMsg(
                    db,
                    b"unable to open a temporary database file for storing temporary tables",
                    &[],
                );
            } else {
                let p = &mut db.parses[iParse];
                p.zErrMsg = Some(
                    b"unable to open a temporary database file for storing temporary tables"
                        .to_vec(),
                );
                p.nErr += 1;
                p.rc = SQLITE_ERROR;
            }
            db.parses[iParse].rc = rc;
            return 1;
        }
        let pBt = pBt.expect("btree");
        db.aDb[1].pBt = Some(pBt.clone());
        if SQLITE_NOMEM == crate::btree::sqlite3BtreeSetPageSize(&pBt, db.nextPagesize, 0, 0) {
            return 1;
        }
    }
    0
}

/// C: `int sqlite3OpenTempDatabase(Parse *pParse)`
///
/// Make sure the TEMP database is open and available for use.  Return
/// the number of errors.  Leave any error messages in the pParse structure.
pub fn sqlite3OpenTempDatabase(db: &mut Sqlite3) -> i32 {
    let i = db.parses.len() - 1;
    openTempDatabase(db, i)
}

/// Record the fact that the schema cookie will need to be verified
/// for database iDb.  The code to actually verify the schema cookie
/// will occur at the end of the top-level VDBE and will be generated
/// later, by sqlite3FinishCoding().
fn sqlite3CodeVerifySchemaAtToplevel(db: &mut Sqlite3, iDb: i32) {
    debug_assert!(iDb >= 0 && iDb < db.nDb());
    debug_assert!(iDb < SQLITE_MAX_DB);
    let iTop = db.ppr().iToplevel;
    if !DbMaskTest(db.parses[iTop].cookieMask, iDb) {
        DbMaskSet(&mut db.parses[iTop].cookieMask, iDb);
        if OMIT_TEMPDB == 0 && iDb == 1 {
            openTempDatabase(db, iTop);
        }
    }
}

/// C: `void sqlite3CodeVerifySchema(Parse *pParse, int iDb)`
pub fn sqlite3CodeVerifySchema(db: &mut Sqlite3, iDb: i32) {
    sqlite3CodeVerifySchemaAtToplevel(db, iDb);
}

/// C: `void sqlite3CodeVerifyNamedSchema(Parse *pParse, const char *zDb)`
///
/// If argument zDb is NULL, then call sqlite3CodeVerifySchema() for each
/// attached database. Otherwise, invoke it for the database named zDb only.
pub fn sqlite3CodeVerifyNamedSchema(db: &mut Sqlite3, zDb: Option<&[u8]>) {
    for i in 0..db.nDb() {
        let ok = {
            let pDb = &db.aDb[i as usize];
            pDb.pBt.is_some()
                && (zDb.is_none() || 0 == sqlite3StrICmp(zDb, pDb.zDbSName.as_deref()))
        };
        if ok {
            sqlite3CodeVerifySchema(db, i);
        }
    }
}

/// C: `void sqlite3BeginWriteOperation(Parse *pParse, int setStatement, int iDb)`
///
/// Generate VDBE code that prepares for doing an operation that
/// might change the database.
///
/// This routine starts a new transaction if we are not already within
/// a transaction.  If we are already within a transaction, then a checkpoint
/// is set if the setStatement parameter is true.  A checkpoint should
/// be set for operations that might fail (due to a constraint) part of
/// the way through and which will need to undo some writes without having to
/// rollback the whole transaction.  For operations where all constraints
/// can be checked before any changes are made to the database, it is never
/// necessary to undo a write and the checkpoint should not be set.
pub fn sqlite3BeginWriteOperation(db: &mut Sqlite3, setStatement: i32, iDb: i32) {
    sqlite3CodeVerifySchemaAtToplevel(db, iDb);
    let pToplevel = db.toplevel();
    DbMaskSet(&mut pToplevel.writeMask, iDb);
    pToplevel.isMultiWrite |= setStatement as u8;
}

/// C: `void sqlite3MultiWrite(Parse *pParse)`
///
/// Indicate that the statement currently under construction might write
/// more than one entry (example: deleting one row then inserting another,
/// inserting multiple rows in a table, or inserting a row and index entries.)
/// If an abort occurs after some of these writes have completed, then it will
/// be necessary to undo the completed writes.
pub fn sqlite3MultiWrite(db: &mut Sqlite3) {
    db.toplevel().isMultiWrite = 1;
}

/// C: `void sqlite3MayAbort(Parse *pParse)`
///
/// The code generator calls this routine if is discovers that it is
/// possible to abort a statement prior to completion.  In order to
/// perform this abort without corrupting the database, we need to make
/// sure that the statement is protected by a statement transaction.
///
/// Technically, we only need to set the mayAbort flag if the
/// isMultiWrite flag was previously set.  There is a time dependency
/// such that the abort must occur after the multiwrite.  This makes
/// some statements involving the REPLACE conflict resolution algorithm
/// go a little faster.  But taking advantage of this time dependency
/// makes it more difficult to prove that the code is correct (in
/// particular, it prevents us from writing an effective
/// implementation of sqlite3AssertMayAbort()) and so we have chosen
/// to take the safe route and skip the optimization.
pub fn sqlite3MayAbort(db: &mut Sqlite3) {
    db.toplevel().mayAbort = 1;
}

/// C: `void sqlite3HaltConstraint( Parse *pParse, int errCode, int onError, char *p4, i8 p4type, u8 p5Errmsg )`
///
/// Code an OP_Halt that causes the vdbe to return an SQLITE_CONSTRAINT
/// error. The onError parameter determines which (if any) of the statement
/// and/or current transaction is rolled back.
pub fn sqlite3HaltConstraint(
    db: &mut Sqlite3,
    errCode: i32,
    onError: i32,
    p4: Option<&[u8]>,
    p4type: i8,
    p5Errmsg: u8,
) {
    debug_assert!(db.ppr().pVdbe.is_some());
    get_vdbe(db);
    debug_assert!((errCode & 0xff) == SQLITE_CONSTRAINT || db.ppr().nested != 0);
    if onError == OE_Abort as i32 {
        sqlite3MayAbort(db);
    }
    let p4v = match p4 {
        Some(z) => P4::Z(z.to_vec()),
        None => P4::None,
    };
    let v = db.v();
    sqlite3VdbeAddOp4(v, OP_Halt, errCode, onError, 0, p4v, p4type as i32);
    sqlite3VdbeChangeP5(v, p5Errmsg as u16);
}

/// C: `void sqlite3UniqueConstraint( Parse *pParse, int onError, Index *pIdx )`
///
/// Code an OP_Halt due to UNIQUE or PRIMARY KEY constraint violation.
pub fn sqlite3UniqueConstraint(db: &mut Sqlite3, onError: i32, pIdx: &IndexRef) {
    use crate::printf::{
        sqlite3_str_append, sqlite3_str_appendall, sqlite3_str_appendf, sqlite3StrAccumFinish,
        sqlite3StrAccumInit,
    };
    let pTab = pIdx.borrow().table();
    let mut errMsg = StrAccum::default();
    sqlite3StrAccumInit(&mut errMsg, 0, db.aLimit[SQLITE_LIMIT_LENGTH as usize]);
    let isPk;
    {
        let x = pIdx.borrow();
        let t = pTab.borrow();
        isPk = x.IsPrimaryKeyIndex();
        if x.aColExpr.is_some() {
            sqlite3_str_appendf(&mut errMsg, b"index '%q'", &[(&x.zName).into()]);
        } else {
            for j in 0..x.nKeyCol as usize {
                debug_assert!(x.aiColumn[j] >= 0);
                let zCol = &t.aCol[x.aiColumn[j] as usize].zCnName;
                if j != 0 {
                    sqlite3_str_append(&mut errMsg, b", ", 2);
                }
                sqlite3_str_appendall(&mut errMsg, &t.zName);
                sqlite3_str_append(&mut errMsg, b".", 1);
                sqlite3_str_appendall(&mut errMsg, zCol);
            }
        }
    }
    let zErr = sqlite3StrAccumFinish(&mut errMsg);
    sqlite3HaltConstraint(
        db,
        if isPk {
            SQLITE_CONSTRAINT_PRIMARYKEY
        } else {
            SQLITE_CONSTRAINT_UNIQUE
        },
        onError,
        zErr.as_deref(),
        P4_DYNAMIC,
        P5_ConstraintUnique as u8,
    );
}

/// C: `void sqlite3RowidConstraint( Parse *pParse, int onError, Table *pTab )`
///
/// Code an OP_Halt due to non-unique rowid.
pub fn sqlite3RowidConstraint(db: &mut Sqlite3, onError: i32, pTab: &TableRef) {
    let (iPKey, zName, zCol) = {
        let t = pTab.borrow();
        let c = if t.iPKey >= 0 {
            t.aCol[t.iPKey as usize].zCnName.clone()
        } else {
            Vec::new()
        };
        (t.iPKey, t.zName.clone(), c)
    };
    let (zMsg, rc) = if iPKey >= 0 {
        (
            mprintf!(db, "%s.%s", &zName, &zCol),
            SQLITE_CONSTRAINT_PRIMARYKEY,
        )
    } else {
        (mprintf!(db, "%s.rowid", &zName), SQLITE_CONSTRAINT_ROWID)
    };
    sqlite3HaltConstraint(
        db,
        rc,
        onError,
        Some(&zMsg),
        P4_DYNAMIC,
        P5_ConstraintUnique as u8,
    );
}

