#[inline]
fn tbl_find(db: &Sqlite3, iDb: usize, zName: &[u8]) -> Option<TableRef> {
    db.aDb[iDb].pSchema.tblHash.find(zName).cloned()
}

/// C: `Table * sqlite3FindTable(sqlite3 *db, const char *zName, const char *zDatabase)`
///
/// Locate the in-memory structure that describes a particular database
/// table given the name of that table and (optionally) the name of the
/// database containing the table.  Return NULL if not found.
///
/// If zDatabase is 0, all databases are searched for the table and the
/// first matching table is returned.  (No checking for duplicate table
/// names is done.)  The search order is TEMP first, then MAIN, then any
/// auxiliary databases added using the ATTACH command.
///
/// See also sqlite3LocateTable().
pub fn sqlite3FindTable(
    db: &mut Sqlite3,
    zName: Option<&[u8]>,
    zDatabase: Option<&[u8]>,
) -> Option<TableRef> {
    let zName = zName.unwrap_or(b"");
    let mut p: Option<TableRef>;
    if let Some(zDatabase) = zDatabase {
        let mut i = 0;
        while i < db.nDb() {
            if sqlite3StrICmp(Some(zDatabase), db.aDb[i as usize].zDbSName.as_deref()) == 0 {
                break;
            }
            i += 1;
        }
        if i >= db.nDb() {
            // No match against the official names.  But always match "main"
            // to schema 0 as a legacy fallback.
            if streq(zDatabase, b"main") {
                i = 0;
            } else {
                return None;
            }
        }
        p = tbl_find(db, i as usize, zName);
        if p.is_none() && strneq(zName, b"sqlite_", 7) {
            let z7 = tail(zName, 7);
            if i == 1 {
                if streq(z7, &PREFERRED_TEMP_SCHEMA_TABLE[7..])
                    || streq(z7, &PREFERRED_SCHEMA_TABLE[7..])
                    || streq(z7, &LEGACY_SCHEMA_TABLE[7..])
                {
                    p = tbl_find(db, 1, LEGACY_TEMP_SCHEMA_TABLE);
                }
            } else if streq(z7, &PREFERRED_SCHEMA_TABLE[7..]) {
                p = tbl_find(db, i as usize, LEGACY_SCHEMA_TABLE);
            }
        }
    } else {
        // Match against TEMP first
        p = tbl_find(db, 1, zName);
        if p.is_some() {
            return p;
        }
        // The main database is second
        p = tbl_find(db, 0, zName);
        if p.is_some() {
            return p;
        }
        // Attached databases are in order of attachment
        for i in 2..db.aDb.len() {
            p = tbl_find(db, i, zName);
            if p.is_some() {
                break;
            }
        }
        if p.is_none() && strneq(zName, b"sqlite_", 7) {
            let z7 = tail(zName, 7);
            if streq(z7, &PREFERRED_SCHEMA_TABLE[7..]) {
                p = tbl_find(db, 0, LEGACY_SCHEMA_TABLE);
            } else if streq(z7, &PREFERRED_TEMP_SCHEMA_TABLE[7..]) {
                p = tbl_find(db, 1, LEGACY_TEMP_SCHEMA_TABLE);
            }
        }
    }
    p
}

/// C: `Table * sqlite3LocateTable( Parse *pParse, u32 flags, const char *zName, const char *zDbase )`
///
/// Locate the in-memory structure that describes a particular database
/// table given the name of that table and (optionally) the name of the
/// database containing the table.  Return NULL if not found.  Also leave an
/// error message in pParse->zErrMsg.
///
/// The difference between this routine and sqlite3FindTable() is that this
/// routine leaves an error message in pParse->zErrMsg where
/// sqlite3FindTable() does not.
pub fn sqlite3LocateTable(
    db: &mut Sqlite3,
    flags: u32,
    zName: Option<&[u8]>,
    zDbase: Option<&[u8]>,
) -> Option<TableRef> {
    // Read the database schema. If an error occurs, leave an error message
    // and code in pParse and return NULL.
    if (db.mDbFlags & DBFLAG_SchemaKnownOk) == 0
        && SQLITE_OK != crate::prepare::sqlite3ReadSchema(db)
    {
        return None;
    }

    let mut p = sqlite3FindTable(db, zName, zDbase);
    if p.is_none() {
        // If zName is the not the name of a table in the schema created using
        // CREATE, then check to see if it is the name of an virtual table that
        // can be an eponymous virtual table.
        if (db.ppr().prepFlags as i32 & SQLITE_PREPARE_NO_VTAB) == 0 && db.init.busy == 0 {
            let z = zName.unwrap_or(b"");
            let mut pMod = db.aModule.find(z).cloned();
            if pMod.is_none() && crate::util::sqlite3StrNICmp(Some(z), Some(b"pragma_"), 7) == 0 {
                pMod = crate::pragma::sqlite3PragmaVtabRegister(db, Some(z));
            }
            if pMod.is_none() && crate::util::sqlite3StrNICmp(Some(z), Some(b"json"), 4) == 0 {
                pMod = crate::json::sqlite3JsonVtabRegister(db, Some(z));
            }
            if let Some(pMod) = pMod {
                if crate::vtab::sqlite3VtabEponymousTableInit(db, &pMod) != 0 {
                    return pMod.borrow().pEpoTab.clone();
                }
            }
        }
        if (flags & LOCATE_NOERR as u32) != 0 {
            return None;
        }
        db.pp().checkSchema = 1;
    } else if p.as_ref().unwrap().borrow().IsVirtual()
        && (db.ppr().prepFlags as i32 & SQLITE_PREPARE_NO_VTAB) != 0
    {
        p = None;
    }

    if p.is_none() {
        let zMsg: &[u8] = if (flags & LOCATE_VIEW as u32) != 0 {
            b"no such view"
        } else {
            b"no such table"
        };
        if let Some(zDbase) = zDbase {
            errmsg!(db, "%s: %s.%s", zMsg, zDbase, zName);
        } else {
            errmsg!(db, "%s: %s", zMsg, zName);
        }
    } else {
        debug_assert!({
            let t = p.as_ref().unwrap().borrow();
            t.HasRowid() || t.iPKey < 0
        });
    }
    p
}

/// C: `Table * sqlite3LocateTableItem( Parse *pParse, u32 flags, SrcItem *p )`
///
/// Locate the table identified by *p.
///
/// This is a wrapper around sqlite3LocateTable(). The difference between
/// sqlite3LocateTable() and this function is that this function restricts
/// the search to schema (p->pSchema) if it is not NULL. p->pSchema may be
/// non-NULL if it is part of a view or trigger program definition. See
/// sqlite3FixSrcList() for details.
pub fn sqlite3LocateTableItem(db: &mut Sqlite3, flags: u32, p: SrcItemId) -> Option<TableRef> {
    let (fixed, pSchema, zDatabase, zName) = {
        let it = db.item(p);
        (
            it.fg.fixedSchema,
            it.u4.pSchema,
            it.u4.zDatabase.clone(),
            it.zName.clone(),
        )
    };
    let zDb: Option<ZStr> = if fixed != 0 {
        let iDb = db.schema_index(pSchema.unwrap_or_default());
        debug_assert!(iDb >= 0 && iDb < db.nDb());
        db.aDb[iDb as usize].zDbSName.clone()
    } else {
        zDatabase
    };
    sqlite3LocateTable(db, flags, zName.as_deref(), zDb.as_deref())
}

/// C: `const char * sqlite3PreferredTableName(const char *zName)`
///
/// Return the preferred table name for system tables.  Translate legacy
/// names into the new preferred names, as appropriate.
pub fn sqlite3PreferredTableName(zName: Option<&[u8]>) -> Option<ZStr> {
    let z = zName?;
    if strneq(z, b"sqlite_", 7) {
        if streq(tail(z, 7), &LEGACY_SCHEMA_TABLE[7..]) {
            return Some(PREFERRED_SCHEMA_TABLE.to_vec());
        }
        if streq(tail(z, 7), &LEGACY_TEMP_SCHEMA_TABLE[7..]) {
            return Some(PREFERRED_TEMP_SCHEMA_TABLE.to_vec());
        }
    }
    Some(z.to_vec())
}

/// C: `Index * sqlite3FindIndex(sqlite3 *db, const char *zName, const char *zDb)`
///
/// Locate the in-memory structure that describes
/// a particular index given the name of that index
/// and the name of the database that contains the index.
/// Return NULL if not found.
///
/// If zDatabase is 0, all databases are searched for the
/// table and the first matching index is returned.  (No checking
/// for duplicate index names is done.)  The search order is
/// TEMP first, then MAIN, then any auxiliary databases added
/// using the ATTACH command.
pub fn sqlite3FindIndex(
    db: &mut Sqlite3,
    zName: Option<&[u8]>,
    zDb: Option<&[u8]>,
) -> Option<IndexRef> {
    let zName = zName.unwrap_or(b"");
    for i in (OMIT_TEMPDB as i32)..db.nDb() {
        let j = if i < 2 { i ^ 1 } else { i }; // Search TEMP before MAIN
        if zDb.is_some() && crate::attach::sqlite3DbIsNamed(db, j, zDb) == 0 {
            continue;
        }
        if let Some(p) = db.aDb[j as usize].pSchema.idxHash.find(zName) {
            return Some(p.clone());
        }
    }
    None
}

/// C: `void sqlite3FreeIndex(sqlite3 *db, Index *p)`
