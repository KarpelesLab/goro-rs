/// C: `int sqlite3IdListIndex(IdList *pList, const char *zName)`
///
/// Return the index in pList of the identifier named zId.  Return -1
/// if not found.
pub fn sqlite3IdListIndex(db: &mut Sqlite3, pList: IdListId, zName: Option<&[u8]>) -> i32 {
    debug_assert!(pList.nn());
    let l = db.idl(pList);
    for (i, it) in l.a.iter().enumerate() {
        if sqlite3StrICmp(it.zName.as_deref(), zName) == 0 {
            return i as i32;
        }
    }
    -1
}

/// C: `SrcList * sqlite3SrcListEnlarge( Parse *pParse, SrcList *pSrc, int nExtra, int iStart )`
///
/// Expand the space allocated for the given SrcList object by
/// creating nExtra new slots beginning at iStart.  iStart is zero based.
/// New slots are zeroed.
///
/// For example, suppose a SrcList initially contains two entries: A,B.
/// To append 3 new entries onto the end, do this:
///
///    sqlite3SrcListEnlarge(db, pSrclist, 3, 2);
///
/// After the call above it would contain:  A, B, nil, nil, nil.
/// If the iStart argument had been 1 instead of 2, then the result
/// would have been:  A, nil, nil, nil, B.  To prepend the new slots,
/// the iStart value would be 0.  The result then would
/// be: nil, nil, nil, A, B.
///
/// If a memory allocation fails or the SrcList becomes too large, leave
/// the original SrcList unchanged, return NULL, and leave an error message
/// in pParse.
///
/// Rust: there is no nAlloc; the size limit is checked as if the list had
/// been grown one entry at a time (error when the list would exceed
/// SQLITE_MAX_SRCLIST entries).
pub fn sqlite3SrcListEnlarge(
    db: &mut Sqlite3,
    pSrc: SrcListId,
    nExtra: i32,
    iStart: i32,
) -> SrcListId {
    debug_assert!(iStart >= 0);
    debug_assert!(nExtra >= 1);
    debug_assert!(pSrc.nn());
    let nSrc = db.src(pSrc).nSrc();
    debug_assert!(iStart <= nSrc);

    if nSrc + nExtra > SQLITE_MAX_SRCLIST {
        errmsg!(
            db,
            "too many FROM clause terms, max: %d",
            SQLITE_MAX_SRCLIST
        );
        return SrcListId::NULL;
    }

    let l = db.srcm(pSrc);
    for _ in 0..nExtra {
        l.a.insert(
            iStart as usize,
            SrcItem {
                iCursor: -1,
                ..Default::default()
            },
        );
    }
    pSrc
}

/// C: `SrcList * sqlite3SrcListAppend( Parse *pParse, SrcList *pList, Token *pTable, Token *pDatabase )`
///
/// Append a new table name to the given SrcList.  Create a new SrcList if
/// need be.  A new entry is created in the SrcList even if pTable is NULL.
///
/// A SrcList is returned, or NULL if there is an OOM error or if the
/// SrcList grows to large.  The returned
/// SrcList might be the same as the SrcList that was input or it might be
/// a new one.  If an OOM error does occurs, then the prior value of pList
/// that is input to this routine is automatically freed.
///
/// If pDatabase is not null, it means that the table has an optional
/// database name prefix.  Like this:  "database.table".  The pDatabase
/// points to the table name and the pTable points to the database name.
/// The SrcList.a[].zName field is filled with the table name which might
/// come from pTable (if pDatabase is NULL) or from pDatabase.
/// SrcList.a[].zDatabase is filled with the database name from pTable,
/// or with NULL if no database is specified.
///
/// In other words, if call like this:
///
///         sqlite3SrcListAppend(D,A,B,0);
///
/// Then B is a table name and the database name is unspecified.  If called
/// like this:
///
///         sqlite3SrcListAppend(D,A,B,C);
///
/// Then C is the table name and B is the database name.  If C is defined
/// then so is B.  In other words, we never have a case where:
///
///         sqlite3SrcListAppend(D,A,0,C);
///
/// Both pTable and pDatabase are assumed to be quoted.  They are dequoted
/// before being added to the SrcList.
///
/// Rust: pTable and pDatabase may be None (C NULL).
pub fn sqlite3SrcListAppend(
    db: &mut Sqlite3,
    mut pList: SrcListId,
    pTable: Option<&Token>,
    pDatabase: Option<&Token>,
) -> SrcListId {
    debug_assert!(pDatabase.is_none() || pTable.is_some()); // Cannot have C without B
    if pList.is_null() {
        pList = db.arena.new_srclist(SrcList {
            a: vec![SrcItem {
                iCursor: -1,
                ..Default::default()
            }],
        });
    } else {
        let nSrc = db.src(pList).nSrc();
        let pNew = sqlite3SrcListEnlarge(db, pList, 1, nSrc);
        if pNew.is_null() {
            sqlite3SrcListDelete(db, pList);
            return SrcListId::NULL;
        }
        pList = pNew;
    }
    let iItem = (db.src(pList).nSrc() - 1) as u32;
    let pDatabase = match pDatabase {
        Some(d) if d.z.is_none() => None,
        x => x,
    };
    let (zName, zDatabase) = if let Some(d) = pDatabase {
        (
            sqlite3NameFromToken(db, d),
            pTable.and_then(|t| sqlite3NameFromToken(db, t)),
        )
    } else {
        (pTable.and_then(|t| sqlite3NameFromToken(db, t)), None)
    };
    let it = db.itemm(SrcItemId(pList, iItem));
    debug_assert!(it.fg.fixedSchema == 0);
    debug_assert!(it.fg.isSubquery == 0);
    it.zName = zName;
    it.u4.zDatabase = zDatabase;
    pList
}

/// C: `void sqlite3SrcListAssignCursors(Parse *pParse, SrcList *pList)`
///
/// Assign VdbeCursor index numbers to all tables in a SrcList
pub fn sqlite3SrcListAssignCursors(db: &mut Sqlite3, pList: SrcListId) {
    if pList.nn() {
        let n = db.src(pList).nSrc();
        for i in 0..n {
            let it = SrcItemId(pList, i as u32);
            if db.item(it).iCursor >= 0 {
                continue;
            }
            let c = {
                let p = db.pp();
                p.nTab += 1;
                p.nTab - 1
            };
            db.itemm(it).iCursor = c;
            let sub = {
                let x = db.item(it);
                if x.fg.isSubquery != 0 {
                    x.u4.pSubq.as_ref().map(|q| q.pSelect)
                } else {
                    None
                }
            };
            if let Some(s) = sub {
                debug_assert!(s.nn());
                let src = db.sel(s).pSrc;
                sqlite3SrcListAssignCursors(db, src);
            }
        }
    }
}

/// C: `void sqlite3SubqueryDelete(sqlite3 *db, Subquery *pSubq)`
///
/// Delete a Subquery object and its substructure.
pub fn sqlite3SubqueryDelete(db: &mut Sqlite3, pSubq: &mut Subquery) {
    debug_assert!(pSubq.pSelect.nn());
    crate::select::sqlite3SelectDelete(db, pSubq.pSelect);
}

/// C: `Select * sqlite3SubqueryDetach(sqlite3 *db, SrcItem *pItem)`
///
/// Remove a Subquery from a SrcItem.  Return the associated Select object.
/// The returned Select becomes the responsibility of the caller.
pub fn sqlite3SubqueryDetach(db: &mut Sqlite3, pItem: SrcItemId) -> SelectId {
    let it = db.itemm(pItem);
    debug_assert!(it.fg.isSubquery != 0);
    let pSel = it.u4.pSubq.take().map(|q| q.pSelect).unwrap_or_default();
    it.fg.isSubquery = 0;
    pSel
}

/// C: `void sqlite3SrcListDelete(sqlite3 *db, SrcList *pList)`
///
/// Delete an entire SrcList including all its substructure.
///
/// Rust: arena nodes are freed with the arena; this keeps the side effects
/// (releasing the references to the pSTab tables, deleting subqueries).
pub fn sqlite3SrcListDelete(db: &mut Sqlite3, pList: SrcListId) {
    if pList.is_null() {
        return;
    }
    let n = db.src(pList).nSrc();
    for i in 0..n {
        let it = SrcItemId(pList, i as u32);
        let (sub, tab, isTabFunc, pFuncArg, isUsing, pOn) = {
            let x = db.itemm(it);
            debug_assert!(x.fg.isIndexedBy == 0 || x.fg.isTabFunc == 0);
            debug_assert!(x.fg.isCte == 0 || x.fg.isIndexedBy == 0);
            debug_assert!(x.fg.fixedSchema == 0 || x.fg.isSubquery == 0);
            let sub = if x.fg.isSubquery != 0 {
                x.u4.pSubq.take()
            } else {
                None
            };
            (
                sub,
                x.pSTab.take(),
                x.fg.isTabFunc,
                x.u1.pFuncArg,
                x.fg.isUsing,
                x.u3.pOn,
            )
        };
        if let Some(mut q) = sub {
            sqlite3SubqueryDelete(db, &mut q);
        }
        if isTabFunc != 0 {
            sqlite3ExprListDelete(db, pFuncArg);
        }
        if let Some(t) = tab {
            sqlite3DeleteTable(db, &t);
        }
        if isUsing == 0 && pOn.nn() {
            sqlite3ExprDelete(db, pOn);
        }
    }
}

/// C: `int sqlite3SrcItemAttachSubquery( Parse *pParse, SrcItem *pItem, Select *pSelect, int dupSelect )`
///
/// Attach a Subquery object to pItem->uv.pSubq.  Set the
/// pSelect value but leave all the other values initialized
/// to zero.
///
/// A copy of the Select object is made if dupSelect is true, and the
/// SrcItem takes responsibility for deleting the copy.  If dupSelect is
/// false, ownership of the Select passes to the SrcItem.  Either way,
/// the SrcItem will take responsibility for deleting the Select.
///
/// When dupSelect is zero, that means the Select might get deleted right
/// away if there is an OOM error.  Beware.
///
/// Return non-zero on success.  Return zero on an OOM error.
pub fn sqlite3SrcItemAttachSubquery(
    db: &mut Sqlite3,
    pItem: SrcItemId,
    mut pSelect: SelectId,
    dupSelect: i32,
) -> i32 {
    debug_assert!(pSelect.nn());
    {
        let it = db.itemm(pItem);
        debug_assert!(it.fg.isSubquery == 0);
        if it.fg.fixedSchema != 0 {
            it.u4.pSchema = None;
            it.fg.fixedSchema = 0;
        } else if it.u4.zDatabase.is_some() {
            it.u4.zDatabase = None;
        }
    }
    if dupSelect != 0 {
        pSelect = crate::expr::sqlite3SelectDup(db, pSelect, 0);
        if pSelect.is_null() {
            return 0;
        }
    }
    let it = db.itemm(pItem);
    it.u4.pSubq = Some(Box::new(Subquery {
        pSelect,
        ..Default::default()
    }));
    it.fg.isSubquery = 1;
    1
}

/// C: `SrcList * sqlite3SrcListAppendFromTerm( Parse *pParse, SrcList *p, Token *pTable, Token *pDatabase, Token *pAlias, Select *pSubquery, OnOrUsing *pOnUsing )`
///
/// This routine is called by the parser to add a new term to the
/// end of a growing FROM clause.  The "p" parameter is the part of
/// the FROM clause that has already been constructed.  "p" is NULL
/// if this is the first term of the FROM clause.  pTable and pDatabase
/// are the name of the table and database named in the FROM clause term.
/// pDatabase is NULL if the database name qualifier is missing - the
/// usual case.  If the term has an alias, then pAlias points to the
/// alias token.  If the term is a subquery, then pSubquery is the
/// SELECT statement that the subquery encodes.  The pTable and
/// pDatabase parameters are NULL for subqueries.  The pOn and pUsing
/// parameters are the content of the ON and USING clauses.
///
/// Return a new SrcList which encodes is the FROM with the new
/// term added.
///
/// Rust: pTable, pDatabase and pOnUsing may be None (C NULL).
pub fn sqlite3SrcListAppendFromTerm(
    db: &mut Sqlite3,
    mut p: SrcListId,
    pTable: Option<&Token>,
    pDatabase: Option<&Token>,
    pAlias: &Token,
    pSubquery: SelectId,
    pOnUsing: Option<&mut OnOrUsing>,
) -> SrcListId {
    'append_from_error: {
        if p.is_null() {
            if let Some(ou) = &pOnUsing {
                if ou.pOn.nn() || ou.pUsing.nn() {
                    let z: &[u8] = if ou.pOn.nn() { b"ON" } else { b"USING" };
                    errmsg!(db, "a JOIN clause is required before %s", z);
                    break 'append_from_error;
                }
            }
        }
        p = sqlite3SrcListAppend(db, p, pTable, pDatabase);
        if p.is_null() {
            break 'append_from_error;
        }
        let nSrc = db.src(p).nSrc();
        debug_assert!(nSrc > 0);
        let pItem = SrcItemId(p, (nSrc - 1) as u32);
        if db.ppr().IN_RENAME_OBJECT() && db.item(pItem).zName.is_some() {
            let pToken = match pDatabase {
                Some(d) if d.z.is_some() => d,
                _ => pTable.unwrap(),
            };
            let tk = pToken.clone();
            sqlite3RenameTokenMap(db, rename_key_srcitem_name(pItem), &tk);
        }
        if pAlias.n != 0 {
            let a = sqlite3NameFromToken(db, pAlias);
            db.itemm(pItem).zAlias = a;
        }
        debug_assert!(pSubquery.is_null() || pDatabase.is_none());
        if pSubquery.nn() && sqlite3SrcItemAttachSubquery(db, pItem, pSubquery, 0) != 0 {
            if (db.sel(pSubquery).selFlags & SF_NestedFrom) != 0 {
                db.itemm(pItem).fg.isNestedFrom = 1;
            }
        }
        let it = db.itemm(pItem);
        debug_assert!(it.fg.isUsing == 0);
        match pOnUsing {
            None => it.u3.pOn = ExprId::NULL,
            Some(ou) => {
                if ou.pUsing.nn() {
                    it.fg.isUsing = 1;
                    it.u3.pUsing = ou.pUsing;
                } else {
                    it.u3.pOn = ou.pOn;
                }
            }
        }
        return p;
    }

    // append_from_error:
    if let Some(ou) = pOnUsing {
        crate::expr::sqlite3ClearOnOrUsing(db, ou);
    }
    crate::select::sqlite3SelectDelete(db, pSubquery);
    SrcListId::NULL
}

/// C: `void sqlite3SrcListIndexedBy(Parse *pParse, SrcList *p, Token *pIndexedBy)`
///
/// Add an INDEXED BY or NOT INDEXED clause to the most recently added
/// element of the source-list passed as the second argument.
pub fn sqlite3SrcListIndexedBy(db: &mut Sqlite3, p: SrcListId, pIndexedBy: &Token) {
    if p.nn() && pIndexedBy.n > 0 {
        let nSrc = db.src(p).nSrc();
        debug_assert!(nSrc > 0);
        let it = SrcItemId(p, (nSrc - 1) as u32);
        if pIndexedBy.n == 1 && pIndexedBy.z.is_none() {
            // A "NOT INDEXED" clause was supplied. See parse.y
            // construct "indexed_opt" for details.
            db.itemm(it).fg.notIndexed = 1;
        } else {
            let z = sqlite3NameFromToken(db, pIndexedBy);
            let x = db.itemm(it);
            x.u1.zIndexedBy = z;
            x.fg.isIndexedBy = 1;
            debug_assert!(x.fg.isCte == 0); // No collision on union u2
        }
    }
}

/// C: `SrcList * sqlite3SrcListAppendList(Parse *pParse, SrcList *p1, SrcList *p2)`
///
/// Append the contents of SrcList p2 to SrcList p1 and return the resulting
/// SrcList. Or, if an error occurs, return NULL. In all cases, p1 and p2
/// are deleted by this function.
pub fn sqlite3SrcListAppendList(db: &mut Sqlite3, mut p1: SrcListId, p2: SrcListId) -> SrcListId {
    debug_assert!(p1.nn());
    if p2.nn() {
        let nOld = db.src(p1).nSrc();
        let n2 = db.src(p2).nSrc();
        let pNew = sqlite3SrcListEnlarge(db, p1, n2, nOld);
        if pNew.is_null() {
            sqlite3SrcListDelete(db, p2);
        } else {
            p1 = pNew;
            let items = std::mem::take(&mut db.srcm(p2).a);
            let jt0 = items.first().map(|x| x.fg.jointype).unwrap_or(0);
            let l = db.srcm(p1);
            for (k, it) in items.into_iter().enumerate() {
                l.a[nOld as usize + k] = it;
            }
            l.a[0].fg.jointype |= JT_LTORJ & jt0;
        }
    }
    p1
}

/// C: `void sqlite3SrcListFuncArgs(Parse *pParse, SrcList *p, ExprList *pList)`
///
/// Add the list of function arguments to the SrcList entry for a
/// table-valued-function.
pub fn sqlite3SrcListFuncArgs(db: &mut Sqlite3, p: SrcListId, pList: ExprListId) {
    if p.nn() {
        let nSrc = db.src(p).nSrc();
        let it = db.itemm(SrcItemId(p, (nSrc - 1) as u32));
        debug_assert!(it.fg.notIndexed == 0);
        debug_assert!(it.fg.isIndexedBy == 0);
        debug_assert!(it.fg.isTabFunc == 0);
        it.u1.pFuncArg = pList;
        it.fg.isTabFunc = 1;
    } else {
        sqlite3ExprListDelete(db, pList);
    }
}

/// C: `void sqlite3SrcListShiftJoinType(Parse *pParse, SrcList *p)`
///
/// When building up a FROM clause in the parser, the join operator
/// is initially attached to the left operand.  But the code generator
/// expects the join operator to be on the right operand.  This routine
/// Shifts all join operators from left to right for an entire FROM
/// clause.
///
/// Example: Suppose the join is like this:
///
///           A natural cross join B
///
/// The operator is "natural cross join".  The A and B operands are stored
/// in p->a[0] and p->a[1], respectively.  The parser initially stores the
/// operator with A.  This routine shifts that operator over to B.
///
/// Additional changes:
///
///   *   All tables to the left of the right-most RIGHT JOIN are tagged with
///       JT_LTORJ (mnemonic: Left Table Of Right Join) so that the
///       code generator can easily tell that the table is part of
///       the left operand of at least one RIGHT JOIN.
pub fn sqlite3SrcListShiftJoinType(db: &mut Sqlite3, p: SrcListId) {
    if p.is_null() {
        return;
    }
    let l = db.srcm(p);
    let n = l.a.len();
    if n > 1 {
        let mut i = n - 1;
        let mut allFlags: u8 = 0;
        loop {
            l.a[i].fg.jointype = l.a[i - 1].fg.jointype;
            allFlags |= l.a[i].fg.jointype;
            i -= 1;
            if i == 0 {
                break;
            }
        }
        l.a[0].fg.jointype = 0;

        // All terms to the left of a RIGHT JOIN should be tagged with the
        // JT_LTORJ flags
        if (allFlags & JT_RIGHT) != 0 {
            let mut i = n - 1;
            while i > 0 && (l.a[i].fg.jointype & JT_RIGHT) == 0 {
                i -= 1;
            }
            debug_assert!(i > 0);
            let mut i = i as isize - 1;
            while i >= 0 {
                l.a[i as usize].fg.jointype |= JT_LTORJ;
                i -= 1;
            }
        }
    }
}

