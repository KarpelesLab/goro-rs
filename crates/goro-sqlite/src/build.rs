///
/// True if PRAGMA writable_schema is ON
pub fn sqlite3WritableSchema(db: &mut Sqlite3) -> i32 {
    ((db.flags & (SQLITE_WriteSchema | SQLITE_Defensive)) == SQLITE_WriteSchema) as i32
}

/// C: `int sqlite3CheckObjectName( Parse *pParse, const char *zName, const char *zType, const char *zTblName )`
///
/// This routine is used to check if the UTF-8 string zName is a legal
/// unqualified name for a new schema object (table, index, view or
/// trigger). All names are legal except those that begin with the string
/// "sqlite_" (in upper, lower or mixed case). This portion of the namespace
/// is reserved for internal use.
///
/// When parsing the sqlite_schema table, this routine also checks to
/// make sure the "type", "name", and "tbl_name" columns are consistent
/// with the SQL.
pub fn sqlite3CheckObjectName(
    db: &mut Sqlite3,
    zName: Option<&[u8]>,
    zType: Option<&[u8]>,
    zTblName: Option<&[u8]>,
) -> i32 {
    if sqlite3WritableSchema(db) != 0
        || db.init.imposterTable != 0
        || crate::global::sqlite3GlobalConfig().bExtraSchemaChecks == 0
    {
        // Skip these error checks for writable_schema=ON
        return SQLITE_OK;
    }
    if db.init.busy != 0 {
        let a0 = db.init.azInit.first().cloned();
        let a1 = db.init.azInit.get(1).cloned();
        let a2 = db.init.azInit.get(2).cloned();
        if sqlite3_stricmp(zType, a0.as_deref()) != 0
            || sqlite3_stricmp(zName, a1.as_deref()) != 0
            || sqlite3_stricmp(zTblName, a2.as_deref()) != 0
        {
            sqlite3ErrorMsg(db, b"", &[]); // corruptSchema() will supply the error
            return SQLITE_ERROR;
        }
    } else {
        let z = zName.unwrap_or(b"");
        if (db.ppr().nested == 0 && strneq(z, b"sqlite_", 7))
            || (sqlite3ReadOnlyShadowTables(db) != 0 && sqlite3ShadowTableName(db, zName) != 0)
        {
            errmsg!(db, "object name reserved for internal use: %s", zName);
            return SQLITE_ERROR;
        }
    }
    SQLITE_OK
}

