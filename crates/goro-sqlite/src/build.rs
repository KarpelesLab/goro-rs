/// C: `void sqlite3StartTable( Parse *pParse, Token *pName1, Token *pName2, int isTemp, int isView, int isVirtual, int noErr )`
///
/// Begin constructing a new table representation in memory.  This is
/// the first of several action routines that get called in response
/// to a CREATE TABLE statement.  In particular, this routine is called
/// after seeing tokens "CREATE" and "TABLE" and the table name. The isTemp
/// flag is true if the table should be stored in the auxiliary database
/// file instead of in the main database file.  This is normally the case
/// when the "TEMP" or "TEMPORARY" keyword occurs in between
/// CREATE and TABLE.
///
/// The new table record is initialized and put in pParse->pNewTable.
/// As more of the CREATE TABLE statement is parsed, additional action
/// routines will be called to add more information to this record.
/// At the end of the CREATE TABLE statement, the sqlite3EndTable() routine
/// is called to complete the construction of the new table record.
pub fn sqlite3StartTable(
    db: &mut Sqlite3,
    pName1: &Token,
    pName2: &Token,
    isTemp: i32,
    isView: i32,
    isVirtual: i32,
    noErr: i32,
) {
    let mut iDb: i32;
    let zName: Option<ZStr>;
    let mut pName = Token::default();
    let mut renameName = false;

    if db.init.busy != 0 && db.init.newTnum == 1 {
        // Special case:  Parsing the sqlite_schema or sqlite_temp_schema schema
        iDb = db.init.iDb as i32;
        zName = Some(SCHEMA_TABLE(iDb).to_vec());
        pName = pName1.clone();
    } else {
        // The common case
        iDb = sqlite3TwoPartName(db, pName1, pName2, &mut pName);
        if iDb < 0 {
            return;
        }
        if OMIT_TEMPDB == 0 && isTemp != 0 && pName2.n > 0 && iDb != 1 {
            // If creating a temp table, the name may not be qualified. Unless
            // the database name is "temp" anyway.
            sqlite3ErrorMsg(db, b"temporary table name must be unqualified", &[]);
            return;
        }
        if OMIT_TEMPDB == 0 && isTemp != 0 {
            iDb = 1;
        }
        zName = sqlite3NameFromToken(db, &pName);
        if db.ppr().IN_RENAME_OBJECT() {
            // sqlite3RenameTokenMap(pParse, (void*)zName, pName): done once
            // the Table object exists (the key is the table identity).
            renameName = true;
        }
    }
    start_table_common(
        db, iDb, zName, pName, isTemp, isView, isVirtual, noErr, renameName,
    );
}

fn start_table_common(
    db: &mut Sqlite3,
    iDb: i32,
    zName: Option<ZStr>,
    pName: Token,
    mut isTemp: i32,
    isView: i32,
    isVirtual: i32,
    noErr: i32,
    renameName: bool,
) {
    db.pp().sNameToken = pName.clone();
    let zName = match zName {
        Some(z) => z,
        None => return,
    };
    'begin_table_error: {
        let zType: &[u8] = if isView != 0 { b"view" } else { b"table" };
        if sqlite3CheckObjectName(db, Some(&zName), Some(zType), Some(&zName)) != 0 {
            break 'begin_table_error;
        }
        if db.init.iDb == 1 {
            isTemp = 1;
        }
        {
            const aCode: [i32; 4] = [
                SQLITE_CREATE_TABLE,
                SQLITE_CREATE_TEMP_TABLE,
                SQLITE_CREATE_VIEW,
                SQLITE_CREATE_TEMP_VIEW,
            ];
            let zDb = db.aDb[iDb as usize].zDbSName.clone();
            if sqlite3AuthCheck(
                db,
                SQLITE_INSERT,
                Some(SCHEMA_TABLE(isTemp)),
                None,
                zDb.as_deref(),
            ) != 0
            {
                break 'begin_table_error;
            }
            if isVirtual == 0
                && sqlite3AuthCheck(
                    db,
                    aCode[(isTemp + 2 * isView) as usize],
                    Some(&zName),
                    None,
                    zDb.as_deref(),
                ) != 0
            {
                break 'begin_table_error;
            }
        }

        // Make sure the new table name does not collide with an existing
        // index or table name in the same database.  Issue an error message if
        // it does. The exception is if the statement being parsed was passed
        // to an sqlite3_declare_vtab() call. In that case only the column names
        // and types will be used, so there is no need to test for namespace
        // collisions.
        if !db.ppr().IN_SPECIAL_PARSE() {
            let zDb = db.aDb[iDb as usize].zDbSName.clone();
            if SQLITE_OK != crate::prepare::sqlite3ReadSchema(db) {
                break 'begin_table_error;
            }
            let pTable = sqlite3FindTable(db, Some(&zName), zDb.as_deref());
            if let Some(pTable) = pTable {
                if noErr == 0 {
                    let isv: &[u8] = if pTable.borrow().IsView() {
                        b"view"
                    } else {
                        b"table"
                    };
                    errmsg!(db, "%s %T already exists", isv, &pName);
                } else {
                    debug_assert!(db.init.busy == 0);
                    sqlite3CodeVerifySchema(db, iDb);
                    sqlite3ForceNotReadOnly(db);
                }
                break 'begin_table_error;
            }
            if sqlite3FindIndex(db, Some(&zName), zDb.as_deref()).is_some() {
                errmsg!(db, "there is already an index named %s", &zName);
                break 'begin_table_error;
            }
        }

        let pTable: TableRef = Rc::new(RefCell::new(Table {
            zName: zName.clone(),
            iPKey: -1,
            pSchema: db.aDb[iDb as usize].pSchema.id,
            nTabRef: 1,
            nRowLogEst: 200,
            ..Default::default()
        }));
        if renameName {
            sqlite3RenameTokenMap(db, rename_key_table_name(&pTable), &pName);
        }
        debug_assert!(db.ppr().pNewTable.is_none());
        db.pp().pNewTable = Some(pTable.clone());

        // Begin generating the code that will insert the table record into
        // the schema table.  Note in particular that we must go ahead
        // and allocate the record number for the table entry now.  Before any
        // PRIMARY KEY or UNIQUE keywords are parsed.  Those keywords will cause
        // indices to be created and the table record must come before the
        // indices.  Hence, the record number for the table must be allocated
        // now.
        if db.init.busy == 0 && get_vdbe(db) {
            // nullRow[] is an OP_Record encoding of a row containing 5 NULLs
            const nullRow: [u8; 6] = [6, 0, 0, 0, 0, 0];
            sqlite3BeginWriteOperation(db, 1, iDb);

            if isVirtual != 0 {
                sqlite3VdbeAddOp0(db.v(), OP_VBegin);
            }

            // If the file format and encoding in the database have not been set,
            // set them now.
            let reg1 = {
                let p = db.pp();
                p.nMem += 1;
                p.u1.cr.regRowid = p.nMem;
                p.nMem
            };
            let reg2 = {
                let p = db.pp();
                p.nMem += 1;
                p.u1.cr.regRoot = p.nMem;
                p.nMem
            };
            let reg3 = {
                let p = db.pp();
                p.nMem += 1;
                p.nMem
            };
            let fileFormat = if (db.flags & SQLITE_LegacyFileFmt) != 0 {
                1
            } else {
                SQLITE_MAX_FILE_FORMAT
            };
            let enc = db.ENC() as i32;
            {
                let v = db.v();
                sqlite3VdbeAddOp3(v, OP_ReadCookie, iDb, reg3, BTREE_FILE_FORMAT);
                sqlite3VdbeUsesBtree(v, iDb);
                let addr1 = sqlite3VdbeAddOp1(v, OP_If, reg3);
                sqlite3VdbeAddOp3(v, OP_SetCookie, iDb, BTREE_FILE_FORMAT, fileFormat);
                sqlite3VdbeAddOp3(v, OP_SetCookie, iDb, BTREE_TEXT_ENCODING, enc);
                sqlite3VdbeJumpHere(v, addr1);
            }

            // This just creates a place-holder record in the sqlite_schema table.
            // The record created does not contain anything yet.  It will be replaced
            // by the real entry in code generated at sqlite3EndTable().
            //
            // The rowid for the new entry is left in register pParse->u1.cr.regRowid.
            // The root page of the new table is left in reg pParse->u1.cr.regRoot.
            // The rowid and root page number values are needed by the code that
            // sqlite3EndTable will generate.
            if isView != 0 || isVirtual != 0 {
                sqlite3VdbeAddOp2(db.v(), OP_Integer, 0, reg2);
            } else {
                debug_assert!(db.ppr().bReturning == 0);
                let a = sqlite3VdbeAddOp3(db.v(), OP_CreateBtree, iDb, reg2, BTREE_INTKEY);
                db.pp().u1.cr.addrCrTab = a;
            }
            sqlite3OpenSchemaTable(db, iDb);
            let v = db.v();
            sqlite3VdbeAddOp2(v, OP_NewRowid, 0, reg1);
            sqlite3VdbeAddOp4(
                v,
                OP_Blob,
                6,
                reg3,
                0,
                P4::Z(nullRow.to_vec()),
                P4_STATIC as i32,
            );
            sqlite3VdbeAddOp3(v, OP_Insert, 0, reg3, reg1);
            sqlite3VdbeChangeP5(v, OPFLAG_APPEND);
            sqlite3VdbeAddOp0(v, OP_Close);
        } else if db.init.imposterTable != 0 {
            let mut t = pTable.borrow_mut();
            t.tabFlags |= TF_Imposter;
            if db.init.imposterTable >= 2 {
                t.tabFlags |= TF_Readonly;
            }
        }

        // Normal (non-error) return.
        return;
    }

    // If an error occurs, we jump here
    // begin_table_error:
    db.pp().checkSchema = 1;
}

