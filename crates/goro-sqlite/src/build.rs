/// C: `void sqlite3FinishCoding(Parse *pParse)`
///
/// This routine is called after a single SQL statement has been
/// parsed and a VDBE program to execute that statement has been
/// prepared.  This routine puts the finishing touches on the
/// VDBE program and resets the pParse structure for the next
/// parse.
///
/// Note that if an error occurred, it might be the case that
/// no VDBE code was generated.
pub fn sqlite3FinishCoding(db: &mut Sqlite3) {
    if db.ppr().nested != 0 {
        return;
    }
    if db.ppr().nErr != 0 {
        if db.mallocFailed != 0 {
            db.pp().rc = SQLITE_NOMEM;
        }
        return;
    }

    // Begin by generating some termination code at the end of the
    // vdbe program
    if db.ppr().pVdbe.is_none() {
        if db.init.busy != 0 {
            db.pp().rc = SQLITE_DONE;
            return;
        }
        if !get_vdbe(db) {
            db.pp().rc = SQLITE_ERROR;
        }
    }
    if db.ppr().pVdbe.is_some() {
        if db.ppr().bReturning != 0 {
            let (nRetCol, iRetCur, reg) = {
                let r = db.ppr().u1.d.pReturning.as_ref().expect("RETURNING");
                (r.nRetCol, r.iRetCur, r.iRetReg)
            };
            if nRetCol != 0 {
                let v = db.v();
                sqlite3VdbeAddOp0(v, OP_FkCheck);
                let addrRewind = sqlite3VdbeAddOp1(v, OP_Rewind, iRetCur);
                for i in 0..nRetCol {
                    sqlite3VdbeAddOp3(v, OP_Column, iRetCur, i, reg + i);
                }
                sqlite3VdbeAddOp2(v, OP_ResultRow, reg, nRetCol);
                sqlite3VdbeAddOp2(v, OP_Next, iRetCur, addrRewind + 1);
                sqlite3VdbeJumpHere(v, addrRewind);
            }
        }
        sqlite3VdbeAddOp0(db.v(), OP_Halt);

        // The cookie mask contains one bit for each database file open.
        // (Bit 0 is for main, bit 1 is for temp, and so forth.)  Bits are
        // set for each database that is used.  Generate code to start a
        // transaction on each used database and to verify the schema cookie
        // on each used database.
        sqlite3VdbeJumpHere(db.v(), 0);
        debug_assert!(db.nDb() > 0);
        let (cookieMask, writeMask) = (db.ppr().cookieMask, db.ppr().writeMask);
        let initBusy = db.init.busy;
        for iDb in 0..db.nDb() {
            if !DbMaskTest(cookieMask, iDb) {
                continue;
            }
            let (cookie, iGen) = {
                let s = &db.aDb[iDb as usize].pSchema;
                (s.schema_cookie, s.iGeneration)
            };
            let v = db.v();
            sqlite3VdbeUsesBtree(v, iDb);
            sqlite3VdbeAddOp4Int(
                v,
                OP_Transaction,                    // Opcode
                iDb,                               // P1
                DbMaskTest(writeMask, iDb) as i32, // P2
                cookie,                            // P3
                iGen,                              // P4
            );
            if initBusy == 0 {
                sqlite3VdbeChangeP5(v, 1);
            }
        }
        let nVtabLock = db.ppr().nVtabLock;
        let locks: Vec<TableRef> = db
            .ppr()
            .apVtabLock
            .iter()
            .take(nVtabLock as usize)
            .cloned()
            .collect();
        for t in locks {
            let vtab = crate::vtab::sqlite3VtabP4(db, &t);
            sqlite3VdbeAddOp4(db.v(), OP_VBegin, 0, 0, 0, vtab, P4_VTAB as i32);
        }
        db.pp().nVtabLock = 0;

        // Once all the cookies have been verified and transactions opened,
        // obtain the required table-locks. This is a no-op unless the
        // shared-cache feature is enabled.
        if !db.ppr().aTableLock.is_empty() {
            codeTableLocks(db);
        }

        // Initialize any AUTOINCREMENT data structures required.
        if db.ppr().usesAinc != 0 {
            crate::insert::sqlite3AutoincrementBegin(db);
        }

        // Code constant expressions that were factored out of inner loops.
        let pEL = db.ppr().pConstExpr;
        if pEL.nn() {
            db.pp().okConstFactor = 0;
            let n = db.el(pEL).nExpr();
            for i in 0..n {
                let (e, r) = {
                    let it = &db.el(pEL).a[i as usize];
                    (it.pExpr, it.u.iConstExprReg)
                };
                debug_assert!(r > 0);
                crate::expr::sqlite3ExprCode(db, e, r);
            }
        }

        if db.ppr().bReturning != 0 {
            let (nRetCol, iRetCur) = {
                let r = db.ppr().u1.d.pReturning.as_ref().expect("RETURNING");
                (r.nRetCol, r.iRetCur)
            };
            if nRetCol != 0 {
                sqlite3VdbeAddOp2(db.v(), OP_OpenEphemeral, iRetCur, nRetCol);
            }
        }

        // Finally, jump back to the beginning of the executable code.
        sqlite3VdbeGoto(db.v(), 1);
    }

    // Get the VDBE program ready for execution
    debug_assert!(db.ppr().pVdbe.is_some() || db.ppr().nErr != 0);
    if db.ppr().nErr == 0 {
        // A minimum of one cursor is required if autoincrement is used
        //  See ticket [a696379c1f08866]
        with_v(db, |db, v| sqlite3VdbeMakeReady(db, v));
        db.pp().rc = SQLITE_DONE;
    } else {
        db.pp().rc = SQLITE_ERROR;
    }
}

/// The part of a Parse that is reset before and after each recursion of
/// the parser (C: PARSE_TAIL, from sLastToken to the end of the struct).
#[derive(Default)]
struct ParseTail {
    sLastToken: Token,
    nVar: ynVar,
    aVnbmc: [u64; 2],
    iPkSortOrder: u8,
    explain: u8,
    eParseMode: u8,
    nVtabLock: i32,
    nHeight: i32,
    addrExplain: i32,
    pVList: VList,
    pReprepare: Option<StmtId>,
    zSql: Option<Rc<[u8]>>,
    zTail: usize,
    pNewTable: Option<TableRef>,
    pNewIndex: Option<IndexRef>,
    pNewTrigger: Option<TriggerRef>,
    zAuthContext: Option<ZStr>,
    sArg: Token,
    apVtabLock: Vec<TableRef>,
    pWith: WithId,
    pRename: Vec<RenameToken>,
}

impl ParseTail {
    /// memcpy(saveBuf, PARSE_TAIL(p)); memset(PARSE_TAIL(p), 0)
    fn take(p: &mut Parse) -> ParseTail {
        use std::mem::take;
        ParseTail {
            sLastToken: take(&mut p.sLastToken),
            nVar: take(&mut p.nVar),
            aVnbmc: take(&mut p.aVnbmc),
            iPkSortOrder: take(&mut p.iPkSortOrder),
            explain: take(&mut p.explain),
            eParseMode: take(&mut p.eParseMode),
            nVtabLock: take(&mut p.nVtabLock),
            nHeight: take(&mut p.nHeight),
            addrExplain: take(&mut p.addrExplain),
            pVList: take(&mut p.pVList),
            pReprepare: take(&mut p.pReprepare),
            zSql: take(&mut p.zSql),
            zTail: take(&mut p.zTail),
            pNewTable: take(&mut p.pNewTable),
            pNewIndex: take(&mut p.pNewIndex),
            pNewTrigger: take(&mut p.pNewTrigger),
            zAuthContext: take(&mut p.zAuthContext),
            sArg: take(&mut p.sArg),
            apVtabLock: take(&mut p.apVtabLock),
            pWith: take(&mut p.pWith),
            pRename: take(&mut p.pRename),
        }
    }
    /// memcpy(PARSE_TAIL(p), saveBuf)
    fn restore(self, p: &mut Parse) {
        p.sLastToken = self.sLastToken;
        p.nVar = self.nVar;
        p.aVnbmc = self.aVnbmc;
        p.iPkSortOrder = self.iPkSortOrder;
        p.explain = self.explain;
        p.eParseMode = self.eParseMode;
        p.nVtabLock = self.nVtabLock;
        p.nHeight = self.nHeight;
        p.addrExplain = self.addrExplain;
        p.pVList = self.pVList;
        p.pReprepare = self.pReprepare;
        p.zSql = self.zSql;
        p.zTail = self.zTail;
        p.pNewTable = self.pNewTable;
        p.pNewIndex = self.pNewIndex;
        p.pNewTrigger = self.pNewTrigger;
        p.zAuthContext = self.zAuthContext;
        p.sArg = self.sArg;
        p.apVtabLock = self.apVtabLock;
        p.pWith = self.pWith;
        p.pRename = self.pRename;
    }
}

/// C: `void sqlite3NestedParse(Parse *pParse, const char *zFormat, ...)`
///
/// Run the parser and code generator recursively in order to generate
/// code for the SQL statement given onto the end of the pParse context
/// currently under construction.  Notes:
///
///   *  The final OP_Halt is not appended and other initialization
///      and finalization steps are omitted because those are handling by the
///      outermost parser.
///
///   *  Built-in SQL functions always take precedence over application-defined
///      SQL functions.  In other words, it is not possible to override a
///      built-in function.
pub fn sqlite3NestedParse(db: &mut Sqlite3, zFormat: Option<&[u8]>, args: &[PfArg]) {
    let savedDbFlags = db.mDbFlags;
    if db.ppr().nErr != 0 {
        return;
    }
    if db.ppr().eParseMode != 0 {
        return;
    }
    debug_assert!(db.ppr().nested < 10);
    let zSql = crate::printf::sqlite3VMPrintf(db, zFormat.unwrap_or(b""), args);
    if zSql.len() as i64 >= db.aLimit[SQLITE_LIMIT_LENGTH as usize] as i64 {
        // This can result either from an OOM or because the formatted string
        // exceeds SQLITE_LIMIT_LENGTH.  In the latter case, we need to set
        // an error
        if db.mallocFailed == 0 {
            db.pp().rc = SQLITE_TOOBIG;
        }
        db.pp().nErr += 1;
        return;
    }
    db.pp().nested += 1;
    let saveBuf = ParseTail::take(db.pp());
    db.mDbFlags |= DBFLAG_PreferBuiltin;
    let zSql: Rc<[u8]> = Rc::from(zSql);
    crate::tokenize::sqlite3RunParser(db, &zSql, 0);
    db.mDbFlags = savedDbFlags;
    saveBuf.restore(db.pp());
    db.pp().nested -= 1;
}

