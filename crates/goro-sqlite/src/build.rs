/// Reclaim the memory used by an index
pub fn sqlite3FreeIndex(db: &mut Sqlite3, p: &IndexRef) {
    crate::analyze::sqlite3DeleteIndexSamples(db, p);
    // The parse trees and arrays are freed when the last reference to the
    // Index goes away.
}

/// C: `void sqlite3UnlinkAndDeleteIndex(sqlite3 *db, int iDb, const char *zIdxName)`
///
/// For the index called zIdxName which is found in the database iDb,
/// unlike that index from its Table then remove the index from
/// the index hash table and free all memory structures associated
/// with the index.
pub fn sqlite3UnlinkAndDeleteIndex(db: &mut Sqlite3, iDb: i32, zIdxName: Option<&[u8]>) {
    let pIndex = db.aDb[iDb as usize]
        .pSchema
        .idxHash
        .remove(zIdxName.unwrap_or(b""));
    if let Some(pIndex) = pIndex {
        if let Some(pTab) = pIndex.borrow().pTable.upgrade() {
            pTab.borrow_mut().pIndex.retain(|x| !Rc::ptr_eq(x, &pIndex));
        }
        sqlite3FreeIndex(db, &pIndex);
    }
    db.mDbFlags |= DBFLAG_SchemaChange;
}

/// C: `void sqlite3CollapseDatabaseArray(sqlite3 *db)`
///
/// Look through the list of open database files in db->aDb[] and if
/// any have been closed, remove them from the list.  Reallocate the
/// db->aDb[] structure to a smaller size, if possible.
///
/// Entry 0 (the "main" database) and entry 1 (the "temp" database)
/// are never candidates for being collapsed.
pub fn sqlite3CollapseDatabaseArray(db: &mut Sqlite3) {
    let mut i = 2;
    while i < db.aDb.len() {
        if db.aDb[i].pBt.is_none() {
            db.aDb.remove(i);
        } else {
            i += 1;
        }
    }
}

/// C: `void sqlite3ResetOneSchema(sqlite3 *db, int iDb)`
///
/// Reset the schema for the database at index iDb.  Also reset the
/// TEMP schema.  The reset is deferred if db->nSchemaLock is not zero.
/// Deferred resets may be run by calling with iDb<0.
pub fn sqlite3ResetOneSchema(db: &mut Sqlite3, iDb: i32) {
    debug_assert!(iDb < db.nDb());
    if iDb >= 0 {
        db.DbSetProperty(iDb, DB_ResetWanted);
        db.DbSetProperty(1, DB_ResetWanted);
        db.mDbFlags &= !DBFLAG_SchemaKnownOk;
    }

    if db.nSchemaLock == 0 {
        for i in 0..db.nDb() {
            if db.DbHasProperty(i, DB_ResetWanted) {
                crate::callback::sqlite3SchemaClear(db, i);
                db.mDbFlags &= !DBFLAG_SchemaKnownOk;
            }
        }
    }
}

/// C: `void sqlite3ResetAllSchemasOfConnection(sqlite3 *db)`
///
/// Erase all schema information from all attached databases (including
/// "main" and "temp") for a single database connection.
pub fn sqlite3ResetAllSchemasOfConnection(db: &mut Sqlite3) {
    for i in 0..db.nDb() {
        if db.nSchemaLock == 0 {
            crate::callback::sqlite3SchemaClear(db, i);
        } else {
            db.DbSetProperty(i, DB_ResetWanted);
        }
    }
    db.mDbFlags &= !(DBFLAG_SchemaChange | DBFLAG_SchemaKnownOk);
    crate::vtab::sqlite3VtabUnlockList(db);
    if db.nSchemaLock == 0 {
        sqlite3CollapseDatabaseArray(db);
    }
}

