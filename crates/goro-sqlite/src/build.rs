/// sqlite3GetVdbe(): make sure the current parse has a Vdbe.
#[inline]
fn get_vdbe(db: &mut Sqlite3) -> bool {
    crate::select::sqlite3GetVdbe(db)
}

/// Run `f` with the Vdbe of the current parse taken out of the Parse, for
/// vdbeaux functions that take both `db` and `v`.
fn with_v<R>(db: &mut Sqlite3, f: impl FnOnce(&mut Sqlite3, &mut Vdbe) -> R) -> R {
    let mut v = db.pp().pVdbe.take().expect("no vdbe");
    let r = f(db, &mut v);
    db.pp().pVdbe = Some(v);
    r
}

/// sqlite3StrICmp(a,b)==0
#[inline]
fn streq(a: &[u8], b: &[u8]) -> bool {
    sqlite3StrICmp(Some(a), Some(b)) == 0
}

/// sqlite3StrNICmp(a,b,n)==0
#[inline]
fn strneq(a: &[u8], b: &[u8], n: i32) -> bool {
    sqlite3_strnicmp(Some(a), Some(b), n) == 0
}

/// `&z[n..]` or an empty string (C `z+n` on a string known to be long
/// enough).
#[inline]
fn tail(z: &[u8], n: usize) -> &[u8] {
    if z.len() >= n { &z[n..] } else { b"" }
}

/// sqlite3DbSpanDup(): copy the text zSrc[iStart..iEnd], with leading and
/// trailing white space removed.
fn span_dup(zSrc: &[u8], mut iStart: usize, iEnd: usize) -> ZStr {
    let iEnd = iEnd.min(zSrc.len());
    while iStart < iEnd && sqlite3Isspace(zSrc[iStart]) {
        iStart += 1;
    }
    let mut n = iEnd.saturating_sub(iStart);
    while n > 0 && sqlite3Isspace(zSrc[iStart + n - 1]) {
        n -= 1;
    }
    zSrc[iStart..iStart + n].to_vec()
}

