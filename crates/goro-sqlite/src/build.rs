/// C: `IdList * sqlite3IdListAppend(Parse *pParse, IdList *pList, Token *pToken)`
///
/// Append a new element to the given IdList.  Create a new IdList if
/// need be.
///
/// A new IdList is returned, or NULL if malloc() fails.
pub fn sqlite3IdListAppend(db: &mut Sqlite3, mut pList: IdListId, pToken: &Token) -> IdListId {
    if pList.is_null() {
        pList = db.arena.new_idlist(IdList::default());
    }
    let zName = sqlite3NameFromToken(db, pToken);
    let has = zName.is_some();
    let i = db.idl(pList).nId();
    db.idlm(pList).a.push(IdListItem { zName });
    if db.ppr().IN_RENAME_OBJECT() && has {
        sqlite3RenameTokenMap(db, rename_key_idlist_item(pList, i), pToken);
    }
    pList
}

