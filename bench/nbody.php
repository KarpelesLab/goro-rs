// Float arithmetic over nested arrays (nbody-style), by-reference updates.
function energy(array $b): float {
    $e = 0.0;
    $n = count($b);
    for ($i = 0; $i < $n; $i++) {
        $bi = $b[$i];
        $e += 0.5 * $bi[6] * ($bi[3] * $bi[3] + $bi[4] * $bi[4] + $bi[5] * $bi[5]);
        for ($j = $i + 1; $j < $n; $j++) {
            $bj = $b[$j];
            $dx = $bi[0] - $bj[0]; $dy = $bi[1] - $bj[1]; $dz = $bi[2] - $bj[2];
            $e -= ($bi[6] * $bj[6]) / sqrt($dx * $dx + $dy * $dy + $dz * $dz);
        }
    }
    return $e;
}
function advance(array &$b, float $dt, int $steps): void {
    $n = count($b);
    for ($s = 0; $s < $steps; $s++) {
        for ($i = 0; $i < $n; $i++) {
            for ($j = $i + 1; $j < $n; $j++) {
                $dx = $b[$i][0] - $b[$j][0];
                $dy = $b[$i][1] - $b[$j][1];
                $dz = $b[$i][2] - $b[$j][2];
                $d2 = $dx * $dx + $dy * $dy + $dz * $dz;
                $mag = $dt / ($d2 * sqrt($d2));
                $mj = $b[$j][6] * $mag;
                $b[$i][3] -= $dx * $mj; $b[$i][4] -= $dy * $mj; $b[$i][5] -= $dz * $mj;
                $mi = $b[$i][6] * $mag;
                $b[$j][3] += $dx * $mi; $b[$j][4] += $dy * $mi; $b[$j][5] += $dz * $mi;
            }
        }
        for ($i = 0; $i < $n; $i++) {
            $b[$i][0] += $dt * $b[$i][3];
            $b[$i][1] += $dt * $b[$i][4];
            $b[$i][2] += $dt * $b[$i][5];
        }
    }
}
